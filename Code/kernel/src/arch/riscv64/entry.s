# Точка входа ядра. OpenSBI прыгает сюда по ФИЗИЧЕСКОМУ 0x8020_0000 в S-mode:
#   a0 = hartid, a1 = указатель на device tree (DTB, тоже физический).
# Сохраняем a0/a1 нетронутыми и передаём их в kmain.
#
# Веха 87 — higher-half: ядро СЛИНКОВАНО по высоким адресам (0xFFFF_FFC0_8020_0000),
# а первые инструкции исполняются по физическим — трансляции ещё нет. Это законно
# только потому, что riscv собран с medany: и `la`, и переходы адресуются
# PC-относительно, поэтому один и тот же код работает по обоим адресам, а разница
# «где мы» проявляется лишь в том, какие адреса даёт `la` (низкие до прыжка,
# высокие после). Задача трамплина ниже — построить ВРЕМЕННУЮ таблицу, где RAM
# видна и там, и там, включить satp и уйти в верхнюю половину.
.section .text.entry
.global _start
_start:
    # На многоядерной системе паркуем все харты, кроме hart 0.
    bnez    a0, park

    # ── 1) Обнулить .bss (границы выровнены по 8 в linker.ld) ────────────────
    # Строго ДО постройки таблицы: таблица трамплина живёт в .bss.
    la      t0, _bss_start
    la      t1, _bss_end
1:
    bgeu    t0, t1, 2f
    sd      zero, 0(t0)
    addi    t0, t0, 8
    j       1b
2:

    # ── 2) Временная таблица: вся физическая память в ОБЕИХ половинах ────────
    # Гигастраницы (листовой PTE на верхнем уровне Sv39) — 512 записей корня и ни
    # одной подтаблицы. Нижние 256 записей: VA == PA (без них следующая же
    # инструкция после `csrw satp` ушла бы в никуда). Верхние 256: VA == PA +
    # KERNEL_OFFSET — в них мы и переедем. Настоящие таблицы (W^X, MMIO, точная
    # граница RAM) строит потом paging::init, эта — только чтобы дожить до неё.
    la      t0, boot_root           # бежит по нижним записям (identity)
    li      t5, 2048                # 256 записей × 8 байт
    add     t5, t0, t5              # бежит по верхним (direct-map)
    li      t1, 0                   # i — номер гигабайта
    li      t2, 0xCF                # V|R|W|X|A|D
    li      t3, 256                 # столько гигабайт в половине Sv39
3:
    slli    t4, t1, 28              # PTE: ((i << 30) >> 12) << 10 == i << 28
    or      t4, t4, t2
    sd      t4, 0(t0)               # нижняя половина (identity)
    sd      t4, 0(t5)               # верхняя половина (VA == PA + KERNEL_OFFSET)
    addi    t0, t0, 8
    addi    t5, t5, 8
    addi    t1, t1, 1
    blt     t1, t3, 3b

    # ── 3) Включить трансляцию: satp = Sv39 | PPN(boot_root) ─────────────────
    la      t0, boot_root
    srli    t4, t0, 12
    li      t5, 8
    slli    t5, t5, 60              # MODE=8 (Sv39)
    or      t4, t4, t5
    sfence.vma                      # записи таблицы — видимыми до её включения
    csrw    satp, t4
    sfence.vma                      # и сбросить кэш трансляций

    # ── 4) Переезд в верхнюю половину ────────────────────────────────────────
    # `la` даёт PC-относительный (пока НИЗКИЙ) адрес метки; прибавив KERNEL_OFFSET,
    # получаем её высокий VMA — и прыгаем туда. После `jr` PC высокий, а значит все
    # дальнейшие PC-относительные адреса — тоже.
    la      t0, 5f
    li      t1, -1
    slli    t1, t1, 38              # -1 << 38 == 0xFFFF_FFC0_0000_0000 (KERNEL_OFFSET)
    add     t0, t0, t1
    jr      t0
5:
    # Стек ядра — теперь `la` возвращает высокий VMA из linker.ld.
    la      sp, _stack_top

    # a0 (hartid), a1 (dtb) всё ещё в регистрах аргументов.
    call    kmain

park:
    wfi
    j       park

# ── данные трамплина ────────────────────────────────────────────────────────
.section .bss
.align 12
boot_root:
    .space 4096                     # корневая таблица Sv39: 512 записей по 8 байт
