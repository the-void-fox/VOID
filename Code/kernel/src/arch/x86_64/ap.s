# Трамплин ПРИКЛАДНОГО ЯДРА (AP) — Веха 170, этап 1.
#
# Прикладное ядро x86 просыпается по SIPI в РЕАЛЬНОМ РЕЖИМЕ, с CS = <вектор>:0000 — то есть
# исполнять оно начинает физический адрес, кратный странице и лежащий ниже мебибайта. Ни
# длинного режима, ни пейджинга, ни нашей GDT у него нет: всё это надо построить заново, ровно
# как строит себе загрузочное ядро в `entry.s`.
#
# Отличий от `entry.s` два, и оба принципиальные:
#
#   1. Начинаем НА ШАГ РАНЬШЕ — с шестнадцати бит. Загрузчик (PVH или GRUB) отдаёт нам уже
#      32-битный защищённый режим, а SIPI — нет.
#   2. Таблицы страниц НЕ СТРОИМ. Загрузочные (`boot_pml4` из `entry.s`) никуда не делись и
#      отображают ровно то, что нужно: первые 4 ГиБ идентично (чтобы пережить включение
#      пейджинга), прямую карту и окно образа ядра. Строить второй комплект значило бы завести
#      вторую истину о раскладке памяти — и однажды разойтись с первой.
#
# ── Почему раскладка задана ЧИСЛАМИ ──────────────────────────────────────────────────────────
#
# Код копируется в низкую память по `AP_BASE`, поэтому все ссылки внутри него должны считаться
# от `AP_BASE`, а не от места, где он слинкован. Написать это разностью меток («AP_BASE плюс
# сколько-то от начала») нельзя: встроенный ассемблер LLVM отказывается брать в адрес операнда
# больше одного символа. Поэтому места частей назначены явно (`.set` ниже) и расставлены
# `.org` — одно место, где раскладка написана, и ассемблер сам проверит, что код в отведённые
# ему рамки уместился.
#
# Наружу метки всё равно экспортируются: смещения полей данных ядро считает по НИМ
# (`smp::start_aps`), а не повторяет числа у себя. Одна истина, два читателя.
#
# Дальние переходы записаны БАЙТАМИ по той же причине: `ljmp` с явным селектором встроенный
# ассемблер принимает по-разному в 16- и 32-битном режиме, а ошибка здесь не диагностируется
# ничем — машина уходит в тройной сбой без единого слова.

.set AP_BASE,    0x8000
.set OFF_PROT,   0x40           # вход в 32-битный защищённый режим
.set OFF_LONG,   0xA0           # вход в длинный режим
.set OFF_GDTR,   0x100
.set OFF_GDT,    0x110
.set OFF_CR3,    0x140
.set OFF_STACK,  0x148
.set OFF_ENTRY,  0x150
.set OFF_END,    0x160

.section .rodata.aptramp, "a"
.code16
.global ap_tramp_start
ap_tramp_start:
    cli
    cld
    xor ax, ax
    mov ds, ax
    mov es, ax
    mov ss, ax
    lgdt [AP_BASE + OFF_GDTR]
    mov eax, cr0
    or eax, 1                       # PE — защищённый режим
    mov cr0, eax
    # ljmp 0x08 : ap_prot  (0x66 = 32-битный операнд в 16-битном режиме)
    .byte 0x66, 0xEA
    .long AP_BASE + OFF_PROT
    .short 0x08

.org OFF_PROT
.code32
.global ap_prot
ap_prot:
    mov ax, 0x10
    mov ds, ax
    mov es, ax
    mov ss, ax
    mov fs, ax
    mov gs, ax

    # PAE обязательна для длинного режима; OSFXSR|OSXMMEXCPT — SSE (тот же набор, что в entry.s:
    # без них любой SSE-опкод в ring3 даёт #UD, а прикладное ядро будет исполнять те же процессы).
    mov eax, cr4
    or eax, (1 << 5) | (1 << 9) | (1 << 10)
    mov cr4, eax

    # Корень таблиц — ЗАГРУЗОЧНЫЙ: его положил сюда BSP перед стартом (см. `smp::start_aps`).
    mov eax, [AP_BASE + OFF_CR3]
    mov cr3, eax

    # EFER: LME (длинный режим) + NXE (бит NX в PTE — без него настоящие таблицы ядра, где
    # он выставлен, дали бы #PF на первой же странице данных).
    mov ecx, 0xC0000080
    rdmsr
    or eax, (1 << 8) | (1 << 11)
    wrmsr

    # CR0: PG | WP | PE — ровно как у загрузочного ядра.
    mov eax, cr0
    or eax, 0x80010001
    mov cr0, eax

    # ljmp 0x18 : ap_long — в 64-битный сегмент. Адрес назначения ещё низкий (он же физический),
    # и это работает ровно потому, что первые 4 ГиБ отображены идентично.
    .byte 0xEA
    .long AP_BASE + OFF_LONG
    .short 0x18

.org OFF_LONG
.code64
.global ap_long
ap_long:
    # Стек и точка входа приехали 64-битными: адрес входа высокий (окно образа ядра), и
    # положить его в 32-битное поле было бы нельзя.
    mov rsp, [AP_BASE + OFF_STACK]
    mov rax, [AP_BASE + OFF_ENTRY]
    jmp rax

# ── данные трамплина ─────────────────────────────────────────────────────────
#
# Лежат ВНУТРИ копируемого куска: у прикладного ядра до самого длинного режима нет ни одного
# способа дотянуться до памяти ядра — ни регистра с базой, ни таблиц.
.org OFF_GDTR
ap_gdtr:
    .short (4 * 8) - 1              # предел: четыре дескриптора
    .long AP_BASE + OFF_GDT

.org OFF_GDT
ap_gdt:
    .quad 0
    .quad 0x00CF9A000000FFFF        # 0x08: код 32 бита
    .quad 0x00CF92000000FFFF        # 0x10: данные
    .quad 0x00AF9A000000FFFF        # 0x18: код 64 бита (L=1)

.org OFF_CR3
.global ap_cr3
ap_cr3:
    .long 0

.org OFF_STACK
.global ap_stack
ap_stack:
    .quad 0

.org OFF_ENTRY
.global ap_entry
ap_entry:
    .quad 0

.org OFF_END
.global ap_tramp_end
ap_tramp_end:
