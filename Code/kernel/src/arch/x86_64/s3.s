# Веха 241 — СОХРАНИТЬ И ВЕРНУТЬ состояние процессора вокруг сна S3.
#
# Устроено как `setjmp`/`longjmp`, и это не аналогия, а тот же приём: `s3_save` возвращается
# ДВАЖДЫ — нулём, когда сохранила, и единицей, когда в неё вернулись из сна. Всё, что между,
# происходит в двух разных жизнях процессора: до засыпания и после пробуждения.
#
# Почему хватает семи регистров. В S3 процессор теряет ВСЁ, но восстанавливать всё и не надо:
# соглашение о вызовах System V само делит регистры на «сохраняет вызываемый» (rbx, rbp,
# r12–r15, rsp) и «сохраняет вызывающий» (остальные). Вернувшись как обычный вызов, мы обязаны
# предъявить только первые — остальные вызывающий код уже не считает своими.
#
# Стек при этом переживает сон вместе с памятью: S3 — это «suspend to RAM», и содержимое RAM
# сохраняется. Поэтому адрес возврата, лежащий на стеке, после пробуждения на месте.

.section .text
.global s3_save
# s3_save(ctx: *mut u64 /* rdi */) -> u64
s3_save:
    mov [rdi + 0], rsp
    mov [rdi + 8], rbp
    mov [rdi + 16], rbx
    mov [rdi + 24], r12
    mov [rdi + 32], r13
    mov [rdi + 40], r14
    mov [rdi + 48], r15
    lea rax, [rip + s3_back]
    mov [rdi + 56], rax
    xor eax, eax                    # первый возврат: «сохранили»
    ret
s3_back:
    mov eax, 1                      # второй возврат: «проснулись»
    ret

.global s3_restore
# s3_restore(ctx: *const u64 /* rdi */) -> !
#
# Зовётся уже в длинном режиме, на таблицах ядра и с настоящей GDT — всё это восстановил
# трамплин и `resume_entry`. Здесь остаётся вернуть регистры и прыгнуть туда, где звали
# `s3_save`: дальше код продолжится так, будто вызов просто вернул единицу.
s3_restore:
    mov rsp, [rdi + 0]
    mov rbp, [rdi + 8]
    mov rbx, [rdi + 16]
    mov r12, [rdi + 24]
    mov r13, [rdi + 32]
    mov r14, [rdi + 40]
    mov r15, [rdi + 48]
    mov rax, [rdi + 56]
    jmp rax
