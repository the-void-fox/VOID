//! Веха 242.1 — **интерфейс Bochs VBE (DISPI)**: им эмуляторы ставят графический режим.
//!
//! ## Зачем он нам понадобился
//!
//! Режим на загрузке ставит не система, а GRUB (тег фреймбуфера multiboot2). После сна S3
//! устройство экрана сброшено, и в QEMU это видно буквально: «Guest has not initialized the
//! display (yet)» — кадр мы пишем, а развёртки нет. Прошивка виртуальной машины его не
//! возвращает, и вернуть его можем только мы.
//!
//! ## Почему это НЕ путь для живой машины
//!
//! DISPI — интерфейс эмуляторов (QEMU stdvga, Bochs, VirtualBox). Настоящая графика им не
//! управляется: там режим ставит драйвер железа (у нас — `intel_fb`, и для него есть свой
//! возврат из сна). Поэтому здесь нет ни единой попытки угадать: если регистр опознания не
//! отвечает знакомым числом, мы не трогаем ничего.

use super::{io_read, io_write};

const INDEX: u16 = 0x1ce;
const DATA: u16 = 0x1cf;

const I_ID: u16 = 0;
const I_XRES: u16 = 1;
const I_YRES: u16 = 2;
const I_BPP: u16 = 3;
const I_ENABLE: u16 = 4;
const I_VIRT_WIDTH: u16 = 6;
const I_X_OFF: u16 = 8;
const I_Y_OFF: u16 = 9;

/// Режим включён, кадр — линейным буфером (а не банками по 64 КиБ), И НЕ ЧИСТИТЬ ПАМЯТЬ.
///
/// Последнее — не мелочь. По умолчанию включение режима затирает видеопамять нулями, а у нас
/// там ЖИВОЙ КАДР, переживший сон вместе с остальной памятью: окна, обои, панель. Без этого
/// бита пробуждение выглядело так — экран вернулся, но на нём осталось только то, что успели
/// перерисовать после (проверено: чёрный стол и два острова панели).
const ENABLE_LFB: u16 = 0x01 | 0x40 | 0x80;

fn rd(index: u16) -> u16 {
    io_write(INDEX, 2, index as u32);
    io_read(DATA, 2) as u16
}

fn wr(index: u16, value: u16) {
    io_write(INDEX, 2, index as u32);
    io_write(DATA, 2, value as u32);
}

/// Отвечает ли машина по этому интерфейсу. Опознание — числа `0xB0C0..0xB0C5` (версии DISPI);
/// на живой машине порты молчат (`0xffff`), и мы ничего не делаем.
pub fn present() -> bool {
    matches!(rd(I_ID), 0xb0c0..=0xb0cf)
}

/// Поставить режим заново — ровно тот, в котором система уже работает.
///
/// Порядок обязателен: сперва выключить режим, потом менять числа, потом включить. Менять
/// размеры на включённом режиме — это писать в регистры, по которым прямо сейчас идёт
/// развёртка.
pub fn restore(width: usize, height: usize, pitch: usize, bpp: usize) -> bool {
    if !present() || width == 0 || height == 0 {
        return false;
    }
    wr(I_ENABLE, 0);
    wr(I_XRES, width as u16);
    wr(I_YRES, height as u16);
    wr(I_BPP, bpp as u16);
    // Ширина в ТОЧКАХ, а не в байтах: шаг строки кадра у нас в байтах, и перепутать их значит
    // получить картинку, уехавшую по диагонали.
    wr(I_VIRT_WIDTH, (pitch / (bpp / 8).max(1)) as u16);
    wr(I_X_OFF, 0);
    wr(I_Y_OFF, 0);
    wr(I_ENABLE, ENABLE_LFB);
    unblank();
    rd(I_ENABLE) & 1 != 0
}

/// СНЯТЬ ГАШЕНИЕ с видеовыхода — то, без чего всё остальное бессмысленно.
///
/// У VGA есть бит «показывать картинку» (PAS) в регистре индекса контроллера атрибутов, и
/// после сброса устройства он сброшен: режим поставлен, кадр на месте, развёртка настроена — а
/// экран чёрный. В QEMU это видно буквально надписью «Guest has not initialized the display
/// (yet)», и первая версия возврата режима спотыкалась ровно здесь: регистры DISPI принимались,
/// читались обратно, а картинки не было.
///
/// Порядок такой: прочитать регистр состояния (он сбрасывает защёлку «индекс/данные» в
/// известное положение), затем записать индекс с установленным битом PAS.
fn unblank() {
    let _ = io_read(0x3da, 1); // сбросить защёлку индекс/данные
    io_write(0x3c0, 1, 0x20); // PAS = 1: выход включён
}
