// ── русская раскладка ЙЦУКЕН (Веха 127.1) ───────────────────────────────────
//
// ВТОРАЯ таблица, а не замена первой, и это принципиально. От раскладки зависит только
// ПЕЧАТАЕМЫЙ СИМВОЛ; код клавиши (`keysym`) всегда берётся из US-таблицы и не меняется никогда.
// Иначе `Super+Q` перестал бы работать по-русски, а привязки конфига (`bind pane h go-left`)
// разъехались бы при переключении — то есть управление системой зависело бы от того, на каком
// языке человек сейчас пишет. Так же устроены X11 и Wayland: код клавиши от раскладки не зависит.
//
// Индекс — тот же скан-код, значения — КОДОВЫЕ ТОЧКИ (кириллица в байт не влезает). 0 — символа
// нет, тогда берётся US-вариант: цифры, знаки препинания и служебные клавиши в обеих раскладках
// одни и те же, дублировать их значило бы завести два места для одной правки.
#[rustfmt::skip]
