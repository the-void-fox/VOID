/// Какая раскладка сейчас: `false` — US, `true` — RU. Живёт В ЯДРЕ, потому что таблица
/// скан-кодов живёт здесь же: вторая раскладка в userspace неминуемо разошлась бы с этой.
/// Спасательный шелл и консоль ядра получают переключение тем же даром.
static mut RU: bool = false;

/// Переключатель — **Alt+Shift**: оба модификатора зажаты и отпущены, не нажав между ними
/// ничего печатного. Так это делает Windows, и так привык владелец.
///
/// Отдельная клавиша не годится (на ноутбуке её нет), а аккорд вида `Super+Space` отобрал бы
/// сочетание у оконного менеджера. Пара модификаторов ничего не отнимает: сама по себе она
/// ничего не печатает и ни к чему не привязана.
static mut COMBO: bool = false;

const SC_LSHIFT: u8 = 0x2A;
const SC_RSHIFT: u8 = 0x36;
const SC_CAPS: u8 = 0x3A;
/// Левый Ctrl. Правый приходит как `0xE0 0x1D` — тот же код за префиксом расширенных клавиш.
const SC_LCTRL: u8 = 0x1D;
const RELEASE: u8 = 0x80; // старший бит скан-кода набора 1 = отпускание

/// Веха 42 — настроить контроллер 8042: включить порт клавиатуры, разрешить генерацию IRQ1 и
/// трансляцию в набор 1, вычистить остатки. BIOS обычно уже это сделал, но переинициализация
/// безопасна и не зависит от его настроек.
pub fn init() {
    unsafe {
        // Слить всё, что накопилось во входном буфере.
        for _ in 0..16 {
            if inb(STATUS) & STAT_OUT_FULL == 0 {
                break;
            }
            let _ = inb(DATA);
        }
        // Разрешить первый PS/2-порт (клавиатуру).
        wait_write();
        outb(STATUS, 0xAE);
        // Прочитать управляющий байт (команда 0x20 → ответ в 0x60).
        wait_write();
        outb(STATUS, 0x20);
        for _ in 0..100_000 {
            if inb(STATUS) & STAT_OUT_FULL != 0 {
                break;
            }
        }
        let mut cmd = inb(DATA);
        cmd |= 1 << 0; // бит0: прерывание клавиатуры (IRQ1) вкл
        cmd |= 1 << 1; // бит1: прерывание мыши (IRQ12) вкл — Веха 115
        cmd |= 1 << 6; // бит6: трансляция скан-кодов в набор 1
        cmd &= !(1 << 4); // бит4=0: тактирование клавиатуры НЕ отключено
        cmd &= !(1 << 5); // бит5=0: тактирование мыши НЕ отключено
        // Записать управляющий байт (команда 0x60, затем значение в 0x60).
        wait_write();
        outb(STATUS, 0x60);
        wait_write();
        outb(DATA, cmd);
        // Веха 115 — включить ВТОРОЙ порт (мышь) и саму мышь. Порядок важен: сперва порт
        // разрешён контроллером (0xA8), только потом устройство слышит команды.
        wait_write();
        outb(STATUS, 0xA8);
        // 0xF6 — настройки по умолчанию (частота 100/с, разрешение, масштаб 1:1).
        MOUSE = mouse_cmd(0xF6);
        // Веха 123.1 — КОЛЕСО. Классический «магический стук» IntelliMouse: три установки
        // частоты подряд (200, 100, 80), после которых мышь меняет свой ID с 0 на 3 и начинает
        // слать пакеты по ЧЕТЫРЕ байта — четвёртый и есть колесо. Мышь без колеса стук просто
        // не понимает и остаётся трёхбайтной, поэтому спрашиваем ID и верим ответу, а не надежде.
        // Веха 198 — сперва спрашиваем, не тачпад ли это: «магический стук» колеса сбил бы
        // устройство в состояние, из которого запросы Synaptics уже не проходят.
        if MOUSE {
            TOUCHPAD = touchpad_init();
        }
        if MOUSE && !TOUCHPAD {
            let rate = |r: u8| mouse_cmd(0xF3) && mouse_cmd(r);
            if rate(200) && rate(100) && rate(80) && mouse_cmd(0xF2) {
                WHEEL = read_data() == Some(3);
            }
            // Веха 142 — ВТОРОЙ стук (200, 200, 80) переводит мышь в режим IntelliMouse Explorer
            // (ID 4): в четвёртом байте к колесу добавляются ЧЕТВЁРТАЯ и ПЯТАЯ кнопки. Ими же
            // тилт-колёса сообщают наклон влево-вправо — отдельной оси для наклона у PS/2 нет,
            // и это единственный способ его получить. Мышь, которая стук не понимает, остаётся
            // с прежним ID, поэтому спрашиваем его снова и верим ответу.
            if WHEEL && rate(200) && rate(200) && rate(80) && mouse_cmd(0xF2) {
                EXPLORER = read_data() == Some(4);
            }
            // Частоту вернули «магическим стуком» в 80/с — поднимаем обратно: 80 событий в
            // секунду это заметно рваный курсор.
            let _ = rate(100);
        }
        // 0xF4 — начать слать пакеты. Без неё мышь молчит, сколько её ни двигай.
        MOUSE = MOUSE && mouse_cmd(0xF4);
        // Ещё раз слить возможный «ack».
        for _ in 0..16 {
            if inb(STATUS) & STAT_OUT_FULL == 0 {
                break;
            }
            let _ = inb(DATA);
        }
    }
}

/// Веха 42 — вычерпать все готовые скан-коды и положить ASCII-байты в кольцо консоли
/// ([`super::rx_push`]). Зовётся из [`super::console_drain`] (тик/IRQ1) с выключенными
/// прерываниями — гонок за состоянием модификаторов и кольцом нет.
pub fn drain() {
    unsafe {
        let mut guard = 0;
        // `STATUS == 0xFF` — контроллера нет (открытая шина); иначе читаем, пока есть коды,
        // но не больше страховочного лимита (защита от флуда/залипшего бита).
        while inb(STATUS) != 0xff && inb(STATUS) & STAT_OUT_FULL != 0 && guard < 256 {
            guard += 1;
            // Клавиатура и мышь делят порт данных; чей это байт, говорит бит статуса — и
            // прочитать его надо ДО чтения 0x60, иначе признак уже потерян.
            let aux = inb(STATUS) & STAT_AUX != 0;
            let sc = inb(DATA);
            if aux {
                mouse_byte(sc);
                continue;
            }
            // 0xE0 — префикс расширенных клавиш; следующий байт — код стрелки/Home/End/Del.
            if sc == 0xE0 {
                EXT = true;
                continue;
            }
            if EXT {
                // Веха 45: расширенная клавиша → стандартная ANSI-последовательность (её понимает
                // и терминал QEMU, и разбор в vga.rs/vsh). Только на НАЖАТИЕ (старший бит = 0).
                EXT = false;
                // Правый Ctrl (`0xE0 0x1D`) — такой же модификатор, как левый, и приходит здесь.
                if sc & !RELEASE == SC_LCTRL {
                    CTRL = sc & RELEASE == 0;
                    super::key_push(0x131, mods(), CTRL, 0);
                    continue;
                }
                // Веха 119 — Super (клавиша с логотипом) и правый Alt приходят тем же префиксом.
                if sc & !RELEASE == SC_LSUPER || sc & !RELEASE == SC_RSUPER {
                    SUPER = sc & RELEASE == 0;
                    super::key_push(0x133, mods(), SUPER, 0);
                    continue;
                }
                if sc & !RELEASE == SC_LALT {
                    ALT = sc & RELEASE == 0;
                    super::key_push(0x132, mods(), ALT, 0);
                    continue;
                }
                if sc & RELEASE == 0 {
                    // Веха 116 — PageUp/PageDown появились здесь же: без них листать вывод
                    // на реальной машине было нечем (на QEMU они приходят из serial готовой
                    // последовательностью, поэтому пробел не замечался).
                    let seq: &[u8] = match (sc, SHIFT) {
                        (0x48, _) => b"\x1b[A",  // Up
                        (0x50, _) => b"\x1b[B",  // Down
                        (0x4D, _) => b"\x1b[C",  // Right
                        (0x4B, _) => b"\x1b[D",  // Left
                        (0x47, _) => b"\x1b[H",  // Home
                        (0x4F, _) => b"\x1b[F",  // End
                        (0x53, _) => b"\x1b[3~", // Delete
                        // Shift несём отдельным параметром (`;2`) — так же, как это делают
                        // xterm-совместимые терминалы: Shift+PageUp принято отдавать
                        // ТЕРМИНАЛУ (прокрутка), а голый PageUp — программе.
                        (0x49, false) => b"\x1b[5~",
                        (0x49, true) => b"\x1b[5;2~",
                        (0x51, false) => b"\x1b[6~",
                        (0x51, true) => b"\x1b[6;2~",
                        _ => b"",
                    };
                    for &b in seq {
                        super::rx_push(b);
                    }
                }
                super::key_push(keysym(sc & !RELEASE, true), mods(), sc & RELEASE == 0, 0);
                continue;
            }
            let released = sc & RELEASE != 0;
            let code = sc & !RELEASE;
            match code {
                SC_LSHIFT | SC_RSHIFT => SHIFT = !released,
                SC_LCTRL => CTRL = !released,
                SC_LALT => ALT = !released,
                SC_CAPS => {
                    if !released {
                        CAPS = !CAPS;
                    }
                }
                // Веха 127.1 — любая ДРУГАЯ нажатая клавиша отменяет заготовку переключения:
                // `Alt+Shift+F` это ввод, а не смена раскладки.
                _ => {
                    if !released {
                        COMBO = false;
                    }
                }
            }
            // Alt+Shift сложились — заготовка взведена; отпустили один из них, ничего между тем
            // не нажав, — переключаемся. Проверка на отпускании, а не на нажатии: иначе раскладка
            // менялась бы в начале любого аккорда с обоими модификаторами.
            if SHIFT && ALT {
                COMBO = true;
            } else if COMBO && (code == SC_LSHIFT || code == SC_RSHIFT || code == SC_LALT) && released
            {
                COMBO = false;
                RU = !RU;
            }
            // Веха 119 — СОБЫТИЕ выдаётся на любую клавишу, включая модификаторы и отпускания:
            // оконному менеджеру нужно знать состояние, а не только напечатанное. ASCII считается
            // тут же и едет в событии, чтобы раскладка осталась в одном месте.
            let mut ch = 0u16;
            if (code as usize) < MAP.len() {
                let (lo_us, up_us) = MAP[code as usize];
                // Раскладка выбирает СИМВОЛ: русский вариант, если он для этой клавиши есть.
                // Цифры и знаки препинания в `MAP_RU` нулевые — для них берётся US, и это не
                // упущение: они в обеих раскладках одинаковы, а дубль означал бы два места для
                // одной правки.
                let (lo, up) = match MAP_RU[code as usize] {
                    (0, _) => (lo_us as u16, up_us as u16),
                    ru if RU => ru,
                    _ => (lo_us as u16, up_us as u16),
                };
                if lo != 0 {
                    // Shift даёт верхний вариант; CapsLock влияет ТОЛЬКО на буквы.
                    let is_letter = lo != up;
                    let upper = SHIFT ^ (CAPS && is_letter);
                    ch = if upper { up } else { lo };
                    // Ctrl+буква → управляющий байт (Ctrl-A = 1 … Ctrl-Z = 26), как это делает
                    // любой терминал. Считается по US-КЛАВИШЕ, а не по печатаемому символу:
                    // `Ctrl+C` обязан оставаться `Ctrl+C` и в русской раскладке, иначе прерывание
                    // программы зависело бы от языка ввода.
                    if CTRL && lo_us.is_ascii_alphabetic() {
                        ch = (lo_us.to_ascii_uppercase() - b'@') as u16;
                    }
                }
            }
            super::key_push(keysym(code, false), mods(), !released, ch);
            if !released && ch != 0 {
                // В байтовое кольцо — UTF-8: консоль ядра и программы читают поток байтов, и
                // кириллица едет в нём двумя байтами, как везде.
                let mut buf = [0u8; 4];
                if let Some(c) = char::from_u32(ch as u32) {
                    for &b in c.encode_utf8(&mut buf).as_bytes() {
                        super::rx_push(b);
                    }
                }
            }
        }
    }
}
