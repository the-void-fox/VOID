//! PS/2-клавиатура (контроллер 8042) — ввод на РЕАЛЬНОМ железе (Веха 42).
//!
//! У ноутбука/мини-ПК нет COM-порта, зато внутренняя клавиатура висит на контроллере 8042 как
//! PS/2 (это делает встроенный контроллер платы). Читаем скан-коды **набора 1** из порта 0x60,
//! переводим в ASCII с учётом Shift/CapsLock и кладём в то же кольцо консоли, что и COM1
//! ([`super::rx_push`]) — `vsh` не различает, откуда пришёл байт. Наполняется двумя путями:
//! опрос на тиках таймера ([`super::console_drain`]) и IRQ1 через IOAPIC (будит сон до ввода,
//! когда таймер замаскирован в `wait_stdin`) — оба маршрутизированы на общий вектор консоли.
//!
//! На QEMU (`-nographic`) ввод идёт через serial, PS/2 молчит — драйвер безвреден. На реальной
//! машине именно он делает `vsh>` интерактивным.

const DATA: u16 = 0x60; // чтение скан-кодов / запись данных устройству
const STATUS: u16 = 0x64; // чтение статуса / запись команд контроллеру
const STAT_OUT_FULL: u8 = 1 << 0; // есть байт для чтения из 0x60
const STAT_IN_FULL: u8 = 1 << 1; // входной буфер занят (нельзя писать)
/// Веха 115: байт пришёл из ВТОРОГО порта (мышь), а не от клавиатуры. Тот же 0x60 на двоих —
/// различить их можно только этим битом статуса, и прочитать его надо ДО чтения данных.
const STAT_AUX: u8 = 1 << 5;

#[inline]
unsafe fn outb(port: u16, v: u8) {
    core::arch::asm!("out dx, al", in("dx") port, in("al") v, options(nomem, nostack));
}
#[inline]
unsafe fn inb(port: u16) -> u8 {
    let v: u8;
    core::arch::asm!("in al, dx", in("dx") port, out("al") v, options(nomem, nostack));
    v
}

/// Дождаться, пока входной буфер контроллера освободится (можно писать). Спин ограничен —
/// на отсутствующем/зависшем 8042 не виснем навечно (реального железа без него у нас нет,
/// но осторожность дешёвая).
unsafe fn wait_write() {
    for _ in 0..100_000 {
        if inb(STATUS) & STAT_IN_FULL == 0 {
            return;
        }
    }
}

// ── мышь (Веха 115) ──────────────────────────────────────────────────────────
//
// Стандартный PS/2-пакет — три байта: флаги (кнопки, знаки, переполнения), затем смещения по X
// и по Y. Знак хранится ОТДЕЛЬНЫМ битом в первом байте, а не в самом смещении, поэтому байт
// доводится до i16 вручную. Ось Y у мыши направлена ВВЕРХ, у экрана — вниз; переворачиваем один
// раз здесь, чтобы каждый потребитель не помнил об этом сам.

/// Есть ли мышь (успела ли ответить на команды включения).
static mut MOUSE: bool = false;
/// Накопитель пакета и позиция в нём.
static mut PKT: [u8; 4] = [0; 4];
static mut PKT_AT: usize = 0;
/// Мышь отвечает пакетами по 4 байта (есть колесо) — выяснено при инициализации.
static mut WHEEL: bool = false;
/// Веха 142 — мышь в режиме IntelliMouse Explorer (ID 4): в четвёртом байте, кроме колеса,
/// приходят четвёртая и пятая кнопки. Наклон колеса влево-вправо приходит именно ими.
static mut EXPLORER: bool = false;

/// Веха 198 — на втором порту не мышь, а ТАЧПАД Synaptics в абсолютном режиме. Тогда пакет
/// шестибайтный, и разбирает его [`void_touch`], а не [`mouse_byte`].
static mut TOUCHPAD: bool = false;
/// Пакет тачпада (шесть байт) и сколько уже собрано.
static mut TP_PKT: [u8; 6] = [0; 6];
static mut TP_AT: usize = 0;
/// Состояние жестов — оно живёт между пакетами (прошлая точка, накопленная прокрутка).
static mut TP: void_touch::Touchpad = void_touch::Touchpad::new();
/// Прошлая маска кнопок: событие кнопок шлём, только когда она изменилась.
static mut TP_BTN: u8 = 0;

/// Прочитать байт из выходного буфера контроллера с ожиданием. `None` — не дождались.
unsafe fn read_data() -> Option<u8> {
    for _ in 0..100_000 {
        if inb(STATUS) & STAT_OUT_FULL != 0 {
            return Some(inb(DATA));
        }
    }
    None
}

/// Отправить команду мыши через контроллер (0xD4 = «следующий байт — во второй порт»).
/// `true` — устройство ответило `0xFA` (ACK).
unsafe fn mouse_cmd(byte: u8) -> bool {
    wait_write();
    outb(STATUS, 0xD4);
    wait_write();
    outb(DATA, byte);
    for _ in 0..100_000 {
        if inb(STATUS) & STAT_OUT_FULL != 0 {
            return inb(DATA) == 0xFA;
        }
    }
    false
}

/// Веха 198 — ЗАПРОС К ТАЧПАДУ. У Synaptics нет своих кодов команд: вопрос передаётся четырьмя
/// командами «установить разрешение» (0xE8), в каждой по два бита номера вопроса, а ответом
/// служит обычный «дай состояние» (0xE9), после которого приходят три байта.
///
/// Приём выглядит дико, но он же и объясняет, почему тачпад совместим с любой мышью: пока не
/// знаешь этой последовательности, устройство — обычная трёхбайтная мышь.
unsafe fn syn_query(q: u8) -> Option<[u8; 3]> {
    for shift in [6, 4, 2, 0] {
        if !mouse_cmd(0xE8) || !mouse_cmd((q >> shift) & 3) {
            return None;
        }
    }
    if !mouse_cmd(0xE9) {
        return None;
    }
    Some([read_data()?, read_data()?, read_data()?])
}

/// Опознать тачпад Synaptics и включить абсолютный режим. `true` — получилось.
///
/// Признак устройства — второй байт ответа на запрос 0x00, он обязан быть 0x47; это
/// единственная проверка, которой верят и Linux, и загрузчики. Модель и возможности читаются
/// следующими запросами и печатаются: на чужой машине первое, что надо знать, — что там стоит.
unsafe fn touchpad_init() -> bool {
    let id = syn_query(0x00);
    if id.map_or(true, |id| id[1] != 0x47) {
        // Сказать, ЧТО ответило устройство. На чужой машине это первое, что нужно знать: у
        // Elantech тот же «стук», но ответ начинается с 0x3c — то есть по этой строке видно,
        // тачпад ли там вообще и какой. Без неё пришлось бы гадать по поведению курсора.
        match id {
            Some(v) => crate::println!(
                "  [ps/2] второй порт: не Synaptics (ответ {:02x} {:02x} {:02x}) — обычная мышь",
                v[0], v[1], v[2],
            ),
            None => crate::println!("  [ps/2] второй порт: на запрос не ответил — обычная мышь"),
        }
        // Не Synaptics. Вернуть НАСТРОЙКИ ПО УМОЛЧАНИЮ обязательно: запрос — это четыре команды
        // «установить разрешение», и обычная мышь их честно исполнила. После запроса 0x00 у неё
        // осталось разрешение 1 точка на миллиметр, то есть курсор еле ползёт — а выглядело бы
        // это как «обновление сломало мышь», и связать это с тачпадом было бы не с чего.
        mouse_cmd(0xF6);
        return false;
    }
    let id = id.expect("проверено выше");
    let caps = syn_query(0x02).unwrap_or([0; 3]);
    // Возможности: бит 7 первого байта — «есть расширенный запрос», бит 0 третьего — несколько
    // пальцев, бит 5 — обнаружение ладони. Печатаем как есть: разбирать их нам пока незачем,
    // а увидеть на незнакомой машине — очень.
    crate::println!(
        "  [ps/2] тачпад Synaptics: версия {}.{}, возможности {:02x}{:02x}{:02x}",
        id[2] & 0x0f, id[0], caps[0], caps[1], caps[2],
    );
    // Режим: бит7 абсолютный, бит6 частота 80/с, бит2 четыре байта на пакет + режим W (шесть),
    // бит0 режим W. Без бита W пакет останется четырёхбайтным, а вместе с ним пропадёт число
    // пальцев — то есть ровно то, ради чего всё это делается.
    const MODE: u8 = 0x80 | 0x40 | 0x04 | 0x01;
    for shift in [6, 4, 2, 0] {
        if !mouse_cmd(0xE8) || !mouse_cmd((MODE >> shift) & 3) {
            return false;
        }
    }
    // «Установить частоту 0x14» — так Synaptics принимает собранный режим. Обычная мышь на этом
    // месте просто выставила бы двадцать пакетов в секунду.
    mouse_cmd(0xF3) && mouse_cmd(0x14)
}

