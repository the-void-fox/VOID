/// Разобрать очередной байт от мыши; полный пакет уходит в кольцо событий.
unsafe fn mouse_byte(b: u8) {
    if TOUCHPAD {
        return touchpad_byte(b);
    }
    // Синхронизация: у первого байта бит 3 всегда 1. Если мы «посреди» пакета и это не так —
    // значит поток сбился (потеряли байт), и начинать надо заново, а не копить мусор.
    if PKT_AT == 0 && b & 0x08 == 0 {
        return;
    }
    PKT[PKT_AT] = b;
    PKT_AT += 1;
    let need = if WHEEL { 4 } else { 3 };
    if PKT_AT < need {
        return;
    }
    PKT_AT = 0;
    let f = PKT[0];
    // Переполнение счётчика — данные бессмысленны, пакет выбрасываем целиком.
    if f & 0xC0 != 0 {
        return;
    }
    let dx = PKT[1] as i16 - if f & 0x10 != 0 { 256 } else { 0 };
    let dy = PKT[2] as i16 - if f & 0x20 != 0 { 256 } else { 0 };
    // Колесо — знаковый полубайт, и знак у него ОБРАТНЫЙ привычному: сырое `0x01` означает
    // «крутнули НА СЕБЯ» (вниз), `0x0F` — «от себя» (вверх). Linux в `psmouse` ровно поэтому
    // ставит минус перед этим байтом. Приводим здесь, чтобы наружу шло человеческое
    // соглашение: +1 — от себя/вверх.
    let wheel = if WHEEL {
        match PKT[3] & 0x0F {
            0x01 => -1i8,
            0x0F => 1i8,
            _ => 0,
        }
    } else {
        0
    };
    // Веха 142 — четвёртая и пятая кнопки живут в битах 4 и 5 того же байта (только ID 4).
    // Складываем их к трём основным старшими битами: наружу идёт одна маска кнопок, и
    // программе незачем знать, каким протоколом её собрали.
    let extra = if EXPLORER { (PKT[3] >> 4) & 0x03 } else { 0 };
    super::mouse_push(dx, -dy, (f & 0x07) | (extra << 3), wheel);
}

/// Веха 198 — байт от тачпада в абсолютном режиме. Собираем шестёрку и отдаём разбор крейту
/// [`void_touch`]: там же и жесты, и там же их тесты — тачпада в эмуляторе нет, и проверить
/// логику иначе негде.
unsafe fn touchpad_byte(b: u8) {
    // Синхронизация по служебным битам: первый байт пакета 10xx_x0xx, четвёртый 11xx_x0xx.
    // Без этой проверки потерянный байт склеил бы два пакета в один, и курсор прыгал бы в
    // случайные места — с видом «драйвер сошёл с ума», а не «потерян байт».
    if TP_AT == 0 && !void_touch::is_first_byte(b) {
        return;
    }
    if TP_AT == 3 && !void_touch::is_fourth_byte(b) {
        TP_AT = 0;
        return;
    }
    TP_PKT[TP_AT] = b;
    TP_AT += 1;
    if TP_AT < 6 {
        return;
    }
    TP_AT = 0;
    // Через сырые указатели, а не ссылки на изменяемый статик: этот модуль весь так устроен
    // (прерывания выключены, второго читателя нет), и компилятор прав, требуя сказать это явно.
    let p = void_touch::decode(&*core::ptr::addr_of!(TP_PKT));
    let btn = void_touch::Touchpad::buttons(&p);
    match (*core::ptr::addr_of_mut!(TP)).feed(&p) {
        void_touch::Move::Cursor { dx, dy } => super::mouse_push(dx, dy, btn, 0),
        void_touch::Move::Wheel(ticks) => super::mouse_push(0, 0, btn, ticks),
        // Кнопки отдаём отдельным событием, и только когда они изменились: иначе каждый пакет
        // лежащего пальца был бы «кнопку не нажимали», а таких пакетов восемьдесят в секунду.
        void_touch::Move::None if btn != TP_BTN => super::mouse_push(0, 0, btn, 0),
        void_touch::Move::None => {}
    }
    TP_BTN = btn;
}

/// Веха 198.1 — настроить чувствительность тачпада из конфига поколения.
///
/// Зовётся ПОСЛЕ чтения конфига, то есть позже подъёма драйвера: до этого момента работают
/// умолчания. Так и правильно — курсор обязан ездить ещё до того, как система нашла свой store.
pub fn touchpad_tune(speed: u8, scroll_mm: u8) {
    unsafe { (*core::ptr::addr_of_mut!(TP)).tune(speed, scroll_mm) }
}

