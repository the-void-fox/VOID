//! GDT с сегментами ring3 + TSS (Веха 26 — вход в U-mode).
//!
//! Трамплин (entry.s) грузит минимальную GDT «код/данные ring0» — её хватает ядру.
//! Для ring3 нужны ещё дескрипторы user-кода/данных (DPL=3) и TSS: при прерывании из
//! CPL=3 процессор сам переключает стек на `TSS.rsp0` — это наш ядерный trap-стек
//! (аналог `sscratch` на RISC-V). Здесь — полная GDT, загружаемая в [`init`];
//! селекторы ядра совпадают с трамплинными (0x08/0x10), перегружать CS не нужно.

use core::mem::size_of;

use super::MAX_CPUS;

/// Селекторы: ядро — как в трамплине; user — с RPL=3 (иначе #GP на iretq).
pub const UDATA_SEL: u16 = 0x18 | 3;
pub const UCODE_SEL: u16 = 0x20 | 3;
const TSS_SEL: u16 = 0x28;

/// 64-битный TSS: интересен только `rsp0` (стек ring0 при трапе из ring3) и пустая
/// карта портов (`iomap` = за пределами лимита ⇒ IN/OUT из ring3 запрещены).
#[repr(C, packed)]
struct Tss {
    _res0: u32,
    rsp0: u64,
    _rsp12: [u64; 2],
    _res1: u64,
    _ist: [u64; 7],
    _res2: u64,
    _res3: u16,
    iomap: u16,
}

/// Веха 170 — TSS у КАЖДОГО ядра своя, и это не оптимизация, а условие правильности.
///
/// В `rsp0` пишется вершина ядерного стека для следующего трапа из ring3, и пишется она на
/// каждом входе в процесс ([`set_rsp0`]). Одна TSS на машину означала бы, что два ядра, войдя в
/// ring3, назначили общий стек, — и первый же одновременный системный вызов положил бы кадры
/// одного поверх кадров другого. Замком это не лечится: к моменту трапа стек уже выбран
/// процессором, спросить разрешения не у кого.
static mut TSS: [Tss; MAX_CPUS] = [const {
    Tss {
        _res0: 0,
        rsp0: 0,
        _rsp12: [0; 2],
        _res1: 0,
        _ist: [0; 7],
        _res2: 0,
        _res3: 0,
        iomap: size_of::<Tss>() as u16,
    }
}; MAX_CPUS];

/// GDT: null, код/данные ring0 (= трамплин), данные/код ring3, TSS (2 слота — 16 байт).
/// Дескриптор TSS зависит от адреса своей [`TSS`] — дозаполняется в [`init`]/[`init_ap`].
///
/// Таблица тоже своя на ядро — по одной причине: в ней сидит дескриптор TSS. Всё остальное в
/// ней у всех ядер одинаково и только читается процессором.
static mut GDT: [[u64; 7]; MAX_CPUS] = [[
    0,
    0x00AF9A000000FFFF, // 0x08: код ring0, L=1
    0x00CF92000000FFFF, // 0x10: данные ring0
    0x00CFF2000000FFFF, // 0x18: данные ring3 (DPL=3)
    0x00AFFA000000FFFF, // 0x20: код ring3, L=1 (DPL=3)
    0,                  // 0x28: TSS (низ)
    0,                  //       TSS (верх)
]; MAX_CPUS];

#[repr(C, packed)]
struct GdtPtr {
    limit: u16,
    base: u64,
}

/// Собрать дескриптор TSS, загрузить GDT и TR. Позвать один раз при старте (до
/// первого входа в U-mode); ядровые селекторы не меняются — далёкий прыжок не нужен.
///
/// Веха 170 — зовётся КАЖДЫМ ядром: загрузочное отсюда, прикладные — из [`init_ap`]. Регистры
/// `gdtr` и `tr` у каждого ядра свои, поэтому «загрузили один раз при старте системы» здесь
/// означает «один раз на ядро».
pub fn init() {
    load(crate::cpu::id());
}

/// Веха 170 — то же для ПРИКЛАДНОГО ядра. Отдельное имя, а не общий [`init`], ради читателя
/// `smp::ap_main`: там видно, что ядро проходит те же шаги подъёма, что и загрузочное.
pub fn init_ap() {
    load(crate::cpu::id());
}

/// Собрать дескриптор TSS ядра `i` в его таблице и загрузить `gdtr`/`tr`.
fn load(i: usize) {
    unsafe {
        let base = &raw const TSS[i] as u64;
        let limit = (size_of::<Tss>() - 1) as u64;
        // Системный дескриптор: limit | base[23:0] | type=0x9 (avail 64-bit TSS) | P | base[31:24].
        GDT[i][5] = limit
            | (base & 0xff_ffff) << 16
            | 0x89u64 << 40
            | ((base >> 24) & 0xff) << 56;
        GDT[i][6] = base >> 32;

        let ptr = GdtPtr {
            limit: (size_of::<[u64; 7]>() - 1) as u16,
            base: &raw const GDT[i] as u64,
        };
        core::arch::asm!(
            "lgdt [{p}]",
            "ltr {sel:x}",
            p = in(reg) &ptr,
            sel = in(reg) TSS_SEL,
            options(nostack),
        );
    }
}

/// Задать стек ring0 для следующего трапа из U-mode — зовётся на каждом входе в
/// процесс ([`super::enter_user`]), как `csrw sscratch` на RISC-V.
///
/// Пишет в TSS ТОГО ядра, которое входит в процесс: у соседнего в этот момент свой стек и свой
/// процесс, и подменить ему `rsp0` значило бы увести его следующий трап на чужой стек.
pub fn set_rsp0(top: usize) {
    unsafe { TSS[crate::cpu::id()].rsp0 = top as u64 }
}
