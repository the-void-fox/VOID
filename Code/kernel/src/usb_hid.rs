//! Разбор отчётов HID — ОБЩИЙ для обоих контроллеров USB (Вехи 199, 200).
//!
//! Протокол загрузочной клавиатуры один и тот же, кто бы её ни вёз: xHCI (Веха 50) или EHCI.
//! Поэтому разбор живёт здесь, а не в драйверах: две копии одного словаря разошлись бы на
//! первой же правке раскладки, и различить их снаружи было бы нечем — «на этом ноутбуке
//! клавиша печатает не то» звучит как что угодно, только не как «драйверов два».
//!
//! Наружу отчёт уходит ДВУМЯ путями, и оба нужны: байтом в кольцо консоли (его читает
//! спасательный шелл, который живёт без графики) и СОБЫТИЕМ клавиатуры с модификаторами (его
//! читает композитор, а через него окна).
//!
//! Веха 200 — здесь же разбор УКАЗАТЕЛЯ (мышь и тачпад загрузочного протокола). Он в том же
//! файле по той же причине: протокол общий для xHCI и EHCI, а на современном ноутбуке USB —
//! единственная шина ввода, какая есть.

/// HID Usage → код клавиши VOID (`KeyEvent::sym`) — тот же словарь, которым говорит PS/2
/// ([`crate::arch`]), иначе оболочка не узнает клавишу по USB.
///
/// Веха 196 — без этого USB-клавиатура в ОКОННОМ сеансе не работала вовсе: репорты уходили
/// байтами в консольное кольцо ядра, а его читает спасательный шелл, а не композитор. То
/// есть на машине, где клавиатура только по USB, сеанс поднимался, а набрать в нём было
/// нечего — и увидеть это можно было только на такой машине.
fn hid_to_sym(k: u8) -> u16 {
    match k {
        0x04..=0x1d => (b'a' + (k - 0x04)) as u16, // буквы: НЕсдвинутый символ, как у PS/2
        0x1e..=0x26 => (b'1' + (k - 0x1e)) as u16, // 1..9
        0x27 => b'0' as u16,
        0x28 => 0x101, // Enter
        0x29 => 0x102, // Esc
        0x2a => 0x104, // Backspace
        0x2b => 0x103, // Tab
        0x2c => b' ' as u16,
        0x2d => b'-' as u16,
        0x2e => b'=' as u16,
        0x2f => b'[' as u16,
        0x30 => b']' as u16,
        0x31 => b'\\' as u16,
        0x33 => b';' as u16,
        0x34 => b'\'' as u16,
        0x35 => b'`' as u16,
        0x36 => b',' as u16,
        0x37 => b'.' as u16,
        0x38 => b'/' as u16,
        0x3a..=0x43 => 0x120 + (k - 0x3a) as u16, // F1..F10
        0x44 => 0x12a,                            // F11
        0x45 => 0x12b,                            // F12
        0x49 => 0x106, // Insert
        0x4a => 0x114, // Home
        0x4b => 0x116, // PageUp
        0x4c => 0x105, // Delete
        0x4d => 0x115, // End
        0x4e => 0x117, // PageDown
        0x4f => 0x111, // Right
        0x50 => 0x110, // Left
        0x51 => 0x113, // Down
        0x52 => 0x112, // Up
        _ => 0,
    }
}

/// HID Usage (boot keyboard) → СКАН-КОД набора 1 (тот, что приходит от PS/2). 0 — нет такого.
///
/// Нужен затем, чтобы раскладка жила в одном месте. Своя таблица HID→символ у этого драйвера
/// уже была, и именно из-за неё переключение раскладки меняло указатель на панели, а
/// печаталась всегда латиница: таблица знала только US. Теперь USB переводит свои коды в
/// скан-коды, а букву по ним считает общая [`crate::arch::keyboard_char`].
///
/// Порядок HID букв — алфавитный (`a`=0x04), у скан-кодов — по рядам клавиатуры; поэтому
/// таблица явная, а не формула.
fn hid_to_scancode(k: u8) -> u8 {
    const LETTERS: [u8; 26] = [
        0x1e, 0x30, 0x2e, 0x20, 0x12, 0x21, 0x22, 0x23, 0x17, 0x24, 0x25, 0x26, 0x32, // a..m
        0x31, 0x18, 0x19, 0x10, 0x13, 0x1f, 0x14, 0x16, 0x2f, 0x11, 0x2d, 0x15, 0x2c, // n..z
    ];
    const DIGITS: [u8; 10] = [0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b]; // 1..9,0
    match k {
        0x04..=0x1d => LETTERS[(k - 0x04) as usize],
        0x1e..=0x27 => DIGITS[(k - 0x1e) as usize],
        0x28 => 0x1c, // Enter
        0x29 => 0x01, // Esc
        0x2a => 0x0e, // Backspace
        0x2b => 0x0f, // Tab
        0x2c => 0x39, // Space
        0x2d => 0x0c, // - _
        0x2e => 0x0d, // = +
        0x2f => 0x1a, // [ {
        0x30 => 0x1b, // ] }
        0x31 => 0x2b, // \ |
        0x33 => 0x27, // ; :
        0x34 => 0x28, // ' "
        0x35 => 0x29, // ` ~
        0x36 => 0x33, // , <
        0x37 => 0x34, // . >
        0x38 => 0x35, // / ?
        _ => 0,
    }
}

/// Опрос USB-клавиатуры — зовётся из `console_drain` (тик/IRQ) наравне с PS/2 и COM1.

/// Разобрать один восьмибайтный отчёт: `prev` — набор клавиш из прошлого отчёта (по нему видно,
/// что НОВОЕ нажали и что отпустили), `r` — свежий отчёт.
// ─── Веха 199.34 — АВТОПОВТОР ЗАЖАТОЙ КЛАВИШИ ───────────────────────────────────────────────
//
// У PS/2 повторы делает САМА КЛАВИАТУРА: в ней сидит typematic-автомат, и система получает
// готовый поток нажатий. У USB этого нет по устройству протокола — клавиатура сообщает лишь
// СОСТОЯНИЕ («сейчас зажаты такие-то клавиши»), а решать, считать ли удержание повторами,
// обязана система. У нас этого не делал никто, и наружу это выглядело как «зажатия не
// работают»: буква печаталась ровно одна, сколько клавишу ни держи.
//
// Правило то же, что у всех: повторяется ПОСЛЕДНЯЯ нажатая клавиша, модификаторы — никогда.
// Сроки взяты обычные (полсекунды до первого повтора, дальше тридцать раз в секунду) — такие
// же, какими по умолчанию отвечает typematic PS/2, чтобы клавиатуры не различались на ощупь.
const REPEAT_DELAY_NS: u64 = 500_000_000;
const REPEAT_PERIOD_NS: u64 = 33_000_000;

/// Что сейчас удерживается. `key == 0` — ничего.
struct Held {
    key: u8,
    sym: u16,
    ch: u16,
    mods: u8,
    since: u64,
    last: u64,
}

static HELD: crate::sync::SpinLock<Held> =
    crate::sync::SpinLock::new(Held { key: 0, sym: 0, ch: 0, mods: 0, since: 0, last: 0 });

/// Веха 199.34 — отмерить повторы удерживаемой клавиши. Зовётся из ОПРОСА обоих драйверов, а не
/// из разбора отчёта: пока клавишу держат, новых отчётов может не приходить вовсе — многие
/// клавиатуры на повторный запрос отвечают «ничего не изменилось».
pub fn tick() {
    let now = crate::clock::uptime_ns();
    let mut h = HELD.lock();
    if h.key == 0 || now < h.since + REPEAT_DELAY_NS || now < h.last + REPEAT_PERIOD_NS {
        return;
    }
    h.last = now;
    let (sym, ch, mods) = (h.sym, h.ch, h.mods);
    drop(h); // наружу зовём БЕЗ замка: обработчики берут свои
    if ch != 0 && ch < 0x100 {
        crate::arch::usb_key(ch as u8);
    }
    if sym != 0 {
        crate::arch::usb_key_event(sym, mods, true, ch);
    }
}

/// Запомнить нажатие как удерживаемое (или забыть отпущенное).
fn hold(key: u8, sym: u16, ch: u16, mods: u8) {
    let now = crate::clock::uptime_ns();
    let mut h = HELD.lock();
    *h = Held { key, sym, ch, mods, since: now, last: now };
}

fn release(key: u8) {
    let mut h = HELD.lock();
    if h.key == key {
        h.key = 0;
    }
}

pub fn report(prev: &mut [u8; 6], r: &[u8]) {
    if r.len() < 8 {
        return;
    }
    let hid_mods = r[0];
    let shift = hid_mods & 0x22 != 0; // Left/Right Shift
    // Модификаторы в наших битах: 1 Shift, 2 Ctrl, 4 Alt, 8 Super — те же, что у PS/2.
    let mut mods = 0u8;
    if shift {
        mods |= 1;
    }
    if hid_mods & 0x11 != 0 {
        mods |= 2; // Left/Right Ctrl
    }
    if hid_mods & 0x44 != 0 {
        mods |= 4; // Left/Right Alt
    }
    if hid_mods & 0x88 != 0 {
        mods |= 8; // Left/Right GUI (Super)
    }
    for &k in &r[2..8] {
        // Новое нажатие: код есть в этом репорте, но не было в прошлом.
        if k != 0 && !prev.contains(&k) {
            // Веха 233.4 — CapsLock это замок сеанса, а не символ: он общий для всех
            // клавиатур машины, и нажатый на USB обязан влиять на то, что печатает PS/2.
            if k == 0x39 {
                crate::arch::keyboard_caps_toggle();
            }
            // Символ считает ОБЩАЯ раскладка по скан-коду — своей таблицы здесь больше нет
            // (она знала только латиницу, и переключение языка её не касалось).
            let ctrl = hid_mods & 0x11 != 0;
            let ch = match hid_to_scancode(k) {
                0 => 0,
                sc => crate::arch::keyboard_char(sc, shift, ctrl),
            };
            if ch != 0 {
                // В консольное кольцо — UTF-8: кириллица едет двумя байтами, как и у PS/2.
                let mut buf = [0u8; 4];
                if let Some(c) = char::from_u32(ch as u32) {
                    for &b in c.encode_utf8(&mut buf).as_bytes() {
                        crate::arch::usb_key(b);
                    }
                }
            }
            // Веха 196 — и СОБЫТИЕ клавиатуры: его читает композитор, а через него —
            // окна. Оба пути нужны: консоль живёт без графики, окна — без консоли.
            let sym = hid_to_sym(k);
            if sym != 0 {
                crate::arch::usb_key_event(sym, mods, true, ch);
            }
            // Веха 199.34 — эта клавиша теперь удерживаемая: с неё пойдут повторы, если её не
            // отпустят. Последнее нажатие вытесняет предыдущее — как и ждёт человек, набирая.
            hold(k, sym, ch, mods);
        }
    }
    // Отпускания: код БЫЛ в прошлом репорте, а в этом его нет. Без них окно считает
    // клавишу зажатой навсегда — и первый же аккорд оболочки залипает.
    for &k in prev.iter() {
        if k != 0 && !r[2..8].contains(&k) {
            let sym = hid_to_sym(k);
            if sym != 0 {
                crate::arch::usb_key_event(sym, mods, false, 0);
            }
            release(k); // Веха 199.34 — отпустили: повторы прекращаются
        }
    }
    prev.copy_from_slice(&r[2..8]);
}

// ── указатель: мышь и тачпад (Веха 200) ──────────────────────────────────────────────────────
//
// Загрузочный протокол мыши — три байта: кнопки, смещение по X, смещение по Y; четвёртый, если
// он есть, — колесо. Ровно то же, что даёт PS/2, и попадает оно в то же кольцо событий, потому
// что композитору безразлично, чьей рукой двигали курсор.
//
// Почему именно загрузочный протокол, а не разбор дескриптора отчётов. Он одинаков у всех
// устройств, объявивших себя мышью, и его достаточно для главного: чтобы на машине без PS/2
// вообще был указатель. Дескриптор нужен тачпадам с абсолютными координатами и мультитачем —
// это следующий шаг, и общий разбор дескриптора будет нужен ему же на шине I2C.

/// Разобрать отчёт указателя загрузочного протокола и отдать событие системе.
///
/// Длина отчёта у устройств разная (три байта у простой мыши, четыре с колесом, больше — у тех,
/// кто дописывает своё), поэтому смотрим на то, что есть, а не требуем точной длины: лишние
/// байты нам не мешают, а отказ от четырёхбайтного отчёта означал бы мышь без колеса.
pub fn pointer_report(r: &[u8]) {
    if r.len() < 3 {
        return;
    }
    // Кнопки: бит 0 — левая, 1 — правая, 2 — средняя. Порядок тот же, что у PS/2, — и это не
    // совпадение, а наследие: загрузочный протокол USB списан с него.
    let buttons = r[0] & 0x07;
    let dx = r[1] as i8 as i16;
    // Ось Y у HID растёт ВНИЗ, у нашего кольца событий — тоже вниз (см. `ps2::mouse_byte`,
    // где знак у PS/2 как раз переворачивается). Значит здесь переворачивать нечего.
    let dy = r[2] as i8 as i16;
    let wheel = if r.len() > 3 { r[3] as i8 } else { 0 };
    if dx == 0 && dy == 0 && wheel == 0 && buttons == last_buttons() {
        return; // отчёт без изменений — устройства шлют их с каждым опросом
    }
    set_last_buttons(buttons);
    crate::arch::usb_mouse_event(dx, dy, buttons, wheel);
}

/// Кнопки прошлого отчёта: нужны, чтобы отличить «ничего не изменилось» от «отпустили всё».
static LAST_BUTTONS: core::sync::atomic::AtomicU8 = core::sync::atomic::AtomicU8::new(0);

fn last_buttons() -> u8 {
    LAST_BUTTONS.load(core::sync::atomic::Ordering::Relaxed)
}

fn set_last_buttons(b: u8) {
    LAST_BUTTONS.store(b, core::sync::atomic::Ordering::Relaxed);
}
