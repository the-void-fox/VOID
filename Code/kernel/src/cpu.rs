//! Веха 170, этап 2 — **что у каждого ядра своё**.
//!
//! Пока ядро было одно, разница между «состоянием системы» и «состоянием ядра процессора» не
//! имела смысла: всё было и тем и другим. С появлением второго ядра эта разница становится
//! главной, потому что общее состояние можно защитить замком, а вот **стек защитить замком
//! нельзя** — на нём в этот момент стоят кадры вызовов.
//!
//! Здесь живёт то, чего замок не спасает: стеки. Всё остальное per-CPU (кто сейчас исполняется,
//! учёт времени, контекст возврата) лежит там, где ему место по смыслу, — в [`crate::proc`], —
//! но индексируется отсюда.
//!
//! ## Как ядро узнаёт, какое оно
//!
//! **По собственному указателю стека.** Стеки всех ядер лежат одним массивом [`STACKS`], блоки
//! равного размера и выровнены; значит номер ядра — это номер блока, в котором стоит `sp`.
//! Одно вычитание, один сдвиг, ни одного обращения к памяти.
//!
//! Дешевле и надёжнее известных альтернатив, и это не вкусовщина:
//!
//! - **Читать идентификатор LAPIC** — обращение к MMIO (сотня тактов) на каждый вызов, а
//!   спрашивать «какое я ядро» ядро будет десятки раз за системный вызов.
//! - **Держать указатель в `GS` (`swapgs`)** — правильный ответ для зрелой системы, но он
//!   требует переписать ассемблерные заглушки трапов и добавить `swapgs` в каждый вход и выход,
//!   включая пути, где кольцо неизвестно. Одна пропущенная пара — и ядро адресует per-CPU блок
//!   по пользовательскому указателю. Это дверь, которую открывают, когда за ней есть что взять;
//!   пока `sp` отвечает на тот же вопрос точнее.
//!
//! **Инвариант**: код ядра исполняется либо на своём трап-стеке (все системные вызовы и
//! прерывания), либо на своём стеке простоя (прикладное ядро между процессами). Всё, что не
//! попало ни в один блок, — это загрузочный стек и стеки ядерных НИТЕЙ ([`crate::sched`]), а
//! они бывают только у загрузочного ядра, и ответ для них — ноль. Поэтому «не в массиве»
//! означает не «неизвестно», а именно «ядро 0».

use core::sync::atomic::{AtomicBool, AtomicUsize, Ordering};

use crate::arch;

/// Сколько ядер система готова обслуживать. Наш потолок, а не свойство машины: см. `arch::smp`.
pub const MAX: usize = arch::MAX_CPUS;

/// Трап-стек: на нём исполняются ВСЕ системные вызовы и прерывания этого ядра.
///
/// 64 КиБ — как загрузочный стек ядра (linker.ld): syscall'ы делают настоящую работу
/// (`object::put` → BLAKE3 + куча + `println!`), а в -O0-сборках кадры были крупные: с 16 КиБ
/// стек однажды переполнялся ВНИЗ в соседнюю read-only секцию (store page fault на записи).
pub const TRAP_STACK: usize = 64 * 1024;

/// Стек простоя: на нём ядро выбирает, кого исполнять, и спит, когда исполнять некого.
/// Отдельный от трап-стека по необходимости: трап приходит именно в тот момент, когда ядро
/// стоит на стеке простоя, и обязан найти свой стек свободным.
pub const IDLE_STACK: usize = 64 * 1024;

/// Стеки одного ядра. Размер блока — степень двойки: номер ядра получается сдвигом.
#[repr(C, align(4096))]
struct Stacks {
    trap: [u8; TRAP_STACK],
    idle: [u8; IDLE_STACK],
}

const BLOCK: usize = size_of::<Stacks>();

static mut STACKS: [Stacks; MAX] =
    [const { Stacks { trap: [0; TRAP_STACK], idle: [0; IDLE_STACK] } }; MAX];

/// Адрес начала массива стеков.
#[inline]
fn base() -> usize {
    &raw const STACKS as usize
}

/// Номер ЭТОГО ядра, `0..MAX`. Загрузочное — всегда 0.
#[inline]
pub fn id() -> usize {
    if MAX == 1 {
        return 0; // однопроцессорная сборка: спрашивать не у кого и незачем
    }
    let off = arch::stack_pointer().wrapping_sub(base());
    if off < MAX * BLOCK { off / BLOCK } else { 0 }
}

/// Вершина трап-стека ядра `i` (стек растёт вниз).
pub fn trap_top(i: usize) -> usize {
    base() + i * BLOCK + TRAP_STACK
}

/// Дно трап-стека ядра `i` — там же лежит сторож переполнения ([`crate::proc`]).
pub fn trap_base(i: usize) -> usize {
    base() + i * BLOCK
}

/// Вершина стека простоя ядра `i`. На однопроцессорной сборке (riscv) спрашивать её некому:
/// прикладных ядер там нет, а загрузочное стоит на загрузочном стеке.
#[cfg_attr(target_arch = "riscv64", allow(dead_code))]
pub fn idle_top(i: usize) -> usize {
    base() + i * BLOCK + BLOCK
}

// ─── большой замок ядра ───────────────────────────────────────────────────────
//
// Веха 170, этап 2. Один замок на ВЕСЬ вход в ядро: пока ядро исполняет системный вызов,
// прерывание или планирование, остальные ядра машины ждут на входе.
//
// ## Почему замок один, а не «по замку на подсистему»
//
// Мелкозернистые замки — правильная цель, но неправильное начало. Ядро VOID писалось
// однопроцессорным, и на этом держатся десятки инвариантов, которых НИКТО не записывал как
// инварианты: стек свободных кадров без ABA (CAS проходит с первой попытки, потому что
// соперника нет), теневой кадр консоли, счётчики store, таблицы прав. Раздать им замки по
// отдельности — значит сначала найти их все; ошибиться можно ровно один раз, и цена ошибки —
// молчаливая порча памяти, которую ищут неделями.
//
// Большой замок сохраняет их ВСЕ разом, потому что он сохраняет само условие: в ядре в каждый
// момент ровно одно ядро. Взамен он не даёт ускорения ВНУТРИ ядра — и не должен: выигрыш
// многоядерности здесь не в ядре, а в кольце 3, где считают пиксели и растрируют глифы.
// Именно там VOID проводит время, и именно там ядра теперь работают одновременно.
//
// ## Почему это не `SpinLock<()>`
//
// Замок берётся на входе в ядро и отпускается на выходе В ПРОЦЕСС — то есть в другой функции,
// через `iretq`, из которого не возвращаются. RAII-страж такую жизнь описать не может.
//
// ## Повторный вход
//
// Ядро исполняется с запрещёнными прерываниями, поэтому взять замок дважды можно только
// вложенным трапом — а это исключение в ядре, то есть авария. Такому входу замок отдаётся без
// ожидания: иначе вместо аварийного дампа система молча зависла бы на замке, который держит она
// сама. [`lock`] в этом случае возвращает `false` — «не твой, не отпускай».

/// Никто. Номер ядра не может быть [`usize::MAX`].
const FREE: usize = usize::MAX;

static OWNER: AtomicUsize = AtomicUsize::new(FREE);

/// Взять большой замок. `true` — взят ЭТИМ вызовом, значит его же и отпускать; `false` — замок
/// уже наш (вложенный вход, см. преамбулу).
pub fn lock() -> bool {
    let me = id();
    if OWNER.load(Ordering::Relaxed) == me {
        return false;
    }
    while OWNER
        .compare_exchange_weak(FREE, me, Ordering::Acquire, Ordering::Relaxed)
        .is_err()
    {
        // Пока ждём — обслуживать просьбы о сбросе TLB. Иначе тупик, и он неизбежен: ядро,
        // держащее замок, ждёт нашего отчёта, а мы ждём его замка, и прерывания у нас
        // запрещены — просьба до нас не доедет никогда (см. [`flush_others`]).
        serve_flush();
        // И заметить аварию: ядро, упавшее с замком в руках, не отпустит его никогда, а
        // крутиться на нём молча — значит спрятать дамп за зависанием (см. [`stop_others`]).
        if panicked() {
            halt_here();
        }
        core::hint::spin_loop();
    }
    true
}

/// Отпустить большой замок.
pub fn unlock() {
    OWNER.store(FREE, Ordering::Release);
}

// ─── авария ───────────────────────────────────────────────────────────────────
//
// Веха 170, этап 4. Пока ядро было одно, «упало» и «остановилось» значило одно и то же. Теперь
// нет: ядро, поймавшее аварию, печатает дамп, а три соседних продолжают исполнять процессы поверх
// ядра, которое только что объявило себя сломанным. Выглядит это хуже, чем зависание, — система
// вроде бы жива, дамп на экране перемешан со свежим выводом, а состояние уже недостоверно.

static PANICKED: AtomicBool = AtomicBool::new(false);

/// Объявлена ли авария.
pub fn panicked() -> bool {
    PANICKED.load(Ordering::Acquire)
}

/// Остановиться навсегда. Прерывания запрещены: обслуживать их нечем и незачем.
pub fn halt_here() -> ! {
    arch::halt_forever()
}

/// Веха 170 — объявить аварию и остановить ОСТАЛЬНЫЕ ядра.
///
/// Побудкой, а не отдельным вектором: обработчик побудки первым делом смотрит на флаг аварии.
/// Ядро, до которого прерывание не доедет (крутится на большом замке с запрещёнными
/// прерываниями), увидит флаг в цикле ожидания замка — [`lock`].
///
/// Возвращается сразу, не дожидаясь: ждать здесь нечего и не у кого — мы уже в аварии.
pub fn stop_others() {
    PANICKED.store(true, Ordering::Release);
    let me = id();
    for j in 0..MAX {
        if j != me {
            arch::wake_cpu(j);
        }
    }
}

// ─── рассылка сброса TLB ──────────────────────────────────────────────────────
//
// Веха 170, этап 3. Ядро сняло страницу с адреса — и это ещё не значит, что она снята: у
// СОСЕДНЕГО ядра в буфере трансляций может лежать та же запись, и оно продолжит писать по
// старому физическому адресу. Кадр к тому времени уже вернулся в аллокатор и, скорее всего,
// выдан кому-то другому. Такую порчу невозможно связать с причиной: пишет один, ломается другой,
// иногда через минуты.
//
// Поэтому: изменил отображение — скажи об этом всем, кто на нём стоит, и ДОЖДИСЬ ответа.
//
// ## Кому говорить
//
// Тем, у кого этот корень в CR3 ([`crate::proc::Table::space`]). Ядру, ушедшему в ядро, говорить
// незачем даже когда оно вернётся в кольцо 3: вход в процесс всегда пишет CR3, а это полный
// сброс буфера. Но и вреда от лишней просьбы нет, поэтому мы не гадаем, где сосед сейчас, —
// список по корню и точный, и дешёвый.
//
// ## Почему ждём ответа
//
// Смысл рассылки ровно в том, чтобы после её возврата НИ ОДНО ядро не имело старой трансляции:
// вызывающий сразу за ней возвращает кадр аллокатору. Без ожидания рассылка не даёт ничего.
//
// ## Почему ожидание не превращается в тупик
//
// Сосед может быть в трёх состояниях, и все три доходят до сброса:
//
//   - **в кольце 3** — прерывания там включены всегда, просьба приезжает сразу;
//   - **крутится на большом замке** — прерывания запрещены, и прерывание не приедет никогда;
//     поэтому [`lock`] обслуживает просьбы прямо в цикле ожидания;
//   - **спит без работы** — у него в CR3 ядерный корень (`proc::release_space`), то есть он
//     вообще не в списке.

static FLUSH_PENDING: AtomicUsize = AtomicUsize::new(0);

/// Сбросить свой буфер трансляций, если об этом просили. Одна атомарная загрузка, когда не
/// просили, — поэтому зовётся из всех мест, где ядро КРУТИТСЯ в ожидании.
#[inline]
pub fn serve_flush() {
    let bit = 1usize << id();
    if FLUSH_PENDING.load(Ordering::Acquire) & bit != 0 {
        arch::flush_tlb();
        FLUSH_PENDING.fetch_and(!bit, Ordering::AcqRel);
    }
}

/// Попросить ядра из `mask` сбросить буфер трансляций и дождаться, пока каждое отчитается.
///
/// Зовётся под большим замком: рассылка одна на систему, и второй маски не бывает.
#[cfg_attr(target_arch = "riscv64", allow(dead_code))]
pub fn flush_others(mask: usize) {
    if mask == 0 {
        return;
    }
    FLUSH_PENDING.fetch_or(mask, Ordering::AcqRel);
    for j in 0..MAX {
        if mask & (1 << j) != 0 {
            arch::flush_cpu(j);
        }
    }
    // Ждём отчёта. Счётчик — не таймаут (уйти отсюда, не дождавшись, нельзя: вызывающий сразу
    // вернёт кадр аллокатору), а голос: молчащее ядро иначе выглядит как «система зависла».
    let mut spins: u64 = 0;
    while FLUSH_PENDING.load(Ordering::Acquire) & mask != 0 {
        core::hint::spin_loop();
        spins += 1;
        if spins % 500_000_000 == 0 {
            crate::println!("  [smp] ядра молчат о сбросе TLB (ждём {:#x}) — повторяю просьбу",
                FLUSH_PENDING.load(Ordering::Relaxed) & mask);
            for j in 0..MAX {
                if mask & (1 << j) != 0 {
                    arch::flush_cpu(j);
                }
            }
        }
    }
}

// ─── кто спит ─────────────────────────────────────────────────────────────────

/// Маска ядер, стоящих без работы (бит на ядро). Спящее ядро стоит в `hlt` и само не узнает,
/// что появился готовый процесс, — его надо разбудить.
static IDLE: AtomicUsize = AtomicUsize::new(0);

/// Отметить это ядро спящим/проснувшимся.
#[cfg_attr(target_arch = "riscv64", allow(dead_code))]
pub fn set_idle(on: bool) {
    let bit = 1usize << id();
    if on {
        IDLE.fetch_or(bit, Ordering::Release);
    } else {
        IDLE.fetch_and(!bit, Ordering::Release);
    }
}

/// Разбудить ядро `i`, если оно СПИТ. Занятому побудка не нужна: оно и так дойдёт до
/// планировщика, а лишнее прерывание стоит ему трапа посреди работы.
#[cfg_attr(target_arch = "riscv64", allow(dead_code))]
pub fn wake_if_idle(i: usize) {
    if IDLE.load(Ordering::Acquire) & (1usize << i) != 0 {
        IDLE.fetch_and(!(1usize << i), Ordering::AcqRel);
        arch::wake_cpu(i);
    }
}

/// Разбудить одно спящее ядро, кроме себя. `false` — спящих нет.
///
/// Одно, а не все: работа появилась одна, и будить четырёх, чтобы трое сразу легли обратно, —
/// это шум на шине и потерянные такты у тех, кто в это время считает пиксели.
#[cfg_attr(target_arch = "riscv64", allow(dead_code))]
pub fn wake_one() -> bool {
    let sleeping = IDLE.load(Ordering::Acquire) & !(1usize << id());
    if sleeping == 0 {
        return false;
    }
    let target = sleeping.trailing_zeros() as usize;
    // Снять бит ЗДЕСЬ, а не в разбуженном: иначе следующий, кому нужна помощь, увидит то же
    // ядро свободным и разбудит его второй раз, оставив остальных спать.
    IDLE.fetch_and(!(1usize << target), Ordering::AcqRel);
    arch::wake_cpu(target);
    true
}
