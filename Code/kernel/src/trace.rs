//! Веха 231 — **трассировка, которую можно СПРОСИТЬ**.
//!
//! ## Зачем, если есть журнал
//!
//! Каждый заход по производительности в этом проекте начинался одинаково: я дописывал счётчики
//! руками в то место, которое подозревал. Так закрылись и вялость старта, и задержка ввода, и
//! голодание срока, и — последним — полноэкранный кадр ([[compositor-damage]]): композитор
//! временно собирал строку в три прохода с замером каждого, потому что иначе не было чем спросить
//! «куда ушли 34 миллисекунды».
//!
//! Это работает, но платится дважды: сперва догадкой (счётчик ставится там, где ПОДОЗРЕВАЕШЬ —
//! а три версии из трёх оказались неверными), потом уборкой. Инструмент нужен такой, которому
//! вопрос задают ПОСЛЕ того, как данные собраны.
//!
//! ## Две разные вещи в одном кольце
//!
//! - **События**: «процесс P сделал вызов N, ядро отработало его за столько-то наносекунд».
//!   Отвечает на вопрос «кто чего ждёт и что происходит слишком часто».
//! - **Выборка** (sampling): «в момент тика процессор был вот по этому адресу». Отвечает на
//!   совсем другой вопрос — «где горит время», и только она нашла бы побайтный цикл по пикселям,
//!   потому что внутри него нет ни одного системного вызова.
//!
//! Различать их важно: трассировка событий показывает ОЖИДАНИЕ, выборка — РАБОТУ. Инструмент,
//! умеющий одно, молча врёт про другое. Но хранятся они в одном кольце, потому что выборка — это
//! тоже событие, только с тегом.
//!
//! ## Правила, которые здесь зашиты
//!
//! 1. **По умолчанию выключено** — маска тегов нулевая, цена живой системы равна одному
//!    атомарному чтению на вызов ([[logging]]: по умолчанию молчим).
//! 2. **Включение и чтение — под правом обзора** (`Sysview`: WRITE на включение, READ на
//!    чтение). Иначе трассировка есть дыра в конфайнменте: она показывает, что делают ЧУЖИЕ
//!    процессы, вплоть до адресов их кода. Право смотреть на систему у нас уже есть и выдаётся
//!    строкой конфига ([[task-manager]]) — новой власти не заводим.
//! 3. **Потери считаются, а не скрываются.** Кольцо конечно; читатель, не поспевший за
//!    системой, получает ЧИСЛО потерянных записей вместе с данными. Молчаливая дыра в трассе
//!    хуже отсутствия трассы: по ней делают выводы.
//!
//! ## Чего здесь нет
//!
//! Записи кладутся без замка и без барьеров: номер в кольце выдаётся атомарно, а сами восемь
//! слов пишутся как попало. Значит читатель, пришедший ровно в момент записи, может увидеть
//! ПОЛУЗАПИСАННУЮ запись. Для отладочного инструмента это верная сделка — замок в обработчике
//! прерывания стоил бы нам дедлока, который уже случался ([[known-gaps]], «Устойчивость»), — но
//! знать об этом надо: одна странная строка в трассе из тысячи не находка, а гонка.
//!
//! Частота выборки равна частоте тика вытеснения (квант 20 мс, то есть 50 отсчётов в секунду).
//! Для горячего цикла, занимающего кадр целиком, этого хватает с запасом; для чего-то, что
//! короче миллисекунды, не хватит вовсе. Поднимать частоту НЕ стали: таймер — это тот же
//! механизм, которым живёт вытеснение, и дёргать его ради замера значит менять то, что меряешь.

use core::sync::atomic::{AtomicU64, Ordering};

use crate::clock;
use crate::cpu;

/// Теги событий. Номер тега — это и номер бита в маске включения.
pub const TAG_SYSCALL: u16 = 1;
/// Вызов чужой ABI (Linux): `a` — номер, `b` — результат.
pub const TAG_LINUX: u16 = 2;
/// Отсчёт выборки в ПОЛЬЗОВАТЕЛЬСКОМ коде: `a` — адрес, по которому застали процесс.
pub const TAG_SAMPLE_U: u16 = 3;
/// Отсчёт выборки в ЯДРЕ: `a` — адрес в ядре. Отличить «ядро работает» от «ядро стоит на
/// холостом ходу» отдельным признаком не пытаемся: холостой цикл — такой же адрес, и
/// разрешается он тем же `ksyms.py`, что и любой другой.
pub const TAG_SAMPLE_K: u16 = 4;

/// Записей в кольце. 4096 × 32 Б = 128 КиБ в BSS — цена, которую платит образ, а не куча.
/// При 50 отсчётах в секунду и сотнях вызовов это секунды истории: достаточно, чтобы читатель
/// успел вычерпать, и мало, чтобы не жалеть памяти.
const CAP: usize = 4096;

/// Размер записи в байтах. Тот же в пользовательской библиотеке — `void_user::trace::REC`.
pub const REC: usize = 32;

/// Одна запись. Раскладка (LE) совпадает с байтами, которые уезжают читателю:
/// `t_ns u64 | tag u16 | pid u16 | cpu u8 | 3 Б запаса | a u64 | b u64`.
#[derive(Clone, Copy)]
struct Rec {
    t_ns: u64,
    tag: u16,
    pid: u16,
    cpu: u8,
    a: u64,
    b: u64,
}

static mut RING: [Rec; CAP] = [Rec { t_ns: 0, tag: 0, pid: 0, cpu: 0, a: 0, b: 0 }; CAP];

/// Сколько записей СДЕЛАНО с начала загрузки. Номер записи — это и её место (`% CAP`).
static WRITTEN: AtomicU64 = AtomicU64::new(0);
/// Докуда дочитал читатель. Читатель один — это отладочный инструмент, а не подписка.
static READ_AT: AtomicU64 = AtomicU64::new(0);
/// Сколько записей затёрлось, не дождавшись читателя.
static DROPPED: AtomicU64 = AtomicU64::new(0);
/// Маска включённых тегов: бит `tag` — писать события этого тега.
static MASK: AtomicU64 = AtomicU64::new(0);

/// Пишем ли сейчас этот тег. Одно атомарное чтение — столько стоит выключенная трассировка.
#[inline(always)]
pub fn on(tag: u16) -> bool {
    MASK.load(Ordering::Relaxed) & (1 << tag) != 0
}

/// Записать событие. Зовётся и из обработчиков прерываний, поэтому без замков.
pub fn rec(tag: u16, pid: u16, a: u64, b: u64) {
    if !on(tag) {
        return;
    }
    let seq = WRITTEN.fetch_add(1, Ordering::Relaxed);
    let slot = (seq % CAP as u64) as usize;
    let r = Rec { t_ns: clock::uptime_ns(), tag, pid, cpu: cpu::id() as u8, a, b };
    // SAFETY: место в кольце закреплено за этим номером атомарным счётчиком, то есть двое в один
    // слот не пишут. Читатель может застать запись недописанной — это названо в шапке.
    unsafe {
        RING[slot] = r;
    }
}

/// Включить набор тегов (маска). Возвращает маску, которая установилась.
pub fn set_mask(mask: u64) -> u64 {
    // Включение всегда начинает трассу С ЧИСТОГО места: старые записи в кольце относятся к
    // прошлому вопросу, и смешивать их с новым ответом — верный способ объяснить одно другим.
    let at = WRITTEN.load(Ordering::Relaxed);
    READ_AT.store(at, Ordering::Relaxed);
    DROPPED.store(0, Ordering::Relaxed);
    MASK.store(mask, Ordering::Relaxed);
    mask
}

/// Переложить новые записи в буфер читателя. Возвращает (сколько байт, сколько записей потеряно).
///
/// Потери считаются ЗДЕСЬ, а не у писателя: писателю в обработчике прерывания не до арифметики,
/// а читатель и так видит разрыв между своим курсором и счётчиком записей.
pub fn read_into(buf: &mut [u8]) -> (usize, u64) {
    let written = WRITTEN.load(Ordering::Relaxed);
    let mut at = READ_AT.load(Ordering::Relaxed);
    let mut lost = 0;
    // Читатель отстал больше, чем кольцо хранит: самые старые записи затёрты.
    if written.saturating_sub(at) > CAP as u64 {
        lost = written - at - CAP as u64;
        at = written - CAP as u64;
    }
    let room = buf.len() / REC;
    let n = (written - at).min(room as u64);
    for k in 0..n {
        let slot = ((at + k) % CAP as u64) as usize;
        // SAFETY: чтение одной записи; гонка с писателем названа в шапке и допущена сознательно.
        let r = unsafe { RING[slot] };
        let off = k as usize * REC;
        buf[off..off + 8].copy_from_slice(&r.t_ns.to_le_bytes());
        buf[off + 8..off + 10].copy_from_slice(&r.tag.to_le_bytes());
        buf[off + 10..off + 12].copy_from_slice(&r.pid.to_le_bytes());
        buf[off + 12] = r.cpu;
        buf[off + 13] = 0;
        buf[off + 14] = 0;
        buf[off + 15] = 0;
        buf[off + 16..off + 24].copy_from_slice(&r.a.to_le_bytes());
        buf[off + 24..off + 32].copy_from_slice(&r.b.to_le_bytes());
    }
    READ_AT.store(at + n, Ordering::Relaxed);
    DROPPED.fetch_add(lost, Ordering::Relaxed);
    (n as usize * REC, lost)
}

/// Числа о самой трассировке: маска, сделано записей, потеряно записей.
pub fn stats() -> (u64, u64, u64) {
    (
        MASK.load(Ordering::Relaxed),
        WRITTEN.load(Ordering::Relaxed),
        DROPPED.load(Ordering::Relaxed),
    )
}
