//! Веха 86 — время системы: монотонное (с загрузки) и настенное (Unix).
//!
//! До этой вехи ядро знало только МОНОТОННЫЙ счётчик (`rdtime`/`rdtsc`), а «настенные часы»
//! подделывались фиктивной базой в порте std (`SystemTime` = выдуманная дата + uptime). Теперь
//! платформа отдаёт реальное время ([`arch::wall_clock_unix_ns`]: CMOS RTC на x86, goldfish-rtc
//! из DTB на riscv), и ядро считает настенное время как **база + uptime**.
//!
//! Почему база, а не поход в RTC на каждый запрос: чтение часов идёт через порты/MMIO и стоит
//! микросекунды, а монотонный счётчик читается одной инструкцией. Часы нужны один раз — узнать,
//! «который час был, когда мы загрузились».
//!
//! **Веха 136 — таймбазу больше не выдумывают, её измеряют.** До этой вехи цена тика была
//! КОНСТАНТОЙ: 100 нс на riscv (умолчание QEMU virt) и 1 нс на x86 («TSC ≈ 1 ГГц в TCG»). На
//! живом процессоре TSC идёт с его собственной частотой, и на этой машине под KVM она оказалась
//! 3 ГГц — то есть **всё время системы шло втрое быстрее настоящего**. Видно это было только
//! снаружи: `date` убегал, сроки в сети истекали втрое раньше объявленных, RTT печатался втрое
//! больше, а «поспать 100 мс» означало 33.
//!
//! Теперь частоту называет платформа ([`arch::timer_hz`]: измерение по PIT на x86, свойство
//! `timebase-frequency` из DTB на riscv), а здесь из неё считаются два множителя Q32 — чтобы
//! перевод «тики ↔ наносекунды» оставался парой умножений, а не делением в горячем пути.
//!
//! **Веха 230 — часы подводятся по сети.** [`set_realtime_ns`] двигает базу; зовёт его сервер
//! сети, сходив к NTP, и только если конфиг дал ему право `clock` ([[0022-app-state-directory]]
//! тут ни при чём — это обычное право, названное строкой). Плавного подвода (slew) нет: время
//! переставляется рывком, зато честно.
//!
//! Ограничения (честно): между синхронизациями остаётся дрейф самого кварца. Часовой пояс ядро
//! по-прежнему не знает — всё в UTC, местное время считают те, кто показывает его человеку.

use core::sync::atomic::{AtomicBool, AtomicU64, Ordering};

use crate::arch;

/// Запасная таймбаза, если платформа не назвала свою: прежние умолчания (riscv 10 МГц QEMU virt,
/// x86 «TSC ≈ 1 ГГц»). Это не «правильное значение», а честно приблизительное — и источник
/// позволяет это увидеть.
#[cfg(target_arch = "riscv64")]
const FALLBACK_HZ: u64 = 10_000_000;
#[cfg(not(target_arch = "riscv64"))]
const FALLBACK_HZ: u64 = 1_000_000_000;

/// Тиков в секунду и два множителя перевода в формате Q32 (значение × 2^32).
///
/// Почему Q32, а не деление: `uptime_ns` зовут из планировщика, IPC и каждого замера времени.
/// 64-битное деление там стоит десятки тактов, умножение с широким промежутком — единицы.
static TICK_HZ: AtomicU64 = AtomicU64::new(FALLBACK_HZ);
static NS_PER_TICK_Q32: AtomicU64 = AtomicU64::new(ns_per_tick_q32(FALLBACK_HZ));
static TICKS_PER_NS_Q32: AtomicU64 = AtomicU64::new(ticks_per_ns_q32(FALLBACK_HZ));
// Признака «измерена/не измерена» здесь больше нет (Веха 226.4): его заменил ИСТОЧНИК
// таймбазы словами — `arch::timer_hz_name`. Два состояния различали меньше, чем нужно: на riscv
// «измерена» было верно всегда, хотя частота могла остаться умолчанием QEMU, а на x86 появился
// третий случай — «со слов CPUID, PIT'а нет».

/// Unix-время (нс), соответствующее нулю монотонного счётчика. 0 — часов нет.
static WALL_BASE_NS: AtomicU64 = AtomicU64::new(0);
/// Удалось ли прочитать настоящие часы (иначе настенное время = uptime от эпохи).
static HAS_RTC: AtomicBool = AtomicBool::new(false);

/// Наносекунд в тике × 2^32 (обе величины считаются один раз, при калибровке).
const fn ns_per_tick_q32(hz: u64) -> u64 {
    (((1_000_000_000u128) << 32) / hz as u128) as u64
}

/// Тиков в наносекунде × 2^32.
const fn ticks_per_ns_q32(hz: u64) -> u64 {
    (((hz as u128) << 32) / 1_000_000_000) as u64
}

/// Таймбаза: тиков монотонного счётчика в секунду.
pub fn tick_hz() -> u64 {
    TICK_HZ.load(Ordering::Relaxed)
}

/// Прочитать часы платформы и запомнить базу. Зовётся один раз на загрузке, ПОСЛЕ `mm_init`
/// (на riscv страница RTC отображается там же) и до старта процессов.
pub fn init() {
    // Сначала таймбаза: настенное время считается как «база + uptime», а uptime без верной цены
    // тика — не время, а количество тиков.
    if let Some(hz) = arch::timer_hz().filter(|hz| *hz > 0) {
        TICK_HZ.store(hz, Ordering::Relaxed);
        NS_PER_TICK_Q32.store(ns_per_tick_q32(hz), Ordering::Relaxed);
        TICKS_PER_NS_Q32.store(ticks_per_ns_q32(hz), Ordering::Relaxed);
    }
    if let Some(ns) = arch::wall_clock_unix_ns() {
        // База = «сколько было на часах, когда счётчик был нулём».
        WALL_BASE_NS.store(ns.saturating_sub(uptime_ns()), Ordering::Relaxed);
        HAS_RTC.store(true, Ordering::Relaxed);
    }
}

/// Есть ли настоящие часы. `false` — RTC не найден: настенное время идёт от эпохи Unix
/// (то есть «1970 + время с загрузки»), и это ЧЕСТНО видно потребителям.
pub fn has_rtc() -> bool {
    HAS_RTC.load(Ordering::Relaxed)
}

/// Монотонное время с загрузки, наносекунды. Не идёт назад и не зависит от RTC.
///
/// Промежуток 128-битный не для точности, а чтобы не переполниться: на 3-гигагерцевом TSC
/// счётчик за сутки набирает 2.6·10¹⁴ тиков, и умножение такого числа в 64 битах вылетает.
pub fn uptime_ns() -> u64 {
    ticks_to_ns(arch::now_ticks())
}

/// Тики счётчика → наносекунды.
pub fn ticks_to_ns(ticks: u64) -> u64 {
    ((ticks as u128 * NS_PER_TICK_Q32.load(Ordering::Relaxed) as u128) >> 32) as u64
}

/// Наносекунды → тики счётчика, вверх. Обратная [`uptime_ns`]: сроки внутри ядра живут в
/// ТИКАХ (`futex_deadline`, `now_ticks`), а снаружи проситься спать удобнее в наносекундах —
/// иначе каждая программа обязана знать таймбазу своей архитектуры (Веха 114).
///
/// Округление вверх намеренно: «поспать 1 нс» на riscv (тик = 100 нс) обязано означать «хотя бы
/// один тик», а не «нисколько».
pub fn ns_to_ticks(ns: u64) -> u64 {
    let q = TICKS_PER_NS_Q32.load(Ordering::Relaxed) as u128;
    ((ns as u128 * q + (1u128 << 32) - 1) >> 32) as u64
}

/// Веха 230 — **ПОДВЕСТИ ЧАСЫ**: сказать, сколько сейчас на самом деле (Unix, нс).
///
/// Двигается только БАЗА — та самая «сколько было, когда счётчик был нулём». Монотонное время
/// (`uptime_ns`) не трогается вовсе: на нём стоят сроки сна, таймауты IPC и замеры, и сдвинуть
/// его значило бы, что подвод часов по сети способен разбудить всех спящих разом или, наоборот,
/// усыпить навсегда.
///
/// Скачок назад настенного времени — цена, которую мы платим сознательно: плавного подвода
/// (slew, как у ntpd) нет, и первая же синхронизация после загрузки с неверным RTC передвинет
/// дату рывком. Для системы, где по дате сверяются только сроки сертификатов, это честнее, чем
/// подводить часы часами.
///
/// Возвращает сдвиг в наносекундах (со знаком) — звать его есть кому: тому, кто подводит,
/// полезно сказать человеку, НАСКОЛЬКО врали часы.
pub fn set_realtime_ns(ns: u64) -> i64 {
    let было = realtime_ns();
    WALL_BASE_NS.store(ns.saturating_sub(uptime_ns()), Ordering::Relaxed);
    // Часы теперь известны — даже если RTC не нашлось вовсе. Потребителям важно не «есть ли
    // микросхема», а «можно ли верить дате»; с этой минуты можно.
    HAS_RTC.store(true, Ordering::Relaxed);
    ns as i64 - было as i64
}

/// Настенное время, наносекунды Unix (UTC).
pub fn realtime_ns() -> u64 {
    WALL_BASE_NS.load(Ordering::Relaxed).wrapping_add(uptime_ns())
}

/// Разложить Unix-секунды в (год, месяц, день, час, минута, секунда) UTC — для печати даты
/// на загрузке и команды `date` в шелле. Обратная к `days_from_civil` часть — алгоритм Хиннанта.
pub fn civil_from_unix(secs: u64) -> (i64, u32, u32, u32, u32, u32) {
    let days = (secs / 86400) as i64;
    let rem = secs % 86400;
    let z = days + 719468; // сдвиг эпохи к 0000-03-01
    let era = if z >= 0 { z } else { z - 146096 } / 146097;
    let doe = z - era * 146097; // день эры, [0, 146096]
    let yoe = (doe - doe / 1460 + doe / 36524 - doe / 146096) / 365; // год эры, [0, 399]
    let y = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100); // день года от 1 марта
    let mp = (5 * doy + 2) / 153; // месяц со сдвигом (0 = март)
    let d = (doy - (153 * mp + 2) / 5 + 1) as u32;
    let m = if mp < 10 { mp + 3 } else { mp - 9 } as u32;
    let y = if m <= 2 { y + 1 } else { y };
    (y, m, d, (rem / 3600) as u32, (rem % 3600 / 60) as u32, (rem % 60) as u32)
}
