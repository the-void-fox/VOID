//! Примитивы синхронизации.
//!
//! Пока одно ядро (один hart), но взаимное исключение уже нужно: глобальный
//! аллокатор обязан быть `Sync`, а значит нужна внутренняя изменяемость под замком.
//! Тот же `SpinLock` пригодится планировщику (Веха 5).
//!
//! **Два способа взять замок, и выбор между ними — вопрос корректности, а не вкуса
//! (Веха 89).**
//!
//! - [`SpinLock::lock`] прерывания НЕ трогает. Годится, только если замок недостижим из
//!   обработчика прерывания.
//! - [`SpinLock::lock_irq`] выключает прерывания на время удержания. **Обязателен для каждого
//!   замка, до которого может дотянуться обработчик** — иначе классический дедлок на одном
//!   ядре: поток берёт замок, приходит прерывание, обработчик пытается взять тот же замок и
//!   крутится вечно, а отпустить его некому.
//!
//! До Вехи 89 этого варианта не было, и опасные места затыкались вручную — `irq_save_disable`
//! вокруг конкретных вызовов (`ASYNC` в virtio_blk, очередь executor'а). Работало, но правило
//! жило в головах: любой новый `lock()` на «горячем» замке молча возвращал дедлок.
//!
//! Кто сегодня достижим из прерывания (и потому берётся через `lock_irq`):
//! таймерный тик → `SCHED` (вытеснение) и кольцо консоли (`RING` на riscv, вычерпывание
//! FIFO); IRQ диска → `ASYNC` и, через пробуждение future, `EXECUTOR`; IRQ консоли →
//! `XHCI` (опрос USB-клавиатуры); и **куча ядра** — потому что пробуждение future может
//! аллоцировать. Прочие замки (store, таблица процессов, c-space, устройства) из обработчиков
//! не берутся: их обработчик диска не трогает, а IRQ userspace-драйверов работает через
//! атомарный флаг именно ради этого.
//!
//! Замок на одном ядре по-прежнему не «настоящий» mutex: ядро невытесняемо, поэтому
//! конкуренции за него нет — есть только реентерантность из прерывания, и именно её
//! закрывает `lock_irq`.

use core::cell::UnsafeCell;
use core::ops::{Deref, DerefMut};
use core::sync::atomic::{AtomicBool, Ordering};

/// Взаимное исключение через активное ожидание (spin).
pub struct SpinLock<T> {
    locked: AtomicBool,
    data: UnsafeCell<T>,
}

// Безопасно делить между потоками: доступ к data только через захваченный замок.
unsafe impl<T: Send> Sync for SpinLock<T> {}

impl<T> SpinLock<T> {
    pub const fn new(data: T) -> Self {
        Self {
            locked: AtomicBool::new(false),
            data: UnsafeCell::new(data),
        }
    }

    /// Захватить замок, крутясь до успеха. Возвращает страж (guard) с доступом к данным.
    ///
    /// Прерывания не трогает — **нельзя** для замка, достижимого из обработчика (см. преамбулу
    /// модуля); для такого есть [`lock_irq`](Self::lock_irq).
    pub fn lock(&self) -> SpinGuard<'_, T> {
        self.spin();
        SpinGuard { lock: self }
    }

    /// Веха 89 — захватить замок, **выключив прерывания** на всё время удержания; прежнее
    /// состояние восстановит `drop` стража. Единственный корректный способ взять замок, который
    /// берёт и обработчик прерывания: иначе прерывание, пришедшее посреди критической секции,
    /// уходит в вечный спин на уже занятом замке (отпустить его некому — ядро одноядерное).
    ///
    /// Секция под этим замком обязана быть КОРОТКОЙ: пока он держится, машина глуха к
    /// устройствам и таймеру.
    pub fn lock_irq(&self) -> IrqSpinGuard<'_, T> {
        // Порядок важен: сперва глушим прерывания, ПОТОМ берём замок. Наоборот — окно, в
        // котором прерывание застаёт замок уже занятым, то есть ровно тот дедлок.
        let irq = crate::arch::irq_save_disable();
        self.spin();
        IrqSpinGuard { lock: self, irq }
    }

    /// Крутиться, пока не удастся взять замок.
    #[inline]
    fn spin(&self) {
        while self
            .locked
            .compare_exchange(false, true, Ordering::Acquire, Ordering::Relaxed)
            .is_err()
        {
            core::hint::spin_loop();
        }
    }
}

/// RAII-страж: пока жив — замок держится; на `drop` — освобождается.
pub struct SpinGuard<'a, T> {
    lock: &'a SpinLock<T>,
}

impl<T> Deref for SpinGuard<'_, T> {
    type Target = T;
    fn deref(&self) -> &T {
        // SAFETY: страж существует только при захваченном замке.
        unsafe { &*self.lock.data.get() }
    }
}

impl<T> DerefMut for SpinGuard<'_, T> {
    fn deref_mut(&mut self) -> &mut T {
        // SAFETY: страж существует только при захваченном замке, и он один.
        unsafe { &mut *self.lock.data.get() }
    }
}

impl<T> Drop for SpinGuard<'_, T> {
    fn drop(&mut self) {
        self.lock.locked.store(false, Ordering::Release);
    }
}

/// Веха 89 — страж [`SpinLock::lock_irq`]: держит замок И выключенные прерывания, на `drop`
/// отпускает замок и возвращает прерывания в прежнее состояние (именно прежнее, а не «включить»:
/// секции вкладываются друг в друга, и внутренняя не должна включать то, что выключила внешняя).
pub struct IrqSpinGuard<'a, T> {
    lock: &'a SpinLock<T>,
    irq: bool,
}

impl<T> Deref for IrqSpinGuard<'_, T> {
    type Target = T;
    fn deref(&self) -> &T {
        // SAFETY: страж существует только при захваченном замке.
        unsafe { &*self.lock.data.get() }
    }
}

impl<T> DerefMut for IrqSpinGuard<'_, T> {
    fn deref_mut(&mut self) -> &mut T {
        // SAFETY: страж существует только при захваченном замке, и он один.
        unsafe { &mut *self.lock.data.get() }
    }
}

impl<T> Drop for IrqSpinGuard<'_, T> {
    fn drop(&mut self) {
        self.lock.locked.store(false, Ordering::Release);
        crate::arch::irq_restore(self.irq);
    }
}
