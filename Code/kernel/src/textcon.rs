//! **Текстовая консоль ядра** — курсор, прокрутка, разбор ANSI и перевод UTF-8 → CP866
//! (Вехи 41, 96, 214; вынесено в общую часть Вехой 226.5).
//!
//! ## Зачем модуль общий
//!
//! Жил он в `arch/x86_64/vga.rs`, и это было верно, пока единственным экраном ядра был текстовый
//! буфер VGA. С Вехи 96 задников стало два (ещё пиксельный кадр), с Вехи 224.1 кадр появился и
//! на riscv — а слой текста остался на x86, и riscv'у консоли на экране не досталось. Ровно тот
//! случай, когда «две меры расходятся молча»: движок знакомест лежит в общей [`crate::fb`], а
//! ходит к нему только одна архитектура.
//!
//! ## Два задника
//!
//! - **пиксельный кадр** ([`crate::fb`]) — если он есть, рисуем в него; геометрия известна лишь
//!   в рантайме, поэтому ширина и высота здесь функции, а не константы;
//! - **текстовая память** (`0xB8000` на x86) — когда кадра нет. Это уже арх-специфично, и
//!   поэтому живёт за [`back`]: на x86 — настоящий VGA, на остальных — «задника нет».
//!
//! Экран мог уйти процессу (Веха 97) — тогда ядро молчит, а вывод остаётся в serial.
//!
//! Курсор — статик; гонок за него нет, потому что весь вывод ядра идёт под замком
//! [`crate::OUT`] (Веха 170; до неё хватало запрета прерываний — исполнение было одно).

/// Задник «текстовая память». На x86 это VGA 80×25 по `0xB8000`; там, где его нет, геометрия
/// нулевая и все вызовы пусты — тогда без пиксельного кадра консоль ядра не рисует ничего
/// (на riscv её роль исполняет UART).
#[cfg(target_arch = "x86_64")]
use crate::arch::vga as back;
#[cfg(not(target_arch = "x86_64"))]
mod back {
    pub const W: usize = 0;
    pub const H: usize = 0;
    pub fn put_cell(_row: usize, _col: usize, _ch: u8, _attr: u8) {}
    pub fn scroll(_attr: u8) {}
    pub fn clear(_attr: u8) {}
    pub fn cursor(_row: usize, _col: usize) {}
}

/// Ширина консоли в знакоместах. Ноль — консоли на экране нет вовсе.
#[inline]
fn w() -> usize {
    if crate::fb::present() {
        crate::fb::cols()
    } else {
        back::W
    }
}

/// Высота консоли в знакоместах. Ноль — консоли на экране нет вовсе.
#[inline]
fn h() -> usize {
    if crate::fb::present() {
        crate::fb::rows()
    } else {
        back::H
    }
}

/// Размер консоли в знакоместах — наружу (Веха 120, `SYS_CONSIZE`). Программе, рисующей во весь
/// экран, геометрия нужна, а из userspace она невыводима: тот же экран бывает и текстовым 80×25,
/// и пиксельным 160×50, и знать об этом может только ядро.
pub fn size() -> (usize, usize) {
    (w(), h())
}

/// Атрибут по умолчанию: светло-серый на чёрном (как классический текстовый BIOS).
const ATTR_DEFAULT: u8 = 0x07;

static mut ROW: usize = 0;
static mut COL: usize = 0;
static mut ATTR: u8 = ATTR_DEFAULT;

#[inline]
unsafe fn put_cell(row: usize, col: usize, ch: u8) {
    if crate::fb::present() {
        // Веха 97: экран мог уйти процессу — тогда ядро молчит (вывод остаётся в serial).
        if !crate::fb::owned_by_user() {
            crate::fb::put_cell(row, col, ch, ATTR);
        }
        return;
    }
    back::put_cell(row, col, ch, ATTR);
}

// ── набранная строка (Вехи 214, 214.1) ──────────────────────────────────────
//
// У консоли ядра ОДИН курсор на многих писателей: журнал ядра, сетевой сервер, файловый сервер
// — и шелл, который в этой же консоли принимает команды. Пока шелл набирает строку, она на
// экране недописана, и всякая чужая строка, пришедшая в этот миг, вклинивается прямо в неё.
//
// Лечим В КОНСОЛИ, а не в шелле, и это главное решение здесь. Шелл про чужой вывод ничего не
// знает и знать не должен: он пишет байты. Зато консоль знает и кто пишет, и что уже написано.
// Значит она и обязана разнять писателей: снять недописанную строку ввода перед чужой печатью и
// вернуть её следом. Шелл при этом не меняется ни на строку — этого владелец и просил.
//
// **Кого защищаем.** Веха 214 делила писателей на «ядро» и «программу» — и потому не помогала
// против ВТОРОЙ ПРОГРАММЫ: сетевой сервер печатает в ту же консоль и сбивал набранное ровно
// так же, как журнал ядра. Владелец это и увидел: «стало меньше, но иногда случается».
//
// Правильный признак не «ядро или программа», а «ЧИТАЕТ ЛИ ЭТОТ ПИСАТЕЛЬ ВВОД». Строку с
// приглашением и эхом набора пишет тот, кто с этой консоли читает, — и ядро это знает точно
// (`reads_console`, Веха 141.1). Все остальные, кем бы они ни были, для набранной строки чужие.

/// Сколько символов набранной строки помним. Ширина консоли меньше при любом режиме.
const LINE_MAX: usize = 256;
/// Содержимое текущей (недописанной) строки: символ и его атрибут. Атрибут нужен, иначе
/// цветное приглашение шелла вернулось бы серым.
static mut LINE_CH: [u8; LINE_MAX] = [0; LINE_MAX];
static mut LINE_AT: [u8; LINE_MAX] = [0; LINE_MAX];
static mut LINE_LEN: usize = 0;
/// СНЯТАЯ строка — отдельной копией, а не ссылкой на текущую.
///
/// Первый заход возвращал строку прямо из `LINE_*` и возвращал из неё один последний символ:
/// чужая печать кончается переводом строки, а перевод строки честно забывает текущую строку —
/// ту самую, которую только что сняли. Снятое обязано лежать там, куда чужая печать не
/// дотянется, иначе оно перестаёт быть снятым.
/// **Только x86.** Снятие набранной строки зовут `console_begin_write`/`console_end_write`, а на
/// riscv они объявлены пустышками намеренно: тамошняя консоль — UART, и набранной строки в ней
/// не ведётся вовсе. Помечено `cfg`, а не `allow(dead_code)`: это асимметрия архитектур, и она
/// должна быть видна в коде, а не заглушена.
#[cfg(target_arch = "x86_64")]
static mut STASH_CH: [u8; LINE_MAX] = [0; LINE_MAX];
/// **Только x86.** Снятие набранной строки зовут `console_begin_write`/`console_end_write`, а на
/// riscv они объявлены пустышками намеренно: тамошняя консоль — UART, и набранной строки в ней
/// не ведётся вовсе. Помечено `cfg`, а не `allow(dead_code)`: это асимметрия архитектур, и она
/// должна быть видна в коде, а не заглушена.
#[cfg(target_arch = "x86_64")]
static mut STASH_AT: [u8; LINE_MAX] = [0; LINE_MAX];
/// **Только x86.** Снятие набранной строки зовут `console_begin_write`/`console_end_write`, а на
/// riscv они объявлены пустышками намеренно: тамошняя консоль — UART, и набранной строки в ней
/// не ведётся вовсе. Помечено `cfg`, а не `allow(dead_code)`: это асимметрия архитектур, и она
/// должна быть видна в коде, а не заглушена.
#[cfg(target_arch = "x86_64")]
static mut STASH_LEN: usize = 0;
/// Пишет ли СЕЙЧАС тот, кто читает ввод с этой консоли.
static mut WRITER_READS: bool = false;
/// Недописанную строку на экране писал ЧИТАТЕЛЬ ВВОДА — значит это набираемая команда.
static mut LINE_IS_INPUT: bool = false;
/// Строка снята с экрана и ждёт возвращения.
/// **Только x86.** Снятие набранной строки зовут `console_begin_write`/`console_end_write`, а на
/// riscv они объявлены пустышками намеренно: тамошняя консоль — UART, и набранной строки в ней
/// не ведётся вовсе. Помечено `cfg`, а не `allow(dead_code)`: это асимметрия архитектур, и она
/// должна быть видна в коде, а не заглушена.
#[cfg(target_arch = "x86_64")]
static mut STASHED: bool = false;

/// Снять набранное с экрана, запомнив.
/// **Только x86.** Снятие набранной строки зовут `console_begin_write`/`console_end_write`, а на
/// riscv они объявлены пустышками намеренно: тамошняя консоль — UART, и набранной строки в ней
/// не ведётся вовсе. Помечено `cfg`, а не `allow(dead_code)`: это асимметрия архитектур, и она
/// должна быть видна в коде, а не заглушена.
#[cfg(target_arch = "x86_64")]
unsafe fn stash() {
    STASH_LEN = LINE_LEN.min(COL);
    STASH_CH[..STASH_LEN].copy_from_slice(&LINE_CH[..STASH_LEN]);
    STASH_AT[..STASH_LEN].copy_from_slice(&LINE_AT[..STASH_LEN]);
    for c in 0..COL {
        put_cell(ROW, c, b' ');
    }
    COL = 0;
    // Строка на экране теперь пуста — и память о ней тоже. Без этого чужой текст дописывался бы
    // к снятому, и возвращалась бы смесь.
    LINE_LEN = 0;
    LINE_IS_INPUT = false;
    STASHED = true;
}

/// Вернуть набранное на текущую (уже пустую) строку.
/// **Только x86.** Снятие набранной строки зовут `console_begin_write`/`console_end_write`, а на
/// riscv они объявлены пустышками намеренно: тамошняя консоль — UART, и набранной строки в ней
/// не ведётся вовсе. Помечено `cfg`, а не `allow(dead_code)`: это асимметрия архитектур, и она
/// должна быть видна в коде, а не заглушена.
#[cfg(target_arch = "x86_64")]
unsafe fn restore() {
    let save = ATTR;
    let n = STASH_LEN.min(w());
    for i in 0..n {
        ATTR = STASH_AT[i];
        put_cell(ROW, i, STASH_CH[i]);
    }
    ATTR = save;
    COL = n;
    // Вернуть и ПАМЯТЬ о строке: следующий набранный символ дописывается к ней, а не начинает
    // её заново. Без этого вторая подряд чужая строка снимала бы одну букву.
    LINE_CH[..n].copy_from_slice(&STASH_CH[..n]);
    LINE_AT[..n].copy_from_slice(&STASH_AT[..n]);
    LINE_LEN = n;
    LINE_IS_INPUT = true;
    STASHED = false;
}

/// Веха 214.1 — НАЧАЛО печати. `reads_input` — читает ли пишущий ввод с этой консоли.
///
/// Зовётся из [`crate::_print`] под замком вывода, поэтому гонок за этими словами нет.
/// **Только x86.** Снятие набранной строки зовут `console_begin_write`/`console_end_write`, а на
/// riscv они объявлены пустышками намеренно: тамошняя консоль — UART, и набранной строки в ней
/// не ведётся вовсе. Помечено `cfg`, а не `allow(dead_code)`: это асимметрия архитектур, и она
/// должна быть видна в коде, а не заглушена.
#[cfg(target_arch = "x86_64")]
pub fn begin_write(reads_input: bool) {
    unsafe {
        if reads_input {
            // Пишет хозяин ввода. Если его строка снята — вернуть на место ПЕРЕД его печатью,
            // оборвав чужую недописанную: иначе эхо набора легло бы в хвост чужой строки, а
            // потом снятое вернулось бы поверх, и набранное пропало бы совсем.
            if STASHED {
                if COL != 0 {
                    emit(b'\n');
                }
                restore();
            }
        } else if !STASHED && COL != 0 && LINE_IS_INPUT {
            stash();
        }
        WRITER_READS = reads_input;
    }
}

/// Веха 214.1 — КОНЕЦ печати: вернуть набранное, если чужая строка дописана.
///
/// Только при курсоре в начале: печатают и по кускам (`print!` без перевода строки), и вернуть
/// набранное в середину такого куска значило бы разорвать уже его. Тогда возврат ждёт конца
/// строки — либо случится раньше, в [`begin_write`], если хозяин ввода заговорит первым.
/// **Только x86.** Снятие набранной строки зовут `console_begin_write`/`console_end_write`, а на
/// riscv они объявлены пустышками намеренно: тамошняя консоль — UART, и набранной строки в ней
/// не ведётся вовсе. Помечено `cfg`, а не `allow(dead_code)`: это асимметрия архитектур, и она
/// должна быть видна в коде, а не заглушена.
#[cfg(target_arch = "x86_64")]
pub fn end_write(reads_input: bool) {
    unsafe {
        if !reads_input && STASHED && COL == 0 {
            restore();
        }
    }
}

/// Запомнить символ как часть текущей строки (зовётся из [`emit`]).
#[inline]
unsafe fn line_push(byte: u8) {
    if LINE_LEN < LINE_MAX {
        LINE_CH[LINE_LEN] = byte;
        LINE_AT[LINE_LEN] = ATTR;
        LINE_LEN += 1;
    }
    // Чья это строка — решает ПЕРВЫЙ писатель: дописавший чужое своим её не присваивает.
    if LINE_LEN == 1 {
        LINE_IS_INPUT = WRITER_READS;
    }
}

unsafe fn newline() {
    COL = 0;
    LINE_LEN = 0; // строка кончилась — помнить нечего (сюда же приходит и перенос по ширине)
    LINE_IS_INPUT = false;
    ROW += 1;
    if ROW >= h() {
        scroll();
        ROW = h() - 1;
    }
}

/// Сдвинуть все строки на одну вверх, очистить последнюю (кольцевого буфера нет — экран мал).
unsafe fn scroll() {
    if crate::fb::present() {
        if !crate::fb::owned_by_user() {
            crate::fb::scroll(ATTR);
        }
        return;
    }
    back::scroll(ATTR);
}

/// Вывести уже-CP866-байт в текущую позицию (ASCII-подмножество + управляющие). Внутреннее.
unsafe fn emit(byte: u8) {
    match byte {
        b'\n' => newline(),
        // Возврат каретки — строку пишут заново, значит и помнить надо заново.
        b'\r' => {
            COL = 0;
            LINE_LEN = 0;
            LINE_IS_INPUT = false;
        }
        0x08 => {
            if COL > 0 {
                COL -= 1;
                put_cell(ROW, COL, b' ');
                LINE_LEN = LINE_LEN.saturating_sub(1);
            }
        }
        _ => {
            put_cell(ROW, COL, byte);
            line_push(byte);
            COL += 1;
            if COL >= w() {
                newline();
            }
        }
    }
}

// ── ANSI-разбор для VGA (Веха 43): цвета/clear/курсор. На serial escape-коды толкует терминал
//    QEMU, а здесь переводим их в атрибуты VGA и действия, НЕ рисуя сами байты последовательности.
//    Так цвет и `clear` работают одинаково и в эмуляторе, и на реальном экране.
#[derive(Clone, Copy, PartialEq)]
enum Ansi {
    Normal,
    Esc, // видели ESC (0x1B)
    Csi, // видели ESC[ — копим параметры до финального байта
}
const PARAMS_MAX: usize = 16;
static mut ANSI: Ansi = Ansi::Normal;
static mut PARAMS: [u8; PARAMS_MAX] = [0; PARAMS_MAX];
static mut PLEN: usize = 0;
static mut FG: u8 = 7; // цвет символа (VGA-палитра)
static mut BG: u8 = 0; // цвет фона
static mut BOLD: bool = false; // яркость символа (VGA-бит 3)

/// ANSI-цвет (0..7) → VGA-цвет: у VGA другой порядок (красный=4, синий=1…).
const ANSI2VGA: [u8; 8] = [0, 4, 2, 6, 1, 5, 3, 7];

/// Собрать текущий атрибут из fg/bg/bold.
unsafe fn recompose() {
    ATTR = (BG << 4) | (if BOLD { 0x08 } else { 0 }) | FG;
}

/// Применить накопленный SGR (`ESC[ … m`): цвета/яркость/сброс.
unsafe fn apply_sgr() {
    let mut nums = [0u32; 8];
    let mut nn = 0usize;
    let mut cur = 0u32;
    for &b in &PARAMS[..PLEN] {
        if b == b';' {
            if nn < 8 {
                nums[nn] = cur;
                nn += 1;
            }
            cur = 0;
        } else if b.is_ascii_digit() {
            cur = cur * 10 + (b - b'0') as u32;
        }
    }
    if nn < 8 {
        nums[nn] = cur;
        nn += 1;
    }
    if PLEN == 0 {
        nums[0] = 0;
        nn = 1; // пустой SGR = reset
    }
    for &n in &nums[..nn] {
        match n {
            0 => {
                FG = 7;
                BG = 0;
                BOLD = false;
            }
            1 => BOLD = true,
            22 => BOLD = false,
            30..=37 => FG = ANSI2VGA[(n - 30) as usize],
            39 => FG = 7,
            40..=47 => BG = ANSI2VGA[(n - 40) as usize],
            49 => BG = 0,
            90..=97 => {
                FG = ANSI2VGA[(n - 90) as usize];
                BOLD = true;
            }
            _ => {}
        }
    }
    recompose();
}

/// Стереть от курсора до конца строки (`ESC[K`).
unsafe fn erase_line() {
    for col in COL..w() {
        put_cell(ROW, col, b' ');
    }
}

/// Первый числовой параметр CSI (для `ESC[nD` и т.п.); нет параметра → `default`, `0` → 1.
unsafe fn first_param(default: usize) -> usize {
    param_at(0, default)
}

/// Числовой параметр CSI по НОМЕРУ (0 — первый): `ESC[12;40H` → строка 12, колонка 40.
///
/// Веха 120 — до неё разбирался только первый параметр, потому что до неё никто не ставил
/// курсор в произвольное место: `ESC[H` уводил в начало, и этого хватало и цвету, и `clear`.
/// Экранному редактору (`bin/ved`) этого мало, а нужен он именно здесь — в спасательном шелле
/// консоль ядра единственный экран, какой есть.
unsafe fn param_at(idx: usize, default: usize) -> usize {
    let mut cur = 0usize;
    let mut any = false;
    let mut n = 0usize;
    for &b in &PARAMS[..PLEN] {
        if b == b';' {
            if n == idx {
                return if any { cur.max(1) } else { default };
            }
            n += 1;
            cur = 0;
            any = false;
        } else if b.is_ascii_digit() {
            cur = cur * 10 + (b - b'0') as usize;
            any = true;
        }
    }
    if n == idx && any {
        cur.max(1)
    } else {
        default
    }
}

/// Веха 41 — перевести Unicode-символ в байт **CP866** (в этой раскладке загружен шрифт
/// знакогенератора, [`load_font`]): ASCII — как есть, кириллица и псевдографика — по таблице,
/// прочее — `?`.
fn map_cp866(c: char) -> u8 {
    match c {
        '\n' | '\r' | '\u{8}' => c as u8,
        ' '..='~' => c as u8, // ASCII 0x20..0x7E
        'А'..='Я' => 0x80 + (c as u32 - 'А' as u32) as u8,
        'а'..='п' => 0xA0 + (c as u32 - 'а' as u32) as u8,
        'р'..='я' => 0xE0 + (c as u32 - 'р' as u32) as u8,
        'Ё' => 0xF0,
        'ё' => 0xF1,
        '═' => 0xCD, '║' => 0xBA, '╔' => 0xC9, '╗' => 0xBB, '╚' => 0xC8, '╝' => 0xBC,
        '╟' => 0xC7, '╢' => 0xB6, '╠' => 0xCC, '╣' => 0xB9, '╦' => 0xCB, '╩' => 0xCA, '╬' => 0xCE,
        '─' => 0xC4, '│' => 0xB3, '┌' => 0xDA, '┐' => 0xBF, '└' => 0xC0, '┘' => 0xD9,
        '├' => 0xC3, '┤' => 0xB4, '┬' => 0xC2, '┴' => 0xC1, '┼' => 0xC5,
        '█' => 0xDB, '░' => 0xB0, '▒' => 0xB1, '▓' => 0xB2, '•' => 0x07, '°' => 0xF8,
        '—' | '–' => 0xC4,
        '·' => 0xFA,
        '«' => 0xAE, '»' => 0xAF,
        '→' => 0x1A, '←' => 0x1B, '↑' => 0x18, '↓' => 0x19,
        '…' => b'.',
        // Знаки, которых в CP866 нет, но которые система печатает о себе сама: размеры экрана
        // («1280×800») и сетки. Без них в собственном баннере стоял вопросительный знак.
        '×' => b'x',
        '≈' => b'~',
        '№' => b'#',
        _ => b'?',
    }
}

/// Веха 41/43 — вывести символ на VGA. Обычные — в CP866 текущим цветом; ANSI-последовательности
/// (`ESC[…m` цвет, `ESC[2J` очистка, `ESC[H` в начало, `ESC[K` до конца строки) перехватываются
/// и НЕ рисуются (на serial те же коды толкует терминал).
pub fn put_char(c: char) {
    unsafe {
        match ANSI {
            Ansi::Normal => {
                if c == '\u{1b}' {
                    ANSI = Ansi::Esc;
                } else {
                    emit(map_cp866(c));
                }
            }
            Ansi::Esc => {
                if c == '[' {
                    PLEN = 0;
                    ANSI = Ansi::Csi;
                } else {
                    ANSI = Ansi::Normal; // не CSI — игнорируем
                }
            }
            Ansi::Csi => {
                // `?` — приватные последовательности (`ESC[?25l` — спрятать курсор). Делать нам
                // по ним нечего, но и глотать их надо ЦЕЛИКОМ: без этого разбор обрывался на
                // самом `?`, и хвост «25l» печатался на экран как текст.
                if c.is_ascii_digit() || c == ';' || c == '?' {
                    if PLEN < PARAMS_MAX {
                        PARAMS[PLEN] = c as u8;
                        PLEN += 1;
                    }
                } else {
                    match c {
                        'm' => apply_sgr(),
                        'J' => clear(),                // ESC[2J — очистить экран (курсор в начало)
                        // CUP: `ESC[H` — в начало, `ESC[r;cH` — в заданное знакоместо (нумерация
                        // с единицы, наша — с нуля).
                        'H' | 'f' => {
                            ROW = (param_at(0, 1) - 1).min(h() - 1);
                            COL = (param_at(1, 1) - 1).min(w() - 1);
                        }
                        'K' => erase_line(),
                        // Веха 45 — перемещение курсора (для редактирования строки в vsh).
                        'A' => ROW = ROW.saturating_sub(first_param(1)),
                        'B' => ROW = (ROW + first_param(1)).min(h() - 1),
                        'C' => COL = (COL + first_param(1)).min(w() - 1),
                        'D' => COL = COL.saturating_sub(first_param(1)),
                        _ => {}
                    }
                    ANSI = Ansi::Normal;
                }
            }
        }
    }
}

/// Очистить экран текущим цветом и увести курсор в начало (для `clear` из vsh — Веха 43).
pub fn clear() {
    unsafe {
        if crate::fb::present() {
            if !crate::fb::owned_by_user() {
                crate::fb::clear(ATTR);
            }
        } else {
            back::clear(ATTR);
        }
        ROW = 0;
        COL = 0;
    }
}

/// Веха 43 — поставить курсор туда, где мы остановились. Зовётся после каждой строки: иначе
/// мигающий курсор «висит» там, где его оставила прошивка, а не где пишем.
pub fn sync_cursor() {
    unsafe {
        // Веха 96: в пиксельном режиме аппаратного курсора нет — рисуем свой (подчёркивание).
        if crate::fb::present() {
            if !crate::fb::owned_by_user() {
                crate::fb::cursor(ROW, COL);
            }
            return;
        }
        back::cursor(ROW, COL);
    }
}
