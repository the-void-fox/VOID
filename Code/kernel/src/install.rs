//! Установка VOID на диск (Веха 48) — «live-USB → install → загрузка с диска».
//!
//! Идея: система, загруженная с USB (GRUB-ISO), сама раскладывает себя на SATA-диск через
//! [`crate::ahci`]. Загрузочный образ (MBR+GRUB+ядро в FAT-разделе p1, см. `Code/boot/mkdisk.sh`)
//! приезжает с USB как **модуль multiboot2** (`module2` в grub.cfg) — GRUB кладёт его в RAM,
//! ядро находит через [`crate::arch::boot_module`]. Так установленное ядро == работающему
//! (один и тот же бинарь в p1 образа), без встраивания образа в само ядро (это было бы циклично).
//!
//! Шаги [`run`]:
//! 1. записать загрузочный префикс образа (сектора 0..начало p2: MBR + зазор с core.img + p1 FAT)
//!    на диск АБСОЛЮТНО ([`Цель::write`]);
//! 2. поправить в MBR диска раздел p2 (store) — растянуть на весь реальный диск;
//! 3. обнулить начало p2 → на ребуте store увидит «пусто» и засеет программы заново;
//! 4. ЗАМОРОЗИТЬ текущий store ([`crate::object::freeze`]) — его кэш больше не должен писать на
//!    диск, иначе group-commit затрёт свежий образ до перезагрузки.
//!
//! После этого пользователь вынимает USB и грузится с диска. **Диск стирается целиком.**
//!
//! ## Куда ставим (Веха 194.1)
//!
//! Раскладка выше не зависит от того, по какой шине едут сектора, и это не случайность: MBR,
//! зазор и таблица разделов — договор с ЗАГРУЗЧИКОМ, а не с контроллером. Поэтому установщик
//! знает про диск ровно четыре действия ([`Цель`]), а какой драйвер их исполняет, решает номер
//! диска: 0..[`crate::arch::MAX_DISKS`] — порты AHCI, от [`crate::nvme::SLOT_BASE`] — NVMe.
//! Без этого v0.2 отвечала бы «да» только наполовину: store с NVMe читается (Веха 194), а
//! поставить систему на машину, где SATA нет вовсе, было нечем.

/// Диск как его видит установщик: открыть, спросить ёмкость, писать и читать АБСОЛЮТНЫМИ
/// секторами. Ровно то и не больше — установка не знает ни про разделы store, ни про кэш.
enum Цель {
    Ahci,
    Nvme,
    /// Веха 196 — USB-накопитель. Ставить НА флешку — не экзотика, а ровно то, ради чего
    /// проект и затевался: переносная система на съёмном носителе.
    Usb,
}

impl Цель {
    /// Выбрать шину по номеру диска и открыть цель. `None` — такого диска нет либо с него
    /// работает система (отказывает сам драйвер, и это правильное место для отказа).
    fn open(slot: usize) -> Option<Self> {
        if slot >= crate::xhci::SLOT_BASE {
            crate::xhci::target_open(slot).then_some(Цель::Usb)
        } else if slot >= crate::nvme::SLOT_BASE {
            crate::nvme::target_open(slot).then_some(Цель::Nvme)
        } else {
            crate::ahci::target_open(slot).then_some(Цель::Ahci)
        }
    }

    fn sectors(&self) -> u64 {
        match self {
            Цель::Ahci => crate::ahci::target_sectors(),
            Цель::Nvme => crate::nvme::target_sectors(),
            Цель::Usb => crate::xhci::target_sectors(),
        }
    }

    fn write(&self, sector: u64, buf: &[u8; 512]) -> bool {
        match self {
            Цель::Ahci => crate::ahci::target_write(sector, buf),
            Цель::Nvme => crate::nvme::target_write(sector, buf),
            Цель::Usb => crate::xhci::target_write(sector, buf),
        }
    }

    fn read(&self, sector: u64, buf: &mut [u8; 512]) -> bool {
        match self {
            Цель::Ahci => crate::ahci::target_read(sector, buf),
            Цель::Nvme => crate::nvme::target_read(sector, buf),
            Цель::Usb => crate::xhci::target_read(sector, buf),
        }
    }
}

/// Выполнить установку на выбранный диск (AHCI или NVMe). `Ok(p2_start)` — префикс записан, диск
/// размечен, можно перезагружаться. `Err(причина)` — не сложилось (диск/образ не годны), система
/// цела.
pub fn run(slot: usize) -> Result<u64, &'static str> {
    let (mbase, mlen) =
        crate::arch::boot_module().ok_or("нет образа установки (модуль multiboot2 с USB)")?;
    // Веха 174 — ставим на ВЫБРАННЫЙ диск, а не на «тот, что нашёлся первым». Открытие цели
    // само отказывает, если названный порт — это диск, с которого работает store: система,
    // стирающая диск из-под себя, не установка, а потеря.
    let Some(цель) = Цель::open(slot) else {
        return Err("такого диска нет либо это диск, с которого работает система");
    };
    let total = цель.sectors();
    if total == 0 {
        return Err("диск не сказал свою ёмкость");
    }
    // Веха 87: GRUB кладёт модуль в RAM и сообщает ФИЗИЧЕСКИЙ адрес — читаем через direct-map.
    let img = unsafe { core::slice::from_raw_parts(crate::frame::ptr(mbase), mlen) };
    if img.len() < 512 || img[510] != 0x55 || img[511] != 0xaa {
        return Err("образ без MBR-подписи 0x55AA");
    }
    // Начало раздела p2 (store) — из таблицы разделов образа (вторая запись, поле lba_start@+8).
    let p2 = 446 + 16;
    let le32 = |b: &[u8], o: usize| {
        b[o] as u64 | (b[o + 1] as u64) << 8 | (b[o + 2] as u64) << 16 | (b[o + 3] as u64) << 24
    };
    let p2_start = le32(img, p2 + 8);
    let need = (p2_start as usize).saturating_mul(512);
    if p2_start == 0 || img.len() < need {
        return Err("образ короче своего загрузочного префикса");
    }
    if total <= p2_start {
        return Err("диск меньше загрузочного раздела");
    }

    // 1) Загрузочный префикс (MBR + зазор core.img + p1 FAT с GRUB и ядром) → диск, сектор в сектор.
    let mut sec = [0u8; 512];
    for s in 0..p2_start {
        let o = (s as usize) * 512;
        sec.copy_from_slice(&img[o..o + 512]);
        if !цель.write(s, &sec) {
            return Err("сбой записи загрузочного префикса на диск");
        }
    }

    // 2) MBR диска: растянуть p2 (store) на весь диск — num_sectors@+12 = total − p2_start.
    if !цель.read(0, &mut sec) {
        return Err("сбой чтения MBR после записи");
    }
    let cnt = ((total - p2_start) as u32).to_le_bytes();
    sec[p2 + 12..p2 + 16].copy_from_slice(&cnt);
    if !цель.write(0, &sec) {
        return Err("сбой записи MBR");
    }

    // 3) Обнулить начало store (p2) — суперблок + область индекса: на ребуте store решит «пусто»
    //    и засеет программы (как первый запуск), не подхватив мусор старого содержимого диска.
    let zero = [0u8; 512];
    for s in 0..64u64 {
        if !цель.write(p2_start + s, &zero) {
            return Err("сбой очистки области store");
        }
    }

    // Веха 174 — заморозки store БОЛЬШЕ НЕТ, и это следствие выбора диска. Она стояла здесь
    // потому, что установка меняла раскладку диска, С КОТОРОГО СИСТЕМА И РАБОТАЛА: писать туда
    // дальше значило затереть свежий образ. Теперь установщик на такой диск не ставит вовсе
    // (`target_open` отказывает), а живой носитель держит store в памяти — замораживать нечего.
    // Заодно сеанс переживает установку: человек может смотреть систему дальше.
    Ok(p2_start)
}

/// Веха 222 — ОБНОВИТЬ систему на диске, НЕ ТРОГАЯ данные.
///
/// ## Почему это оказалось так дёшево
///
/// Потому что содержимое у нас адресуется содержимым. Программы системы лежат в store корнями
/// `bin/<арх>/<имя>`, и ядро на каждой загрузке сверяет их с тем, что вложено в него самого
/// (`seed_programs`): совпало — оставить, разошлось — переписать корень. То есть **новое ядро
/// обновляет систему само**, просто загрузившись. Файлы человека, поколения конфига, пакеты и
/// секреты при этом ни при чём: у них другие корни, и никто их не трогает.
///
/// Значит обновление — это ровно одно действие: положить на диск НОВОЕ ЯДРО. Всё остальное —
/// то, чего делать НЕЛЬЗЯ:
///
/// | установка ([`run`]) | обновление |
/// |---|---|
/// | пишет весь загрузочный префикс, включая MBR целиком | таблицу разделов диска СОХРАНЯЕТ |
/// | растягивает раздел store на весь диск | не трогает разметку вовсе |
/// | обнуляет начало store — «начни с чистого листа» | не трогает store НИ ОДНИМ сектором |
///
/// Таблица разделов сохраняется побайтно, а не переписывается заново, по простой причине: она
/// описывает ЭТОТ диск (store растянут под его ёмкость), а в образе лежит таблица флешки. Взять
/// её оттуда — значит объявить store размером с образ и потерять всё, что за этой границей.
///
/// ## Чего здесь нет
///
/// Отката. Новое ядро ложится поверх старого, и если оно не загрузится, вернуть прежнее можно
/// только той же флешкой. Поколения конфига откатываются (`switch`), а ядро — нет: оно одно и
/// живёт вне store. Это честная граница сегодняшнего дня, а не недосмотр.
pub fn update(slot: usize) -> Result<u64, &'static str> {
    let (mbase, mlen) =
        crate::arch::boot_module().ok_or("нет образа (обновляют с той же флешки, что и ставят)")?;
    let Some(цель) = Цель::open(slot) else {
        return Err("такого диска нет либо это диск, с которого работает система");
    };
    let img = unsafe { core::slice::from_raw_parts(crate::frame::ptr(mbase), mlen) };
    if img.len() < 512 || img[510] != 0x55 || img[511] != 0xaa {
        return Err("образ без MBR-подписи 0x55AA");
    }
    let p2 = 446 + 16;
    let le32 = |b: &[u8], o: usize| {
        b[o] as u64 | (b[o + 1] as u64) << 8 | (b[o + 2] as u64) << 16 | (b[o + 3] as u64) << 24
    };
    let p2_start = le32(img, p2 + 8);
    if p2_start == 0 || img.len() < (p2_start as usize) * 512 {
        return Err("образ короче своего загрузочного префикса");
    }

    // 1) Читаем MBR ДИСКА и убеждаемся, что обновлять есть что. Диск без нашего раздела store —
    //    это не «старая версия VOID», это чужой диск, и писать на него загрузчик значило бы
    //    сломать чужую систему молча.
    let mut диск_mbr = [0u8; 512];
    if !цель.read(0, &mut диск_mbr) {
        return Err("MBR диска не читается");
    }
    if диск_mbr[510] != 0x55 || диск_mbr[511] != 0xaa {
        return Err("на диске нет MBR — это не установленная система (нужна `install`)");
    }
    let наш = (0..4).any(|i| диск_mbr[446 + i * 16 + 4] == crate::ahci::VOID_STORE_TYPE);
    if !наш {
        return Err("на диске нет раздела store — VOID сюда не ставили (нужна `install`)");
    }
    let старый_p2 = le32(&диск_mbr, p2 + 8);

    // 2) Загрузочный префикс из образа — кроме нулевого сектора. В нём зазор с `core.img` и
    //    раздел p1 с GRUB и ЯДРОМ; ядро и есть вся система.
    //
    //    Начало p2 у диска и у образа обязано совпадать: иначе новый загрузчик будет искать
    //    store не там, где он лежит. Разойтись они могут, только если менялась сама раскладка
    //    образа, — и тогда честнее отказать, чем оставить машину, которая не грузится.
    if старый_p2 != p2_start {
        return Err("раскладка диска не совпадает с образом — обновить нельзя, нужна установка");
    }
    let mut sec = [0u8; 512];
    for s in 1..p2_start {
        let o = (s as usize) * 512;
        sec.copy_from_slice(&img[o..o + 512]);
        if !цель.write(s, &sec) {
            return Err("сбой записи загрузочного раздела");
        }
    }

    // 3) MBR: код загрузчика из образа, ТАБЛИЦА РАЗДЕЛОВ — с диска. Первые 446 байт — начало
    //    GRUB, и обновлять его надо вместе с остальным; всё, что после, описывает этот диск.
    let mut новый_mbr = диск_mbr;
    новый_mbr[..446].copy_from_slice(&img[..446]);
    if !цель.write(0, &новый_mbr) {
        return Err("сбой записи MBR");
    }
    Ok(p2_start)
}
