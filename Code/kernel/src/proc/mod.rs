    /// рукой пользователя. Это и есть честный признак «системного» ([[task-manager]]): не флаг,
    /// приклеенный к процессу, а ПРОИСХОЖДЕНИЕ. Ставит только [`crate::init`]; всё, что поднято
    /// через `SYS_EXEC`/`SYS_SPAWN`, — `false`.
