/// Веха 52 — «пришло прерывание userspace-драйвера» (вектор `VEC_USERDRV`). Обработчик IRQ
/// выставляет флаг БЕЗ замка таблицы процессов (иначе дедлок с прерванным контекстом), а
/// планировщик снимает его и будит спящих в `SYS_IRQ_WAIT` ([`drain_userdrv_irq`]).
static USERDRV_IRQ_PENDING: AtomicBool = AtomicBool::new(false);

/// Веха 197 — нажата КНОПКА ПИТАНИЯ (отметка из обработчика SCI).
static POWER_BUTTON: AtomicBool = AtomicBool::new(false);

/// Зовётся из обработчика SCI. Здесь только отметка: выключать машину из прерванного контекста
/// нельзя — синк store берёт замки, а мы могли прервать того, кто их держит.
#[cfg_attr(not(target_arch = "x86_64"), allow(dead_code))]
pub fn on_power_button() {
    POWER_BUTTON.store(true, Ordering::Relaxed);
}

/// Нажата ли кнопка питания — и если да, выключить машину ЧИСТО: синк store, сообщение, питание.
///
/// Зовётся планировщиком (`resume`), то есть в месте, где замков мы не держим. Поведение выбрано
/// самое простое из честных: нажатие = «выключи», как на любой машине без графической оболочки.
/// Спрашивать человека «точно?» было бы приятнее, но это диалог, окно и ответ от композитора —
/// то есть работа оболочки, а не ядра, и делать её видом, что ядро само справится, нельзя.
fn drain_power_button() {
    if !POWER_BUTTON.swap(false, Ordering::Relaxed) {
        return;
    }
    println!("  [power] нажата кнопка питания — выключаюсь");
    crate::object::commit();
    println!(
        "  [store] финальный синк: поколение {} · записано за сессию: {} КиБ",
        crate::object::generation(),
        crate::object::bytes_written() / 1024,
    );
    arch::power_off();
}

/// Веха 52 — из обработчика прерывания (trap): просто отметить, что IRQ пришёл. Пробуждение —
/// на планировщике, где замок таблицы берётся законно. Зовётся из x86-обработчика VEC_USERDRV;
/// на riscv userspace-драйверов с IRQ пока нет (USB/e1000 — x86), поэтому там это мёртвый код.
#[cfg_attr(not(target_arch = "x86_64"), allow(dead_code))]
pub fn on_userdrv_irq() {
    USERDRV_IRQ_PENDING.store(true, Ordering::Relaxed);
}

/// Веха 195 — растолкать драйвера-карту: стек положил в очередь исходящий кадр.
///
/// Будим и из `IrqWait`, и из `Sleeping`, и это не вольность. Кооперативный планировщик шима
/// спит на прерывании ТОЛЬКО когда у него нет ни одного таймера; стоит вендорному коду завести
/// отложенную работу (а `8139too` заводит — проверка линка), и процесс уходит в `SYS_SLEEP` на
/// секунды. Не разбуди мы его оттуда — исходящий кадр ждал бы этих секунд, и «сеть работает»
/// стало бы «сеть иногда работает».
///
/// Ранний выход из сна безвреден по построению: шим в своём цикле заново сверяет `jiffies` и,
/// если срок не вышел, засыпает снова. Пробуждение без кадра — тоже: драйвер просто не найдёт
/// в очереди ничего.
/// Веха 199.11 — тело `SYS_PCI_CFG` для машин, у которых PCI есть. На riscv-virt его нет вовсе,
/// и отдельная функция здесь ровно затем, чтобы разница жила В ОДНОМ месте, а не `#[cfg]`-ом
/// посреди разбора системного вызова.
#[cfg(target_arch = "x86_64")]
fn cfg_pci(base: usize, off: usize, val: usize, write: usize) -> usize {
    match arch::pci_bdf_by_bar(base) {
        Some(bdf) if write == 0 => arch::pci_cfg_read32(bdf, off as u8) as usize,
        Some(bdf) => {
            arch::pci_cfg_write32(bdf, off as u8, val as u32);
            0
        }
        // Окно есть, а устройства с таким BAR на шине нет: право выдано не под PCI
        // (фреймбуфер, контроллер платформы). Отказ — честный ответ, падать не за что.
        None => usize::MAX,
    }
}

#[cfg(not(target_arch = "x86_64"))]
fn cfg_pci(_base: usize, _off: usize, _val: usize, _write: usize) -> usize {
    usize::MAX // riscv-virt: конфигурационного пространства PCI у нас нет
}

/// Веха 200 — тело `SYS_HWPROBE`: заглянуть в регистр устройства.
///
/// `kind` 0 — окно MMIO (`a` = физический адрес), 1 — конфигурация PCI (`a` = BDF, `b` =
/// смещение). Разделено на два вида, а не сведено к «адресу», потому что это два разных
/// пространства: у конфигурации PCI своя адресация и свой механизм доступа.
#[cfg(target_arch = "x86_64")]
fn hw_probe(kind: usize, a: usize, b: usize, val: usize, write: usize) -> usize {
    match kind {
        0 => {
            // ГЛАВНАЯ ПРОВЕРКА: это не оперативная память.
            //
            // Без неё право «заглянуть в железо» означало бы «прочитать любую страницу любого
            // процесса», то есть отменяло бы изоляцию целиком — и отменяло бы тихо, потому что
            // выглядит инструмент отладки безобидно. Регистры устройств в RAM не живут, так что
            // запрет ничего не отнимает у настоящей задачи.
            // `in_ram`, а НЕ `is_ram`: второй исключает всё ниже границы выдачи фреймов, то есть
            // сам образ ядра — и по его мнению адрес ядерного кода «не RAM». Для этого права
            // такой ответ был бы приглашением прочитать ядро (см. `frame::in_ram`).
            if a % 4 != 0 || crate::frame::in_ram(a) {
                return usize::MAX;
            }
            if write == 0 {
                arch::hw_read32(a) as usize
            } else {
                arch::hw_write32(a, val as u32);
                0
            }
        }
        1 if b < 256 && b % 4 == 0 => {
            if write == 0 {
                arch::pci_cfg_read32(a as u16, b as u8) as usize
            } else {
                arch::pci_cfg_write32(a as u16, b as u8, val as u32);
                0
            }
        }
        _ => usize::MAX,
    }
}

#[cfg(not(target_arch = "x86_64"))]
fn hw_probe(_k: usize, _a: usize, _b: usize, _v: usize, _w: usize) -> usize {
    usize::MAX // riscv-virt: ни конфигурации PCI, ни привычных окон регистров
}

fn wake_netdev_owner(t: &mut Table) -> Option<usize> {
    let pid = crate::net::ext_owner()?;
    let mut woken = None;
    for i in 0..t.procs.len() {
        // Драйвер — это группа нитей; спать на прерывании или таймере может любая из них.
        if t.procs[i].group != pid {
            continue;
        }
        match t.procs[i].state {
            State::IrqWait => {
                // Кадр уже продвинут при блокировке — вернётся 0, как от настоящего прерывания.
            }
            State::Sleeping => {
                let f = &mut t.procs[i].frame;
                f.set_ret(0);
                f.advance();
            }
            _ => continue,
        }
        t.procs[i].state = State::Runnable;
        t.procs[i].ready_at = arch::now_ticks();
        t.procs[i].futex_deadline = None;
        woken = Some(i);
    }
    woken
}

/// Веха 52 — если пришёл IRQ драйвера, разбудить всех в `IrqWait` (сделать `Runnable`). Драйвер
/// сам сверится с состоянием устройства (ICR) при пробуждении — ложное пробуждение безвредно.
fn drain_userdrv_irq(t: &mut Table) -> bool {
    if !USERDRV_IRQ_PENDING.swap(false, Ordering::Relaxed) {
        return false;
    }
    let mut woke = false;
    for p in &mut t.procs {
        if p.state == State::IrqWait {
            p.state = State::Runnable;
            p.ready_at = arch::now_ticks();
            woke = true;
        }
    }
    woke
}

/// Веха 52 — есть ли процессы, спящие в `SYS_IRQ_WAIT` (нужно `wait_stdin`: не завершать сессию,
/// пока драйвер ждёт прерывания).
fn any_irq_waiting(t: &Table) -> bool {
    t.procs.iter().any(|p| p.state == State::IrqWait)
}

