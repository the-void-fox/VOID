//! Веха 86 — источник случайности ядра.
//!
//! Зачем в ядре: `getrandom` порта std (сейчас — xorshift от счётчика, сам себя честно помечает
//! некриптографическим), сиды хэш-таблиц, ASLR-подобные мелочи и — главное впереди — TLS
//! ([[0009-ondevice-packages]]), где предсказуемая случайность означает предсказуемые ключи.
//!
//! Устройство: три источника, смешиваемые через BLAKE3 (он уже линкуется ради контент-адресации).
//! 1. **Аппаратный ГСЧ процессора** — [`arch::hw_random_u64`] (`RDRAND` на x86; на riscv его нет).
//! 2. **virtio-rng** — [`crate::virtio_rng`], энтропия от гипервизора. Арх-нейтральный, поэтому
//!    подмешивается здесь, а не в `arch`.
//! 3. **Пул событий** — [`stir`]: моменты прерываний и нажатий клавиш подмешивают в накопитель
//!    младшие биты монотонного счётчика. Это классический сбор джиттера: интервалы между
//!    внешними событиями непредсказуемы для программы.
//!
//! Выдача — всегда хэш от (пул ‖ счётчик выдач ‖ тики ‖ аппаратное слово ‖ слово virtio-rng):
//! источники СМЕШИВАЮТСЯ, а не выбираются — слабость любого из них не портит выход (whitening).
//!
//! **Честная оговорка (переписана после измерения).** Раньше здесь стояло «на x86 с `RDRAND`
//! качество криптографическое» — и это оказалось неверно для нашей же среды: **QEMU по умолчанию
//! поднимает модель CPU без `RDRAND`** (он появляется только с `-cpu max`/`-cpu host`). То есть
//! до virtio-rng криптографического источника не было НИ НА ОДНОЙ из арх, хотя документация
//! утверждала обратное про x86. Проверяется одной строкой баннера: `[rng]` печатает, что реально
//! нашлось, а [`has_strong_source`] отвечает на это честным `false`.
//!
//! **Реальное железо остаётся открытым вопросом.** virtio-rng есть только под гипервизором, а
//! `RDRAND` — с Ivy Bridge (2012); на более старых машинах (тот же ASUS X54C, Sandy Bridge)
//! сильного источника не будет, и на нём нельзя строить ключи TLS. См. [[known-gaps]].
//!
//! Гонки: `stir` зовётся ИЗ ОБРАБОТЧИКОВ ПРЕРЫВАНИЙ, поэтому здесь нет ни одного замка — только
//! атомарные операции (замок в этом месте — тот самый дедлок, см. [[known-gaps]], «Устойчивость»).

use core::sync::atomic::{AtomicU64, Ordering};

use void_abi::ContentId;

use crate::arch;

/// Накопитель энтропии: перемешивается моментами внешних событий.
static POOL: AtomicU64 = AtomicU64::new(0x9e37_79b9_7f4a_7c15);
/// Счётчик выдач — гарантирует, что два вызова подряд дадут разные блоки.
static COUNTER: AtomicU64 = AtomicU64::new(0);

/// Подмешать событие в пул. Дёшево и безопасно из прерывания: одно чтение счётчика тиков и CAS-free
/// атомарный XOR со сдвигом (важна не «правильность» смешивания, а накопление джиттера).
pub fn stir(tag: u64) {
    let t = arch::now_ticks();
    let prev = POOL.load(Ordering::Relaxed);
    // Умножение на нечётную константу разносит младшие биты по слову, XOR — накапливает.
    let mixed = (prev.rotate_left(17) ^ t.wrapping_mul(0x2545_f491_4f6c_dd1d)) ^ tag;
    POOL.store(mixed, Ordering::Relaxed);
}

/// Заполнить буфер случайными байтами.
pub fn fill(buf: &mut [u8]) {
    let mut off = 0;
    while off < buf.len() {
        let mut seed = [0u8; 40];
        let c = COUNTER.fetch_add(1, Ordering::Relaxed);
        let pool = POOL.load(Ordering::Relaxed);
        let ticks = arch::now_ticks();
        let hw = arch::hw_random_u64().unwrap_or(0);
        // Третий источник (закрытие долга Вехи 86): virtio-rng. Арх-нейтральный и потому
        // подмешивается ЗДЕСЬ, а не в `arch`: на riscv он единственный настоящий (аппаратного
        // ГСЧ у QEMU virt нет вовсе), на x86 — второй независимый рядом с RDRAND. Смешиваем
        // все источники, а не выбираем один: слабость любого из них не портит выход.
        let vrng = crate::virtio_rng::next_u64().unwrap_or(0);
        // Джиттер стоит тысяч обращений к памяти, поэтому он подмешивается не каждый раз, а
        // ПЕРЕЗАСЕВАЕТ пул раз в 64 выдачи. Для источника это правильнее, чем дёргать его на
        // каждый байт: энтропия копится в пуле, а выдача остаётся дешёвой.
        if c % 64 == 0 {
            if let Some(j) = crate::jitter::next_u64() {
                stir(j);
            }
        }
        seed[0..8].copy_from_slice(&c.to_le_bytes());
        seed[8..16].copy_from_slice(&pool.to_le_bytes());
        seed[16..24].copy_from_slice(&ticks.to_le_bytes());
        seed[24..32].copy_from_slice(&hw.to_le_bytes());
        seed[32..40].copy_from_slice(&vrng.to_le_bytes());
        let block = ContentId::hash(&seed).0;
        let n = (buf.len() - off).min(block.len());
        buf[off..off + n].copy_from_slice(&block[..n]);
        off += n;
        // Продвинуть пул, чтобы следующий блок не зависел от того же состояния.
        stir(c ^ hw ^ vrng);
    }
}

/// Есть ли у системы источник, на который МОЖНО опереться: аппаратный ГСЧ процессора,
/// virtio-rng или прошедший санитарные тесты джиттер-источник.
///
/// `false` означает буквально «ключи здесь генерировать нельзя» — и это должно быть слышно,
/// а не выведено читателем из отсутствия сообщений.
pub fn has_strong_source() -> bool {
    arch::hw_random_u64().is_some() || crate::virtio_rng::present() || crate::jitter::healthy()
}

/// Имя корня, в котором лежит семя, переживающее перезагрузку.
const SEED_ROOT: &str = "system/random-seed";
/// Длина семени: 32 байта — блок BLAKE3, больше смысла не имеет.
const SEED_LEN: usize = 32;

/// Подмешать семя ПРОШЛОЙ загрузки в пул и тут же записать новое.
///
/// Это то, что делает любой Unix (`/var/lib/systemd/random-seed`), и у нас оно достаётся почти
/// даром: store персистентен. Смысл — снять худший случай, «холодная загрузка без энтропии»:
/// после первой же загрузки система стартует с накопленным состоянием, а не с константы.
///
/// Новое семя пишется СРАЗУ после чтения, до того как старое где-либо использовано: иначе
/// падение до записи заставило бы следующую загрузку повторить ту же случайность.
pub fn load_seed() -> bool {
    let had = match crate::object::root(SEED_ROOT) {
        Some(id) => crate::object::with(&id, |b| match b {
            Some(bytes) if bytes.len() == SEED_LEN => {
                // Мешаем семя в пул по слову: `stir` для того и сделан.
                for chunk in bytes.chunks_exact(8) {
                    let mut w = [0u8; 8];
                    w.copy_from_slice(chunk);
                    stir(u64::from_le_bytes(w));
                }
                true
            }
            _ => false,
        }),
        None => false,
    };
    save_seed();
    had
}

/// Записать свежее семя на следующую загрузку.
pub fn save_seed() {
    let mut seed = [0u8; SEED_LEN];
    fill(&mut seed);
    let id = crate::object::put(&seed);
    crate::object::set_root(SEED_ROOT, id);
}
