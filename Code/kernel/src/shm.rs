//! Веха 129 — **разделяемая память**: одни и те же физические страницы в двух адресных
//! пространствах.
//!
//! Зачем. До сих пор кадр окна ехал в композитор через объектный store: клиент клал изменившийся
//! кусок объектом, композитор читал его по content-id. Замер (Веха 129, [[compositor-damage]])
//! показал цену: **кусок в двести раз больший стоит всего в 1.3 раза дороже**, то есть платим мы
//! не за пиксели, а за сам факт объекта — syscall, BLAKE3, куча ядра, индекс и групповой коммит,
//! который вставка тащит за собой. Строка окна обходилась в миллисекунды при бюджете кадра 16 мс.
//!
//! Store тут ни при чём и виноват не он: он сделан для того, что ДОЛЖНО пережить перезагрузку и
//! адресоваться хэшем. Пиксели живут один кадр — им нужна не персистентность, а общая страница.
//!
//! ## Как это укладывается в модель прав
//!
//! Область — это **ресурс под capability** ([`crate::cap::Target::Shm`]), как эндпоинт или
//! устройство. Создатель получает право на неё и передаёт его по IPC тому, с кем делится; без
//! права отобразить область нельзя, и подделать право невозможно. То есть «этот процесс имеет
//! доступ к буферу того окна» — не соглашение, а проверяемый факт.
//!
//! ## Кто освобождает страницы
//!
//! Считаем ДЕРЖАТЕЛЕЙ (число отображений). Страницы возвращаются в общий котёл, когда уходит
//! последний, — и это не мелочь: без счётчика смерть клиента освободила бы страницы, в которые
//! композитор продолжает смотреть. Поэтому же в записях таблиц стоит программный бит
//! `PTE_SHARED`: `free_private` умирающего процесса такие листья пропускает.

use alloc::vec::Vec;

use crate::frame::{self, PAGE_SIZE};
use crate::sync::SpinLock;

/// Одна область: её фреймы, длина и сколько процессов её сейчас держат.
struct Region {
    frames: Vec<usize>,
    len: usize,
    holders: usize,
}

/// Таблица областей. Индекс — то, что лежит в capability; слот освобождается вместе с областью.
static REGIONS: SpinLock<Vec<Option<Region>>> = SpinLock::new(Vec::new());

/// Потолок одной области: 16 МиБ. Полноэкранный кадр 1920×1080×4 — это 8 МиБ, так что запас
/// двойной; больше давать незачем, а ограничение здесь — защита от процесса, который попросит
/// всю память одним вызовом.
pub const MAX_LEN: usize = 16 * 1024 * 1024;

/// Создать область под `len` байт. Возвращает её индекс; `None` — не хватило памяти или запрос
/// вне разумного. Создатель становится первым держателем.
pub fn create(len: usize) -> Option<usize> {
    if len == 0 || len > MAX_LEN {
        return None;
    }
    let pages = len.div_ceil(PAGE_SIZE);
    let mut frames = Vec::new();
    for _ in 0..pages {
        match frame::alloc() {
            Some(pa) => frames.push(pa),
            None => {
                // Не хватило на середине — вернуть уже взятое, а не оставить висеть.
                for pa in frames {
                    frame::free(pa);
                }
                return None;
            }
        }
    }
    let mut t = REGIONS.lock();
    let region = Region { frames, len, holders: 1 };
    let id = match t.iter().position(|s| s.is_none()) {
        Some(i) => {
            t[i] = Some(region);
            i
        }
        None => {
            t.push(Some(region));
            t.len() - 1
        }
    };
    Some(id)
}

/// Длина области в байтах (0 — области нет).
pub fn len(id: usize) -> usize {
    REGIONS.lock().get(id).and_then(|s| s.as_ref()).map(|r| r.len).unwrap_or(0)
}

/// Физические адреса страниц области. Копией, а не ссылкой: отображать их будет `proc`, а
/// держать замок таблицы областей, пока идёт хождение по таблицам страниц, незачем.
pub fn frames(id: usize) -> Vec<usize> {
    REGIONS
        .lock()
        .get(id)
        .and_then(|s| s.as_ref())
        .map(|r| r.frames.clone())
        .unwrap_or_default()
}

/// Прибавить держателя (отображение появилось). `false` — области нет.
pub fn retain(id: usize) -> bool {
    let mut t = REGIONS.lock();
    match t.get_mut(id).and_then(|s| s.as_mut()) {
        Some(r) => {
            r.holders += 1;
            true
        }
        None => false,
    }
}

/// Убавить держателя. Ушёл последний — страницы возвращаются в общий котёл.
pub fn release(id: usize) {
    let mut t = REGIONS.lock();
    let Some(slot) = t.get_mut(id) else { return };
    let Some(r) = slot.as_mut() else { return };
    r.holders -= 1;
    if r.holders > 0 {
        return;
    }
    let region = slot.take().expect("слот только что был занят");
    drop(t); // освобождать фреймы под замком таблицы областей незачем
    for pa in region.frames {
        frame::free(pa);
    }
}
