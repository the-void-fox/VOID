//! Периодический таймер поверх SBI — источник вытеснения (preemption).
//!
//! Аппаратный таймер RISC-V одноразовый: срабатывает, когда счётчик `time` доходит до
//! запрограммированного значения. Чтобы получать прерывания периодически, на каждом
//! срабатывании программируем следующее (паттерн «перевзвести»).
//!
//! На каждом тике мы вытесняем текущую задачу — вызываем [`crate::sched::yield_now`],
//! который переключит на следующую готовую. Так задачи чередуются, даже если сами
//! никогда не уступают процессор.

use core::sync::atomic::{AtomicU64, Ordering};

use crate::arch;

/// Сколько таймерных прерываний (вытеснений) уже произошло.
static TICKS: AtomicU64 = AtomicU64::new(0);

/// Запустить таймер: вооружить первое срабатывание и включить прерывания.
/// Вызывать после [`crate::arch::trap_init`] и [`crate::sched::init`].
/// Квант вытеснения — дело арха ([`arch::timer_arm`]): таймбазы у всех разные.
pub fn init() {
    arm_next();
    arch::timer_hw_init(); // размаскировать таймер + глобально включить прерывания
}

/// Запрограммировать следующее срабатывание на «сейчас + квант».
fn arm_next() {
    arch::timer_arm();
}

/// Вооружить следующее срабатывание (публично) — для старта вытеснения процессов в
/// [`crate::proc::run`], где таймер включают на время сессии.
pub fn arm() {
    arm_next();
}

/// Тик вытеснения ПРОЦЕССА: перевзвести таймер и учесть тик, но БЕЗ [`crate::sched::yield_now`]
/// (им вытесняются ядерные нити). Планированием процессов рулит [`crate::proc`].
pub fn preempt_tick() {
    TICKS.fetch_add(1, Ordering::Relaxed);
    arm_next();
    // Веха 20.1: в сессиях процессов внешние прерывания выключены (SEIE=0) — вычерпываем
    // ввод UART опросом на каждом тике, чтобы FIFO/буферы QEMU не переполнялись.
    drain_input();
}

/// Сколько было вытеснений с момента запуска таймера.
pub fn ticks() -> u64 {
    TICKS.load(Ordering::Relaxed)
}

/// Вызывается диспетчером trap'ов на каждое таймерное прерывание.
pub fn on_tick() {
    TICKS.fetch_add(1, Ordering::Relaxed);
    arm_next(); // перевзвести (это же сбрасывает pending-бит таймера)
    drain_input(); // Веха 20.1: подобрать ввод, пришедший между прерываниями
    // ВЫТЕСНЕНИЕ ядерных нитей — только на загрузочном ядре. Веха 170: нити [`crate::sched`]
    // заводятся и живут на нём одном (их контексты, стеки и очередь ничего не знают о втором
    // ядре), и «уступить процессор следующей задаче» на прикладном ядре означало бы прыгнуть в
    // чужой контекст с чужим стеком.
    if crate::cpu::id() == 0 {
        crate::sched::yield_now();
    }
}

/// Веха 170.8 — вычерпать ввод устройств. **Только ЗАГРУЗОЧНОЕ ядро.**
///
/// Устройства на машине одни, и опрашивать их с каждого ядра незачем: чтения портов COM1 и 8042
/// стоят микросекунд каждое, идут под большим замком — и всё это лишь затем, чтобы четыре ядра
/// узнали одно и то же. Прерывания устройств тоже приходят сюда (`ioapic::route` называет
/// адресатом загрузочное ядро), так что и по смыслу ввод — его дело.
///
/// Заодно отсюда ушёл толчок соседу: пока ввод подбирало любое ядро, разбудить спящего в
/// `SYS_READ` умело всё равно только загрузочное, и приходилось звать его прерыванием. Теперь
/// подбирает оно само — звать некого.
fn drain_input() {
    if crate::cpu::id() == 0 {
        arch::console_drain();
    }
}
