//! Периодический таймер поверх SBI.
//!
//! Аппаратный таймер RISC-V одноразовый: он срабатывает, когда счётчик `time`
//! доходит до запрограммированного значения. Чтобы получать прерывания периодически,
//! на каждом срабатывании мы заново программируем следующее (паттерн «перевзвести»).
//!
//! Программируем через [`crate::sbi::set_timer`] (расширение TIME). Это же действие
//! сбрасывает pending-бит таймера, поэтому отдельной «очистки» прерывания не нужно.

use core::sync::atomic::{AtomicU64, Ordering};

use crate::{csr, println, sbi};

/// Таймбаза QEMU virt — 10 МГц, значит 10_000_000 тиков = 1 секунда.
const INTERVAL: u64 = 10_000_000;

/// Сколько прерываний таймера уже обработали (одно ядро — хватает Relaxed).
static TICKS: AtomicU64 = AtomicU64::new(0);

/// Запустить таймер: вооружить первое срабатывание и включить прерывания.
/// Вызывать после [`crate::trap::init`].
pub fn init() {
    arm_next();
    csr::enable_timer_interrupt(); // sie.STIE — разрешить именно таймерные
    csr::enable_interrupts(); // sstatus.SIE — глобально включить прерывания
}

/// Запрограммировать следующее срабатывание на «сейчас + INTERVAL».
fn arm_next() {
    let next = csr::read_time() + INTERVAL;
    sbi::set_timer(next);
}

/// Вызывается диспетчером trap'ов на каждое таймерное прерывание.
pub fn on_tick() {
    let n = TICKS.fetch_add(1, Ordering::Relaxed) + 1;
    println!("  [timer] тик #{} (time={})", n, csr::read_time());
    arm_next(); // перевзвести на следующую секунду
}
