//! Джиттер-источник энтропии: разброс времени исполнения на самом процессоре.
//!
//! **Зачем.** `RDRAND` появился с Ivy Bridge (2012), virtio-rng существует только под
//! гипервизором. На машине старше — например, на ASUS X54C (Sandy Bridge), которую VOID и
//! метит заменить, — нет ни того, ни другого. Без этого модуля там не на чем строить ключи TLS,
//! и HTTPS был бы театром. Так делали до `RDRAND` все и так до сих пор делает Linux
//! (jitterentropy Мюллера): источником служит сам процессор.
//!
//! **Откуда берётся случайность.** Время выполнения одной и той же последовательности команд
//! не постоянно: промахи кэша, предсказатель переходов, буферы записи, состояние TLB, обновление
//! DRAM, прерывания. Разброс младших битов счётчика ТАКТОВ между повторами не воспроизводится —
//! ни программой, ни наблюдателем снаружи. Мы измеряем именно разброс (`delta`), а не время.
//!
//! **Что здесь НЕ утверждается.** Это не сертифицированная по NIST SP 800-90B оценка энтропии —
//! такая оценка требует отдельной дисциплины и валидации на конкретном железе. И тесты ниже
//! ловят не «слабый» источник, а **вставший**: счётчик не идёт, дельты перестали различаться,
//! машина оказалась полностью детерминированной. Это осознанная граница: катастрофический отказ
//! обязан быть замечен, а тонкая оценка качества — отдельная работа. Пока тесты не пройдены,
//! система честно считает, что сильного источника нет ([`crate::random::has_strong_source`]);
//! и джиттер никогда не бывает ЕДИНСТВЕННЫМ входом — он смешивается с остальными в `random`.
//!
//! **Измерено (QEMU, обе арх).** Среди 256 отсчётов различных младших байтов дельт: x86 — 52–74,
//! riscv — 54–55; дельты на x86 гуляют в тысячах тактов, на riscv жмутся к 1850–2050. Разброс
//! под эмуляцией У́ЖЕ, чем будет на железе: TCG детерминированнее живого конвейера с кэшами и
//! обновлением DRAM. То есть проверка шла в ХУДШИХ условиях, чем целевые, — и прошла.
//!
//! **Осторожно с оптимизатором.** Всё измеряемое обязано пережить оптимизацию: пустой цикл
//! компилятор выбросит, а вместе с ним и весь источник. Отсюда `black_box` и запись в память,
//! которую нельзя доказать мёртвой.

use core::sync::atomic::{AtomicBool, AtomicU64, Ordering};

use void_abi::ContentId;

use crate::arch;

/// Размер рабочей области, которую топчет измеряемая нагрузка. Должна заметно превышать L1,
/// чтобы промахи кэша реально случались; 64 КиБ — компромисс между этим и ценой прогона.
const WORK_BYTES: usize = 64 * 1024;

/// Сколько отсчётов собираем в одно слово энтропии. Каждый даёт заведомо меньше бита, поэтому
/// берём с большим запасом и сжимаем хэшем.
const SAMPLES: usize = 256;

/// Тест повторов (SP 800-90B): столько одинаковых дельт подряд означают, что источник встал
/// (счётчик не идёт, машина детерминирована). Порог намеренно мал — лучше отказать, чем
/// выдать предсказуемое.
const REPETITION_LIMIT: usize = 8;

/// Тест адаптивной пропорции: в окне из [`SAMPLES`] отсчётов одно значение не должно занимать
/// больше этой доли. Ловит «дельта почти всегда одна и та же» — вырожденный источник.
const PROPORTION_LIMIT: usize = SAMPLES / 2;

/// Рабочая область. `static mut` намеренно: нагрузка обязана ходить по настоящей памяти, а не
/// по регистрам, и жить всё время работы ядра. Доступ — только из этого модуля, под замком
/// вызывающего ([`crate::random`] зовёт нас из одного места).
static mut WORK: [u8; WORK_BYTES] = [0; WORK_BYTES];

/// Прошёл ли источник санитарные тесты хотя бы раз.
static HEALTHY: AtomicBool = AtomicBool::new(false);
/// Проверяли ли уже.
static CHECKED: AtomicBool = AtomicBool::new(false);
/// Накопитель между вызовами — чтобы соседние слова не выводились одно из другого.
static ACC: AtomicU64 = AtomicU64::new(0x243f_6a88_85a3_08d3);

/// Одна измеряемая нагрузка: пройтись по области с шагом, который гарантированно промахивается
/// мимо кэш-линии, и что-то с данными сделать. Возвращает число тактов, которое это заняло.
///
/// `#[inline(never)]` не случайно: встроенная в цикл сбора нагрузка могла бы быть переупорядочена
/// вокруг чтений счётчика, и мы измеряли бы не её.
#[inline(never)]
fn workload(seed: u64) -> u64 {
    let Some(t0) = arch::now_cycles() else { return 0 };
    let mut x = seed | 1;
    unsafe {
        let p = core::ptr::addr_of_mut!(WORK) as *mut u8;
        // 64 шага по псевдослучайным смещениям: линейный проход префетчер бы предсказал.
        for _ in 0..64 {
            x = x.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407);
            let off = (x >> 33) as usize % WORK_BYTES;
            let v = core::ptr::read_volatile(p.add(off));
            core::ptr::write_volatile(p.add(off), v.wrapping_add(1));
        }
    }
    let t1 = arch::now_cycles().unwrap_or(t0);
    core::hint::black_box(x);
    t1.wrapping_sub(t0)
}

/// Собрать `SAMPLES` дельт и проверить их санитарными тестами. Возвращает хэш от собранного
/// либо `None`, если источник не прошёл проверку.
fn collect() -> Option<u64> {
    arch::now_cycles()?; // счётчика тактов нет — источника нет
    let mut buf = [0u8; SAMPLES * 2];
    let mut prev = 0u64;
    let mut repeats = 0usize;
    // Для теста пропорции хватает счёта самого частого значения среди младших байтов дельт:
    // вырожденный источник виден именно там.
    let mut counts = [0u16; 256];
    let mut ok = false;

    let mut seed = ACC.load(Ordering::Relaxed) ^ arch::now_ticks();
    for i in 0..SAMPLES {
        seed = seed.wrapping_mul(0x2545_f491_4f6c_dd1d).wrapping_add(i as u64);
        let d = workload(seed);
        // Берём два младших байта дельты: старшие предсказуемы (общая длительность нагрузки),
        // случайность живёт в младших.
        buf[i * 2] = d as u8;
        buf[i * 2 + 1] = (d >> 8) as u8;
        counts[d as u8 as usize] += 1;

        if d == prev {
            repeats += 1;
            if repeats >= REPETITION_LIMIT {
                return None; // источник встал: дельты перестали различаться
            }
        } else {
            repeats = 0;
            ok = true; // хоть какое-то различие видели
        }
        prev = d;
    }
    if !ok || counts.iter().any(|&c| c as usize > PROPORTION_LIMIT) {
        return None; // вырожденное распределение — доверять нечему
    }

    let mut seedbuf = [0u8; SAMPLES * 2 + 8];
    seedbuf[..SAMPLES * 2].copy_from_slice(&buf);
    seedbuf[SAMPLES * 2..].copy_from_slice(&ACC.load(Ordering::Relaxed).to_le_bytes());
    let h = ContentId::hash(&seedbuf).0;
    let mut w = [0u8; 8];
    w.copy_from_slice(&h[..8]);
    let word = u64::from_le_bytes(w);
    ACC.store(ACC.load(Ordering::Relaxed) ^ word.rotate_left(23), Ordering::Relaxed);
    Some(word)
}

/// Проверить источник на загрузке. Дорого (несколько прогонов), поэтому зовётся один раз.
/// `true` — тесты пройдены и на джиттер можно опираться.
pub fn init() -> bool {
    // Два независимых сбора: одиночный успех мог быть случайностью, а нам нужно утверждение.
    let healthy = collect().is_some() && collect().is_some();
    HEALTHY.store(healthy, Ordering::Relaxed);
    CHECKED.store(true, Ordering::Relaxed);
    healthy
}

/// Прошёл ли источник проверку (после [`init`]).
pub fn healthy() -> bool {
    CHECKED.load(Ordering::Relaxed) && HEALTHY.load(Ordering::Relaxed)
}

/// Слово энтропии от джиттера. `None` — источник не проверен или прямо сейчас не прошёл тесты
/// (это не ошибка: значит именно в этот момент доверять ему нельзя).
pub fn next_u64() -> Option<u64> {
    healthy().then(collect).flatten()
}
