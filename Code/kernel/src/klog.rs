//! Журнал ядра — кольцо последних сообщений (Веха 116).
//!
//! ## Зачем
//!
//! До этой вехи всё, что печатает ядро, существовало ровно один миг. На QEMU это терпимо
//! (сообщения оседают в serial-логе), а на реальной машине — нет: **у ноутбука нет COM-порта**,
//! и как только терминал забирает экран (Веха 97), вывод ядра уходит в никуда. Владелец видел
//! строки загрузки ровно до первого кадра `term` и не мог их перечитать — включая те, где
//! написано, какой шрифт взят и с какой скоростью работает экран.
//!
//! Теперь всё напечатанное попадает ещё и сюда, а `bin/klog` показывает это обратно.
//!
//! ## Почему кольцо, а не «весь журнал»
//!
//! Память ядра конечна, а поток сообщений — нет: один `pkg update` печатает сотни строк.
//! Кольцо даёт постоянную цену (64 КиБ) и теряет СТАРОЕ, а не новое — при разборе неполадки
//! ценны последние строки. Сколько потеряно, считается и говорится вслух: «журнал начинается не
//! с начала» — это факт, о котором читатель обязан знать.
//!
//! ## Что сюда НЕ попадает
//!
//! Вывод программ, идущий в панель терминала по stdio ([[process-stdio]]): он и так на экране, а
//! дублировать его в журнал ядра значило бы смешать «что делала система» с «что печатала
//! программа». В журнал попадает то, что прошло через консоль ядра, — включая `SYS_WRITE`
//! программ, у которых хоста stdio нет (например, диагностика `term` до первого кадра).

use core::sync::atomic::{AtomicBool, AtomicUsize, Ordering};

/// Веха 239 — **каждая строка журнала помечается временем**, и только здесь, а не в консоли.
///
/// Разделение нарочное: консоль читает человек, который смотрит на загрузку, — ему время не
/// нужно, он его и так видит. Журнал читают, когда что-то пошло не так, и первый вопрос к нему
/// всегда «сколько это заняло». До этой вехи ответа не было вовсе: на живой машине ядро
/// сообщало одно число на всю загрузку (18.3 с на X54C), и внутри него не различались ни
/// перечисление USB, ни посев программ, ни подъём экрана.
///
/// Отметка идёт от входа в ЯДРО ([`crate::clock::since_entry_ns`]), а не от включения питания:
/// POST прошивки и загрузчик — не наша работа, и записывать их себе было бы неправдой.
///
/// Ёмкость кольца. 64 КиБ — это около 800 строк, то есть вся загрузка с запасом.
const CAP: usize = 64 * 1024;

static mut BUF: [u8; CAP] = [0; CAP];
/// Сколько байт всего прошло через журнал (не сбрасывается). Разность с `CAP` даёт потерянное.
static WRITTEN: AtomicUsize = AtomicUsize::new(0);
/// Стоим ли в начале строки — то есть получит ли следующий байт отметку времени. Защищён тем же
/// замком вывода, что и [`WRITTEN`]: писатель здесь один (см. [`push`]).
static AT_LINE_START: AtomicBool = AtomicBool::new(true);

// ─── журнал, переживающий перезагрузку (Веха 243.5) ──────────────────────────
//
// ## Зачем
//
// Журнал в кольце живёт ровно до перезагрузки — и это оказалось стеной. На живой машине
// владельца пробуждение из сна оставляло мёртвый экран и мёртвый USB: система, возможно, и
// работала, но СКАЗАТЬ об этом ей было нечем, а прочитать её журнал было негде. Всякая
// неполадка, которая убивает экран, убивает и способ о ней узнать.
//
// Лечение простое и старое (у Linux это `ramoops`): держать кольцо в памяти, которую НИКТО не
// раздаёт, и на следующей загрузке проверить, не лежит ли там журнал прошлой жизни. Память
// переживает тёплую перезагрузку — ту, что без снятия питания.
//
// ## Где эта память
//
// Хвост самого верхнего региона карты ([`crate::frame::carve_persist`]). Хвост — потому что он
// постоянен: карта у машины одна и та же, значит и адрес тот же. Знать, ГДЕ лежит журнал, не
// менее важно, чем сохранить сами байты.
//
// ## Что лежит в начале
//
// Шапка: слово-примета, длина и позиция записи. Примета отвечает на главный вопрос — журнал
// это или мусор, оставшийся от чего угодно другого: холодный старт стирает память не всегда и
// не целиком, и принять случайные байты за журнал было бы хуже, чем не иметь его вовсе.

/// Сколько памяти просить под сохранённый журнал: шапка плюс кольцо.
pub const PERSIST_BYTES: usize = HDR + CAP;

/// Примета в начале сохранённого журнала: «здесь журнал VOID».
const MAGIC: u64 = 0x564f_4944_4c4f_4701; // "VOIDLOG"

/// Адрес сохранённого кольца (VA прямой карты) — 0, если отрезать память не вышло.
static PERSIST: AtomicUsize = AtomicUsize::new(0);
/// Сколько байт прошлого журнала удалось снять (0 — прошлого журнала нет).
static PREV_LEN: AtomicUsize = AtomicUsize::new(0);
/// Копия прошлого журнала. В `.bss`, а не в сохранённой памяти: ту мы тут же начинаем
/// переписывать своей, а прошлую хотим отдать целиком и спокойно.
static mut PREV: [u8; CAP] = [0; CAP];

/// Шапка сохранённого журнала: примета и сколько байт всего прошло через кольцо.
const HDR: usize = 16;

/// Веха 243.5 — принять память под журнал, переживающий перезагрузку, и снять с неё прошлый.
///
/// Зовётся на загрузке, сразу как стали известны регионы RAM. `va` — начало отрезанного куска
/// в прямой карте, `len` — его длина (шапка плюс кольцо).
/// Найти зеркало ПРОШЛОЙ жизни. Сперва там, куда положили сейчас, затем по страницам рядом:
/// пересборка ядра сдвигает место, а журнал от этого терять нельзя.
fn find_prev(va: usize) -> Option<usize> {
    const STEP: usize = 4096;
    const REACH: usize = 512; // по два мегабайта в каждую сторону
    unsafe {
        if core::ptr::read_volatile(va as *const u64) == MAGIC {
            return Some(va);
        }
        for i in 1..=REACH {
            for cand in [va + i * STEP, va.wrapping_sub(i * STEP)] {
                // Вниз — не дальше, чем на отведённые два мегабайта, и не в нулевые адреса:
                // там прямой карты может не быть вовсе.
                if cand < STEP {
                    continue;
                }
                if core::ptr::read_volatile(cand as *const u64) == MAGIC
                    && core::ptr::read_volatile((cand + 8) as *const u64) as usize <= CAP
                {
                    return Some(cand);
                }
            }
        }
    }
    None
}

pub fn adopt_persistent(va: usize, len: usize) {
    if len < HDR + CAP {
        return;
    }
    // ГДЕ ИСКАТЬ ПРОШЛЫЙ ЖУРНАЛ. Зеркало лежит сразу за образом ядра, а образ от сборки к
    // сборке меняет размер — значит после пересборки место уезжает, и прошлый журнал
    // оказывается «ничей». Ровно так он и пропал у владельца в самый нужный заход.
    //
    // Поэтому ищем отметку рядом: страница за страницей на два мегабайта вниз и вверх. Это
    // тысяча чтений, то есть ничто, а взамен журнал переживает пересборку ядра.
    let src = find_prev(va).unwrap_or(va);
    unsafe {
        let magic = core::ptr::read_volatile(src as *const u64);
        let written = core::ptr::read_volatile((src + 8) as *const u64) as usize;
        if magic == MAGIC && written > 0 {
            // Прошлая жизнь оставила журнал — снять его, пока не затёрли своим.
            let have = written.min(CAP);
            let start = written - have;
            let ring = (src + HDR) as *const u8;
            let prev = &raw mut PREV as *mut u8;
            for i in 0..have {
                core::ptr::write(prev.add(i), core::ptr::read_volatile(ring.add((start + i) % CAP)));
            }
            PREV_LEN.store(have, Ordering::Relaxed);
        }
        core::ptr::write_volatile(va as *mut u64, MAGIC);
        core::ptr::write_volatile((va + 8) as *mut u64, 0);
    }
    PERSIST.store(va, Ordering::Relaxed);
    // Перенести в зеркало то, что уже напечатано ДО его появления: баннер, карту памяти,
    // экран. Иначе сохранённый журнал начинается с мусора — тех байт, которых мы не писали, —
    // и читатель первым делом решает, что он битый (так и вышло у владельца).
    let have = WRITTEN.load(Ordering::Relaxed).min(CAP);
    unsafe {
        for i in 0..have {
            core::ptr::write_volatile((va + HDR + i) as *mut u8, BUF[i]);
        }
        core::ptr::write_volatile((va + 8) as *mut u64, have as u64);
    }
    FLUSHED.store(0, Ordering::Relaxed);
    flush_persist(va, have);
}

/// Сколько байт прошлого журнала сохранилось (0 — прошлого нет).
pub fn prev_len() -> usize {
    PREV_LEN.load(Ordering::Relaxed)
}

/// Отдать журнал ПРОШЛОЙ загрузки. Возвращает, сколько скопировано.
pub fn read_prev(out: &mut [u8]) -> usize {
    let have = prev_len();
    let n = have.min(out.len());
    let from = have - n; // при нехватке места отдаём ХВОСТ: свежее важнее
    unsafe {
        let prev = &raw const PREV as *const u8;
        for i in 0..n {
            out[i] = core::ptr::read(prev.add(from + i));
        }
    }
    n
}

/// Добавить байты в журнал.
///
/// # Safety
/// Единственный писатель — `_print`, и он держит замок вывода ([`crate::OUT`]). Веха 170: до неё
/// хватало запрета прерываний, потому что исполнение было одно; теперь запрет прерываний ничего
/// не говорит о соседнем ядре, и общий с консолью замок — единственное, что здесь работает.
pub fn push(bytes: &[u8]) {
    let mut at = WRITTEN.load(Ordering::Relaxed);
    for &b in bytes {
        // Пустую строку не помечаем: отметка у строки без текста говорила бы о времени
        // печати перевода строки, а не о времени события.
        if AT_LINE_START.load(Ordering::Relaxed) && b != b'\n' {
            at = stamp(at);
        }
        at = put(at, b);
        AT_LINE_START.store(b == b'\n', Ordering::Relaxed);
    }
    WRITTEN.store(at, Ordering::Relaxed);
    let p = PERSIST.load(Ordering::Relaxed);
    if p != 0 {
        unsafe { core::ptr::write_volatile((p + 8) as *mut u64, at as u64) };
    }
}

/// Положить в кольцо отметку начала строки — `[   12.345] ` — и вернуть новую позицию.
///
/// Форматируется руками, а не через `write!`: `core::fmt` пришёл бы сюда же через [`Tee`], и
/// отметка получила бы отметку. Ширина полей постоянная — журнал читают столбцом.
fn stamp(mut at: usize) -> usize {
    let ms = crate::clock::since_entry_ns() / 1_000_000;
    // 99999 с — 27 часов; дольше работающая машина получит время «не меньше этого», а не
    // съехавшие столбцы. Кольцо всё равно хранит только последние строки.
    let secs = (ms / 1000).min(99_999);
    let frac = ms % 1000;
    let mut buf = [b' '; 11];
    buf[0] = b'[';
    let mut i = 5; // позиция последней цифры секунд: цифры кладутся справа налево
    let mut v = secs;
    loop {
        buf[i] = b'0' + (v % 10) as u8;
        v /= 10;
        if v == 0 || i == 1 {
            break;
        }
        i -= 1;
    }
    buf[6] = b'.';
    buf[7] = b'0' + (frac / 100) as u8;
    buf[8] = b'0' + (frac / 10 % 10) as u8;
    buf[9] = b'0' + (frac % 10) as u8;
    buf[10] = b']';
    for &b in buf.iter().chain(b" ".iter()) {
        at = put(at, b);
    }
    at
}

/// Положить байт в кольцо И в его зеркало, переживающее перезагрузку.
///
/// Отдельной функцией, потому что писать в оба места надо ВЕЗДЕ: первая версия зеркалила
/// только строки, а отметку времени писала мимо — и сохранённый журнал приехал с мусором
/// вместо каждой отметки. Одна дверь вместо двух — чтобы такого больше не вышло.
#[inline]
fn put(at: usize, b: u8) -> usize {
    unsafe { BUF[at % CAP] = b };
    let p = PERSIST.load(Ordering::Relaxed);
    if p != 0 {
        unsafe { core::ptr::write_volatile((p + HDR + at % CAP) as *mut u8, b) };
        // Конец строки — вытолкнуть написанное в ПАМЯТЬ. Без этого зеркало живёт в кэше, а
        // кэш не переживает ни зависания, ни снятия питания: после жёсткой перезагрузки
        // журнал обрывался на том месте, до которого процессор СЛУЧАЙНО успел выгрузить
        // строки, — и это стоило нам нескольких заходов разбора вслепую (24.11). Хуже того,
        // счётчик в заголовке мог выгрузиться позже данных, и журнал выглядел длиннее, чем
        // был, — хвост читался как мусор.
        if b == b'\n' || at.wrapping_sub(FLUSHED.load(Ordering::Relaxed)) >= 512 {
            flush_persist(p, at.wrapping_add(1));
        }
    }
    at.wrapping_add(1)
}

/// Докуда зеркало вытолкнуто в память (а не осело в кэше).
static FLUSHED: AtomicUsize = AtomicUsize::new(0);

/// Вытолкнуть в память всё зеркало до позиции `upto` и заголовок при нём.
///
/// Заголовок — ОБЯЗАТЕЛЬНО вместе с данными и ПОСЛЕ них: он говорит, сколько байт считать
/// настоящими, и если он уйдёт в память раньше хвоста, читатель примет за журнал то, чего
/// никто не писал.
fn flush_persist(p: usize, upto: usize) {
    let from = FLUSHED.swap(upto, Ordering::Relaxed);
    if upto.wrapping_sub(from) > CAP {
        // Отстали больше, чем вмещает кольцо, — вытолкнуть его целиком.
        return flush_range(p, upto.wrapping_sub(CAP), upto);
    }
    flush_range(p, from, upto);
}

fn flush_range(p: usize, from: usize, upto: usize) {
    #[cfg(target_arch = "x86_64")]
    unsafe {
        use core::arch::x86_64::{_mm_clflush, _mm_sfence};
        let mut pos = from;
        while pos < upto {
            let a = p + HDR + pos % CAP;
            _mm_clflush(a as *const u8);
            // До конца этой линии кэша — остальные байты в ней уже накрыты.
            pos += 64 - a % 64;
        }
        _mm_clflush(p as *const u8);
        _mm_sfence();
    }
    #[cfg(not(target_arch = "x86_64"))]
    {
        let _ = (p, from, upto);
        core::sync::atomic::fence(Ordering::SeqCst);
    }
}

/// Сколько байт потеряно вытеснением (0 — журнал с самого начала загрузки).
pub fn lost() -> usize {
    WRITTEN.load(Ordering::Relaxed).saturating_sub(CAP)
}

/// Скопировать журнал в буфер, начиная с самого старого доступного байта. Возвращает,
/// сколько скопировано; если буфер меньше журнала, отдаются ПОСЛЕДНИЕ байты (свежее важнее).
pub fn read(out: &mut [u8]) -> usize {
    // Веха 170 — под тем же замком, что и запись: читателя зовёт системный вызов (то есть другое
    // ядро, чем то, что сейчас печатает), и копия из-под пишущей руки — это гонка за данные,
    // а не «немного устаревший журнал».
    let _out = crate::OUT.lock();
    let total = WRITTEN.load(Ordering::Relaxed);
    let have = total.min(CAP);
    let n = have.min(out.len());
    let start = total - n; // абсолютная позиция первого отдаваемого байта
    for i in 0..n {
        out[i] = unsafe { BUF[(start + i) % CAP] };
    }
    n
}

/// Приёмник `core::fmt` — чтобы `_print` писал в журнал тем же вызовом, что и в консоль.
pub struct Tee;

impl core::fmt::Write for Tee {
    fn write_str(&mut self, s: &str) -> core::fmt::Result {
        push(s.as_bytes());
        Ok(())
    }
}
