//! Журнал ядра — кольцо последних сообщений (Веха 116).
//!
//! ## Зачем
//!
//! До этой вехи всё, что печатает ядро, существовало ровно один миг. На QEMU это терпимо
//! (сообщения оседают в serial-логе), а на реальной машине — нет: **у ноутбука нет COM-порта**,
//! и как только терминал забирает экран (Веха 97), вывод ядра уходит в никуда. Владелец видел
//! строки загрузки ровно до первого кадра `term` и не мог их перечитать — включая те, где
//! написано, какой шрифт взят и с какой скоростью работает экран.
//!
//! Теперь всё напечатанное попадает ещё и сюда, а `bin/klog` показывает это обратно.
//!
//! ## Почему кольцо, а не «весь журнал»
//!
//! Память ядра конечна, а поток сообщений — нет: один `pkg update` печатает сотни строк.
//! Кольцо даёт постоянную цену (64 КиБ) и теряет СТАРОЕ, а не новое — при разборе неполадки
//! ценны последние строки. Сколько потеряно, считается и говорится вслух: «журнал начинается не
//! с начала» — это факт, о котором читатель обязан знать.
//!
//! ## Что сюда НЕ попадает
//!
//! Вывод программ, идущий в панель терминала по stdio ([[process-stdio]]): он и так на экране, а
//! дублировать его в журнал ядра значило бы смешать «что делала система» с «что печатала
//! программа». В журнал попадает то, что прошло через консоль ядра, — включая `SYS_WRITE`
//! программ, у которых хоста stdio нет (например, диагностика `term` до первого кадра).

use core::sync::atomic::{AtomicUsize, Ordering};

/// Ёмкость кольца. 64 КиБ — это около 800 строк, то есть вся загрузка с запасом.
const CAP: usize = 64 * 1024;

static mut BUF: [u8; CAP] = [0; CAP];
/// Сколько байт всего прошло через журнал (не сбрасывается). Разность с `CAP` даёт потерянное.
static WRITTEN: AtomicUsize = AtomicUsize::new(0);

/// Добавить байты в журнал. Зовётся из `_print` с ВЫКЛЮЧЕННЫМИ прерываниями — гонок нет.
///
/// # Safety
/// Единственный писатель — `_print` под `irq_save_disable`; читатель ([`read`]) копирует под тем
/// же условием.
pub fn push(bytes: &[u8]) {
    let mut at = WRITTEN.load(Ordering::Relaxed);
    for &b in bytes {
        unsafe { BUF[at % CAP] = b };
        at = at.wrapping_add(1);
    }
    WRITTEN.store(at, Ordering::Relaxed);
}

/// Сколько байт потеряно вытеснением (0 — журнал с самого начала загрузки).
pub fn lost() -> usize {
    WRITTEN.load(Ordering::Relaxed).saturating_sub(CAP)
}

/// Скопировать журнал в буфер, начиная с самого старого доступного байта. Возвращает,
/// сколько скопировано; если буфер меньше журнала, отдаются ПОСЛЕДНИЕ байты (свежее важнее).
pub fn read(out: &mut [u8]) -> usize {
    let total = WRITTEN.load(Ordering::Relaxed);
    let have = total.min(CAP);
    let n = have.min(out.len());
    let start = total - n; // абсолютная позиция первого отдаваемого байта
    for i in 0..n {
        out[i] = unsafe { BUF[(start + i) % CAP] };
    }
    n
}

/// Приёмник `core::fmt` — чтобы `_print` писал в журнал тем же вызовом, что и в консоль.
pub struct Tee;

impl core::fmt::Write for Tee {
    fn write_str(&mut self, s: &str) -> core::fmt::Result {
        push(s.as_bytes());
        Ok(())
    }
}
