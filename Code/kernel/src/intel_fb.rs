//! Веха 233 — **переключение страницы на графике Intel** (Sandy Bridge и родня).
//!
//! ## Что это чинит
//!
//! На машине владельца кадр рвётся, и причина теперь известна точно, а не предположительно:
//! буфер один. Композитор пишет пиксели ровно в ту память, из которой прямо сейчас читает
//! развёртка, — и граница между старым и новым кадром видна глазом ([[intel-display]]).
//!
//! ## Что показала разведка (прогоны владельца 14.11.2026)
//!
//! ```text
//! кадр от GRUB      0xc0000000  — это АПЕРТУРА (BAR2), а не обычная память
//! плоскость A       поверхность = смещение 0x0 в таблице GTT
//! запись GTT #0     0xbc000001 → страница 0xbc000000 (начало украденной памяти)
//! записи #768…#8192 0xbc300001 … 0xbe000001 — украденная память отображена ЛИНЕЙНО
//! украденной памяти 64 МиБ (GGC 0x211), кадр 1024×768×4 = 3 МиБ
//! ```
//!
//! Отсюда всё и следует. Писать пиксели через апертуру по смещению 3 МиБ — значит писать в
//! страницы украденной памяти, которых развёртка сейчас не читает. А чтобы она начала их
//! читать, довольно записать это смещение в регистр поверхности: защёлкнется на обратном ходе
//! луча, то есть между кадрами. **Ни одной страницы заводить не надо** — прошивка уже отобразила
//! всю украденную память в таблицу.
//!
//! ## Почему это в ядре
//!
//! Там же, где остальной экран: кадр от загрузчика принимает `fb`, кадр virtio-gpu — `virtio_gpu`.
//! Композитору незачем знать, откуда взялся его буфер и чем он показывается ([[framebuffer]]):
//! он рисует и говорит «показать», а чем это обернётся — делом ядра. Здесь это правило и
//! держится: наружу уходит ОДНО число — смещение, по которому рисовать следующий кадр.
//!
//! ## Чего эта веха НЕ делает
//!
//! Не настраивает режим (разрешение, частота, порт — как их выставила прошивка, так и
//! остаётся), не трогает плитку (`tiling`), не работает со вторым конвейером и не притворяется
//! драйвером. Всё, на чём она стоит, проверяется при загрузке, и любая несходимость выключает
//! её целиком — с объяснением в журнале, а не молча.

#![cfg(target_arch = "x86_64")]

use core::sync::atomic::{AtomicBool, AtomicUsize, Ordering};

use crate::arch;

/// Смещения регистров от начала BAR0 — те же, что читает разведка `intel` в шелле.
mod reg {
    pub const PIPEACONF: usize = 0x70008;
    pub const DSPACNTR: usize = 0x70180;
    pub const DSPASTRIDE: usize = 0x70188;
    /// Поверхность плоскости A. Запись сюда и есть переключение страницы.
    pub const DSPASURF: usize = 0x7019c;
    /// Что развёртка читает ПРЯМО СЕЙЧАС (в отличие от [`DSPASURF`], где лежит ожидающее
    /// значение). По нему проверяется, что переключение вообще случилось.
    pub const DSPASURFLIVE: usize = 0x701ac;
    /// Плоскость КУРСОРА конвейера A: вид, адрес картинки (смещение в GTT) и положение.
    /// Отдельная плоскость — поэтому курсор и не стоит кадра: двигает его развёртка, а не мы.
    /// Счётчик кадров конвейера A: растёт на каждом обратном ходе луча.
    pub const FRMCOUNT: usize = 0x70040;
    pub const CURACNTR: usize = 0x70080;
    pub const CURABASE: usize = 0x70084;
    pub const CURAPOS: usize = 0x70088;
    /// Вид курсора: 64×64, 32 бита с альфой. Младшие шесть бит — размер и глубина, бит 5 —
    /// смешивание по альфе; ноль в этом поле выключает плоскость.
    pub const CURSOR_64_ARGB: u32 = 0x27;
}

/// Окно регистров (BAR0). Ноль — двойной буферизации нет.
static BAR0: AtomicUsize = AtomicUsize::new(0);
/// Смещение таблицы GTT внутри BAR0.
static GTT_OFF: AtomicUsize = AtomicUsize::new(0);
/// Шаг между буферами в байтах (он же смещение второго).
static STEP: AtomicUsize = AtomicUsize::new(0);
/// Смещение картинки курсора в GTT (0 — курсора нет).
static CURSOR_OFF: AtomicUsize = AtomicUsize::new(0);
/// Апертура (BAR2): через неё пишется картинка курсора — тем же путём, которым композитор
/// пишет пиксели кадра.
static APERTURE: AtomicUsize = AtomicUsize::new(0);

/// Сторона картинки курсора в точках. Железо умеет 64, 128 и 256; берём наименьшую — наш
/// указатель 12×19, и класть его в большее поле значит возить по шине пустоту.
pub const CURSOR_SIDE: usize = 64;

/// Какой буфер СЕЙЧАС на экране: 0 — первый, 1 — второй.
static SHOWN: AtomicUsize = AtomicUsize::new(0);
/// В какой буфер рисует композитор. Он же уедет на экран ближайшим переключением: показывать
/// надо нарисованное, а не следующее по счёту.
static DRAWN: AtomicUsize = AtomicUsize::new(0);
static READY: AtomicBool = AtomicBool::new(false);
/// Сколько раз переключали и видели ли мы хоть раз, что железо это приняло. Нужны для
/// САМОПРОВЕРКИ: см. [`flip`].
static FLIPS: AtomicUsize = AtomicUsize::new(0);
static ACCEPTED: AtomicBool = AtomicBool::new(false);

/// Сколько переключений ждём подтверждения, прежде чем сдаться. Тридцать — это полсекунды живой
/// анимации: обратный ход луча за это время случается наверняка (экран идёт на шестидесяти
/// герцах), а человек не успевает долго смотреть на застывший кадр, если мы ошиблись.
const TRIES: usize = 30;

/// Готова ли двойная буферизация.
pub fn present() -> bool {
    READY.load(Ordering::Relaxed)
}

/// Шаг между буферами в байтах (0 — буфер один).
pub fn step() -> usize {
    if present() { STEP.load(Ordering::Relaxed) } else { 0 }
}

/// Сколько буферов у экрана.
pub fn buffers() -> usize {
    if present() { 2 } else { 1 }
}

/// Прочитать слово регистра.
fn rd(off: usize) -> u32 {
    arch::hw_read32(BAR0.load(Ordering::Relaxed) + off)
}

/// Разобрать запись таблицы GTT шестого поколения: 4 байта, бит 0 — годна, биты 31:12 —
/// страница, биты 11:4 — её старшие биты (адреса выше 4 ГиБ).
fn gtt_page(idx: usize) -> Option<u64> {
    let pte = arch::hw_read32(BAR0.load(Ordering::Relaxed) + GTT_OFF.load(Ordering::Relaxed) + idx * 4);
    // Все единицы — это не отображение, а непрограммированная память: бит годности там тоже
    // стоит, и принять такую запись за настоящую значило бы поверить мусору.
    if pte == u32::MAX || pte & 1 == 0 {
        return None;
    }
    Some((pte as u64 & 0xffff_f000) | ((pte as u64 & 0xff0) << 28))
}

/// Найти встроенную графику Intel на нулевой шине: вендор `8086` и класс «дисплей».
fn find() -> Option<u16> {
    for dev in 0..32u16 {
        let bdf = dev << 3;
        let id = arch::pci_cfg_read32(bdf, 0);
        if id == u32::MAX || id & 0xffff != 0x8086 {
            continue;
        }
        if arch::pci_cfg_read32(bdf, 0x08) >> 24 == 0x03 {
            return Some(bdf);
        }
    }
    None
}

/// 64-битное окно памяти по смещению `off` в конфигурации PCI.
fn bar(bdf: u16, off: u8) -> usize {
    let lo = arch::pci_cfg_read32(bdf, off);
    let hi = arch::pci_cfg_read32(bdf, off + 4);
    ((hi as usize) << 32) | (lo as usize & !0xf)
}

/// Подготовить двойную буферизацию. Зовётся один раз на загрузке, ПОСЛЕ того как принят кадр.
///
/// `fb_phys` — физический адрес кадра, каким его отдал загрузчик; `pitch` и `height` — его
/// геометрия. Возвращает `true`, если всё сошлось и переключать страницу теперь есть чем.
///
/// Проверок много, и ни одна не лишняя: каждая отвечает за своё предположение, и провал любого
/// означает, что мы понимаем железо хуже, чем думаем. В этом случае система работает как
/// работала — одним буфером, — а в журнале стоит строка с причиной.
pub fn init(fb_phys: usize, pitch: usize, height: usize) -> bool {
    let Some(bdf) = find() else { return false };
    let bar0 = bar(bdf, 0x10);
    let aperture = bar(bdf, 0x18);
    if bar0 == 0 || aperture == 0 {
        crate::println!("  [intel] окна регистров не прочитались — двойного буфера нет");
        return false;
    }
    // Кадр обязан быть НАЧАЛОМ АПЕРТУРЫ: только тогда наши записи идут через ту же таблицу GTT,
    // по которой читает развёртка, и смещение в окне равно смещению в таблице.
    if fb_phys != aperture {
        crate::println!(
            "  [intel] кадр {:#x} не совпал с апертурой {:#x} — двойного буфера нет",
            fb_phys, aperture,
        );
        return false;
    }
    // Размер таблицы GTT из GGC хоста моста (00:00.0 +0x50): биты 9:8. Таблица лежит во второй
    // половине BAR0, поэтому её размер — он же смещение.
    let ggc = arch::pci_cfg_read32(0, 0x50);
    let gtt_mib = match (ggc >> 8) & 3 {
        1 => 1,
        2 => 2,
        _ => {
            crate::println!("  [intel] размер таблицы GTT неизвестен (GGC {:#x})", ggc);
            return false;
        }
    };
    let gtt_off = gtt_mib * 1024 * 1024;
    // Украденной памяти должно хватить на два кадра. GMS (биты 7:3) считает её тридцатью
    // двумя мегабайтами на единицу.
    let stolen = (((ggc >> 3) & 0x1f) as usize) * 32 * 1024 * 1024;
    BAR0.store(bar0, Ordering::Relaxed);
    GTT_OFF.store(gtt_off, Ordering::Relaxed);

    let frame = pitch * height;
    let step = (frame + 0xfff) & !0xfff;
    if stolen < step * 2 {
        crate::println!(
            "  [intel] украденной памяти {} МиБ — на два кадра по {} КиБ не хватает",
            stolen / (1024 * 1024),
            step / 1024,
        );
        return false;
    }

    // Развёртка обязана быть включена и настроена так, как мы собираемся ей подсовывать кадр.
    let conf = rd(reg::PIPEACONF);
    let cntr = rd(reg::DSPACNTR);
    let stride = rd(reg::DSPASTRIDE) as usize;
    let surf = rd(reg::DSPASURF) as usize;
    let format = (cntr >> 26) & 0xf;
    if conf & (1 << 31) == 0 || cntr & (1 << 31) == 0 {
        crate::println!("  [intel] конвейер или плоскость выключены — двойного буфера нет");
        return false;
    }
    if format != 0x6 || cntr & (1 << 10) != 0 || stride != pitch || surf != 0 {
        crate::println!(
            "  [intel] плоскость не та, что ожидалось: формат {:#x}, плитка {}, шаг {} (у кадра {}), поверхность {:#x}",
            format,
            (cntr >> 10) & 1,
            stride,
            pitch,
            surf,
        );
        return false;
    }

    // И главное: страницы ВТОРОГО буфера должны быть отображены в таблицу и не совпадать с
    // первым. Проверяем каждую — их меньше тысячи, а цена ошибки это чужие пиксели на экране.
    let first_page = step / 4096;
    let pages = (frame + 0xfff) / 4096;
    let front_lo = gtt_page(0).unwrap_or(0);
    let front_hi = front_lo + frame as u64;
    for i in 0..pages {
        let Some(page) = gtt_page(first_page + i) else {
            crate::println!(
                "  [intel] запись GTT #{} не отображена — второго буфера в памяти нет",
                first_page + i,
            );
            return false;
        };
        if page >= front_lo && page < front_hi {
            crate::println!(
                "  [intel] запись GTT #{} ведёт в сам кадр ({:#x}) — буферы наложились бы",
                first_page + i,
                page,
            );
            return false;
        }
    }

    STEP.store(step, Ordering::Relaxed);
    SHOWN.store(0, Ordering::Relaxed);
    APERTURE.store(aperture, Ordering::Relaxed);
    READY.store(true, Ordering::Relaxed);
    // Место под картинку курсора — сразу за обоими кадрами. Требования те же: записи таблицы
    // отображены и ведут не в кадр. Не сошлось — курсора в железе не будет, а кадры останутся:
    // это разные вещи, и валить одну из-за другой незачем.
    let cursor_off = step * 2;
    let cursor_pages = (CURSOR_SIDE * CURSOR_SIDE * 4).div_ceil(4096);
    if stolen >= cursor_off + cursor_pages * 4096
        && (0..cursor_pages).all(|i| {
            gtt_page(cursor_off / 4096 + i).is_some_and(|page| page < front_lo || page >= front_hi)
        })
    {
        CURSOR_OFF.store(cursor_off, Ordering::Relaxed);
    }
    crate::println!(
        "  [intel] двойная буферизация: второй кадр по смещению {:#x} ({} КиБ), украденной памяти {} МиБ, курсор {}",
        step,
        step / 1024,
        stolen / (1024 * 1024),
        if CURSOR_OFF.load(Ordering::Relaxed) != 0 { "аппаратный" } else { "НЕТ (рисует композитор)" },
    );
    true
}

/// Показать НАРИСОВАННОЕ и вернуть смещение, по которому рисовать следующий кадр.
///
/// Записанное в регистр поверхности защёлкивается на обратном ходе луча — то есть между
/// кадрами, а не посреди. В этом вся цель: разрыв становится невозможен не потому, что мы
/// успели, а потому, что переключает железо.
///
/// **Показывается именно тот буфер, в который рисовали** ([`DRAWN`]), а не «следующий по
/// кругу». Первая редакция считала, что очередь можно вывести из того, что показано сейчас, —
/// и на первом же кадре выводила на экран буфер, в который ещё никто не писал: на машине
/// владельца это была белая вспышка с точками при загрузке (содержимое украденной памяти,
/// оставшееся от прошивки).
pub fn flip() -> usize {
    if !present() {
        return 0;
    }
    let shown = SHOWN.load(Ordering::Relaxed);
    // Показываем то, во что рисовали; рисовать дальше будут в тот, что сейчас на экране.
    let drawn = DRAWN.load(Ordering::Relaxed);
    let step = STEP.load(Ordering::Relaxed);
    // САМОПРОВЕРКА. Регистр «что читает развёртка ПРЯМО СЕЙЧАС» — единственный способ узнать,
    // что переключение дошло до железа, а не осталось нашим мнением. Проверяем ДО записи: к
    // этому моменту прошлое переключение уже должно было защёлкнуться.
    //
    // Не сошлось сто двадцать раз подряд — выключаем себя и говорим об этом. Система при этом
    // работает как работала (один буфер), а не показывает человеку застывший кадр: ошибиться в
    // понимании чужого железа можно, молча оставить человека без экрана — нет.
    if !ACCEPTED.load(Ordering::Relaxed) {
        // Сверяем ТОЛЬКО переключение на ВТОРОЙ буфер: совпадение нуля с нулём не доказывает
        // ничего — ноль там и так стоял от прошивки. Первая редакция проверки принимала именно
        // его и объявляла железо исправным, ни разу ничего не проверив.
        if shown == 1 && live() == step as u32 {
            ACCEPTED.store(true, Ordering::Relaxed);
        } else if FLIPS.fetch_add(1, Ordering::Relaxed) >= TRIES {
            READY.store(false, Ordering::Relaxed);
            arch::hw_write32(BAR0.load(Ordering::Relaxed) + reg::DSPASURF, 0);
            SHOWN.store(0, Ordering::Relaxed);
            DRAWN.store(0, Ordering::Relaxed);
            crate::println!(
                "  [intel] переключение страницы до железа не дошло ({} проб) — вернулись к одному буферу",
                TRIES,
            );
            return 0;
        }
    }
    arch::hw_write32(BAR0.load(Ordering::Relaxed) + reg::DSPASURF, (drawn * step) as u32);
    SHOWN.store(drawn, Ordering::Relaxed);
    let next = 1 - drawn;
    DRAWN.store(next, Ordering::Relaxed);
    next * step
}

/// Вернуть развёртку на первый буфер. Нужно там, где экран забирает ядро: его консоль рисует
/// по началу окна, и оставить развёртку на втором буфере значило бы показывать человеку кадр,
/// в который больше никто не пишет.
pub fn to_front() {
    DRAWN.store(0, Ordering::Relaxed);
    if present() && SHOWN.swap(0, Ordering::Relaxed) != 0 {
        arch::hw_write32(BAR0.load(Ordering::Relaxed) + reg::DSPASURF, 0);
    }
}

/// Есть ли аппаратный курсор.
pub fn cursor_present() -> bool {
    present() && CURSOR_OFF.load(Ordering::Relaxed) != 0
}

/// Положить картинку курсора: `px` — 64×64 точки в формате `0xAARRGGBB`.
///
/// Пишется ЧЕРЕЗ АПЕРТУРУ — тем же путём, которым композитор пишет пиксели кадра: апертура
/// переводит адрес той же таблицей GTT, в которую мы вписали эти страницы. Отдельного
/// отображения для картинки курсора заводить не надо.
///
/// Зовётся редко (картинка меняется, когда меняется сам указатель), поэтому запись идёт
/// словами, а не блоком: шестнадцать килобайт один раз — это дешевле, чем ещё одна дорога к
/// памяти ради скорости, которой здесь никто не ждёт.
pub fn cursor_image(px: &[u32]) -> bool {
    let off = CURSOR_OFF.load(Ordering::Relaxed);
    if !cursor_present() || px.len() < CURSOR_SIDE * CURSOR_SIDE {
        return false;
    }
    let base = APERTURE.load(Ordering::Relaxed) + off;
    for (i, &p) in px.iter().take(CURSOR_SIDE * CURSOR_SIDE).enumerate() {
        arch::hw_write32(base + i * 4, p);
    }
    // Адрес картинки — он же включение плоскости: вид ставим до адреса, чтобы развёртка не
    // успела прочитать старое поле новым видом.
    arch::hw_write32(BAR0.load(Ordering::Relaxed) + reg::CURACNTR, reg::CURSOR_64_ARGB);
    arch::hw_write32(BAR0.load(Ordering::Relaxed) + reg::CURABASE, off as u32);
    true
}

/// Передвинуть курсор. Отрицательные координаты — это курсор, наполовину ушедший за левый или
/// верхний край: у железа для них отдельный бит знака, а не дополнительный код.
pub fn cursor_move(x: i32, y: i32) -> bool {
    if !cursor_present() {
        return false;
    }
    let pack = |v: i32| -> u32 {
        if v < 0 {
            (1 << 15) | ((-v) as u32 & 0x7fff)
        } else {
            v as u32 & 0x7fff
        }
    };
    let pos = (pack(y) << 16) | pack(x);
    arch::hw_write32(BAR0.load(Ordering::Relaxed) + reg::CURAPOS, pos);
    true
}

/// Спрятать курсор (ноль в поле вида выключает плоскость) или показать снова.
pub fn cursor_show(on: bool) -> bool {
    if !cursor_present() {
        return false;
    }
    let cntr = if on { reg::CURSOR_64_ARGB } else { 0 };
    arch::hw_write32(BAR0.load(Ordering::Relaxed) + reg::CURACNTR, cntr);
    if on {
        // Адрес надо повторить: плоскость, включённая заново, читает его при первом же кадре.
        let off = CURSOR_OFF.load(Ordering::Relaxed);
        arch::hw_write32(BAR0.load(Ordering::Relaxed) + reg::CURABASE, off as u32);
    }
    true
}

/// Защёлкнулось ли последнее переключение страницы.
///
/// **Зачем это наружу.** Запись в регистр поверхности — не показ, а ПРОСЬБА показать: железо
/// исполнит её на ближайшем обратном ходе луча, а до тех пор читает прежний буфер. Значит
/// рисующий, получив «рисуй дальше вот сюда», имеет право делать это не раньше, чем просьба
/// исполнилась: иначе он пишет в тот самый буфер, который сейчас на экране, — и разрыв кадра
/// возвращается, только теперь изредка и необъяснимо.
///
/// До этой вехи спасал ритм композитора (кадр в шестнадцать миллисекунд почти всегда дольше
/// ожидания), но «почти всегда» — не свойство, а везение.
pub fn latched() -> bool {
    if !present() {
        return true;
    }
    let shown = SHOWN.load(Ordering::Relaxed) * STEP.load(Ordering::Relaxed);
    live() == shown as u32
}

/// Счётчик кадров развёртки — им меряется НАСТОЯЩИЙ ритм экрана, а не наш расчётный.
pub fn vblank_count() -> u32 {
    if present() { rd(reg::FRMCOUNT) } else { 0 }
}

/// Что развёртка читает прямо сейчас. В отличие от регистра поверхности, где лежит ОЖИДАЮЩЕЕ
/// значение, этот показывает защёлкнутое — то есть настоящее положение дел.
fn live() -> u32 {
    rd(reg::DSPASURFLIVE)
}
