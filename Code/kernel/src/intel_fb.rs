//! Веха 233 — **переключение страницы на графике Intel** (Sandy Bridge и родня).
//!
//! ## Что это чинит
//!
//! На машине владельца кадр рвётся, и причина теперь известна точно, а не предположительно:
//! буфер один. Композитор пишет пиксели ровно в ту память, из которой прямо сейчас читает
//! развёртка, — и граница между старым и новым кадром видна глазом ([[intel-display]]).
//!
//! ## Что показала разведка (прогоны владельца 14.11.2026)
//!
//! ```text
//! кадр от GRUB      0xc0000000  — это АПЕРТУРА (BAR2), а не обычная память
//! плоскость A       поверхность = смещение 0x0 в таблице GTT
//! запись GTT #0     0xbc000001 → страница 0xbc000000 (начало украденной памяти)
//! записи #768…#8192 0xbc300001 … 0xbe000001 — украденная память отображена ЛИНЕЙНО
//! украденной памяти 64 МиБ (GGC 0x211), кадр 1024×768×4 = 3 МиБ
//! ```
//!
//! Отсюда всё и следует. Писать пиксели через апертуру по смещению 3 МиБ — значит писать в
//! страницы украденной памяти, которых развёртка сейчас не читает. А чтобы она начала их
//! читать, довольно записать это смещение в регистр поверхности: защёлкнется на обратном ходе
//! луча, то есть между кадрами. **Ни одной страницы заводить не надо** — прошивка уже отобразила
//! всю украденную память в таблицу.
//!
//! ## Почему это в ядре
//!
//! Там же, где остальной экран: кадр от загрузчика принимает `fb`, кадр virtio-gpu — `virtio_gpu`.
//! Композитору незачем знать, откуда взялся его буфер и чем он показывается ([[framebuffer]]):
//! он рисует и говорит «показать», а чем это обернётся — делом ядра. Здесь это правило и
//! держится: наружу уходит ОДНО число — смещение, по которому рисовать следующий кадр.
//!
//! ## Чего эта веха НЕ делает
//!
//! Не настраивает режим (разрешение, частота, порт — как их выставила прошивка, так и
//! остаётся), не трогает плитку (`tiling`), не работает со вторым конвейером и не притворяется
//! драйвером. Всё, на чём она стоит, проверяется при загрузке, и любая несходимость выключает
//! её целиком — с объяснением в журнале, а не молча.

#![cfg(target_arch = "x86_64")]

use core::sync::atomic::{AtomicBool, AtomicUsize, Ordering};

use crate::arch;

/// Смещения регистров от начала BAR0 — те же, что читает разведка `intel` в шелле.
mod reg {
    pub const PIPEACONF: usize = 0x70008;
    pub const DSPACNTR: usize = 0x70180;
    pub const DSPASTRIDE: usize = 0x70188;
    /// Поверхность плоскости A. Запись сюда и есть переключение страницы.
    pub const DSPASURF: usize = 0x7019c;
    /// Что развёртка читает ПРЯМО СЕЙЧАС (в отличие от [`DSPASURF`], где лежит ожидающее
    /// значение). По нему проверяется, что переключение вообще случилось.
    pub const DSPASURFLIVE: usize = 0x701ac;
    /// Плоскость КУРСОРА конвейера A: вид, адрес картинки (смещение в GTT) и положение.
    /// Отдельная плоскость — поэтому курсор и не стоит кадра: двигает его развёртка, а не мы.
    /// Счётчик кадров конвейера A: растёт на каждом обратном ходе луча.
    pub const FRMCOUNT: usize = 0x70040;
    /// Размер источника конвейера: `(ширина-1) << 16 | (высота-1)`. Это то, сколько точек
    /// конвейер БЕРЁТ ИЗ ПАМЯТИ, — а сколько показывает панель, говорит её развёртка.
    pub const PIPEASRC: usize = 0x6001c;
    /// Временная развёртка: активных точек и всего. Активная часть — это размер ПАНЕЛИ.
    pub const HTOTAL_A: usize = 0x60000;
    pub const VTOTAL_A: usize = 0x6000c;
    /// Масштабатор панели: он растягивает картинку конвейера, когда она меньше панели.
    pub const PF_CTL_A: usize = 0x68080;
    pub const PF_WIN_SZ_A: usize = 0x68074;
    /// Подсветка панели. У шестого и седьмого поколения её две половины: ПЕРИОД ШИМ живёт в
    /// микросхеме PCH, а УРОВЕНЬ — в регистре процессора. Путать их нельзя: запись уровня в
    /// PCH не меняет ничего (проверено на живой машине владельца).
    pub const BLC_PCH_CTL2: usize = 0xc8254;
    pub const BLC_CPU_CTL: usize = 0x48254;
    pub const BLC_CPU_CTL2: usize = 0x48250;
    /// Питание панели (PCH): состояние и управление. Веха 243.2 — нужны ПРОБУЖДЕНИЮ: после сна
    /// панель выключена, и по этим двум словам видно, выключена она или просто не светится.
    pub const PP_STATUS: usize = 0xc7200;
    pub const PP_CONTROL: usize = 0xc7204;
    pub const CURACNTR: usize = 0x70080;
    pub const CURABASE: usize = 0x70084;
    pub const CURAPOS: usize = 0x70088;
    /// Вид курсора: 64×64, 32 бита с альфой. Младшие шесть бит — размер и глубина, бит 5 —
    /// смешивание по альфе; ноль в этом поле выключает плоскость.
    pub const CURSOR_64_ARGB: u32 = 0x27;
}

/// Окно регистров (BAR0). Ноль — двойной буферизации нет.
static BAR0: AtomicUsize = AtomicUsize::new(0);
/// Смещение таблицы GTT внутри BAR0.
static GTT_OFF: AtomicUsize = AtomicUsize::new(0);
/// Шаг между буферами в байтах (он же смещение второго).
static STEP: AtomicUsize = AtomicUsize::new(0);
/// Новый размер экрана, если мы перешли на родной размер панели. Ноль в ширине — не переходили.
/// Применяет его не этот модуль, а тот, кто владеет геометрией экрана (`fb`): здесь мы знаем
/// железо, но не знаем, кто на него смотрит.
static NEW_W: AtomicUsize = AtomicUsize::new(0);
static NEW_H: AtomicUsize = AtomicUsize::new(0);
static NEW_PITCH: AtomicUsize = AtomicUsize::new(0);

/// Сколько украденной памяти у графики (байт).
static STOLEN: AtomicUsize = AtomicUsize::new(0);
/// Смещение картинки курсора в GTT (0 — курсора нет).
static CURSOR_OFF: AtomicUsize = AtomicUsize::new(0);
/// Апертура (BAR2): через неё пишется картинка курсора — тем же путём, которым композитор
/// пишет пиксели кадра.
static APERTURE: AtomicUsize = AtomicUsize::new(0);

/// Сторона картинки курсора в точках. Железо умеет 64, 128 и 256; берём наименьшую — наш
/// указатель 12×19, и класть его в большее поле значит возить по шине пустоту.
pub const CURSOR_SIDE: usize = 64;

/// Какой буфер СЕЙЧАС на экране: 0 — первый, 1 — второй.
static SHOWN: AtomicUsize = AtomicUsize::new(0);
/// В какой буфер рисует композитор. Он же уедет на экран ближайшим переключением: показывать
/// надо нарисованное, а не следующее по счёту.
static DRAWN: AtomicUsize = AtomicUsize::new(0);
static READY: AtomicBool = AtomicBool::new(false);
/// Сколько раз переключали и видели ли мы хоть раз, что железо это приняло. Нужны для
/// САМОПРОВЕРКИ: см. [`flip`].
static FLIPS: AtomicUsize = AtomicUsize::new(0);
static ACCEPTED: AtomicBool = AtomicBool::new(false);

/// Пробовать ли переходить на родной размер панели.
///
/// Включено снова (Веха 233.16): чёрная дыра на экране была НЕ в смене режима, а в композиторе
/// — быстрая строка окна молча пропускала пиксели, когда буфер клиента короче объявленного им
/// размера, а стол под окном уже не рисовался. Теперь такое место закрашивается фоном окна и
/// один раз называется в журнале.
const TRY_NATIVE: bool = true;

/// Сколько переключений ждём подтверждения, прежде чем сдаться. Тридцать — это полсекунды живой
/// анимации: обратный ход луча за это время случается наверняка (экран идёт на шестидесяти
/// герцах), а человек не успевает долго смотреть на застывший кадр, если мы ошиблись.
const TRIES: usize = 30;

/// Новый размер экрана, если мы перешли на родной размер панели. `None` — геометрия прежняя.
pub fn new_mode() -> Option<(usize, usize, usize)> {
    let w = NEW_W.load(Ordering::Relaxed);
    (w != 0).then(|| (w, NEW_H.load(Ordering::Relaxed), NEW_PITCH.load(Ordering::Relaxed)))
}

/// Готова ли двойная буферизация.
pub fn present() -> bool {
    READY.load(Ordering::Relaxed)
}

/// Эта ли машина — наша (разведка сошлась, регистры найдены). ОТДЕЛЬНО от [`present`], и
/// разделение куплено дорого: `present` означает «работает двойная буферизация», а её
/// рисующий может выключить сам ([`to_single`]). До Вехи 244.4 на этом же флаге висели
/// подсветка, аппаратный курсор и — главное — подъём панели после сна. Стоило композитору
/// один раз сказать «вернусь к одному буферу» (а он говорит это всякий раз, когда экран
/// гаснет на время модсета), как ядро начинало считать, что графики Intel тут нет вовсе:
/// после сна панель не поднимал никто.
pub fn known() -> bool {
    BAR0.load(Ordering::Relaxed) != 0
}

/// Шаг между буферами в байтах (0 — буфер один).
pub fn step() -> usize {
    if present() { STEP.load(Ordering::Relaxed) } else { 0 }
}

/// Сколько буферов у экрана.
pub fn buffers() -> usize {
    if present() { 2 } else { 1 }
}

/// Прочитать слово регистра.
/// Окно регистров устройства. Нужно соседнему модулю модсета: он пишет в те же регистры, а
/// заводить второй поиск устройства значило бы завести и второй источник правды.
pub(crate) fn bar0() -> usize {
    BAR0.load(Ordering::Relaxed)
}

fn rd(off: usize) -> u32 {
    arch::hw_read32(BAR0.load(Ordering::Relaxed) + off)
}

/// Разобрать запись таблицы GTT шестого поколения: 4 байта, бит 0 — годна, биты 31:12 —
/// страница, биты 11:4 — её старшие биты (адреса выше 4 ГиБ).
/// Сколько записей таблицы отображения храним. Хватает на оба кадра, курсор и запас:
/// 4096 страниц — это 16 МиБ видеопамяти при наших 8,4 МиБ под два кадра.
const GTT_SNAP: usize = 4096;

/// Снимок таблицы отображения графики, снятый на загрузке.
///
/// **Зачем.** Таблица переводит смещение кадра в НАСТОЯЩИЕ страницы памяти, и живёт она в
/// украденной памяти, которую сон обязан сохранить. Обязан — но у владельца после
/// пробуждения экран чёрный, а редкие точки стоят ровной решёткой с одинаковыми пропусками:
/// так выглядит ОДНА повторяющаяся страница почти-нулей вместо кадра. То есть развёртка
/// читает не туда, и переводить ей нечем (Веха 244.7).
static GTT_SAVED: crate::sync::SpinLock<[u32; GTT_SNAP]> =
    crate::sync::SpinLock::new([0; GTT_SNAP]);
static GTT_HAVE: AtomicBool = AtomicBool::new(false);

fn gtt_raw(idx: usize) -> u32 {
    arch::hw_read32(BAR0.load(Ordering::Relaxed) + GTT_OFF.load(Ordering::Relaxed) + idx * 4)
}

fn gtt_write(idx: usize, v: u32) {
    arch::hw_write32(BAR0.load(Ordering::Relaxed) + GTT_OFF.load(Ordering::Relaxed) + idx * 4, v);
}

/// Снять таблицу отображения. Зовётся на загрузке, когда она заведомо верна.
pub fn gtt_snapshot() {
    if !known() {
        return;
    }
    let mut g = GTT_SAVED.lock();
    for (i, slot) in g.iter_mut().enumerate() {
        *slot = gtt_raw(i);
    }
    GTT_HAVE.store(true, Ordering::Relaxed);
}

/// Сверить таблицу с загрузкой и вернуть, если разошлась. Отвечает числом исправленных записей.
pub fn gtt_restore() -> usize {
    if !known() || !GTT_HAVE.load(Ordering::Relaxed) {
        return 0;
    }
    let g = GTT_SAVED.lock();
    let mut bad = 0;
    let mut first = usize::MAX;
    for (i, want) in g.iter().enumerate() {
        if gtt_raw(i) != *want {
            gtt_write(i, *want);
            if first == usize::MAX {
                first = i;
            }
            bad += 1;
        }
    }
    if bad > 0 {
        crate::println!(
            "  [intel] таблица отображения после сна разошлась: {bad} записей из {GTT_SNAP}, \
             первая №{first} — вернули из снимка",
        );
    }
    bad
}

fn gtt_page(idx: usize) -> Option<u64> {
    let pte = arch::hw_read32(BAR0.load(Ordering::Relaxed) + GTT_OFF.load(Ordering::Relaxed) + idx * 4);
    // Все единицы — это не отображение, а непрограммированная память: бит годности там тоже
    // стоит, и принять такую запись за настоящую значило бы поверить мусору.
    if pte == u32::MAX || pte & 1 == 0 {
        return None;
    }
    Some((pte as u64 & 0xffff_f000) | ((pte as u64 & 0xff0) << 28))
}

/// Поколение графики Intel, раскладку регистров которого мы ЗНАЕМ.
///
/// ## Почему нельзя просто «вендор 8086 и класс дисплея»
///
/// Именно так искала первая редакция — и это был худший вид привязки к одной машине. Смещения
/// регистров, формат записи таблицы GTT, разбор размера украденной памяти — всё это у Intel
/// менялось от поколения к поколению: с восьмого запись таблицы стала восьмибайтной, у Haswell
/// переехала половина дисплейных регистров, у девятого плоскости стали универсальными. Найти
/// «какую-нибудь Intel» и начать писать по смещениям шестого поколения — значит записать
/// случайные числа в случайные регистры чужой видеокарты.
///
/// Поэтому поддержка объявляется СПИСКОМ, а не догадкой: знаем — работаем, не знаем — честно
/// говорим об этом в журнале и оставляем систему с одним буфером. Расширяется список одной
/// строкой, когда появится машина, на которой это проверено.
///
/// Проверки устройства этим не отменяются: даже на знакомом поколении мы сверяем кадр с
/// апертурой, плоскость с нашим шагом строки и каждую запись таблицы — потому что «знаем
/// поколение» и «эта конкретная машина настроена так, как мы думаем» — разные утверждения.
fn generation(device: u16) -> Option<&'static str> {
    match device {
        // Шестое поколение, Sandy Bridge: проверено на ASUS X54C (8086:0106).
        0x0102 | 0x0106 | 0x010a | 0x0112 | 0x0116 | 0x0122 | 0x0126 => Some("Sandy Bridge"),
        // Седьмое, Ivy Bridge: раскладка дисплейной части та же, что у шестого. На живой машине
        // НЕ проверено — но отличий, о которых мы знаем, здесь нет, и проверки ниже поймают их,
        // если они всё же есть.
        0x0152 | 0x0156 | 0x015a | 0x0162 | 0x0166 | 0x016a => Some("Ivy Bridge"),
        _ => None,
    }
}

/// Найти встроенную графику Intel на нулевой шине: вендор `8086` и класс «дисплей».
fn find() -> Option<u16> {
    for dev in 0..32u16 {
        let bdf = dev << 3;
        let id = arch::pci_cfg_read32(bdf, 0);
        if id == u32::MAX || id & 0xffff != 0x8086 {
            continue;
        }
        if arch::pci_cfg_read32(bdf, 0x08) >> 24 == 0x03 {
            return Some(bdf);
        }
    }
    None
}

/// 64-битное окно памяти по смещению `off` в конфигурации PCI.
fn bar(bdf: u16, off: u8) -> usize {
    let lo = arch::pci_cfg_read32(bdf, off);
    let hi = arch::pci_cfg_read32(bdf, off + 4);
    ((hi as usize) << 32) | (lo as usize & !0xf)
}

/// Подготовить двойную буферизацию. Зовётся один раз на загрузке, ПОСЛЕ того как принят кадр.
///
/// `fb_phys` — физический адрес кадра, каким его отдал загрузчик; `pitch`, `width` и `height` —
/// его геометрия. Возвращает `true`, если всё сошлось и переключать страницу теперь есть чем.
///
/// Проверок много, и ни одна не лишняя: каждая отвечает за своё предположение, и провал любого
/// означает, что мы понимаем железо хуже, чем думаем. В этом случае система работает как
/// работала — одним буфером, — а в журнале стоит строка с причиной.
pub fn init(fb_phys: usize, pitch: usize, width: usize, height: usize) -> bool {
    let Some(bdf) = find() else { return false };
    // ПОКОЛЕНИЕ — прежде всего остального: по нему решается, верны ли вообще смещения, по
    // которым мы собираемся читать и писать.
    let device = (arch::pci_cfg_read32(bdf, 0) >> 16) as u16;
    let Some(gen) = generation(device) else {
        crate::println!(
            "  [intel] графика 8086:{:04x} — поколение незнакомо, раскладку регистров не знаем; \
             двойного буфера нет",
            device,
        );
        return false;
    };
    let bar0 = bar(bdf, 0x10);
    let aperture = bar(bdf, 0x18);
    if bar0 == 0 || aperture == 0 {
        crate::println!("  [intel] окна регистров не прочитались — двойного буфера нет");
        return false;
    }
    // Кадр обязан быть НАЧАЛОМ АПЕРТУРЫ: только тогда наши записи идут через ту же таблицу GTT,
    // по которой читает развёртка, и смещение в окне равно смещению в таблице.
    if fb_phys != aperture {
        crate::println!(
            "  [intel] кадр {:#x} не совпал с апертурой {:#x} — двойного буфера нет",
            fb_phys, aperture,
        );
        return false;
    }
    // Размер таблицы GTT из GGC хоста моста (00:00.0 +0x50): биты 9:8. Таблица лежит во второй
    // половине BAR0, поэтому её размер — он же смещение.
    let ggc = arch::pci_cfg_read32(0, 0x50);
    let gtt_mib = match (ggc >> 8) & 3 {
        1 => 1,
        2 => 2,
        _ => {
            crate::println!("  [intel] размер таблицы GTT неизвестен (GGC {:#x})", ggc);
            return false;
        }
    };
    let gtt_off = gtt_mib * 1024 * 1024;
    // Украденной памяти должно хватить на два кадра. GMS (биты 7:3) считает её тридцатью
    // двумя мегабайтами на единицу.
    let stolen = (((ggc >> 3) & 0x1f) as usize) * 32 * 1024 * 1024;
    BAR0.store(bar0, Ordering::Relaxed);
    GTT_OFF.store(gtt_off, Ordering::Relaxed);

    STOLEN.store(stolen, Ordering::Relaxed);

    // Развёртка обязана быть включена и настроена так, как мы собираемся ей подсовывать кадр.
    let conf = rd(reg::PIPEACONF);
    let cntr = rd(reg::DSPACNTR);
    let stride = rd(reg::DSPASTRIDE) as usize;
    let surf = rd(reg::DSPASURF) as usize;
    let format = (cntr >> 26) & 0xf;
    if conf & (1 << 31) == 0 || cntr & (1 << 31) == 0 {
        crate::println!("  [intel] конвейер или плоскость выключены — двойного буфера нет");
        return false;
    }
    if format != 0x6 || cntr & (1 << 10) != 0 || stride != pitch || surf != 0 {
        crate::println!(
            "  [intel] плоскость не та, что ожидалось: формат {:#x}, плитка {}, шаг {} (у кадра {}), поверхность {:#x}",
            format,
            (cntr >> 10) & 1,
            stride,
            pitch,
            surf,
        );
        return false;
    }

    // Плоскость проверена — ТЕПЕРЬ можно её менять. Порядок именно такой: убедиться, что
    // железо настроено так, как мы думаем, и только потом трогать. Обратный порядок означал бы
    // проверку собственных же записей.
    let (width, height, pitch) = match try_native_mode(width, height) {
        Some((w, h, p)) => {
            crate::println!(
                "  [intel] родной размер панели: {}×{} (было {}×{}, масштабатор выключен)",
                w, h, width, height,
            );
            NEW_W.store(w, Ordering::Relaxed);
            NEW_H.store(h, Ordering::Relaxed);
            NEW_PITCH.store(p, Ordering::Relaxed);
            (w, h, p)
        }
        None => (width, height, pitch),
    };
    let _ = width; // дальше считается по шагу строки: он и есть ширина в байтах
    let frame = pitch * height;
    let step = (frame + 0xfff) & !0xfff;
    if stolen < step * 2 {
        crate::println!(
            "  [intel] украденной памяти {} МиБ — на два кадра по {} КиБ не хватает",
            stolen / (1024 * 1024),
            step / 1024,
        );
        return false;
    }

    // И главное: страницы ВТОРОГО буфера должны быть отображены в таблицу и не совпадать с
    // первым. Проверяем каждую — их меньше тысячи, а цена ошибки это чужие пиксели на экране.
    let first_page = step / 4096;
    let pages = (frame + 0xfff) / 4096;
    let front_lo = gtt_page(0).unwrap_or(0);
    let front_hi = front_lo + frame as u64;
    for i in 0..pages {
        let Some(page) = gtt_page(first_page + i) else {
            crate::println!(
                "  [intel] запись GTT #{} не отображена — второго буфера в памяти нет",
                first_page + i,
            );
            return false;
        };
        if page >= front_lo && page < front_hi {
            crate::println!(
                "  [intel] запись GTT #{} ведёт в сам кадр ({:#x}) — буферы наложились бы",
                first_page + i,
                page,
            );
            return false;
        }
    }

    STEP.store(step, Ordering::Relaxed);
    SHOWN.store(0, Ordering::Relaxed);
    APERTURE.store(aperture, Ordering::Relaxed);
    READY.store(true, Ordering::Relaxed);
    // Место под картинку курсора — сразу за обоими кадрами. Требования те же: записи таблицы
    // отображены и ведут не в кадр. Не сошлось — курсора в железе не будет, а кадры останутся:
    // это разные вещи, и валить одну из-за другой незачем.
    let cursor_off = step * 2;
    let cursor_pages = (CURSOR_SIDE * CURSOR_SIDE * 4).div_ceil(4096);
    if stolen >= cursor_off + cursor_pages * 4096
        && (0..cursor_pages).all(|i| {
            gtt_page(cursor_off / 4096 + i).is_some_and(|page| page < front_lo || page >= front_hi)
        })
    {
        CURSOR_OFF.store(cursor_off, Ordering::Relaxed);
    }
    crate::println!(
        "  [intel] {}: двойная буферизация, второй кадр по смещению {:#x} ({} КиБ), украденной памяти {} МиБ, курсор {}",
        gen,
        step,
        step / 1024,
        stolen / (1024 * 1024),
        if CURSOR_OFF.load(Ordering::Relaxed) != 0 { "аппаратный" } else { "НЕТ (рисует композитор)" },
    );
    true
}

/// Показать НАРИСОВАННОЕ и вернуть смещение, по которому рисовать следующий кадр.
///
/// Записанное в регистр поверхности защёлкивается на обратном ходе луча — то есть между
/// кадрами, а не посреди. В этом вся цель: разрыв становится невозможен не потому, что мы
/// успели, а потому, что переключает железо.
///
/// **Показывается именно тот буфер, в который рисовали** ([`DRAWN`]), а не «следующий по
/// кругу». Первая редакция считала, что очередь можно вывести из того, что показано сейчас, —
/// и на первом же кадре выводила на экран буфер, в который ещё никто не писал: на машине
/// владельца это была белая вспышка с точками при загрузке (содержимое украденной памяти,
/// оставшееся от прошивки).
pub fn flip() -> usize {
    if !present() {
        return 0;
    }
    let shown = SHOWN.load(Ordering::Relaxed);
    // Показываем то, во что рисовали; рисовать дальше будут в тот, что сейчас на экране.
    let drawn = DRAWN.load(Ordering::Relaxed);
    let step = STEP.load(Ordering::Relaxed);
    // САМОПРОВЕРКА. Регистр «что читает развёртка ПРЯМО СЕЙЧАС» — единственный способ узнать,
    // что переключение дошло до железа, а не осталось нашим мнением. Проверяем ДО записи: к
    // этому моменту прошлое переключение уже должно было защёлкнуться.
    //
    // Не сошлось сто двадцать раз подряд — выключаем себя и говорим об этом. Система при этом
    // работает как работала (один буфер), а не показывает человеку застывший кадр: ошибиться в
    // понимании чужого железа можно, молча оставить человека без экрана — нет.
    if !ACCEPTED.load(Ordering::Relaxed) {
        // Сверяем ТОЛЬКО переключение на ВТОРОЙ буфер: совпадение нуля с нулём не доказывает
        // ничего — ноль там и так стоял от прошивки. Первая редакция проверки принимала именно
        // его и объявляла железо исправным, ни разу ничего не проверив.
        if shown == 1 && live() == step as u32 {
            ACCEPTED.store(true, Ordering::Relaxed);
        } else if FLIPS.fetch_add(1, Ordering::Relaxed) >= TRIES {
            READY.store(false, Ordering::Relaxed);
            arch::hw_write32(BAR0.load(Ordering::Relaxed) + reg::DSPASURF, 0);
            SHOWN.store(0, Ordering::Relaxed);
            DRAWN.store(0, Ordering::Relaxed);
            crate::println!(
                "  [intel] переключение страницы до железа не дошло ({} проб) — вернулись к одному буферу",
                TRIES,
            );
            return 0;
        }
    }
    arch::hw_write32(BAR0.load(Ordering::Relaxed) + reg::DSPASURF, (drawn * step) as u32);
    SHOWN.store(drawn, Ordering::Relaxed);
    let next = 1 - drawn;
    DRAWN.store(next, Ordering::Relaxed);
    next * step
}

/// Отказаться от двойной буферизации и вернуть развёртку на первый буфер.
///
/// Зовёт это тот, кто рисует, когда видит, что переключения перестали защёлкиваться. Решение
/// за ним, а не за нами: мы видим регистр, а он видит, что кадр не меняется.
pub fn to_single() {
    if READY.swap(false, Ordering::Relaxed) {
        arch::hw_write32(BAR0.load(Ordering::Relaxed) + reg::DSPASURF, 0);
        SHOWN.store(0, Ordering::Relaxed);
        DRAWN.store(0, Ordering::Relaxed);
        crate::println!("  [intel] двойная буферизация выключена по просьбе рисующего");
    }
}

/// Вернуть развёртку на первый буфер. Нужно там, где экран забирает ядро: его консоль рисует
/// по началу окна, и оставить развёртку на втором буфере значило бы показывать человеку кадр,
/// в который больше никто не пишет.
/// Привести учёт страниц в соответствие с железом ПОСЛЕ МОДСЕТА.
///
/// Модсет ставит плоскости тот буфер, что лежал в снимке (нулевой), а рисующий к этому
/// времени мог показывать второй. Расхождение видно ему как «переключения перестали
/// защёлкиваться» — и он уходит на ОДИН буфер. А один буфер значит, что он рисует прямо в то,
/// что развёртка читает сейчас, причём записью с объединением, долетающей кусками: по экрану
/// идёт цветная рябь. Ровно это владелец и видел после каждого сна (Веха 244.6).
pub fn after_modeset() {
    if !known() {
        return;
    }
    arch::hw_write32(BAR0.load(Ordering::Relaxed) + reg::DSPASURF, 0);
    SHOWN.store(0, Ordering::Relaxed);
    DRAWN.store(0, Ordering::Relaxed);
    FLIPS.store(0, Ordering::Relaxed);
}

pub fn to_front() {
    DRAWN.store(0, Ordering::Relaxed);
    if present() && SHOWN.swap(0, Ordering::Relaxed) != 0 {
        arch::hw_write32(BAR0.load(Ordering::Relaxed) + reg::DSPASURF, 0);
    }
}

/// Веха 242.1 — ЧТО ОСТАЛОСЬ ОТ ЭКРАНА ПОСЛЕ СНА, и что из этого можно вернуть.
///
/// В S3 питание снимается и с графики: конвейер развёртки гаснет, подсветка — тоже. Полный
/// модсет (PLL, тайминги панели, последовательность включения подсветки) мы не умеем и честно
/// этого не скрываем: мы не ставили режим сами, его оставила прошивка, а мы только проверили и
/// подправили размер ([`init`]).
///
/// Поэтому здесь делается ровно то, что принадлежит НАМ, и говорится, что увидели:
///
/// * конвейер и плоскость живы — вернуть развёртку на первый буфер и поднять подсветку до
///   уровня, который был до сна (регистр ШИМ обнулён, и панель может остаться чёрной при
///   работающем конвейере — это самый обидный вид «экран не вернулся»);
/// * конвейер погас — сказать об этом прямо, одной строкой: дальше это вопрос модсета, и
///   молчаливый чёрный экран был бы худшим из ответов.
///
/// `saved` — яркость, снятая перед сном ([`backlight`]).
pub fn resume(saved: Option<u32>) {
    if !known() {
        return;
    }
    let conf = rd(reg::PIPEACONF);
    let cntr = rd(reg::DSPACNTR);
    // Печатаем ВСЁ, что отвечает на вопрос «почему темно», одной строкой: конвейер, плоскость,
    // питание панели и ШИМ подсветки. Эти четыре слова различают четыре разные беды, и без них
    // каждая выглядит одинаково — чёрным экраном. Строка нужна прежде всего там, где её нельзя
    // прочитать сразу (живая машина, журнал потом), поэтому она длинная и одна.
    crate::println!(
        "  [intel] после сна: PIPEACONF {:#010x}, DSPACNTR {:#010x}, PP_STATUS {:#010x}, \
         PP_CONTROL {:#010x}, ШИМ {:#010x}/{:#010x}",
        conf,
        cntr,
        rd(reg::PP_STATUS),
        rd(reg::PP_CONTROL),
        rd(reg::BLC_CPU_CTL2),
        rd(reg::BLC_PCH_CTL2),
    );
    // Таблица GTT живёт в украденной памяти, а она сон переживает. Но проверить это дешевле,
    // чем потом гадать, почему экран включился и показывает мусор: если первая запись
    // пропала, плоскость читает не те страницы, и беда не в модсете.
    match gtt_page(0) {
        Some(page) => crate::println!("  [intel] после сна GTT №0 → страница {page:#x}"),
        None => crate::println!("  [intel] после сна таблица GTT пуста — кадр читать неоткуда"),
    }
    // ВКЛЮЧЕНИЕ таблицы — первым делом: пока его нет, окно графики не отвечает, и наша же
    // проба кадра валит машину аппаратным отказом (так и вышло, Machine Check 25.11).
    crate::intel_modeset::restore_gtt_ctl();
    // Проверить и вернуть ВСЮ таблицу, а не одну запись: запись №0 может уцелеть, а
    // остальные — нет, и тогда развёртка читает одну и ту же чужую страницу вместо кадра.
    gtt_restore();
    // Отметка об ошибке перевода адреса: если развёртка ходила по несуществующей записи
    // таблицы, здесь стоит не ноль — и гадать больше не о чем.
    let err = arch::hw_read32(BAR0.load(Ordering::Relaxed) + 0x2024);
    if err != 0 {
        crate::println!("  [intel] железо жалуется на перевод адреса: PGTBL_ER {err:#010x}");
        arch::hw_write32(BAR0.load(Ordering::Relaxed) + 0x2024, err);
    }
    if conf & (1 << 31) == 0 || cntr & (1 << 31) == 0 {
        // Веха 244 — конвейер после сна мёртв. Раньше здесь всё и кончалось; теперь пробуем
        // поднять панель сами, по снимку, снятому на загрузке ([[intel-display]]).
        if !crate::intel_modeset::have() {
            crate::println!("  [intel] конвейер выключен, а снимка режима нет — поднимать нечем");
            return;
        }
        crate::intel_modeset::set_trace(true);
        let raised = crate::intel_modeset::enable();
        crate::intel_modeset::set_trace(false);
        if !raised {
            crate::println!("  [intel] свой модсет не поднял панель — экран останется тёмным");
            return;
        }
    }
    // ВИДИМАЯ отметка: белая полоса поперёк экрана, нарисованная ядром мимо композитора.
    // Видна она или нет — ответ, которого нет ни в одном регистре.
    //
    // Но только если окно графики ПЕРЕВОДИТСЯ: пока таблица отображения выключена, любая
    // запись в кадр отбивается шиной и валит машину аппаратным отказом. Проверка стоит одно
    // чтение регистра и спасает заход целиком.
    // Писать в кадр можно, только если конфигурация графики на шине в порядке: иначе окно
    // не отвечает, и запись — не ошибка, а аппаратный отказ, валящий машину.
    if !crate::arch::gfx_config_ok() {
        crate::println!("  [intel] конфигурация графики не восстановлена — в кадр не пишем");
        return;
    }
    unsafe { crate::fb::mark(96, 8, 0x00ff_ffff) };
    // И проба памяти: записать метку в кадр и прочитать её обратно тем же путём.
    //
    // ЧИТАТЬ ТУ ЖЕ СТРАНИЦУ ПО ФИЗИЧЕСКОМУ АДРЕСУ ЗДЕСЬ НЕЛЬЗЯ, и это стоило владельцу
    // зависшей машины: `hw_read32` по новому адресу ОТОБРАЖАЕТ страницу, а пробуждение идёт
    // там, где ядро держит замки. Отображение за ними не ходит.
    let magic = 0x00ff_00ffu32;
    let back = crate::fb::probe(magic);
    crate::println!("  [intel] проба кадра: записали {magic:#010x}, прочли {back:#010x}");

    // Развёртку — на первый буфер: композитор после пробуждения начнёт с него, а регистр
    // поверхности мог обнулиться вместе со всем остальным.
    to_front();
    match saved.and_then(backlight_set) {
        Some(got) => crate::println!("  [intel] после сна экран жив, подсветка {} %", got),
        None => crate::println!("  [intel] после сна экран жив (подсветкой правит прошивка)"),
    }
}

/// Есть ли аппаратный курсор.
pub fn cursor_present() -> bool {
    known() && CURSOR_OFF.load(Ordering::Relaxed) != 0
}

/// Положить картинку курсора: `px` — 64×64 точки в формате `0xAARRGGBB`.
///
/// Пишется ЧЕРЕЗ АПЕРТУРУ — тем же путём, которым композитор пишет пиксели кадра: апертура
/// переводит адрес той же таблицей GTT, в которую мы вписали эти страницы. Отдельного
/// отображения для картинки курсора заводить не надо.
///
/// Зовётся редко (картинка меняется, когда меняется сам указатель), поэтому запись идёт
/// словами, а не блоком: шестнадцать килобайт один раз — это дешевле, чем ещё одна дорога к
/// памяти ради скорости, которой здесь никто не ждёт.
pub fn cursor_image(px: &[u32]) -> bool {
    let off = CURSOR_OFF.load(Ordering::Relaxed);
    if !cursor_present() || px.len() < CURSOR_SIDE * CURSOR_SIDE {
        return false;
    }
    let base = APERTURE.load(Ordering::Relaxed) + off;
    for (i, &p) in px.iter().take(CURSOR_SIDE * CURSOR_SIDE).enumerate() {
        arch::hw_write32(base + i * 4, p);
    }
    // Адрес картинки — он же включение плоскости: вид ставим до адреса, чтобы развёртка не
    // успела прочитать старое поле новым видом.
    arch::hw_write32(BAR0.load(Ordering::Relaxed) + reg::CURACNTR, reg::CURSOR_64_ARGB);
    arch::hw_write32(BAR0.load(Ordering::Relaxed) + reg::CURABASE, off as u32);
    true
}

/// Передвинуть курсор. Отрицательные координаты — это курсор, наполовину ушедший за левый или
/// верхний край: у железа для них отдельный бит знака, а не дополнительный код.
pub fn cursor_move(x: i32, y: i32) -> bool {
    if !cursor_present() {
        return false;
    }
    let pack = |v: i32| -> u32 {
        if v < 0 {
            (1 << 15) | ((-v) as u32 & 0x7fff)
        } else {
            v as u32 & 0x7fff
        }
    };
    let pos = (pack(y) << 16) | pack(x);
    arch::hw_write32(BAR0.load(Ordering::Relaxed) + reg::CURAPOS, pos);
    true
}

/// Спрятать курсор (ноль в поле вида выключает плоскость) или показать снова.
pub fn cursor_show(on: bool) -> bool {
    if !cursor_present() {
        return false;
    }
    let cntr = if on { reg::CURSOR_64_ARGB } else { 0 };
    arch::hw_write32(BAR0.load(Ordering::Relaxed) + reg::CURACNTR, cntr);
    if on {
        // Адрес надо повторить: плоскость, включённая заново, читает его при первом же кадре.
        let off = CURSOR_OFF.load(Ordering::Relaxed);
        arch::hw_write32(BAR0.load(Ordering::Relaxed) + reg::CURABASE, off as u32);
    }
    true
}

/// Попробовать перейти на РОДНОЙ размер панели, если прошивка оставила нас растянутыми.
///
/// ## Что тут происходит
///
/// У панели ноутбука размер один и навсегда — тот, что в её развёртке. Прошивка же может
/// отдать конвейеру картинку поменьше и включить МАСШТАБАТОР, который растянет её на панель:
/// картинка при этом мыльная, и человек видит это как «нечёткий шрифт». Ровно так и вышло у
/// владельца: панель 1366×768, конвейер 1024×768, масштабатор включён.
///
/// Переход при этом не требует программирования частот — самой опасной части установки режима.
/// Развёртка УЖЕ идёт по панели: меняются только размер источника, шаг строки плоскости и
/// выключается масштабатор.
///
/// ## Почему это не «подгонка под одну машину»
///
/// Ни одного числа отсюда: размер берётся из развёртки и окна масштабатора, то есть у самого
/// железа. На машине, где прошивка уже дала родной режим, условия не сойдутся и мы ничего не
/// тронем. Трогаем, только если ВСЁ сошлось: масштабатор включён, его окно больше источника и
/// совпадает с активной развёрткой, а украденной памяти хватает на два новых кадра.
///
/// Возвращает новые `(ширина, высота, шаг строки)` — или `None`, если ничего не меняли.
fn try_native_mode(width: usize, height: usize) -> Option<(usize, usize, usize)> {
    // Переход однажды выключался: после него экран показывал кадр лишь частью, а остальное
    // оставалось чёрным. Замер пикселями через апертуру показал, что виновата была НЕ смена
    // режима (кадр в памяти лежал верно), а композитор — см. [`TRY_NATIVE`].
    if !TRY_NATIVE {
        return None;
    }
    // ДВА РАЗНЫХ формата, и путать их нельзя — на этом я уже ошибся, и переход не состоялся:
    //   развёртка   — `(всего-1) << 16 | (активно-1)`, то есть активное число в МЛАДШЕЙ половине;
    //   размер источника — `(ширина-1) << 16 | (высота-1)`, то есть ширина в СТАРШЕЙ.
    // Поэтому у каждого своё имя, а не одна «универсальная» функция на оба.
    let timing_active = |v: u32| ((v & 0xffff) + 1) as usize;
    let src_size = |v: u32| ((((v >> 16) + 1) as usize), (((v & 0xffff) + 1) as usize));
    let panel_w = timing_active(rd(reg::HTOTAL_A));
    let panel_h = timing_active(rd(reg::VTOTAL_A));
    let pf_ctl = rd(reg::PF_CTL_A);
    let win = rd(reg::PF_WIN_SZ_A);
    let (win_w, win_h) = ((win >> 16) as usize, (win & 0xffff) as usize);
    // Масштабатор выключен — значит нас не растягивают, и делать нечего.
    if pf_ctl & (1 << 31) == 0 {
        return None;
    }
    // Окно масштабатора обязано совпасть с активной развёрткой: это и есть проверка «мы верно
    // поняли, какого размера панель». Не совпало — мы чего-то не понимаем, и трогать нельзя.
    if win_w != panel_w || win_h != panel_h || panel_w <= width || panel_h < height {
        return None;
    }
    // Шаг строки плоскости кратен 64 байтам — требование железа, а не наше удобство.
    let pitch = (panel_w * 4).div_ceil(64) * 64;
    let frame = pitch * panel_h;
    let step = (frame + 0xfff) & !0xfff;
    if STOLEN.load(Ordering::Relaxed) < step * 2 + CURSOR_SIDE * CURSOR_SIDE * 4 {
        return None;
    }
    // Порядок важен: сперва убрать растяжение, потом сказать конвейеру новый размер, и только
    // после этого показать плоскости кадр с новым шагом. Обратный порядок на один кадр показал
    // бы мусор, растянутый мусор или и то и другое.
    //
    // ## Выключатель масштабатора — ДВА регистра, и второй из них взводящий
    //
    // Веха 233.18. Первая редакция писала ноль только в `PF_CTL_A` — и этого мало: у этой пары
    // защёлкивает запись в `PF_WIN_SZ_A`, ровно как у плоскости защёлкивает запись в `DSPASURF`.
    // Пока окно не переписано, ноль в выключателе остаётся НАШИМ МНЕНИЕМ: регистр читается
    // нулём, а железо продолжает растягивать по старой настройке.
    //
    // Чего это стоило. Масштабатор остался включённым с источником прежнего размера, и его
    // вертикальная развёртка поехала: панель показывала НУЛЕВУЮ СТРОКУ кадра, повторённую на
    // все линии. Снаружи это выглядит как «экран одного цвета» — у композитора нулевая строка
    // это верх панели, у консоли ядра она пустая, — и ни на что не похоже, потому что кадр в
    // памяти при этом верен весь, до последней точки. Разобрало это не рассуждение, а проба
    // узором (`intel test`): по тому, КАК узор появлялся на экране, стало видно, что строка на
    // экране ровно одна.
    //
    // Отсюда правило на все такие пары: регистр, который взводит, пишется ПОСЛЕДНИМ и пишется
    // ВСЕГДА — даже когда его значение не меняется.
    arch::hw_write32(BAR0.load(Ordering::Relaxed) + reg::PF_CTL_A, 0);
    arch::hw_write32(BAR0.load(Ordering::Relaxed) + reg::PF_WIN_SZ_A, 0);
    arch::hw_write32(
        BAR0.load(Ordering::Relaxed) + reg::PIPEASRC,
        (((panel_w - 1) as u32) << 16) | (panel_h - 1) as u32,
    );
    arch::hw_write32(BAR0.load(Ordering::Relaxed) + reg::DSPASTRIDE, pitch as u32);
    arch::hw_write32(BAR0.load(Ordering::Relaxed) + reg::DSPASURF, 0);
    // Сверяем ЧТЕНИЕМ: регистры могли не принять записанное, и тогда честнее вернуть всё, как
    // было, чем работать с кадром, которого на экране нет.
    let ok = rd(reg::DSPASTRIDE) as usize == pitch
        && src_size(rd(reg::PIPEASRC)) == (panel_w, panel_h);
    if !ok {
        // Возвращаем так же: выключатель, потом ВЗВОД. Иначе откат оставил бы железо в том же
        // полусостоянии, из-за которого вся эта веха и случилась.
        arch::hw_write32(BAR0.load(Ordering::Relaxed) + reg::PF_CTL_A, pf_ctl);
        arch::hw_write32(BAR0.load(Ordering::Relaxed) + reg::PF_WIN_SZ_A, win);
        arch::hw_write32(
            BAR0.load(Ordering::Relaxed) + reg::PIPEASRC,
            (((width - 1) as u32) << 16) | (height - 1) as u32,
        );
        arch::hw_write32(BAR0.load(Ordering::Relaxed) + reg::DSPASTRIDE, (width * 4) as u32);
        crate::println!("  [intel] родной размер панели не принят железом — остаёмся как были");
        return None;
    }
    Some((panel_w, panel_h, pitch))
}

/// Яркость панели в процентах: `(сколько сейчас, можно ли ставить)`.
///
/// `None` — машина не та, где мы знаем раскладку этих регистров (см. [`generation`]), либо
/// период ШИМ нулевой: тогда подсветкой правит не эта пара регистров, и писать наугад нельзя.
pub fn backlight() -> Option<u32> {
    if !known() {
        return None;
    }
    let period = rd(reg::BLC_PCH_CTL2) >> 16;
    // Выключенный ШИМ процессора — это «яркостью правит не эта половина»: отвечать числом из
    // регистра, который ни на что не влияет, значит врать.
    let on = rd(reg::BLC_CPU_CTL2) & (1 << 31) != 0;
    (period > 0 && on).then(|| (rd(reg::BLC_CPU_CTL) & 0xffff) * 100 / period)
}

/// Поставить яркость панели (проценты). Возвращает, сколько получилось ПО ЧТЕНИЮ регистра, —
/// не то, что мы просили: регистр мог оказаться доступным только для чтения, и тогда «поставлено»
/// было бы враньём.
///
/// Пишется только поле уровня; период остаётся как есть — его задаёт прошивка под конкретную
/// панель, и менять частоту мерцания вслепую незачем. Ниже пяти процентов не ставим совсем: ноль
/// это чёрный экран на машине, где экран единственный способ что-то увидеть.
pub fn backlight_set(percent: u32) -> Option<u32> {
    if !known() {
        return None;
    }
    let period = rd(reg::BLC_PCH_CTL2) >> 16;
    if period == 0 || rd(reg::BLC_CPU_CTL2) & (1 << 31) == 0 {
        return None;
    }
    let want = percent.clamp(5, 100);
    let level = (period * want / 100).max(1);
    let cpu = rd(reg::BLC_CPU_CTL);
    arch::hw_write32(BAR0.load(Ordering::Relaxed) + reg::BLC_CPU_CTL, (cpu & !0xffff) | level);
    Some((rd(reg::BLC_CPU_CTL) & 0xffff) * 100 / period)
}

/// Защёлкнулось ли последнее переключение страницы.
///
/// **Зачем это наружу.** Запись в регистр поверхности — не показ, а ПРОСЬБА показать: железо
/// исполнит её на ближайшем обратном ходе луча, а до тех пор читает прежний буфер. Значит
/// рисующий, получив «рисуй дальше вот сюда», имеет право делать это не раньше, чем просьба
/// исполнилась: иначе он пишет в тот самый буфер, который сейчас на экране, — и разрыв кадра
/// возвращается, только теперь изредка и необъяснимо.
///
/// До этой вехи спасал ритм композитора (кадр в шестнадцать миллисекунд почти всегда дольше
/// ожидания), но «почти всегда» — не свойство, а везение.
pub fn latched() -> bool {
    if !present() {
        return true;
    }
    // Пока идёт модсет, экран не показывает ничего, и переключения страниц, разумеется, не
    // защёлкиваются. Сказать об этом рисующему — значит получить отказ от двойной
    // буферизации насовсем: композитор решит, что железо сломалось.
    if crate::intel_modeset::busy() {
        return true;
    }
    let shown = SHOWN.load(Ordering::Relaxed) * STEP.load(Ordering::Relaxed);
    live() == shown as u32
}

/// Счётчик кадров развёртки — им меряется НАСТОЯЩИЙ ритм экрана, а не наш расчётный.
pub fn vblank_count() -> u32 {
    if known() { rd(reg::FRMCOUNT) } else { 0 }
}

/// Что развёртка читает прямо сейчас. В отличие от регистра поверхности, где лежит ОЖИДАЮЩЕЕ
/// значение, этот показывает защёлкнутое — то есть настоящее положение дел.
fn live() -> u32 {
    rd(reg::DSPASURFLIVE)
}
