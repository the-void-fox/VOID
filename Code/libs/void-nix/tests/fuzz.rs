//! Фаззинг вычислителя языка Nix (Веха 225.2).
//!
//! Выражение приходит С ПАКЕТАМИ, то есть из сети: `nixpkgs` скачивается и вычисляется на самой
//! машине (ADR 0019). Вычислитель — не чтение формата, а исполнение чужой программы, и у него
//! два риска вместо одного: паника и НЕОСТАНОВКА.
//!
//! Второй здесь не проверяется, и это честно сказано, а не упущено: доказать остановку нельзя, а
//! ловить её сроком — значит мерить скорость машины. Потолок рекурсии и бюджет шагов — отдельная
//! работа; пока здесь ловится только паника.

fn корпус() -> Vec<Vec<u8>> {
    vec![
        "{ a = 1; b = \"два\"; c = [ 1 2 3 ]; }".as_bytes().to_vec(),
        b"let x = 1; y = x + 2; in { inherit x y; }".to_vec(),
        b"rec { a = 1; b = a + 1; f = x: x * 2; v = f b; }".to_vec(),
        b"if true then { ok = 1; } else { ok = 0; }".to_vec(),
        b"with { a = 1; }; a".to_vec(),
    ]
}

#[test]
fn вычислитель_не_паникует_на_мусоре() {
    void_fuzz::run("nix::eval_str", 2026, void_fuzz::rounds(), &корпус(), |b| {
        let s = String::from_utf8_lossy(b);
        let _ = void_nix::eval_str(&s);
    });
}
