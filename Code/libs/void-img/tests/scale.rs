//! Масштабирование: «точный размер» ([`Image::scaled`]) и «заполнить с обрезкой»
//! ([`Image::cover`], Веха 139).
//!
//! Эталона со стороны тут нет и быть не может — политика кадрирования наша. Поэтому проверяем
//! СВОЙСТВА, которые обязаны выполняться при любой реализации: что взято из источника, что
//! осталось за кадром и не поехал ли цвет. Свойство ловит ошибку не хуже эталона: перепутанные
//! оси или обрезка от угла вместо центра нарушают их сразу.

use void_img::Image;

/// Картинка из функции `(x, y) -> RGBA`.
fn make(w: u32, h: u32, f: impl Fn(u32, u32) -> [u8; 4]) -> Image {
    let mut img = Image::new(w, h).unwrap();
    for y in 0..h {
        for x in 0..w {
            let p = ((y * w + x) * 4) as usize;
            img.px[p..p + 4].copy_from_slice(&f(x, y));
        }
    }
    img
}

fn at(img: &Image, x: u32, y: u32) -> [u8; 4] {
    let p = ((y * img.w + x) * 4) as usize;
    img.px[p..p + 4].try_into().unwrap()
}

/// Три вертикальные полосы: красная, зелёная, синяя.
fn stripes(w: u32, h: u32) -> Image {
    make(w, h, |x, _| match x * 3 / w {
        0 => [255, 0, 0, 255],
        1 => [0, 255, 0, 255],
        _ => [0, 0, 255, 255],
    })
}

#[test]
fn cover_takes_the_middle() {
    // Источник 3:1, цель 1:1 — по ширине влезает ровно средняя треть, то есть зелёная полоса.
    // Обрезка от левого края (частая ошибка) дала бы красный, от правого — синий.
    let out = stripes(300, 100).cover(100, 100).unwrap();
    assert_eq!((out.w, out.h), (100, 100));
    for (x, y) in [(0, 0), (50, 50), (99, 99), (0, 99), (99, 0)] {
        assert_eq!(at(&out, x, y), [0, 255, 0, 255], "точка ({x},{y}) должна быть из середины");
    }
}

#[test]
fn cover_crops_the_other_axis_too() {
    // Тот же расклад, повёрнутый на 90°: источник ВЫШЕ цели — режется верх и низ.
    let src = make(100, 300, |_, y| match y * 3 / 300 {
        0 => [255, 0, 0, 255],
        1 => [0, 255, 0, 255],
        _ => [0, 0, 255, 255],
    });
    let out = src.cover(100, 100).unwrap();
    for (x, y) in [(0, 0), (50, 50), (99, 99)] {
        assert_eq!(at(&out, x, y), [0, 255, 0, 255], "точка ({x},{y}) должна быть из середины");
    }
}

#[test]
fn cover_fills_whole_target() {
    // Ни одного «непокрытого» пикселя: заливка с обрезкой обязана занять кадр целиком, иначе на
    // экране останутся полосы цвета стола — ровно то, ради чего от «вписать целиком» и ушли.
    let src = make(1000, 200, |x, y| [(x % 251) as u8, (y % 199) as u8, 7, 255]);
    let out = src.cover(640, 480).unwrap();
    assert_eq!((out.w, out.h), (640, 480));
    assert!(out.px.chunks(4).all(|p| p[3] == 255), "прозрачных пикселей взяться неоткуда");
    assert!(out.px.chunks(4).all(|p| p[2] == 7), "синий канал источника постоянен — он и должен остаться");
}

#[test]
fn cover_of_same_aspect_is_plain_scale() {
    // Пропорции сошлись — резать нечего, и `cover` обязан совпасть со `scaled` байт в байт.
    let src = make(600, 300, |x, y| [(x % 256) as u8, (y % 256) as u8, ((x + y) % 256) as u8, 255]);
    assert_eq!(src.cover(200, 100).unwrap().px, src.scaled(200, 100).unwrap().px);
}

#[test]
fn solid_colour_does_not_drift() {
    // Усреднение целыми числами округляет вниз, и на однотонной картинке это было бы видно
    // сразу: обои «выцветали» бы на единицу при каждом пересчёте.
    let src = make(777, 333, |_, _| [17, 200, 99, 255]);
    for out in [src.cover(1024, 768).unwrap(), src.scaled(100, 100).unwrap()] {
        assert!(out.px.chunks(4).all(|p| p == [17, 200, 99, 255]), "цвет уехал при пересчёте");
    }
}

#[test]
fn upscaling_is_allowed_and_exact_on_blocks() {
    // Обои МЕНЬШЕ экрана — обычное дело, и растянуть их надо без отказа. Целочисленное
    // увеличение ровно в N раз обязано давать блоки: усреднять нечего, берётся сосед.
    let src = stripes(3, 1);
    let out = src.cover(300, 100).unwrap();
    assert_eq!(at(&out, 10, 50), [255, 0, 0, 255]);
    assert_eq!(at(&out, 150, 50), [0, 255, 0, 255]);
    assert_eq!(at(&out, 290, 50), [0, 0, 255, 255]);
}

#[test]
fn degenerate_sizes_are_refused_not_panicked() {
    let src = stripes(9, 3);
    assert!(src.cover(0, 10).is_err());
    assert!(src.cover(10, 0).is_err());
    assert!(src.scaled(0, 0).is_err());
    // А вот 1×1 — не вырожденный случай, а законный: средний цвет всей картинки.
    assert_eq!(src.cover(1, 1).unwrap().px.len(), 4);
}
