// ─── проверка шаблонов (Веха 216) ────────────────────────────────────────────
//
// Один тест на всё: собрать поколение ровно так, как его соберёт машина, и потребовать, чтобы в
// нём было то, без чего система теряет возможности. Список требований короткий и растёт только
// от боли — каждая строка здесь стоит одного сломанного дня.
#[cfg(test)]
mod tests {
    use super::*;
    use alloc::string::{String, ToString};
    use crate::{build_config_with, ModuleLoader};

    /// Загрузчик «из шаблонов»: `import("услуги.vv")` отдаёт ровно тот текст, который сеется на
    /// чистую машину. Значит тест собирает не выдумку, а то же самое поколение.
    struct Шаблоны;

    impl ModuleLoader for Шаблоны {
        fn load(&self, name: &str) -> Result<String, String> {
            let t = match name {
                "net.vv" => NET_VV,
                "services.vv" => SERVICES_VV,
                "networking.vv" => NETWORKING_VV,
                "terminal.vv" => TERMINAL_VV,
                "bar.vv" => BAR_VV,
                "packages.vv" => PACKAGES_VV,
                "apps.vv" => APPS_VV,
                "autostart.vv" => AUTOSTART_VV,
                "hardware.vv" => HARDWARE_VV,
                _ => return Err(alloc::format!("нет такого модуля: {name}")),
            };
            Ok(t.to_string())
        }
    }

    fn поколение() -> String {
        build_config_with(DEFAULT_VV, &Шаблоны).expect("шаблоны обязаны собираться")
    }

    /// Пересборка конфига НЕ ДОЛЖНА ОТНИМАТЬ ВОЗМОЖНОСТЕЙ.
    ///
    /// Дважды шаблон молча расходился с тем, что ядро считает правильным поколением, и оба раза
    /// владелец терял работающую систему: сперва звук, потом сеть. Здесь перечислено то, без
    /// чего поколение неполно.
    #[test]
    fn пересборка_не_отнимает_возможностей() {
        let g = поколение();

        // Сервисы. Машина без соответствующего железа строку просто не поднимет — и это верно;
        // а вот ОТСУТСТВИЕ строки значит, что возможности нет ни на какой машине.
        for s in ["service posixfs", "service net-srv", "service hda", "service wifi"] {
            assert!(g.contains(s), "в поколении нет строки `{s}`:\n{g}");
        }

        // Права шелла. `sg!` — раздавать можно, наследовать нельзя. Без `g` композитор держит
        // канал, которым не может поделиться; без `!` сеть достаётся каждому окну.
        assert!(
            g.contains("endpoint:net-srv:sg!"),
            "композитор получил канал к сети без права раздать его (или без пометки `!`):\n{g}"
        );

        // И кому он его раздаёт. Право, которое некому отдать, — это отсутствие возможности:
        // сервер жив, адрес взят, а `ping` из терминала отвечает «канала к сети нет».
        assert!(g.contains("desktop net bin/vvsh"), "сеть не отдана шеллу терминала:\n{g}");
        assert!(g.contains("desktop net taskmgr"), "сеть не отдана диспетчеру задач:\n{g}");

        // То же для остальных раздаваемых прав — они уже были верны, и пусть такими остаются.
        for s in ["desktop sysview taskmgr", "desktop power bin/vvsh", "endpoint:hda"] {
            assert!(g.contains(s), "в поколении нет строки `{s}`:\n{g}");
        }
    }

    /// Веха 220.1 — ШАБЛОНЫ обязаны проходить строгую проверку сами.
    ///
    /// С этой вехи `rebuild` не собирает конфиг с опечаткой в праве. Если бы её содержали те
    /// самые шаблоны, которые система сеет на чистую машину, первая же пересборка у владельца
    /// кончилась бы отказом — и виноватой выглядела бы проверка, а не шаблон.
    #[test]
    fn шаблоны_проходят_строгую_проверку() {
        let беды = crate::check_config(&поколение());
        assert!(беды.is_empty(), "шаблоны не проходят собственную проверку: {:?}", беды);
    }

    /// Выключенная сеть выключает СЕТЬ, а не всё подряд: ни сервера, ни раздачи канала.
    #[test]
    fn без_сети_поколение_остаётся_целым() {
        struct БезСети;
        impl ModuleLoader for БезСети {
            fn load(&self, name: &str) -> Result<String, String> {
                if name == "net.vv" {
                    return Ok("false\n".to_string());
                }
                Шаблоны.load(name)
            }
        }
        let g = build_config_with(DEFAULT_VV, &БезСети).expect("сборка без сети");
        assert!(!g.contains("service net-srv"), "сеть выключена, а сервер остался:\n{g}");
        assert!(!g.contains("endpoint:net-srv"), "сеть выключена, а канал выдан:\n{g}");
        assert!(!g.contains("desktop net"), "сеть выключена, а канал кому-то раздаётся:\n{g}");
        // Всё остальное на месте — выключение сети не должно ронять оболочку.
        assert!(g.contains("shell wm"), "без сети пропал и композитор:\n{g}");
        assert!(g.contains("service posixfs"), "без сети пропали файлы:\n{g}");
    }
}
