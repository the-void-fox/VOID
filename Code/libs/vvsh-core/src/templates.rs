//! Веха 216 — **шаблоны конфигурации**: то, чем система описывает саму себя.
//!
//! Это тексты `/etc/system/*.vv`, которые `vvsh` сеет на чистой машине и из которых `rebuild`
//! собирает поколение. Данные, а не код: ни одной строчки логики.
//!
//! **Почему они здесь, а не в `vvsh`.** Потому что их надо ПРОВЕРЯТЬ, а `vvsh` — `no_std`-бинарь
//! под голое железо, и тестов там не бывает. Здесь же рядом лежит сам вычислитель конфига,
//! и тест может собрать поколение из шаблонов ровно так, как это сделает машина.
//!
//! Проверять есть что, и это не предосторожность. Дважды шаблон молча расходился с тем, что
//! ядро считает правильным поколением, и оба раза это стоило владельцу работающей системы:
//!
//! - сперва в `services.vv` не было строки звука — первая же пересборка отняла звук;
//! - потом в правах шелла не было `endpoint:net-srv:sg!` и не порождалось ни одной строки
//!   `desktop net` — пересборка отняла СЕТЬ у всего, что ею пользуется. Сервер при этом жив и
//!   адрес берёт, поэтому со стороны это выглядит как «сеть отвалилась целиком, даже кабель».
//!
//! Общее у обоих: **пересборка конфига не должна отнимать возможностей**. Проверка этого —
//! в тестах модуля.

