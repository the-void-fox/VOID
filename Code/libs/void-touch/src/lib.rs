#![cfg_attr(not(test), no_std)]

//! Тачпад Synaptics: абсолютные пакеты и жесты (Веха 198).
//!
//! ## Зачем вообще абсолютный режим
//!
//! По умолчанию тачпад притворяется обычной PS/2-мышью и шлёт ОТНОСИТЕЛЬНЫЕ пакеты: «сдвинулось
//! на столько-то». Курсор от этого работает — и на этом всё: в относительном потоке нет понятия
//! «сколько пальцев на панели», поэтому прокрутка двумя пальцами там не то что не реализована, а
//! невыразима в принципе. Ровно поэтому у нас до сих пор «тачпад — мышь без колеса».
//!
//! Абсолютный режим отдаёт КООРДИНАТЫ касания, силу нажатия и код `w`, по которому видно число
//! пальцев. Разница в цене невелика: шесть байт на пакет вместо трёх и десяток строк разбора.
//!
//! ## Что здесь есть и чего нет
//!
//! Есть: раскладка битов пакета ([`decode`]) и превращение касаний в движение курсора и щелчки
//! прокрутки ([`Touchpad`]). Нет: касания как щелчка (tap-to-click), жестов тремя и четырьмя
//! пальцами, инерции. Первое — отдельный разговор про время (щелчок отличается от касания
//! длительностью и неподвижностью), остальное — работа оболочки, а не драйвера: «три пальца
//! влево» значит «переключи стол», и решать это должен тот, кто знает про столы.
//!
//! ## Почему числа именно такие
//!
//! Тачпад меряет в своих единицах: поле примерно от 1200 до 5700 по обеим осям, то есть около
//! 45 единиц на миллиметр. Все пороги ниже выведены из этого и названы в миллиметрах — так их
//! можно обсуждать, не зная протокола.

/// Пакет абсолютного режима, разобранный по полям.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Default)]
pub struct Packet {
    /// Координаты касания в единицах тачпада. Начало отсчёта — левый НИЖНИЙ угол: `y` растёт
    /// вверх, в отличие от экрана.
    pub x: u16,
    pub y: u16,
    /// Сила нажатия: 0 — пальца нет, ~10 — касание, 80+ — заметное давление.
    pub z: u8,
    /// Код ширины/числа пальцев: 0 — ДВА пальца, 1 — три и больше, 2 — «палец» шире панели
    /// (ладонь), 4..15 — ширина одного пальца.
    pub w: u8,
    /// Физические кнопки под панелью.
    pub left: bool,
    pub right: bool,
}

/// Разобрать шестибайтный абсолютный пакет.
///
/// Раскладка у Synaptics рваная — старшие биты координат разнесены по двум служебным байтам,
/// потому что протокол дорос до 13 бит, не сломав совместимости с шестибайтным кадром:
///
/// ```text
///   байт 0:  1  0  W3 W2  0  W1 R  L
///   байт 1:  Y11..Y8      X11..X8
///   байт 2:  Z7..Z0                    (сила нажатия)
///   байт 3:  1  1  Y12 X12 0 W0 R  L
///   байт 4:  X7..X0
///   байт 5:  Y7..Y0
/// ```
pub fn decode(p: &[u8; 6]) -> Packet {
    let x = ((p[3] as u16 & 0x10) << 8) | ((p[1] as u16 & 0x0f) << 8) | p[4] as u16;
    let y = ((p[3] as u16 & 0x20) << 7) | ((p[1] as u16 & 0xf0) << 4) | p[5] as u16;
    // `w` собран из трёх кусков: два бита из байта 0 старшими, один оттуда же и один из байта 3.
    let w = ((p[0] & 0x30) >> 2) | ((p[0] & 0x04) >> 1) | ((p[3] & 0x04) >> 2);
    Packet { x, y, z: p[2], w, left: p[0] & 1 != 0, right: p[0] & 2 != 0 }
}

/// Первый байт абсолютного пакета опознаётся по маске: старшие два бита 10.
///
/// Нужно для пересинхронизации: байт может потеряться (контроллер 8042 переполняется), и без
/// проверки мы бы собирали пакеты из хвоста одного и головы другого — курсор при этом прыгает
/// в случайные места, а причина выглядит как «драйвер сошёл с ума».
pub fn is_first_byte(b: u8) -> bool {
    b & 0xc8 == 0x80
}

/// Четвёртый байт пакета (индекс 3) — вторая служебная тройка бит: старшие два бита 11.
pub fn is_fourth_byte(b: u8) -> bool {
    b & 0xc8 == 0xc0
}

/// Единиц тачпада в миллиметре (типично для Synaptics: поле ~1200..5700 по обеим осям).
const PER_MM: i32 = 45;

/// Палец считается лежащим на панели с этой силы нажатия. Ниже — шум и «почти коснулся».
const Z_TOUCH: u8 = 25;

/// Сколько единиц даёт один щелчок прокрутки.
///
/// Веха 202.12 — было 4 мм, стало 2. Прежнее число считалось «примерно ползунок на строку», но
/// щелчок у нас двигает список на ТРИ строки ([`ui::Scroll::STEP_ROWS`]), и вместе это давало
/// четыре миллиметра пальца на три записи — то есть панель отзывалась на прокрутку примерно
/// раз в полсекунды спокойного движения. Настраивается строкой `touchpad("scroll", мм)`.
const SCROLL_STEP: i32 = 2 * PER_MM;

/// Во сколько раз движение пальца медленнее движения курсора — ПО УМОЛЧАНИЮ.
///
/// Веха 198.1 — было 2, стало 6. Владелец проверил на живой панели и сказал коротко:
/// «чувствительность крайне высока». Цифра 2 бралась из расчёта «экран за 14 мм», и на бумаге
/// это выглядело удобно; на панели ноутбука таким курсором невозможно попасть в кнопку.
/// Настраивается строкой `touchpad("speed", N)` — см. [`Touchpad::tune`].
const CURSOR_DIV: i32 = 6;

/// Скачок больше этого — не движение пальца, а НОВОЕ касание в другом месте (палец подняли и
/// поставили). Семь миллиметров за один пакет (тачпад шлёт их 80 раз в секунду) — это уже
/// нечеловеческая скорость.
const JUMP_MM: i32 = 7;

/// Что делать по пакету. Ровно одно из трёх: тачпад либо ведёт курсор, либо крутит, либо
/// сообщает о кнопках — смешивать нельзя, иначе страница едет вместе с курсором.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Move {
    /// Двигать курсор (в точках экрана; `dy` уже в экранном направлении — вниз положительно).
    Cursor { dx: i16, dy: i16 },
    /// Крутить колесо: +1 — от себя (вверх), −1 — на себя.
    Wheel(i8),
    /// Ничего: палец снят, только что поставлен либо движение ещё не набралось.
    None,
}

/// Состояние жестов: где был палец в прошлый раз и сколько прокрутки накопилось.
///
/// `Default` здесь НЕ выводится: нулевой делитель чувствительности — это деление на ноль в
/// горячем пути. Единственный вход — [`Touchpad::new`], где стоят умолчания.
pub struct Touchpad {
    /// Во сколько раз курсор медленнее пальца (больше — медленнее).
    cursor_div: i32,
    /// Сколько единиц панели на один щелчок прокрутки (больше — крупнее шаг).
    scroll_step: i32,
    /// Прошлая точка касания, пока палец на панели.
    prev: Option<(u16, u16)>,
    /// Сколько пальцев было в прошлом пакете — смена числа пальцев рвёт непрерывность
    /// движения, и продолжать с прежней точки нельзя.
    fingers: u8,
    /// Накопленная прокрутка в единицах тачпада (щелчок отдаётся по достижении шага).
    scroll: i32,
}

impl Default for Touchpad {
    fn default() -> Self {
        Self::new()
    }
}

impl Touchpad {
    pub const fn new() -> Self {
        Touchpad {
            cursor_div: CURSOR_DIV,
            scroll_step: SCROLL_STEP,
            prev: None,
            fingers: 0,
            scroll: 0,
        }
    }

    /// Веха 198.1 — настроить под руку хозяина. `speed` — во сколько раз курсор медленнее
    /// пальца (1 — как палец, 16 — очень медленно), `scroll_mm` — сколько миллиметров на один
    /// щелчок прокрутки. Ноль в любом из них значит «оставь как было»: пустая строка в конфиге
    /// не должна превращать тачпад в неуправляемый.
    pub fn tune(&mut self, speed: u8, scroll_mm: u8) {
        if speed > 0 {
            self.cursor_div = (speed as i32).clamp(1, 16);
        }
        if scroll_mm > 0 {
            self.scroll_step = (scroll_mm as i32).clamp(1, 30) * PER_MM;
        }
    }

    /// Сколько пальцев на панели по коду `w`. Ладонь (`w == 2`) считаем отсутствием пальцев:
    /// класть ладонь на тачпад при наборе — обычное дело, и курсор от этого ездить не должен.
    fn fingers_of(p: &Packet) -> u8 {
        if p.z < Z_TOUCH {
            return 0;
        }
        match p.w {
            0 => 2,
            1 => 3,
            2 => 0, // ладонь
            _ => 1,
        }
    }

    /// Кнопки в маске события мыши (бит 0 левая, бит 1 правая) — их тачпад отдаёт как есть.
    pub fn buttons(p: &Packet) -> u8 {
        (p.left as u8) | ((p.right as u8) << 1)
    }

    /// Обработать пакет. Возвращает, что делать курсору.
    pub fn feed(&mut self, p: &Packet) -> Move {
        let fingers = Self::fingers_of(p);
        if fingers != self.fingers {
            // Число пальцев изменилось: начинаем отсчёт заново, но НИЧЕГО не двигаем. Иначе
            // второй палец, поставленный на сантиметр в стороне, дал бы прыжок курсора ровно
            // в тот момент, когда человек собрался прокручивать.
            self.fingers = fingers;
            self.prev = if fingers == 0 { None } else { Some((p.x, p.y)) };
            self.scroll = 0;
            return Move::None;
        }
        if fingers == 0 {
            return Move::None;
        }
        let Some((px, py)) = self.prev else {
            self.prev = Some((p.x, p.y));
            return Move::None;
        };
        let dx = p.x as i32 - px as i32;
        let dy = p.y as i32 - py as i32;
        if dx.abs() > JUMP_MM * PER_MM || dy.abs() > JUMP_MM * PER_MM {
            // Палец «телепортировался» — значит это другое касание. Принимаем новую точку и
            // молчим: лучше пропустить одно движение, чем швырнуть курсор через экран.
            self.prev = Some((p.x, p.y));
            return Move::None;
        }
        self.prev = Some((p.x, p.y));

        if fingers == 2 {
            // ПРОКРУТКА. Копим, пока не набрался шаг: тачпад шлёт по восемьдесят пакетов в
            // секунду, и щелчок на каждый превратил бы страницу в размазню.
            self.scroll += dy;
            let mut ticks = 0i32;
            while self.scroll >= self.scroll_step {
                self.scroll -= self.scroll_step;
                ticks += 1; // палец вверх = страница вверх (от себя)
            }
            while self.scroll <= -self.scroll_step {
                self.scroll += self.scroll_step;
                ticks -= 1;
            }
            return if ticks == 0 { Move::None } else { Move::Wheel(ticks.clamp(-8, 8) as i8) };
        }

        // КУРСОР. `y` у тачпада растёт вверх, у экрана вниз — знак меняем здесь, чтобы наружу
        // шло экранное соглашение и никто больше об этом не думал.
        let mx = dx / self.cursor_div;
        let my = -dy / self.cursor_div;
        if mx == 0 && my == 0 {
            return Move::None;
        }
        Move::Cursor { dx: mx.clamp(-2048, 2048) as i16, dy: my.clamp(-2048, 2048) as i16 }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Собрать байты пакета из полей — обратная к [`decode`], только для тестов.
    fn pack(x: u16, y: u16, z: u8, w: u8, left: bool, right: bool) -> [u8; 6] {
        let mut b = [0u8; 6];
        b[0] = 0x80
            | ((w & 0b1100) << 2)
            | ((w & 0b0010) << 1)
            | (left as u8)
            | ((right as u8) << 1);
        b[1] = (((y >> 8) & 0x0f) << 4) as u8 | ((x >> 8) & 0x0f) as u8;
        b[2] = z;
        b[3] = 0xc0
            | (((x >> 12) & 1) << 4) as u8
            | (((y >> 12) & 1) << 5) as u8
            | ((w & 1) << 2)
            | (left as u8)
            | ((right as u8) << 1);
        b[4] = x as u8;
        b[5] = y as u8;
        b
    }

    #[test]
    fn разбор_пакета_возвращает_поля() {
        let p = decode(&pack(3000, 2500, 60, 5, true, false));
        assert_eq!((p.x, p.y, p.z, p.w), (3000, 2500, 60, 5));
        assert!(p.left && !p.right);
    }

    #[test]
    fn старшие_биты_координат_из_служебных_байт() {
        // 13-битные координаты: бит 12 живёт в байте 3 и легко теряется при разборе.
        let p = decode(&pack(5000, 4600, 40, 4, false, true));
        assert_eq!((p.x, p.y), (5000, 4600));
        assert!(!p.left && p.right);
    }

    #[test]
    fn два_пальца_кодируются_нулевой_шириной() {
        assert_eq!(decode(&pack(1000, 1000, 50, 0, false, false)).w, 0);
        assert_eq!(decode(&pack(1000, 1000, 50, 1, false, false)).w, 1);
        assert_eq!(decode(&pack(1000, 1000, 50, 12, false, false)).w, 12);
    }

    #[test]
    fn синхронизация_по_служебным_битам() {
        let b = pack(2000, 2000, 50, 4, false, false);
        assert!(is_first_byte(b[0]));
        assert!(is_fourth_byte(b[3]));
        // Байт координаты первым быть не может — иначе поток не пересобрать после потери.
        assert!(!is_first_byte(b[5]) || b[5] & 0xc8 == 0x80);
    }

    #[test]
    fn первое_касание_не_двигает_курсор() {
        let mut t = Touchpad::new();
        let p = decode(&pack(3000, 3000, 60, 5, false, false));
        assert_eq!(t.feed(&p), Move::None);
    }

    #[test]
    fn палец_ведёт_курсор() {
        let mut t = Touchpad::new();
        t.feed(&decode(&pack(3000, 3000, 60, 5, false, false)));
        let m = t.feed(&decode(&pack(3120, 3060, 60, 5, false, false)));
        // 120 единиц вправо и 60 вверх при умолчании «курсор вшестеро медленнее пальца» →
        // 20 точек вправо и 10 ВВЕРХ по-экранному (dy отрицательный).
        assert_eq!(m, Move::Cursor { dx: 20, dy: -10 });
    }

    #[test]
    fn поднятый_палец_ничего_не_двигает() {
        let mut t = Touchpad::new();
        t.feed(&decode(&pack(3000, 3000, 60, 5, false, false)));
        let m = t.feed(&decode(&pack(4000, 4000, 0, 0, false, false)));
        assert_eq!(m, Move::None);
        // И следующее касание тоже не прыгает, хотя палец в другом месте.
        assert_eq!(t.feed(&decode(&pack(4000, 4000, 60, 5, false, false))), Move::None);
    }

    #[test]
    fn два_пальца_крутят_а_не_ведут() {
        let mut t = Touchpad::new();
        t.feed(&decode(&pack(3000, 3000, 60, 0, false, false)));
        // Считаем ОТ ШАГА, а не от числа: величина шага — настройка под руку (Веха 202.12
        // уменьшила её вдвое), и тест, знающий её наизусть, ломался бы при каждой правке,
        // ничего при этом не проверяя.
        let half = SCROLL_STEP / 2;
        assert_eq!(t.feed(&decode(&pack(3000, (3000 + half) as u16, 60, 0, false, false))), Move::None);
        // Добрали до шага — один щелчок вверх, и ни одного движения курсора.
        assert_eq!(
            t.feed(&decode(&pack(3000, (3000 + SCROLL_STEP) as u16, 60, 0, false, false))),
            Move::Wheel(1),
        );
    }

    #[test]
    fn прокрутка_вниз_отрицательна() {
        let mut t = Touchpad::new();
        t.feed(&decode(&pack(3000, 3000, 60, 0, false, false)));
        assert_eq!(
            t.feed(&decode(&pack(3000, (3000 - SCROLL_STEP) as u16, 60, 0, false, false))),
            Move::Wheel(-1),
        );
    }

    #[test]
    fn ладонь_не_водит_курсор() {
        let mut t = Touchpad::new();
        t.feed(&decode(&pack(3000, 3000, 90, 2, false, false)));
        assert_eq!(t.feed(&decode(&pack(3200, 3200, 90, 2, false, false))), Move::None);
    }

    #[test]
    fn второй_палец_не_швыряет_курсор() {
        let mut t = Touchpad::new();
        t.feed(&decode(&pack(3000, 3000, 60, 5, false, false)));
        t.feed(&decode(&pack(3020, 3000, 60, 5, false, false)));
        // Второй палец лёг в стороне: число пальцев сменилось — молчим.
        assert_eq!(t.feed(&decode(&pack(2000, 2500, 60, 0, false, false))), Move::None);
    }

    #[test]
    fn настройка_меняет_скорость_курсора() {
        let mut t = Touchpad::new();
        t.tune(1, 0); // курсор один в один с пальцем
        t.feed(&decode(&pack(3000, 3000, 60, 5, false, false)));
        assert_eq!(
            t.feed(&decode(&pack(3120, 3000, 60, 5, false, false))),
            Move::Cursor { dx: 120, dy: 0 }
        );
        let mut t = Touchpad::new();
        t.tune(12, 0); // вдвое медленнее умолчания
        t.feed(&decode(&pack(3000, 3000, 60, 5, false, false)));
        assert_eq!(
            t.feed(&decode(&pack(3120, 3000, 60, 5, false, false))),
            Move::Cursor { dx: 10, dy: 0 }
        );
    }

    #[test]
    fn настройка_меняет_шаг_прокрутки() {
        let mut t = Touchpad::new();
        t.tune(0, 2); // щелчок каждые два миллиметра
        t.feed(&decode(&pack(3000, 3000, 60, 0, false, false)));
        assert_eq!(t.feed(&decode(&pack(3000, 3090, 60, 0, false, false))), Move::Wheel(1));
    }

    #[test]
    fn ноль_в_настройке_ничего_не_меняет() {
        // Пустая строка конфига не должна превращать тачпад в неуправляемый (и уж точно не
        // должна делить на ноль).
        let mut t = Touchpad::new();
        t.tune(0, 0);
        t.feed(&decode(&pack(3000, 3000, 60, 5, false, false)));
        assert_eq!(
            t.feed(&decode(&pack(3060, 3000, 60, 5, false, false))),
            Move::Cursor { dx: 10, dy: 0 }
        );
    }

    #[test]
    fn кнопки_идут_как_есть() {
        let p = decode(&pack(1000, 1000, 0, 0, true, true));
        assert_eq!(Touchpad::buttons(&p), 0b11);
    }
}
