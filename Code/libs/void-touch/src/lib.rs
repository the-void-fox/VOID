    /// Шаг свайпа по умолчанию, в единицах панели.
    const STEP: i32 = SWIPE_STEP_MM * PER_MM;

    /// ПРОВЕСТИ пальцами из (x,y) на `dx`,`dy` — серией мелких пакетов, как живая панель.
    ///
    /// Одним прыжком вести нельзя, и это не придирка к тесту: движение длиннее [`JUMP_MM`] за
    /// пакет драйвер считает новым касанием (палец сняли и поставили). Тест, ведущий палец
    /// одним прыжком, проверял бы ровно эту защиту, а не то, что написано в его имени.
    fn glide(t: &mut Touchpad, w: u8, from: (i32, i32), dx: i32, dy: i32) -> Vec<Move> {
        let steps = (dx.abs().max(dy.abs()) / 90).max(1); // ~2 мм на пакет
        let mut out = Vec::new();
        for i in 1..=steps {
            let x = (from.0 + dx * i / steps) as u16;
            let y = (from.1 + dy * i / steps) as u16;
            match t.feed(&decode(&pack(x, y, 60, w, false, false))) {
                Move::None => {}
                m => out.push(m),
            }
        }
        out
    }

    /// Поставить три пальца в (3000,3000) и провести их на `dx`,`dy`.
    fn swipe3(t: &mut Touchpad, dx: i32, dy: i32) -> Vec<Move> {
        t.feed(&decode(&pack(3000, 3000, 60, 1, false, false)));
        glide(t, 1, (3000, 3000), dx, dy)
    }

    #[test]
    fn три_пальца_дают_свайп_в_свою_сторону() {
        // `y` тачпада растёт вверх, наружу уходит ЭКРАННАЯ сторона.
        for (dx, dy, dir) in [
            (0, STEP, Dir::Up),
            (0, -STEP, Dir::Down),
            (STEP, 0, Dir::Right),
            (-STEP, 0, Dir::Left),
        ] {
            let mut t = Touchpad::new();
            assert_eq!(swipe3(&mut t, dx, dy), vec![Move::Swipe { fingers: 3, dir }]);
        }
    }

    #[test]
    fn три_пальца_не_водят_курсор() {
        // До Вехи 203 жест приходил в программу под курсором: три пальца шли в ветку курсора.
        let mut t = Touchpad::new();
        assert!(swipe3(&mut t, 60, 60).is_empty());
    }

    #[test]
    fn короткое_движение_свайпа_не_даёт() {
        let mut t = Touchpad::new();
        assert!(swipe3(&mut t, 0, STEP / 2).is_empty());
    }

    #[test]
    fn ось_свайпа_выбирается_один_раз() {
        // Человеческое движение всегда диагональное: набрав шаг по вертикали, дальше едем по ней
        // же, даже если рука увела пальцы вбок сильнее.
        let mut t = Touchpad::new();
        assert_eq!(swipe3(&mut t, 0, STEP), vec![Move::Swipe { fingers: 3, dir: Dir::Up }]);
        assert!(glide(&mut t, 1, (3000, 3000 + STEP), STEP + STEP / 2, 0).is_empty());
    }

    #[test]
    fn длинный_свайп_даёт_шаг_за_шагом() {
        // Остаток не теряется: в движении через всю панель шагов столько, сколько в нём влезло.
        let mut t = Touchpad::new();
        assert_eq!(swipe3(&mut t, 0, STEP * 3).len(), 3);
    }

    #[test]
    fn снятые_пальцы_обнуляют_накопленное() {
        let mut t = Touchpad::new();
        assert!(swipe3(&mut t, 0, STEP * 3 / 4).is_empty());
        t.feed(&decode(&pack(3000, 3000, 0, 0, false, false))); // пальцы сняли
        // Новое касание начинает счёт заново — иначе три четверти шага «доехали» бы потом сами.
        assert!(swipe3(&mut t, 0, STEP / 2).is_empty());
    }

    #[test]
    fn настройка_меняет_шаг_свайпа() {
        let mut t = Touchpad::new();
        t.tune(0, 0, 5); // шаг в пять миллиметров
        assert_eq!(
            swipe3(&mut t, 0, 5 * PER_MM),
            vec![Move::Swipe { fingers: 3, dir: Dir::Up }],
        );
    }

    #[test]
    fn кнопки_идут_как_есть() {
        let p = decode(&pack(1000, 1000, 0, 0, true, true));
        assert_eq!(Touchpad::buttons(&p), 0b11);
    }
