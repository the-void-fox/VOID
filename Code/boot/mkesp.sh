#!/usr/bin/env bash
# mkesp.sh — собрать ОБРАЗ СИСТЕМНОГО РАЗДЕЛА EFI (ESP) для загрузки VOID по UEFI (Веха 226).
#
# ── Зачем отдельный скрипт ───────────────────────────────────────────────────────────────────
#
# У этого образа, как и у `void-disk-boot.img`, ДВА применения, и оба нужны:
#
#   1) **живой носитель**: ISO вкладывает его разделом, и UEFI-прошивка грузится прямо с него —
#      и когда ISO записан на флешку, и когда он подан приводом;
#   2) **установка**: `install` шьёт этот же образ на раздел ESP целевого диска.
#
# Своего форматтера FAT32 мы не пишем НАРОЧНО (решение 11.10.2026): образ ESP всё равно нужен для
# ISO, и делать то же самое второй раз незачем. Один файл на оба применения — ровно тот довод, по
# которому так сделан и образ диска в `mkboot.sh`: расходиться «тому, что показывают» и «тому, что
# ставят» негде.
#
# ── Почему GRUB здесь ДРУГОЙ ─────────────────────────────────────────────────────────────────
#
# В nixpkgs `grub2` собран под одну платформу: у нас это `i386-pc` (BIOS). EFI-платформа живёт в
# отдельном пакете `grub2_efi`, и обе в одном каталоге не встречаются — поэтому `grub-mkrescue`
# гибрид сам не сделает. Путь к EFI-сборке приходит в `VOID_GRUB_EFI` из `shell.nix`.
#
# ── Почему переходник ВШИТ в образ, а не лежит файлом ────────────────────────────────────────
#
# Встроенный префикс указывает туда, откуда прошивка загрузила `BOOTX64.EFI`, и угадать это
# нельзя. Первый заход положил переходник файлом в ESP (`/EFI/BOOT/grub.cfg`) — и GRUB упал в
# свою консоль. Спросили у него самого: `echo $prefix` ответил **`(cd0)/EFI/BOOT`** — то есть
# прошивка загрузила нас из ESP, а GRUB счёл своим устройством ВЕСЬ диск, на котором каталога
# `/EFI/BOOT` нет. Файл лежал там, куда GRUB не смотрел.
#
# Поэтому переходник вшивается в сам образ (`grub-mkimage -c`): он исполняется ДО того, как
# префикс кому-то понадобится, и ищет том по СОДЕРЖИМОМУ — `search --file /boot/void-kernel`.
# Тот же вызов в консоли ответил `cd0`, то есть поиск работает там, где префикс врёт.
#
# Так один образ годится обоим случаям: живому носителю (ядро на ISO9660) и установленному диску
# (ядро на FAT-разделе) — ищется не раздел по номеру, а том по тому, что на нём лежит.
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"

# Два режима, и второй появился ради `mkdisk.sh` (Веха 226.7).
#
#   mkesp.sh <out.img> [каталог]  — собрать ОБРАЗ раздела ESP;
#   mkesp.sh --дерево <каталог>   — только разложить `EFI/BOOT/` в указанный каталог.
#
# Второй нужен там, где FAT-раздел уже есть и форматировать его заново нельзя: на загрузочном
# образе диска в нём уже лежат GRUB для BIOS и ядро. Собирать `BOOTX64.EFI` вторым экземпляром
# кода было бы ровно тем расхождением, от которого в этом проекте уже страдали.
tree_only=""
if [ "${1:-}" = "--дерево" ]; then
    tree_only="${2:?--дерево требует каталог}"
fi
out="${1:-$here/esp.img}"
# Второй аргумент — каталог, содержимое которого едет в ESP рядом с `EFI/BOOT`. Нужен диску с
# установленной системой: там на этом же разделе лежат ядро и `grub.cfg`, потому что больше им
# лежать негде — store VOID читает только само ядро, а GRUB его формата не знает.
extra="${2:-}"

: "${VOID_GRUB_EFI:?нет VOID_GRUB_EFI — войди в nix-shell (там он ставится из grub2_efi)}"
plat="$VOID_GRUB_EFI/lib/grub/x86_64-efi"
[ -d "$plat" ] || { echo "в $VOID_GRUB_EFI нет платформы x86_64-efi"; exit 1; }

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
mkdir -p "$tmp/EFI/BOOT"

# Модули, вшитые в образ. Каждый назван с причиной — иначе список превращается в карго-культ,
# который никто не решается тронуть.
modules=(
    part_gpt part_msdos   # таблицы разделов: ESP на GPT, но ISO подаёт себя и защитным MBR
    fat iso9660           # ФС, на которых может лежать ядро: ESP и живой носитель
    search search_fs_file # найти том по файлу, а не по номеру раздела
    configfile normal     # передать управление настоящему конфигу
    multiboot2            # чем грузится VOID
    all_video            # кадр от прошивки (GOP) — без него ядру не достанется фреймбуфер
    # `gfxterm`/`font` не нужны: меню текстовое, шрифта мы не возим (см. ниже)
    echo test ls halt reboot # на случай ручного разбирательства в консоли GRUB
)

# Переходник, который уедет ВНУТРЬ образа. Дальше GRUB сам возьмёт `$prefix/grub.cfg` — то есть
# настоящий конфиг VOID; `configfile` здесь звать не надо и не стоит (меню собирает `normal`,
# а он к этому моменту ещё не поднят).
#
# Сообщение на случай неудачи обязательно: иначе «прошивка нашла GRUB, а GRUB не нашёл систему»
# выглядит на экране как пустая консоль, и искать будут в прошивке.
# Порядок строк тут — ответ на настоящую находку: в РАННЕМ конфиге `search` тома не находит
# (устройства ещё не перебраны), хотя в консоли GRUB тот же вызов отвечает `cd0`. Первая
# редакция поэтому печатала «GRUB не нашёл систему» на КАЖДОЙ загрузке, а грузилась всё равно —
# потому что `($root)` с пустым `$root` GRUB разрешал в устройство, с которого его загрузили.
# Ложная тревога плюс работа по случайности: два дефекта в четырёх строках.
#
# Теперь умолчание ставится ПЕРВЫМ и без устройства — то есть «то, с чего нас загрузили», и для
# живого носителя это сразу верно. `search` только УЛУЧШАЕТ результат, когда ему есть что
# сказать: это понадобится установленному диску, где ядро лежит не там, где `BOOTX64.EFI`.
early="$tmp/early.cfg" # удаляется перед копированием: нужен сборке, не диску
cat > "$early" <<'CFG'
set prefix=/boot/grub
search --set=root --file /boot/void-kernel
if [ -n "$root" ]; then
    set prefix=($root)/boot/grub
fi
CFG

grub-mkimage --directory="$plat" -O x86_64-efi -p /boot/grub -c "$early" \
    -o "$tmp/EFI/BOOT/BOOTX64.EFI" "${modules[@]}"
# Шрифт `unicode.pf2` сюда НЕ кладём, хотя его кладут все. Он весит 2.4 МиБ — больше, чем сам
# загрузчик, — и нужен только графическому меню (`gfxterm`), которого у нас нет: меню VOID
# текстовое и скрытое. На ISO эти мегабайты просто лишние, а на диске они едва не стоили
# загрузки: раздел p1 переполнился, и образ собрался «успешно» с обрезанным файлом.

# Режим «только дерево»: отдать собранное и уйти. FAT-образа здесь не будет.
if [ -n "$tree_only" ]; then
    mkdir -p "$tree_only"
    cp -r "$tmp/EFI" "$tree_only/"
    echo "готово: $tree_only/EFI/BOOT (BOOTX64.EFI + переходник)"
    exit 0
fi

[ -z "$extra" ] || cp -r "$extra"/. "$tmp/"

# Размер — по содержимому плюс запас на служебные структуры FAT, и дальше вверх до мегабайта:
# раздел меньше мегабайта некоторые прошивки не любят, а точный размер здесь ничего не стоит.
need_kb=$(( $(du -sk --apparent-size "$tmp" | cut -f1) ))
size_kb=$(( ((need_kb * 12 / 10) / 1024 + 1) * 1024 ))
rm -f "$out"
truncate --size="${size_kb}K" "$out"
mkfs.vfat -n VOIDESP "$out" >/dev/null

( cd "$tmp" && rm -f early.cfg
  for d in $(find . -mindepth 1 -type d | sed 's|^\./||' | sort); do mmd -i "$out" "::/$d"; done
  for f in $(find . -type f | sed 's|^\./||' | sort); do mcopy -i "$out" "$f" "::/$f"; done )

# Проверяем СВОЙ результат, а не надеемся на него: молчаливо битый ESP выглядит как «прошивка не
# видит носитель», и искать это потом будут в прошивке.
fsck.vfat -n "$out" >/dev/null || { echo "ESP собрался БИТЫМ — это ошибка сборки, а не прошивки"; exit 1; }
echo "готово: $out ($((size_kb / 1024)) МиБ, BOOTX64.EFI + переходник${extra:+ + содержимое $extra})"
