# layout.sh — РАЗМЕР ЗАГРУЗОЧНОГО РАЗДЕЛА, посчитанный в одном месте (Веха 227.6).
#
# Подключается точкой: `. "$here/layout.sh"`, дальше `void_p1_mb <ядро>`.
#
# ## Зачем это отдельным файлом
#
# Формула жила в двух местах — `mkdisk.sh` считала `ядро + ESP + 3`, а `mkboot.sh` свою копию
# `ядро + 3`, без ESP, — и копии успели разойтись: у живого носителя store оказывался меньше
# обещанного ровно на размер загрузчика UEFI. Тихо, как и положено двум мерам одной вещи.
#
# ## Почему размер КРУГЛЫЙ, а не «сколько надо»
#
# Это и есть суть вехи. Обновление системы (`install update`) переписывает загрузочный префикс
# диска и требует, чтобы раздел store начинался ТАМ ЖЕ, где в образе: иначе новый загрузчик
# будет искать систему не там, где она лежит. А начало store — это конец p1, то есть размер
# ядра плюс запас.
#
# Пока размер считался «впритык», КАЖДЫЙ мегабайт, на который вырастало ядро, сдвигал store — и
# установленная система переставала обновляться. Выглядело это как отказ «раскладка диска не
# совпадает с образом», и чинилось только полной переустановкой со стиранием диска. На практике
# это значило, что обновление не работает почти никогда: ядро растёт с каждой вехой.
#
# Поэтому p1 округляется вверх до [`СЕТКА`] МиБ. Ядру есть куда расти, не двигая store, а цена —
# несколько мегабайт в образе, которых на диске всё равно не жалко.
#
# Сменить сетку = сломать обновление всем, кто уже поставил систему: их p1 останется на прежней
# отметке. Поэтому число здесь — договор, а не настройка.

# Шаг сетки, МиБ. 16 выбрано по месту: сегодня нужно 11 (ядро 7 + ESP 1 + 3 служебных), и до
# следующей отметки ядру остаётся пять мегабайт роста — это годы при нынешнем темпе.
VOID_P1_GRID_MB=16

# Размер p1 в МиБ для данного ядра. Второй аргумент — каталог `EFI/BOOT`, если он уже собран;
# иначе он собирается во временный (нужен `VOID_GRUB_EFI`, то есть nix-shell).
void_p1_mb() {
    local kernel="$1" efi_dir="${2:-}" here_sh kernel_mb efi_mb need
    here_sh="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
    kernel_mb=$(( ( $(stat -c%s "$kernel") + 1048575 ) / 1048576 ))
    efi_mb=0
    if [ -n "$efi_dir" ]; then
        efi_mb=$(( ( $(du -sb --apparent-size "$efi_dir" | cut -f1) + 1048575 ) / 1048576 ))
    elif [ -n "${VOID_GRUB_EFI:-}" ]; then
        # Веха 226.7 — загрузчик UEFI едет в том же p1, и его размер надо ЗНАТЬ, а не угадывать:
        # первая редакция этого не учла, раздел переполнился, и `mcopy` сказал «Disk full» уже
        # в CI. Локально при этом оставалось 400 КиБ — то есть прошло бы незамеченным.
        local probe
        probe="$(mktemp -d)"
        "$here_sh/mkesp.sh" --дерево "$probe" >/dev/null
        efi_mb=$(( ( $(du -sb --apparent-size "$probe" | cut -f1) + 1048575 ) / 1048576 ))
        rm -rf "$probe"
    fi
    # +3 МиБ: модули GRUB, каталоги, служебные структуры FAT.
    need=$(( kernel_mb + efi_mb + 3 ))
    # Округление ВВЕРХ до сетки — ради обновляемости (см. шапку).
    echo $(( ( (need + VOID_P1_GRID_MB - 1) / VOID_P1_GRID_MB ) * VOID_P1_GRID_MB ))
}
