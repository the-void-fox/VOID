//! `lx-fuzz` — **граница ЛИЧНОСТИ LINUX под обстрелом аргументами** (Веха 225.3).
//!
//! ## Зачем отдельный зонд, если есть `sysfuzz`
//!
//! `sysfuzz` бьёт по РОДНЫМ вызовам VOID. Путь Linux он не трогает вовсе, а это отдельная
//! поверхность и притом самая новая: `fork`, `execve`, трубы, нити, `wait4`, `poll` и настоящий
//! busybox появились ПОСЛЕ того, как написана модель угроз (ADR 0023). Каждый обработчик в
//! `lxabi` берёт пользовательские указатели, и верить им нельзя ровно так же.
//!
//! Что уже находили в этом коде случайно, без инструмента:
//!
//! * `read(0, NULL, 1)` из любой Linux-программы РОНЯЛ ЯДРО (Веха 223.6);
//! * пробуждение заблокированного вызова затирало НОМЕР вызова (Веха 223.5).
//!
//! Оба — аргументного рода, и оба нашлись случайно. Этот зонд ищет их нарочно.
//!
//! ## Что считается находкой
//!
//! Только одно: **ядро не пережило вызов** — паника, аварийная ловушка, зависание. Отказ
//! (`-ENOSYS`, `-EFAULT`, `-EINVAL`) — правильный ответ. Смерть самого зонда находкой не
//! является: процесс вправе умереть от того, что сам себе сделал, — но видно её по тому, на
//! каком случае оборвался вывод.
//!
//! ## Почему это НАСТОЯЩИЙ Linux-бинарь, а не родная программа
//!
//! Путь `lxabi` выбирается по тому, КАК процесс вошёл в ядро: инструкцией `syscall` (на x86 она
//! ловится как #UD — EFER.SCE у нас выключен), а не родным шлюзом. Родная программа, как бы она
//! ни звала, попадёт в родной обработчик. Проверить личность Linux можно только изнутри неё.
//!
//! ## Сборка (в репозиторий кладётся ИСХОДНИК, не бинарь — как у `lx-probe` и `lx-threads`)
//!
//! ```sh
//! nix-shell --run 'rustc --edition 2021 -O --target x86_64-unknown-linux-musl \
//!   -C panic=abort -C relocation-model=pie -C link-arg=-static-pie \
//!   -C default-linker-libraries=yes -o /tmp/lx-fuzz Code/programs/lx-fuzz/main.rs'
//! Code/tools/void-store-import <образ> put /tmp/lx-fuzz bin/x86_64/lx-fuzz
//! # в системе:  run lx-fuzz        — все случаи
//! #             run lx-fuzz 400    — продолжить с номера 400 (после гибели зонда)
//! ```

#![no_std]
#![no_main]

use core::arch::asm;

/// Сырой системный вызов Linux: номер в `rax`, аргументы в `rdi`, `rsi`, `rdx`.
///
/// # Safety
/// Делает ровно то, что сказано: номер может быть чужим, аргументы — указателями в никуда.
/// В этом и назначение.
unsafe fn sys(nr: usize, a0: usize, a1: usize, a2: usize) -> isize {
    let r: isize;
    asm!("syscall", inlateout("rax") nr as isize => r,
         in("rdi") a0, in("rsi") a1, in("rdx") a2,
         lateout("rcx") _, lateout("r11") _, options(nostack));
    r
}

/// Печать — ПРАВИЛЬНЫМ вызовом `write`, с проверенными аргументами. Сам `write` при этом тоже
/// обстреливается, но отдельно: иначе рассказать о находке было бы нечем.
fn w(s: &[u8]) {
    unsafe {
        sys(1, 1, s.as_ptr() as usize, s.len());
    }
}

fn num(mut v: usize) {
    if v == 0 {
        w(b"0");
        return;
    }
    let mut buf = [0u8; 20];
    let mut i = buf.len();
    while v > 0 {
        i -= 1;
        buf[i] = b'0' + (v % 10) as u8;
        v /= 10;
    }
    w(&buf[i..]);
}

/// Потолок перебираемых номеров: таблица личности кончается на 334 (`Renameat2`), выше —
/// заведомо неизвестные. Неизвестный номер тоже случай: ядро обязано ответить `-ENOSYS`, а не
/// чем попало.
const NR_MAX: usize = 350;

/// Что делать с вызовом. Пропуск — ВСЕГДА с причиной: молча пропущенный вызов в отчёте
/// неотличим от проверенного и создаёт ровно ту уверенность, которой нет.
enum Policy {
    /// Бить всеми наборами, включая указатель на свою память.
    Fire,
    /// Бить, но НЕ давать свой адрес: вызов перекраивает адресное пространство, и настоящий
    /// указатель на свой код или стек зонд убьёт — а ядро тут будет ни при чём.
    WildOnly,
    Skip(&'static str),
}

fn policy(nr: usize) -> Policy {
    match nr {
        60 | 231 => Policy::Skip("exit / exit_group — кончают зонд"),
        59 => Policy::Skip("execve — подменяет образ процесса"),
        56 | 57 | 58 => Policy::Skip("fork / vfork / clone — удачное ветвление размножит сам зонд"),
        61 => Policy::Skip("wait4 — ждёт потомка бесконечно"),
        202 => Policy::Skip("futex — ждёт бесконечно"),
        7 => Policy::Skip("poll — ждёт столько, сколько сказали"),
        0 => Policy::Skip("read — ждёт ввода; по нему бьёт отдельный случай ниже"),
        35 | 230 => Policy::Skip("nanosleep — спит столько, сколько сказали"),
        62 | 200 | 234 => Policy::Skip("kill / tkill / tgkill — зонд убьёт себя или шелл"),
        // Поймано на хосте первым же прогоном: `close(1)` закрывает СВОЙ ЖЕ вывод, и зонд
        // немеет на случае 68. На VOID это выглядело бы как зависание — то есть ЛОЖНАЯ
        // находка, а она хуже пропуска: обесценивает весь отчёт.
        //
        // Враждебный номер дескриптора при этом не остаётся непроверенным: его берёт первым
        // аргументом добрая дюжина соседей (`write`, `fstat`, `lseek`, `ioctl`, `fcntl`…), и по
        // ним он обстреливается теми же числами.
        3 => Policy::Skip("close — закроет свой же вывод, и зонд онемеет"),
        33 => Policy::Skip("dup3 — подменит свой же вывод чужим дескриптором"),
        // Семейство памяти: бьём, но дикими адресами. Снять отображение со своего кода — это
        // законная смерть процесса, а не находка; ядро же проверяется теми же случаями.
        9 | 10 | 11 | 12 | 25 | 28 => Policy::WildOnly,
        _ => Policy::Fire,
    }
}

/// Враждебные числа. Каждое — известный способ обмануть проверку диапазона.
const EVIL: &[(usize, &[u8])] = &[
    (0, "ноль".as_bytes()),
    (1, b"1"),
    (usize::MAX, b"MAX"),
    (usize::MAX - 7, b"MAX-7"),
    // Половина ядра: higher-half с Вехи 87. Процесс не вправе ни читать её, ни заставить ядро
    // писать туда по своей просьбе.
    (0xFFFF_8000_0000_0000, b"KERNEL"),
    // Под началом области процесса: соседняя страница уже не наша.
    (0x4000_0000 - 8, b"<USER"),
    // В области процесса, но заведомо не отображено.
    (0x5F00_0000, b"UNMAPPED"),
];

const LENS: &[(usize, &[u8])] = &[(0, b"len0"), (1, b"len1"), (usize::MAX, b"lenMAX"), (1 << 40, b"lenTB")];

fn shot(idx: usize, nr: usize, tag: &[u8], a: usize, b: usize, c: usize) {
    // Объявляем случай ДО выстрела: если машина встала, последняя строка и есть виновник.
    // Печать после сказала бы лишь то, что пережитые случаи пережиты.
    w(b"LXFUZZ CASE ");
    num(idx);
    w(b" nr=");
    num(nr);
    w(b" ");
    w(tag);
    w(b"\n");
    unsafe {
        sys(nr, a, b, c);
    }
}

/// Входная точка — `main`, а не `_start`: у статического PIE `_start` даёт `rcrt1.o` из musl
/// (он разбирает стек и зовёт `main`), и своё определение столкнулось бы с ним на линковке.
/// Тот же приём, что у соседнего зонда `lx-threads`.
#[no_mangle]
pub extern "C" fn main(argc: i32, argv: *const *const u8) -> i32 {
    // Номер случая, с которого начинать: `lx-fuzz 400` продолжает после гибели зонда. Разбор
    // руками — тащить сюда форматирование ради одного числа незачем.
    let from = if argc > 1 {
        let mut v = 0usize;
        let mut p = unsafe { *argv.add(1) };
        unsafe {
            while *p != 0 {
                let c = *p;
                if !c.is_ascii_digit() {
                    break;
                }
                v = v * 10 + (c - b'0') as usize;
                p = p.add(1);
            }
        }
        v
    } else {
        0
    };

    w(b"LXFUZZ START from=");
    num(from);
    w(b"\n");
    let mine = [0u8; 64];
    let mine_ptr = mine.as_ptr() as usize;

    let mut idx = 0usize;
    let mut fired = 0usize;
    let mut skipped = 0usize;
    for nr in 0..=NR_MAX {
        let pol = policy(nr);
        if let Policy::Skip(why) = pol {
            skipped += 1;
            w(b"LXFUZZ SKIP nr=");
            num(nr);
            w(b" - ");
            w(why.as_bytes());
            w(b"\n");
            continue;
        }
        for (a, tag) in EVIL {
            for (l, _) in LENS {
                if idx >= from {
                    shot(idx, nr, tag, *a, *l, *a);
                    fired += 1;
                }
                idx += 1;
            }
        }
        // Честный адрес с дикой длиной — самый тихий способ прочитать чужое. Семейству памяти
        // его не даём (см. [`Policy::WildOnly`]).
        if !matches!(pol, Policy::WildOnly) {
            for (l, tag) in LENS {
                if idx >= from {
                    shot(idx, nr, tag, mine_ptr, *l, mine_ptr);
                    fired += 1;
                }
                idx += 1;
            }
        }
    }

    w(b"LXFUZZ VERDICT SURVIVED cases=");
    num(fired);
    w(b" skipped=");
    num(skipped);
    w(b"\n");
    // Кончаем САМИ, не возвращаясь в musl. Первый полный прогон кончился так: вердикт
    // напечатан, а следом «P3 'lx-fuzz' page fault (exec) @ 0x0 — ПРОЦЕСС УБИТ». Виноват не
    // выход, а обстрел: среди случаев есть `arch_prctl(ARCH_SET_FS, …)` с диким адресом, и
    // после него TLS у процесса не тот, а разбор завершения в musl на него опирается.
    //
    // Само по себе это не находка (ядро честно сказало «ядро живо»), но в журнале выглядит
    // пугающе и спорит с вердиктом строкой ниже. `exit_group` обрывает это одной инструкцией.
    unsafe {
        sys(231, 0, 0, 0);
    }
    0
}

#[panic_handler]
fn panic(_: &core::panic::PanicInfo) -> ! {
    w("LXFUZZ PANIC (сам зонд, не ядро)\n".as_bytes());
    unsafe {
        sys(231, 1, 0, 0);
    }
    loop {}
}
