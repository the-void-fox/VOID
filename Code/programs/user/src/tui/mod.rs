//! **Тулкит терминала** — пара к оконному `ui/` ([[void-ui]]), Веха 230.3.
//!
//! ## Зачем он
//!
//! Писать программу для терминала в VOID было нечем. `ved` рисует escape-кодами руками, `vvsh`
//! носит свой разбор клавиш, диспетчер задач в текстовом режиме не существует вовсе — а
//! терминал это то, чем систему чинят, когда оболочка не поднялась. Каждая следующая программа
//! начиналась бы с собственной рамки, собственного списка и собственного понимания, что такое
//! `ESC[3~`.
//!
//! Образец взят у `ratatui` (и вообще у грамотных TUI), а не выдуман: **буфер ячеек, в который
//! рисуют виджеты, и отправка РАЗНИЦЫ между кадрами**. Это сразу снимает мерцание и делает
//! перерисовку дешёвой — у нас особенно, потому что байты уезжают через IPC, а на том конце их
//! разбирает парсер VT и кладёт в свой грид.
//!
//! ## Как этим пользуются
//!
//! ```ignore
//! let mut app = tui::App::open();           // запасной экран, курсор спрятан
//! let mut top = 0;                          // прокрутка списка — состояние программы
//! loop {
//!     let area = app.screen().area();
//!     let buf = app.screen().frame();       // чистый кадр
//!     let (head, rest) = area.cut_top(1);
//!     tui::status(buf, head, "заголовок", "справа", tui::Style::SELECTED);
//!     let inner = tui::block(buf, rest, "список", tui::Style::MUTED);
//!     tui::list(buf, inner, &items, Some(sel), &mut top, tui::Style::PLAIN);
//!     app.screen().flush();                 // уедет только изменившееся
//!     match app.next() {
//!         tui::Event::Key(tui::Key::Ctrl('q')) | tui::Event::Eof => break,
//!         tui::Event::Key(tui::Key::Down) => sel += 1,
//!         _ => {}
//!     }
//! }
//! app.close();
//! ```
//!
//! ## Правила, которые стоит знать заранее
//!
//! - **Экран собирают ИСКЛЮЧИТЕЛЬНО из [`widget`]**. Не хватает — дописать туда. Свой список в
//!   каждой программе — это свой цвет выделения и своя прокрутка, и расходятся они молча.
//! - **Цвет по умолчанию — «не трогай»** ([`Color::Default`]). Программа, красящая всё подряд,
//!   на чужой теме выглядит сломанной.
//! - **Размер окна и прерывание приезжают СОБЫТИЯМИ** ([`Event::Resized`], [`Event::Interrupted`]):
//!   сигналов нет, и проглотить их молча нельзя.
//! - **Ширина знака — одна ячейка.** Для встроенного шрифта (8×16, CP866) это правда; широкие
//!   знаки (иероглифы, эмодзи) поедут. Сказано вслух, чтобы это было известным ограничением, а
//!   не сюрпризом.

// «Не используется» про тулкит ничего не значит — тот же довод, что у оконного `ui/` (Веха
// 223.4): модуль подключается по `#[path]` в каждую полноэкранную программу, и каждая берёт
// свою горсть виджетов. Для компилятора остальные мертвы: редактору не нужна полоса хода,
// диспетчеру — поле ввода. Решение принадлежит модулю, а не его потребителям.
