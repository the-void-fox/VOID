//! Буфер ячеек — то, во что программа рисует, и разница между двумя кадрами.
//!
//! ## Почему буфер, а не печать на месте
//!
//! Печатать сразу — значит печатать всё и каждый раз. Так устроен `ved` до этой вехи: на каждую
//! клавишу он проходит экран строками и шлёт их целиком. Стоит это дорого именно у нас: байты
//! уезжают через IPC к терминалу, тот разбирает их парсером VT и кладёт в свой грид — то есть
//! цена не «байты в трубу», а три чужие работы на каждый знак.
//!
//! С буфером программа рисует в память, а на экран уходит РАЗНИЦА: сменилась строка состояния —
//! уедет строка состояния. Это же снимает мерцание: кадр не бывает наполовину стёртым, потому
//! что стирания нет вовсе.
//!
//! Идея не наша — так устроены ratatui и все грамотные TUI. Взято сознательно: своё изобретение
//! здесь было бы хуже и медленнее.

use alloc::string::String;
use alloc::vec;
use alloc::vec::Vec;

use super::layout::Rect;
use super::style::{sgr, Style};

/// Одна ячейка экрана: знак и его стиль.
///
/// Знак, а не строка: в гриде терминала ячейка и есть знак. Многобайтные символы занимают одну
/// ячейку — и это ПРАВДА ровно для того шрифта, который у нас есть (8×16 CP866, моноширинный).
/// Широкие знаки (иероглифы, эмодзи) заняли бы две, и когда они понадобятся, это будет видно
/// сразу: текст поедет вправо. Честнее знать об этом сейчас, чем подпирать половинчатым учётом.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct Cell {
    pub ch: char,
    pub style: Style,
}

impl Default for Cell {
    fn default() -> Self {
        Cell { ch: ' ', style: Style::PLAIN }
    }
}

/// Прямоугольник ячеек, в который рисуют виджеты.
pub struct Buffer {
    pub w: u16,
    pub h: u16,
    cells: Vec<Cell>,
}

impl Buffer {
    pub fn new(w: u16, h: u16) -> Buffer {
        Buffer { w, h, cells: vec![Cell::default(); w as usize * h as usize] }
    }

    /// Перемерить под новый размер окна. Содержимое при этом ТЕРЯЕТСЯ — после смены размера
    /// кадр всё равно считается заново: ширина меняет переносы, раскладку и всё остальное.
    pub fn resize(&mut self, w: u16, h: u16) {
        self.w = w;
        self.h = h;
        self.cells.clear();
        self.cells.resize(w as usize * h as usize, Cell::default());
    }

    pub fn clear(&mut self) {
        for c in &mut self.cells {
            *c = Cell::default();
        }
    }

    pub fn area(&self) -> Rect {
        Rect { x: 0, y: 0, w: self.w, h: self.h }
    }

    fn idx(&self, x: u16, y: u16) -> Option<usize> {
        (x < self.w && y < self.h).then(|| y as usize * self.w as usize + x as usize)
    }

    pub fn get(&self, x: u16, y: u16) -> Cell {
        self.idx(x, y).map(|i| self.cells[i]).unwrap_or_default()
    }

    /// Положить знак. Выход за край — не ошибка, а обычное дело: виджет рисует по своему
    /// прямоугольнику и не обязан помнить, что экран кончился.
    pub fn set(&mut self, x: u16, y: u16, ch: char, style: Style) {
        if let Some(i) = self.idx(x, y) {
            self.cells[i] = Cell { ch, style };
        }
    }

    /// Написать строку от `x`, не выходя за `max_w` и за край. Возвращает, сколько ячеек занято.
    ///
    /// Обрезает по ЗНАКАМ, а не по байтам: в русском тексте байт — это полсимвола, и обрезание
    /// по ним давало бы кракозябры (на этом уже обжигались в баре).
    pub fn put(&mut self, x: u16, y: u16, s: &str, max_w: u16, style: Style) -> u16 {
        let mut n = 0u16;
        for ch in s.chars() {
            if n >= max_w || x + n >= self.w {
                break;
            }
            self.set(x + n, y, ch, style);
            n += 1;
        }
        n
    }

    /// Написать строку, обрезав её многоточием, если не влезает.
    ///
    /// Многоточие — один знак `…`: во встроенном шрифте он есть (CP866 рисует его точкой-точкой
    /// -точкой), а три отдельные точки съели бы три ячейки из тех, что и так кончились.
    pub fn put_clip(&mut self, x: u16, y: u16, s: &str, max_w: u16, style: Style) -> u16 {
        if max_w == 0 {
            return 0;
        }
        let len = s.chars().count() as u16;
        if len <= max_w {
            return self.put(x, y, s, max_w, style);
        }
        let keep = max_w.saturating_sub(1);
        let mut n = 0;
        for ch in s.chars().take(keep as usize) {
            self.set(x + n, y, ch, style);
            n += 1;
        }
        self.set(x + n, y, '…', style);
        n + 1
    }

    /// Залить прямоугольник знаком (обычно пробелом — так красят фон).
    pub fn fill(&mut self, r: Rect, ch: char, style: Style) {
        for y in r.y..r.bottom().min(self.h) {
            for x in r.x..r.right().min(self.w) {
                self.set(x, y, ch, style);
            }
        }
    }
}

/// Собрать байты, превращающие экран `prev` в экран `next`.
///
/// Обходим ячейки построчно и склеиваем ПОЛОСЫ подряд идущих изменений: на каждую полосу — один
/// перевод курсора (`CUP`), дальше просто знаки. Стиль переписывается только там, где он
/// сменился, но не хитрее того (см. [`sgr`]): правильность важнее нескольких байт.
///
/// Пустая строка на выходе значит «кадр не изменился» — и тогда в терминал не уходит ничего.
/// Это не оптимизация, а требование: программа, перерисовывающая неизменный экран двадцать раз
/// в секунду, не даёт терминалу спать, а в VOID за сон платят временем батареи ([[cpu-budget]]).
///
/// ## Последняя ячейка последней строки НЕ ПИШЕТСЯ НИКОГДА
///
/// Запись в правый нижний угол доводит курсор до края, а дальше терминал переводит строку и
/// ПРОКРУЧИВАЕТ экран. Кадр уезжает на строку вверх, мы об этом не знаем — и следующая разница
/// считается от выдумки: на экране две строки состояния, старая и новая.
///
/// Это и случилось на первом же прогоне Вехи 230.3, причём дважды обмануло. Сначала я защитил
/// угол в [`super::Screen::flush`] — сделал ячейку пустой, рассудив, что равная прошлой она не
/// попадёт в разницу. Не помогло, и правильно: полосу изменений разрывают только ДВЕ совпавшие
/// ячейки подряд (так дешевле, чем переставлять курсор), а у края второй ячейке взяться неоткуда
/// — и совпавший угол уезжал в терминал вместе с полосой. Пустой, но уезжал, и прокручивал.
///
/// Вывод, который стоит помнить: **защищать надо там, где пишут, а не там, где рисуют.**
pub fn diff(prev: &Buffer, next: &Buffer, out: &mut String) {
    use core::fmt::Write;
    debug_assert!(prev.w == next.w && prev.h == next.h, "кадры разного размера не сравнивают");
    let mut pen: Option<Style> = None;
    for y in 0..next.h {
        // Правый нижний угол исключаем из рассмотрения совсем — см. шапку.
        let край = if y + 1 == next.h { next.w.saturating_sub(1) } else { next.w };
        let mut x = 0;
        while x < край {
            if prev.get(x, y) == next.get(x, y) {
                x += 1;
                continue;
            }
            // Начало полосы: ставим курсор (строки и колонки у CSI считаются с единицы).
            let _ = write!(out, "\x1b[{};{}H", y + 1, x + 1);
            while x < край {
                let c = next.get(x, y);
                if prev.get(x, y) == c {
                    // Одна совпавшая ячейка — не повод рвать полосу: перевод курсора стоит
                    // восемь байт, а знак один. Рвём, когда совпало две подряд — или когда
                    // совпавшая ячейка последняя в строке: тянуть полосу дальше некуда.
                    if x + 1 >= край || prev.get(x + 1, y) == next.get(x + 1, y) {
                        break;
                    }
                }
                if pen != Some(c.style) {
                    sgr(out, c.style);
                    pen = Some(c.style);
                }
                out.push(c.ch);
                x += 1;
            }
        }
    }
    // Перо возвращаем в обычное состояние: следующим в этот терминал печатает кто-то другой —
    // шелл, ядро, другая программа, — и красить их своим последним цветом мы права не имеем.
    if pen.is_some() {
        out.push_str("\x1b[0m");
    }
}
