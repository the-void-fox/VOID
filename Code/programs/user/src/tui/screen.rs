//! Экран: два кадра, разница между ними и всё, что надо сказать терминалу вокруг рисования.
//!
//! ## Отдельный экран программы (alt-screen)
//!
//! Полноэкранная программа въезжает на ЗАПАСНОЙ экран (`ESC[?1049h`) и съезжает с него при
//! выходе. Так лента шелла — команды, вывод сборки, сообщение об ошибке, ради которого человек
//! и полез в редактор, — остаётся на месте. До этой вехи `ved` просто стирал экран (`ESC[2J`),
//! и всё, что было до него, пропадало навсегда.
//!
//! Запасного экрана может и не быть: консоль ядра (спасательный шелл) приватные
//! последовательности ГЛОТАЕТ, не рисуя. Это ровно то поведение, на которое можно опереться:
//! там, где alt-screen не поддержан, программа просто рисует поверх, а при выходе чистит за
//! собой. Поэтому выход делает и то, и другое — и чистку, и съезд.

use alloc::string::String;

use void_user as sys;
use void_user::stdio;

use super::buf::{diff, Buffer};
use super::layout::Rect;

/// Размер, когда его не назвал никто — ни хост stdio, ни ядро. 80×25 есть у любого терминала:
/// это не догадка, а безопасное подмножество (тот же довод, что у `ved`).
const FALLBACK: (u16, u16) = (80, 25);

pub struct Screen {
    /// Что сейчас на экране (по нашему мнению).
    shown: Buffer,
    /// Кадр, который рисуется прямо сейчас.
    next: Buffer,
    /// Куда поставить курсор после отрисовки. `None` — спрятать.
    cursor: Option<(u16, u16)>,
    /// Байты кадра — поле, а не локальная: строка переиспользуется между кадрами, иначе каждый
    /// кадр это выделение в куче на несколько килобайт.
    out: String,
}

impl Screen {
    /// Войти в полноэкранный режим: запасной экран, курсор спрятан, кадр чист.
    pub fn open() -> Screen {
        let (w, h) = measure();
        sys::write(b"\x1b[?1049h\x1b[?25l\x1b[0m\x1b[2J");
        Screen {
            shown: Buffer::new(w, h),
            next: Buffer::new(w, h),
            cursor: None,
            out: String::new(),
        }
    }

    /// Съехать: показать курсор, прибрать за собой и вернуть ленту шелла.
    ///
    /// Чистка И съезд вместе — потому что заранее неизвестно, был ли запасной экран (см. шапку).
    pub fn close(&mut self) {
        sys::write(b"\x1b[0m\x1b[2J\x1b[H\x1b[?25h\x1b[?1049l");
    }

    pub fn area(&self) -> Rect {
        self.next.area()
    }

    pub fn w(&self) -> u16 {
        self.next.w
    }

    pub fn h(&self) -> u16 {
        self.next.h
    }

    /// Перемерить окно. `true` — размер изменился, кадр надо считать заново.
    ///
    /// Зовётся на `In::Resized`: сигналов у нас нет и не будет, про новый размер программа
    /// узнаёт ВИДОМ ОТВЕТА на чтение ([[process-stdio]]).
    pub fn measure(&mut self) -> bool {
        let (w, h) = measure();
        if w == self.next.w && h == self.next.h {
            return false;
        }
        self.next.resize(w, h);
        self.shown.resize(w, h);
        // Экран чужого размера мы не видели вовсе — значит на нём может быть что угодно.
        // Стираем и считаем, что показано пусто: иначе разница посчиталась бы от выдумки.
        sys::write(b"\x1b[0m\x1b[2J");
        true
    }

    /// Начать кадр: чистый буфер, в который рисуют виджеты.
    pub fn frame(&mut self) -> &mut Buffer {
        self.next.clear();
        self.cursor = None;
        &mut self.next
    }

    /// Куда поставить курсор (ячейка). `None` — спрятать; так и стоит по умолчанию.
    ///
    /// Курсор — не украшение: в поле ввода он единственное, что говорит человеку, куда поедет
    /// следующий знак. Зато в списке или на витрине он мешает — поэтому по умолчанию его нет.
    pub fn cursor(&mut self, at: Option<(u16, u16)>) {
        self.cursor = at;
    }

    /// Отправить кадр в терминал: только разницу с прошлым.
    pub fn flush(&mut self) {
        self.out.clear();
        diff(&self.shown, &self.next, &mut self.out);
        match self.cursor {
            Some((x, y)) if x < self.next.w && y < self.next.h => {
                let _ = core::fmt::Write::write_fmt(
                    &mut self.out,
                    format_args!("\x1b[{};{}H\x1b[?25h", y + 1, x + 1),
                );
            }
            _ => {
                // Прятать курсор каждый кадр не нужно — он и так спрятан с `open`. Но если
                // прошлый кадр его показывал, убрать надо: иначе он останется мигать там, где
                // ввода больше нет.
                self.out.push_str("\x1b[?25l");
            }
        }
        if !self.out.is_empty() {
            sys::write(self.out.as_bytes());
        }
        core::mem::swap(&mut self.shown, &mut self.next);
    }

    /// Забыть, что показано: следующий кадр уедет целиком.
    ///
    /// Нужно после всего, что рисует мимо нас: чужой вывод в тот же терминал, возврат из
    /// другой программы, `^L` от человека, который видит мусор и хочет чистый экран.
    pub fn repaint(&mut self) {
        self.shown.clear();
        sys::write(b"\x1b[0m\x1b[2J");
    }
}

/// Размер окна в ячейках.
///
/// Порядок опроса — порядок осведомлённости: свой хост знает размер ОКНА (панель терминала),
/// ядро — размер своей консоли (спасательный шелл), и только если молчат оба, берём умолчание.
fn measure() -> (u16, u16) {
    let (c, r) = stdio::win_size().or_else(sys::console_size).unwrap_or(FALLBACK);
    (c.clamp(20, 400), r.clamp(4, 200))
}
