const MCU_BOOT_SIGNAL: u32 = 0x72;

/// Имя корня, под которым прошивка лежит в store (сеет ядро, см. `FIRMWARE` в `main.rs`).
const FW_ROOT: &[u8] = b"fw/rt2860";

/// Сколько слов EEPROM читаем. Дальше лежат калибровки по каналам — они понадобятся передаче,
/// а приёму хватает начала. Сорок, а не тридцать два: усиление усилителя лежит по `0x22`, и
/// прежней границы на него не хватало — пороги чувствительности считались от нуля.
const EE_WORDS: usize = 40;

unsafe fn rd32(off: usize) -> u32 {
    read_volatile((MMIO_VA + off) as *const u32)
}

unsafe fn wr32(off: usize, v: u32) {
    write_volatile((MMIO_VA + off) as *mut u32, v);
}

/// Прочитать блок EFUSE в 16 байт, начиная со слова `word` (адрес — в БАЙТАХ, кратен 16).
///
/// Это первая и единственная запись, которую делает разведка: в `EFUSE_CTRL` кладётся адрес,
/// режим «чтение» (ноль) и бит «поехали», после чего железо само гасит этот бит. Ничего в карте
/// при этом не меняется — EFUSE только читается.
///
/// `None` — бит «поехали» не погас: карта не ответила, и верить содержимому регистров нельзя.
fn efuse_block(word: usize, out: &mut [u16]) -> Option<()> {
    // Адрес задаётся В СЛОВАХ, а не в байтах (так его ставит Linux: `EFUSE_CTRL_ADDRESS_IN, i`,
    // где `i` — индекс слова с шагом 8). Первый заход умножал на два, и все блоки, кроме
    // нулевого, приезжали из вдвое более далёкого места — дамп выглядел правдоподобно и был
    // сдвинут целиком.
    let addr = (word as u32) << EFUSE_ADDR_SHIFT & EFUSE_ADDR_MASK;
    unsafe {
        let reg = (rd32(EFUSE_CTRL) & !(EFUSE_ADDR_MASK | EFUSE_MODE_MASK)) | addr | EFUSE_KICK;
        wr32(EFUSE_CTRL, reg);
    }
    // Ждём СНОМ, а не пустым циклом: EFUSE отвечает за микросекунды, но мы в обычном процессе,
    // и крутить процессор ради чужой задержки — отнимать его у всей системы (правило Вехи 168).
    let mut left = 100;
    while left > 0 && unsafe { rd32(EFUSE_CTRL) } & EFUSE_KICK != 0 {
        sys::sleep_ns(100_000);
        left -= 1;
    }
    if left == 0 {
        return None;
    }
    // Слова приезжают с конца блока: DATA3 — первые четыре байта, DATA0 — последние.
    for i in 0..4 {
        let v = unsafe { rd32(EFUSE_DATA3 - i * 4) };
        let at = i * 2;
        if at + 1 < out.len() {
            out[at] = v as u16;
            out[at + 1] = (v >> 16) as u16;
        }
    }
    Some(())
}

/// Веха 211 — ВЫТАЩИТЬ ИМЯ СЕТИ из кадра-маяка. `None` — это не маяк.
///
/// Кадр 802.11 начинается с двух байт управления: в них тип (биты 2–3) и подтип (4–7). Маяк —
/// тип 0 (управляющий) и подтип 8. Дальше 24 байта заголовка (длительность, три адреса, номер),
/// затем 12 байт тела маяка (метка времени, интервал, возможности), и только потом элементы
/// вида «номер, длина, данные». Имя сети — элемент с номером 0.
///
/// Скрытая сеть шлёт его пустым или из одних нулей: это не ошибка разбора, а выбор её хозяина,
/// и в списке она появится безымянной.
/// Что маяк рассказывает о сети (Веха 211.3).
struct Beacon {
    /// Адрес точки доступа. Именно он, а не имя, отличает сети друг от друга: имя могут носить
    /// одинаковое несколько точек одной сети, и две разные сети тоже могут назваться одинаково.
    bssid: [u8; 6],
    ssid: alloc::string::String,
    /// Канал, который точка называет сама. Ноль — не назвала; тогда считаем, что это тот, на
    /// котором мы её услышали. Спрашивать стоит: соседний канал «протекает» в наш, и точка с
    /// пятого бывает слышна на шестом.
    ch: u8,
    /// Требует ли сеть ключа.
    secure: bool,
}

/// Разобрать маяк. `None` — это не маяк или кадр оборван.
///
/// Кадр 802.11 начинается с двух байт управления: в них тип и подтип, маяк — тип 0 подтип 8.
/// Дальше фиксированная часть (адреса, номер, метка времени, интервал, возможности) и только
/// потом элементы вида «номер, длина, данные».
fn parse_beacon(f: &[u8]) -> Option<Beacon> {
    if f.len() < 36 {
        return None;
    }
    let (ftype, subtype) = ((f[0] >> 2) & 0x3, (f[0] >> 4) & 0xf);
    if ftype != 0 || subtype != 8 {
        return None;
    }
    let mut bssid = [0u8; 6];
    bssid.copy_from_slice(&f[16..22]);
    // Возможности — два байта сразу после метки времени и интервала. Бит 4 значит «сеть с
    // ключом». Это ответ на «защищена ли», но не на «чем»: старую WEP и современную WPA2 он не
    // различает, для этого дальше смотрим элементы.
    let caps = u16::from_le_bytes([f[34], f[35]]);
    let mut b = Beacon {
        bssid,
        ssid: alloc::string::String::new(),
        ch: 0,
        secure: caps & 0x0010 != 0,
    };
    let mut named = false;
    let mut at = 36;
    while at + 2 <= f.len() {
        let (id, len) = (f[at], f[at + 1] as usize);
        let body = at + 2;
        if body + len > f.len() {
            break; // кадр оборван — дальше уже не элементы
        }
        let data = &f[body..body + len];
        match id {
            // Имя сети. Пустое или из одних нулей — скрытая: это не ошибка разбора, а выбор
            // хозяина сети, и в списке она появится безымянной.
            0 => {
                named = true;
                b.ssid = if data.is_empty() || data.iter().all(|&x| x == 0) {
                    alloc::string::String::from("<скрытая>")
                } else {
                    match core::str::from_utf8(data) {
                        Ok(s) => alloc::string::String::from(s),
                        // Имя — произвольные байты, а не обязательно текст. Своё «не читается»
                        // честнее, чем выбросить сеть из списка.
                        Err(_) => alloc::string::String::from("<не текст>"),
                    }
                };
            }
            // Номер канала, названный самой точкой.
            3 if len == 1 => b.ch = data[0],
            // Современная защита (WPA2/WPA3) — элемент есть, значит ключ нужен.
            48 => b.secure = true,
            // Старая WPA жила в элементе производителя: код 00:50:f2, вид 1.
            221 if len >= 4 && data[..4] == [0x00, 0x50, 0xf2, 0x01] => b.secure = true,
            _ => {}
        }
        at = body + len;
    }
    named.then_some(b)
}

// ── разговор с точкой доступа (Веха 215) ─────────────────────────────────────────────────────
//
// Обзор эфира слушал молча. Подключение — разговор, и начинает его СТАНЦИЯ: пока мы не
// представились, для сети нас не существует. Разговор открытой системы короткий:
//
//   мы → точка   Authentication (алгоритм 0 «открытая система», шаг 1)
//   точка → мы   Authentication (шаг 2, состояние 0 — узнали)
//   мы → точка   Association Request (кто мы, что умеем, чем шифруем)
//   точка → мы   Association Response (состояние 0 и НАШ НОМЕР в сети — AID)
//
// «Открытая система» здесь не значит «сеть без пароля»: WPA2 пользуется ровно этой же
// аутентификацией, а пароль проверяется потом, четырёхэтапным рукопожатием (шаг 4 ADR 0021).
// Поэтому и на закрытой сети первые три шага обязаны пройти — иначе ошибка не там, где ключ.

/// Подтипы управляющих кадров, которые нам нужны.
const MGMT_ASSOC_REQ: u8 = 0x0;
const MGMT_ASSOC_RESP: u8 = 0x1;
const MGMT_AUTH: u8 = 0xb;

/// Собрать шапку управляющего кадра: кому, от кого, в какой сети.
///
/// У управляющего кадра три адреса, и все три здесь совпадают не случайно: получатель — точка,
/// отправитель — мы, сеть — та же точка. Номер кадра оставляем нулём: его ставит карта сама
/// (бит `NSEQ` наряда), и делать это в двух местах значило бы однажды разойтись.
fn mgmt_head(subtype: u8, bssid: &[u8; 6], mac: &[u8; 6], out: &mut alloc::vec::Vec<u8>) {
    out.push(subtype << 4); // тип 0 (управляющий) + подтип, версия 0
    out.push(0); // флаги: ни ретрансляции, ни фрагментов
    out.extend_from_slice(&[0, 0]); // длительность — её считает карта
    out.extend_from_slice(bssid); // адрес 1: получатель
    out.extend_from_slice(mac); // адрес 2: отправитель
    out.extend_from_slice(bssid); // адрес 3: сеть
    out.extend_from_slice(&[0, 0]); // номер кадра — ставит карта
}

/// Кадр «представляюсь»: открытая система, шаг первый.
fn frame_auth(bssid: &[u8; 6], mac: &[u8; 6]) -> alloc::vec::Vec<u8> {
    let mut f = alloc::vec::Vec::new();
    mgmt_head(MGMT_AUTH, bssid, mac, &mut f);
    f.extend_from_slice(&0u16.to_le_bytes()); // алгоритм: открытая система
    f.extend_from_slice(&1u16.to_le_bytes()); // шаг 1
    f.extend_from_slice(&0u16.to_le_bytes()); // состояние: успех (в запросе всегда ноль)
    f
}

/// Описание защиты (элемент 48): версия 1, групповой шифр CCMP, парный CCMP, ключ из пароля.
///
/// Веха 219 — байты лежат ОДНИМ куском и в одном месте не для красоты: ровно эти же байты мы
/// обязаны повторить во втором кадре рукопожатия, и точка сверяет их побайтно. Разойдись две
/// копии на один байт — точка сочтёт, что кто-то подменил кадр в эфире, и оборвёт соединение;
/// выглядело бы это как неверный пароль.
///
/// Коды вида `00-0f-ac-N` — это OUI консорциума Wi-Fi плюс номер шифра: 4 — CCMP, 2 — ключ из
/// пароля (PSK).
const RSN_IE: [u8; 22] = [
    48, 20, // элемент 48, длина 20
    1, 0, // версия описания
    0x00, 0x0f, 0xac, 4, // групповой шифр: CCMP
    1, 0, 0x00, 0x0f, 0xac, 4, // парных шифров один: CCMP
    1, 0, 0x00, 0x0f, 0xac, 2, // способов получить ключ один: из пароля
    0, 0, // возможности защиты — ничего особого
];

/// Кадр «прошусь в сеть»: что умеем и чем шифруем.
///
/// `rsn` — прикладывать ли описание защиты. Для сети с ключом это обязательно: точка сверяет
/// предложенные шифры со своими и отказывает, если их нет. Для открытой — наоборот, лишнее.
fn frame_assoc(bssid: &[u8; 6], mac: &[u8; 6], ssid: &[u8], rsn: bool) -> alloc::vec::Vec<u8> {
    let mut f = alloc::vec::Vec::new();
    mgmt_head(MGMT_ASSOC_REQ, bssid, mac, &mut f);
    // Возможности: инфраструктурная сеть (бит 0) и, если сеть с ключом, бит защиты (4).
    let caps: u16 = 0x0001 | if rsn { 0x0010 } else { 0 };
    f.extend_from_slice(&caps.to_le_bytes());
    // Как часто обещаем просыпаться слушать маяки. Десять — обычное значение; спать мы всё
    // равно не умеем, но поле обязательное.
    f.extend_from_slice(&10u16.to_le_bytes());
    // Имя сети.
    f.push(0);
    f.push(ssid.len() as u8);
    f.extend_from_slice(ssid);
    // Скорости. Старший бит — «базовая», то есть обязательная к поддержке: 1, 2, 5,5 и 11
    // Мбит/с. Дальше необязательные из набора OFDM.
    f.extend_from_slice(&[1, 8, 0x82, 0x84, 0x8b, 0x96, 0x0c, 0x18, 0x30, 0x48]);
    if rsn {
        f.extend_from_slice(&RSN_IE);
    }
    f
}

/// Ответ точки, если он адресован НАМ. `None` — кадр не тот или не нам.
///
/// Проверка адреса обязательна: фильтр карты пропускает всё подряд (мы просили видеть чужие
/// маяки), и ответ соседней станции выглядит ровно так же, как наш.
fn mgmt_reply<'a>(f: &'a [u8], mac: &[u8; 6]) -> Option<(u8, &'a [u8])> {
    if f.len() < 24 || f[0] & 0x0c != 0 {
        return None; // не управляющий кадр
    }
    if &f[4..10] != mac {
        return None; // адресовано не нам
    }
    Some((f[0] >> 4, &f[24..]))
}

/// Сеть в списке: то же, что в маяке, плюс где и как громко её слышно.
struct Net {
    bssid: [u8; 6],
    ssid: alloc::string::String,
    ch: u8,
    /// Лучший уровень из всех услышанных маяков, дБм.
    rssi: i32,
    secure: bool,
    beacons: u32,
}

/// Веха 211.3 — перевести число из заголовка приёма в дБм.
///
/// В заголовке лежит не уровень, а положение регулировки усиления, и отсчитывается оно ВНИЗ:
/// чем больше число, тем слабее сигнал. Поправки две — общая для карты (`base`, у нашей `-12`) и
/// своя для экземпляра (из EEPROM), плюс усиление усилителя, которое мы уже знаем по каналу.
///
/// Ноль значит «уровень не измерен», а не «тишина»: так его и понимает Linux, отдавая в этом
/// случае заведомо низкое значение.
fn rssi_dbm(raw: u8, offset: i32, lna_gain: u8) -> i32 {
    if raw == 0 {
        return -128;
    }
    -12 - offset - lna_gain as i32 - raw as i32
}

// ── кольца глазами программы (Веха 219) ──────────────────────────────────────────────────────
//
// До этой вехи кольцо приёма обходили в трёх местах: обзор эфира, ожидание ответа точки и — если
// бы дописали так же — рукопожатие. Обход один и тот же, а ошибиться в нём можно по-разному:
// забыть вернуть буфер карте, вернуть дважды, сдвинуть индекс не тогда. Поэтому обход здесь один,
// а разбор кадров — снаружи.

/// Принятый кадр и то, что карта о нём сообщила.
struct Frame {
    /// Сам кадр 802.11, без заголовка приёма и без набивки.
    body: alloc::vec::Vec<u8>,
    /// Положение регулировки усиления из заголовка приёма — сырьё для [`rssi_dbm`].
    rssi_raw: u8,
}

/// Кольцо приёма: где дескрипторы, где буферы и на каком месте мы стоим.
struct Rx {
    desc_va: usize,
    buf_va: usize,
    idx: usize,
    /// Сколько кадров карта не сумела расшифровать. Веха 220 — считаем, а не молчим: ноль здесь
    /// и растущее число — разные поломки, и по journal-строке их надо различать.
    порченых: u64,
}

impl Rx {
    /// Забрать следующий готовый кадр. `None` — карта в это место ещё ничего не положила.
    ///
    /// Кадр КОПИРУЕТСЯ в кучу, а не отдаётся ссылкой в DMA-буфер: буфер тут же возвращается карте,
    /// и ссылка на него прожила бы до первого же принятого кадра, после чего указывала бы в эфир.
    fn next(&mut self) -> Option<Frame> {
        let d = (self.desc_va + self.idx * rt2800::RXD_WORDS * 4) as *mut u32;
        let w1 = unsafe { core::ptr::read_volatile(d.add(1)) };
        if w1 & rt2800::RXD_DMA_DONE == 0 {
            return None;
        }
        let w3 = unsafe { core::ptr::read_volatile(d.add(3)) };
        let len = ((w1 >> rt2800::RXD_SDL0_SHIFT) & rt2800::RXD_SDL0_MASK) as usize;
        let head = self.buf_va + self.idx * rt2800::RX_BUF;
        let mut кадр = Frame { body: alloc::vec::Vec::new(), rssi_raw: 0 };
        // Кадр, который карта не сумела расшифровать, — мусор: длины и адреса в нём случайные.
        // Отдать такой сети значит накормить стек выдумкой.
        if w3 & rt2800::RXD_CIPHER_ERROR != 0 {
            self.порченых += 1;
        } else if len > rt2800::RXWI_SIZE {
            // Уровень сигнала лежит в заголовке приёма, который карта кладёт ПЕРЕД кадром.
            кадр.rssi_raw = unsafe { core::ptr::read_volatile((head + 8) as *const u32) } as u8;
            let n = (len - rt2800::RXWI_SIZE).min(rt2800::RX_BUF - rt2800::RXWI_SIZE);
            кадр.body.extend_from_slice(unsafe {
                core::slice::from_raw_parts((head + rt2800::RXWI_SIZE) as *const u8, n)
            });
            if w3 & rt2800::RXD_L2PAD != 0 {
                wpa::strip_l2pad(&mut кадр.body);
            }
        }
        // Буфер забрали — вернуть его карте: снять признак готовности и подвинуть свой индекс.
        unsafe { core::ptr::write_volatile(d.add(1), 0) };
        rt2800::wr32(rt2800::RX_CRX_IDX, self.idx as u32);
        self.idx = (self.idx + 1) % rt2800::RX_RING;
        (!кадр.body.is_empty()).then_some(кадр)
    }
}

/// Кольцо передачи: где дескрипторы, где буферы и на каком месте мы стоим.
struct Tx {
    desc_va: usize,
    buf_va: usize,
    idx: usize,
}

impl Tx {
    /// Отдать кадр карте и дождаться, пока она его забрала. `false` — не забрала за сто мс.
    ///
    /// «Забрала» — это НЕ «дошло до точки»: DMA лишь вынул кадр из памяти. Дошёл ли он, скажет
    /// только ответ из эфира.
    ///
    /// Ждать здесь можно и нужно: так уходят кадры разговора, которых единицы, и следующий шаг
    /// всё равно начинается с ожидания ответа.
    fn send(&mut self, frame: &[u8], wcid: Option<usize>) -> bool {
        let положили = rt2800::tx_send(self.desc_va, self.buf_va, self.idx, frame, true, wcid);
        let забрали = положили && rt2800::tx_drained(self.idx, 100);
        self.idx = (self.idx + 1) % rt2800::TX_RING;
        забрали
    }

    /// Веха 220 — ПОЛОЖИТЬ кадр и не ждать. `false` — кольцо полно, кадр не взят.
    ///
    /// Так уходят кадры сети. Ждать по сто миллисекунд на каждый значило бы отдать десять кадров
    /// в секунду; кольцо на то и кольцо, чтобы карта разбирала его своим ходом.
    ///
    /// Полное кольцо — не ошибка, а нормальная работа сети: кадр лучше отбросить, чем задержать.
    /// Но знать об этом стоит, поэтому отказ считается и попадает в отчёт.
    fn post(&mut self, frame: &[u8], wcid: Option<usize>) -> bool {
        // Карта стоит на `TX_DTX_IDX0`; дойдя до неё своим индексом, мы затёрли бы кадр, который
        // она ещё не забрала.
        let next = (self.idx + 1) % rt2800::TX_RING;
        if next as u32 == rt2800::rd32(rt2800::TX_DTX_IDX0) {
            return false;
        }
        if !rt2800::tx_send(self.desc_va, self.buf_va, self.idx, frame, true, wcid) {
            return false;
        }
        self.idx = next;
        true
    }
}

/// Ждать ответ точки на управляющий кадр нужного подтипа.
///
/// Кадры рукопожатия, попавшиеся по пути, НЕ выбрасываем, а откладываем: точка начинает
/// рукопожатие сразу за ответом о подключении, и её первый кадр нередко приезжает раньше, чем мы
/// собрались его ждать. Выброшенный здесь, он вернётся только через срок ожидания точки — а может
/// и не вернуться.
fn wait_mgmt(
    rx: &mut Rx,
    mac: &[u8; 6],
    subtype: u8,
    мс: u64,
    отложенные: &mut alloc::vec::Vec<alloc::vec::Vec<u8>>,
) -> Option<alloc::vec::Vec<u8>> {
    let until = sys::monotonic_ns() + мс * 1_000_000;
    loop {
        while let Some(f) = rx.next() {
            if let Some((подтип, хвост)) = mgmt_reply(&f.body, mac) {
                if подтип == subtype {
                    return Some(alloc::vec::Vec::from(хвост));
                }
            } else if let Some(b) = wpa::eapol_of(&f.body, mac) {
                отложенные.push(alloc::vec::Vec::from(b));
            }
        }
        if sys::monotonic_ns() >= until {
            return None;
        }
        sys::sleep_ns(1_000_000);
    }
}

/// Ждать кадр рукопожатия — сперва из отложенных, потом из эфира.
fn wait_eapol(
    rx: &mut Rx,
    mac: &[u8; 6],
    мс: u64,
    отложенные: &mut alloc::vec::Vec<alloc::vec::Vec<u8>>,
) -> Option<alloc::vec::Vec<u8>> {
    if !отложенные.is_empty() {
        return Some(отложенные.remove(0));
    }
    let until = sys::monotonic_ns() + мс * 1_000_000;
    loop {
        while let Some(f) = rx.next() {
            if let Some(b) = wpa::eapol_of(&f.body, mac) {
                return Some(alloc::vec::Vec::from(b));
            }
        }
        if sys::monotonic_ns() >= until {
            return None;
        }
        sys::sleep_ns(1_000_000);
    }
}

/// Ключи, добытые рукопожатием.
struct Keys {
    /// Парный ключ: им шифруется наш разговор с точкой.
    tk: [u8; 16],
    /// Групповой ключ и его номер. `None` — точка его не прислала.
    gtk: Option<(u8, [u8; 16])>,
    /// Ключ подписи и ключ упаковки — те же, что в рукопожатии.
    ///
    /// Нужны ПОСЛЕ него: точка время от времени меняет групповой ключ и присылает новый тем же
    /// порядком, подписанным и завёрнутым. Выбросив их вместе с рукопожатием, мы через час
    /// перестали бы слышать всё, что точка шлёт сразу всем, — и выглядело бы это как «сеть
    /// сломалась сама по себе».
    kck: [u8; 16],
    kek: [u8; 16],
}

/// Веха 219 — ЧЕТЫРЁХЭТАПНОЕ РУКОПОЖАТИЕ: единственное место, где проверяется пароль.
///
/// Открытая аутентификация не проверяет ничего, ассоциация — только совместимость шифров. Пароль
/// доказывается здесь, и доказывается ОБОЮДНО: точка убеждается, что мы его знаем, по подписи
/// нашего второго кадра, а мы, что его знает точка, — по подписи её третьего. В эфир пароль при
/// этом не идёт ни разу: из него выводится ключ сеанса, и подписи считаются им.
///
///   точка → мы   первый кадр: своё случайное число
///   мы → точка   второй: наше случайное число и подпись
///   точка → мы   третий: подпись и групповой ключ, завёрнутый в наш ключ
///   мы → точка   четвёртый: подпись — «ключи ставлю»
///
/// `Err` — где именно не сошлось. Человеку нужно именно это: «не подключилось» без места отказа
/// не отличает неверный пароль от занятого эфира.
fn handshake(
    rx: &mut Rx,
    tx: &mut Tx,
    addr: &[u8; 6],
    bssid: &[u8; 6],
    pmk: &[u8; 32],
    отложенные: &mut alloc::vec::Vec<alloc::vec::Vec<u8>>,
) -> Result<Keys, &'static str> {
    // Наше случайное число. Слабый источник — ОТКАЗ, а не «как-нибудь»: предсказуемое число здесь
    // значит, что ключ сеанса можно посчитать со стороны, и защита остаётся только на вид.
    let mut snonce = [0u8; 32];
    if !sys::random_is_strong() {
        return Err("в системе нет криптографического источника случайности");
    }
    if sys::random(&mut snonce) != snonce.len() {
        return Err("случайных чисел не дали");
    }

    // ── первый кадр: случайное число точки ──
    let м1 = wait_eapol(rx, addr, 3000, отложенные).ok_or("точка не начала рукопожатие")?;
    let (anonce, replay1) = {
        let k = wpa::parse_key_frame(&м1).ok_or("первый кадр рукопожатия не разобрался")?;
        if k.info & wpa::KI_MIC != 0 || k.info & wpa::KI_PAIRWISE == 0 {
            return Err("первый кадр рукопожатия пришёл не первым");
        }
        (k.nonce, k.replay)
    };
    let ptk = wpa::ptk(pmk, addr, bssid, &snonce, &anonce);
    let (kck, kek) = (&ptk[..16], &ptk[16..32]);

    // ── второй кадр: наше число и подпись ──
    let м2 = wpa::build_key_frame(
        wpa::KI_VERSION_2 | wpa::KI_PAIRWISE | wpa::KI_MIC,
        0,
        &replay1,
        &snonce,
        kck,
        &RSN_IE,
    );
    if !tx.send(&wpa::frame_eapol(bssid, addr, &м2), None) {
        return Err("карта не забрала второй кадр рукопожатия");
    }

    // ── третий кадр: подпись точки и групповой ключ ──
    let м3 = wait_eapol(rx, addr, 2000, отложенные).ok_or("точка не ответила на наш второй кадр")?;
    let k3 = wpa::parse_key_frame(&м3).ok_or("третий кадр рукопожатия не разобрался")?;
    // Неверный пароль выглядит НЕ как отказ, а как повтор: точка не приняла нашу подпись, молча
    // выбросила второй кадр и присылает первый заново. Ждать в этом случае нечего.
    if k3.info & wpa::KI_MIC == 0 {
        return Err("точка переспрашивает первым кадром — наша подпись ей не подошла: пароль не тот");
    }
    if !wpa::key_mic_ok(kck, &м3, &k3.mic) {
        return Err("подпись точки не сошлась — пароль не тот");
    }
    // Групповой ключ приезжает завёрнутым в наш ключ: точка отдаёт его только тому, кто знает
    // пароль. Контрольное слово упаковки — вторая проверка того же.
    let mut gtk = None;
    if k3.info & wpa::KI_ENCRYPTED != 0 && k3.data.len() >= 24 {
        let mut внутри = alloc::vec![0u8; k3.data.len() - 8];
        if !wpa::aes_unwrap(kek, k3.data, &mut внутри) {
            return Err("групповой ключ не развернулся");
        }
        if let Some((номер, ключ)) = wpa::find_gtk(&внутри) {
            if ключ.len() >= 16 {
                let mut k = [0u8; 16];
                k.copy_from_slice(&ключ[..16]);
                gtk = Some((номер, k));
            }
        }
        внутри.fill(0);
    }

    // ── четвёртый кадр: «подпись сошлась, ключи ставлю» ──
    //
    // Отправляется ДО того, как ключ уйдёт в карту: с установленным ключом карта зашифрует и его,
    // а точка ждёт этот кадр открытым — она сама поставит ключ только получив его.
    let м4 = wpa::build_key_frame(
        wpa::KI_VERSION_2 | wpa::KI_PAIRWISE | wpa::KI_MIC | wpa::KI_SECURE,
        0,
        &k3.replay,
        &[0; 32],
        kck,
        &[],
    );
    if !tx.send(&wpa::frame_eapol(bssid, addr, &м4), None) {
        return Err("карта не забрала четвёртый кадр рукопожатия");
    }
    let mut ключи = Keys { tk: [0; 16], gtk, kck: [0; 16], kek: [0; 16] };
    ключи.tk.copy_from_slice(&ptk[32..48]);
    ключи.kck.copy_from_slice(kck);
    ключи.kek.copy_from_slice(kek);
    Ok(ключи)
}

/// Веха 220 — ДЕРЖАТЬ СОЕДИНЕНИЕ: кадры из эфира в стек, из стека в эфир.
///
/// До этой вехи программа выходила сразу после рукопожатия — и соединение уходило вместе с ней:
/// держать его было некому, а остановленная карта не слышит ничего. Здесь она наконец становится
/// тем, чем должна: КАРТОЙ СИСТЕМЫ. Ядро уже умеет, чтобы картой был процесс (Веха 195), и
/// `net-srv` не знает и не должен знать, что кадры приходят по воздуху.
///
/// Шифрованием занимается карта: ключи в её таблицах, и отправляемым кадрам достаточно назвать
/// номер станции — заголовок защиты и подпись она приписывает сама, а с принятых снимает.
///
/// Возвращается, когда соединение кончилось: точка нас отключила либо стек отвалился.
fn serve(
    rx: &mut Rx,
    tx: &mut Tx,
    netdev: usize,
    addr: &[u8; 6],
    bssid: &[u8; 6],
    keys: &mut Keys,
) -> &'static str {
    if !sys::netdev_attach(netdev, addr) {
        return "ядро не приняло нас картой системы";
    }
    let mut из_эфира = 0u64;
    let mut в_эфир = 0u64;
    let mut потеряно = 0u64;
    let mut сказано = sys::monotonic_ns();
    let mut исходящий = [0u8; 2048];
    loop {
        let mut дело = false;

        // ── из эфира в стек ──
        while let Some(f) = rx.next() {
            дело = true;
            // Точка прощается — управляющим кадром, и это конец соединения, а не сбой связи.
            // Подтип 10 — «выходи из сети», 12 — «я тебя не знаю».
            if let Some((подтип, хвост)) = mgmt_reply(&f.body, addr) {
                if подтип == 10 || подтип == 12 {
                    let причина =
                        if хвост.len() >= 2 { u16::from_le_bytes([хвост[0], хвост[1]]) } else { 0 };
                    sys::write(
                        alloc::format!("[wifi] точка отключила нас (причина {})\n", причина)
                            .as_bytes(),
                    );
                    sys::netdev_detach(netdev);
                    return "точка разорвала соединение";
                }
                continue;
            }
            // Разговор о ключах: точка меняет групповой ключ, не спрашивая станцию.
            if let Some(тело) = wpa::eapol_of(&f.body, addr) {
                rekey(tx, addr, bssid, &alloc::vec::Vec::from(тело), keys);
                continue;
            }
            match wpa::wifi_to_eth(&f.body) {
                Some(eth) => {
                    if sys::netdev_rx(netdev, &eth) {
                        из_эфира += 1;
                    } else {
                        потеряно += 1;
                    }
                }
                None => {} // не наш кадр с данными — маяк соседа, подтверждение, пустышка
            }
        }

        // ── из стека в эфир ──
        loop {
            let n = sys::netdev_tx_pop(netdev, &mut исходящий);
            if n == 0 {
                break;
            }
            дело = true;
            match wpa::eth_to_wifi(bssid, &исходящий[..n]) {
                Some(кадр) => {
                    if tx.post(&кадр, Some(rt2800::WCID_AP)) {
                        в_эфир += 1;
                    } else {
                        потеряно += 1;
                    }
                }
                None => потеряно += 1,
            }
        }

        // Раз в минуту — строка в журнал. Не ради красоты: «сеть не работает» без чисел не
        // отличает «кадры не приходят» от «приходят и теряются», а это разные поломки.
        let сейчас = sys::monotonic_ns();
        if сейчас - сказано >= 60_000_000_000 {
            сказано = сейчас;
            sys::write(
                alloc::format!(
                    "[wifi] принято {}, отправлено {}, потеряно {}, не расшифровано {}\n",
                    из_эфира, в_эфир, потеряно, rx.порченых
                )
                .as_bytes(),
            );
        }
        if !дело {
            // Прерывание карты мы не заводили — значит опрос; но опрос без сна жжёт процессор
            // впустую (правило Вехи 168). Миллисекунда — компромисс: задержка незаметна человеку,
            // а ядру остаётся девятьсот девяносто девять тысячных.
            //
            // Стек, положивший кадр, будит нас раньше срока сам (`wake_netdev_owner` в ядре), так
            // что на отправку этот сон не влияет.
            sys::sleep_ns(1_000_000);
        }
    }
}

/// Веха 220 — точка СМЕНИЛА ГРУППОВОЙ КЛЮЧ: принять новый и подтвердить.
///
/// Двухэтапный разговор, младший брат рукопожатия: точка шлёт ключ, завёрнутый в наш ключ
/// упаковки и подписанный ключом подписи, а мы отвечаем подписью — «поставил». Случается это
/// само собой, раз в час или чаще, и не ответить значит потерять всё, что точка шлёт сразу всем.
///
/// Парный кадр (`KI_PAIRWISE`) сюда попасть не должен: это была бы попытка начать рукопожатие
/// заново, и разбираться с ней — отдельная работа. Молча его игнорируем: своих ключей не меняем.
fn rekey(tx: &mut Tx, addr: &[u8; 6], bssid: &[u8; 6], кадр: &[u8], keys: &mut Keys) {
    let Some(k) = wpa::parse_key_frame(кадр) else { return };
    if k.info & wpa::KI_PAIRWISE != 0 || k.info & wpa::KI_MIC == 0 {
        return;
    }
    // Подпись — единственное, что отличает точку от соседа, решившего прислать нам ключ.
    if !wpa::key_mic_ok(&keys.kck, кадр, &k.mic) {
        w("[wifi] чужая подпись на смене группового ключа — не беру\n");
        return;
    }
    if k.info & wpa::KI_ENCRYPTED == 0 || k.data.len() < 24 {
        return;
    }
    let mut внутри = alloc::vec![0u8; k.data.len() - 8];
    if !wpa::aes_unwrap(&keys.kek, k.data, &mut внутри) {
        w("[wifi] новый групповой ключ не развернулся\n");
        return;
    }
    if let Some((номер, ключ)) = wpa::find_gtk(&внутри) {
        if ключ.len() >= 16 {
            let mut k16 = [0u8; 16];
            k16.copy_from_slice(&ключ[..16]);
            rt2800::install_group_key(номер, &k16);
            keys.gtk = Some((номер, k16));
            sys::write(alloc::format!("[wifi] групповой ключ сменился на {}\n", номер).as_bytes());
        }
    }
    внутри.fill(0);
    // Ответ идёт УЖЕ ПОД ШИФРОМ: соединение защищено, и открытый кадр точка не примет.
    let ответ = wpa::build_key_frame(
        wpa::KI_VERSION_2 | wpa::KI_MIC | wpa::KI_SECURE,
        0,
        &k.replay,
        &[0; 32],
        &keys.kck,
        &[],
    );
    tx.send(&wpa::frame_eapol(bssid, addr, &ответ), Some(rt2800::WCID_AP));
}

/// Веха 219 — прочитать пароль сети из корня store.
///
/// Пароль не лежит в конфиге и лежать там не должен: конфиг показывают, копируют между машинами и
/// держат в поколениях системы. В конфиге стоит ИМЯ КОРНЯ (`arg:key=@wifi/upc`), а значение кладёт
/// человек командой `secret`. Нет корня — внятный отказ, а не молчаливая попытка подключиться
/// без пароля.
fn read_secret(store: usize, root: &[u8], out: &mut [u8]) -> Result<usize, &'static str> {
    let mut id = [0u8; 32];
    if sys::obj_get_root(store, root, &mut id) != 32 {
        return Err("такого корня нет — задай пароль командой `secret ИМЯ`");
    }
    let (got, full) = sys::obj_get_ex(store, &id, out);
    if got == 0 || got != full {
        return Err("пароль из store не читается целиком");
    }
    // Конец строки в пароль не входит: набранное через `secret` его не содержит, но значение,
    // положенное иначе, может кончаться переводом строки — а пароль из одних печатных знаков.
    let mut n = got;
    while n > 0 && (out[n - 1] == b'\n' || out[n - 1] == b'\r') {
        n -= 1;
    }
    Ok(n)
}

/// Значение строки `имя=…` среди аргументов сервиса. `None` — её не передали или она пуста.
fn arg<'a>(args: &'a [u8], имя: &[u8]) -> Option<&'a [u8]> {
    args.split(|&b| b == 0).find_map(|a| a.strip_prefix(имя)).filter(|s| !s.is_empty())
}

fn w(s: &str) {
    sys::write(s.as_bytes());
}

/// Ждать, пока бит `mask` в регистре `off` примет значение `want`. `false` — не дождались.
///
/// Сном, а не пустым циклом: мы в обычном процессе, и крутить процессор, пока железо думает
/// свою миллисекунду, значит отнимать его у всей системы (правило Вехи 168).
fn wait32(off: usize, mask: u32, want: u32, ms: usize) -> bool {
    for _ in 0..ms * 10 {
        if unsafe { rd32(off) } & mask == want {
            return true;
        }
        sys::sleep_ns(100_000);
    }
    false
}

/// Веха 207 — ЗАГРУЗИТЬ ПРОШИВКУ в буферный процессор карты.
///
/// Порядок действий взят из `rt2800_load_firmware` и `rt2800pci_write_firmware` (Linux
/// 6.18.7, GPL-2.0-or-later). Он не выводится из общих соображений: каждый шаг здесь лечит
/// свою болезнь железа, и это тот случай, когда «сделать по-своему» значит не сделать вовсе.
///
/// `Err` — на каком шаге карта не ответила. Человеку это и нужно знать: «не грузится» без места
/// отказа ничего не говорит.
fn load_firmware(fw: &[u8]) -> Result<(), &'static str> {
    // 1. Снять автопробуждение. Без этого загрузка виснет намертво — прямое предупреждение из
    //    Linux, а не наша осторожность.
    unsafe { wr32(AUTOWAKEUP_CFG, 0) };
    // 2. Дождаться, пока железо вообще отвечает осмысленно.
    let mut stable = false;
    for _ in 0..1000 {
        let v = unsafe { rd32(MAC_CSR0) };
        if v != 0 && v != 0xffff_ffff {
            stable = true;
            break;
        }
        sys::sleep_ns(1_000_000);
    }
    if !stable {
        return Err("железо не стабилизировалось (MAC_CSR0 молчит)");
    }
    // 3. Разбудить PCIe-часть и включить её такт: у RT5390 это обязательный шаг.
    unsafe {
        let aux = rd32(AUX_CTRL) | AUX_FORCE_PCIE_CLK | AUX_WAKE_PCIE_EN;
        wr32(AUX_CTRL, aux);
        wr32(PWR_PIN_CFG, 0x0000_0002);
    }
    // 4. Погасить DMA: прошивка грузится в память карты, и движок в это время трогать нельзя.
    disable_wpdma();
    // 5. Открыть хосту запись в память буферного процессора и вылить туда образ.
    unsafe {
        wr32(PBF_SYS_CTRL, PBF_HOST_RAM_WRITE);
        for (i, chunk) in fw.chunks(4).enumerate() {
            let mut word = [0u8; 4];
            word[..chunk.len()].copy_from_slice(chunk);
            wr32(FIRMWARE_BASE + i * 4, u32::from_le_bytes(word));
        }
        // Закрыть окно записи и дать процессору стартовать.
        wr32(PBF_SYS_CTRL, 0);
        wr32(PBF_SYS_CTRL, 1);
        wr32(H2M_BBP_AGENT, 0);
        wr32(H2M_MAILBOX_CSR, 0);
    }
    // 6. Дождаться, пока он скажет «готов».
    if !wait32(PBF_SYS_CTRL, PBF_READY, PBF_READY, 100) {
        return Err("буферный процессор не поднялся (PBF_SYS_CTRL без бита готовности)");
    }
    // 7. DMA снова гасим: включит его тот, кто будет заводить кольца.
    disable_wpdma();
    unsafe {
        wr32(H2M_BBP_AGENT, 0);
        wr32(H2M_MAILBOX_CSR, 0);
    }
    sys::sleep_ns(1_000_000);
    Ok(())
}

/// Веха 207.1 — СПРОСИТЬ ПРОШИВКУ и дождаться, что она забрала письмо.
///
/// Записанная прошивка и работающая прошивка — разные вещи, а по регистрам они выглядят
/// одинаково: байты в памяти карты лежат в обоих случаях. Разницу видно только так — положить
/// письмо в почтовый ящик и посмотреть, заберут ли его. Поле `OWNER` гасит тот, кто письмо
/// забрал; если в карте никто не проснулся, оно останется нашим навсегда.
///
/// `false` — не забрали: прошивка записана, но не ожила.
fn mcu_command(cmd: u32, arg0: u32, arg1: u32) -> bool {
    // Сперва дождаться, что ящик свободен: писать в занятый — затирать чужое письмо.
    if !wait32(H2M_MAILBOX_CSR, H2M_OWNER, 0, 100) {
        return false;
    }
    unsafe {
        wr32(H2M_MAILBOX_CSR, H2M_OWNER | (arg1 & 0xff) << 8 | (arg0 & 0xff));
        wr32(HOST_CMD_CSR, cmd & 0xff);
    }
    wait32(H2M_MAILBOX_CSR, H2M_OWNER, 0, 100)
}

/// Погасить движок DMA: приём, передача и признаки занятости — в ноль, «запись результата» — в
/// единицу (так делает Linux; бит отвечает за то, куда движок кладёт отчёт о передаче).
fn disable_wpdma() {
    unsafe {
        let reg = rd32(WPDMA_GLO_CFG) & !0x0000_000f | 0x0000_0020;
        wr32(WPDMA_GLO_CFG, reg);
    }
}

#[no_mangle]
pub extern "C" fn _start(mmio_cap: usize, dma_cap: usize) -> ! {
    if !sys::mmio_map(mmio_cap, MMIO_VA) {
        // Веха 206.1 — РАЗЛИЧАЕМ ДВА СЛУЧАЯ. Программа это СЕРВИС: окно регистров ей выдаёт
        // ядро по строке `service wifi mmio:wifi dma`, первым аргументом. Запущенная руками из
        // шелла, она получает на этом месте чужое право — и раньше говорила «карты не нашлось»,
        // хотя карта в машине есть и ядро её нашло. Ровно на это владелец и наткнулся.
        //
        // Отличаем по тому, дали ли нам право вообще: `NO_CAP` значит «запустили без прав».
        if mmio_cap == sys::NO_CAP {
            w("[wifi] это сервис, а не команда: окно регистров даёт ядро по строке \
`service wifi mmio:wifi dma` в конфиге поколения. Отчёт смотри в `klog`.\n");
        } else {
            w("[wifi] окна регистров нет — беспроводной карты в машине не нашлось\n");
        }
        sys::exit(1);
    }
    // Сырой дамп ДВУХ блоков: системного (с нуля) и MAC (с 0x1000). Печатается всегда, потому
    // что именно он позволяет заметить ошибку в смещении — на ней разведка уже споткнулась.
    for (label, base) in [("сис", 0usize), ("mac", 0x1000usize)] {
        let mut line = alloc::format!("[wifi] {} {:#06x}:", label, base);
        for i in 0..8 {
            line += &alloc::format!(" {:08x}", unsafe { rd32(base + i * 4) });
        }
        sys::write((line + "\n").as_bytes());
    }
    // Первое же число отвечает на главный вопрос. `ffffffff` значит «на шине никто не ответил»
    // (так читается отключённое или несуществующее устройство), ноль — «окно есть, карта молчит».
    let csr0 = unsafe { rd32(MAC_CSR0) };
    if csr0 == 0xffff_ffff || csr0 == 0 {
        sys::write(
            alloc::format!(
                "[wifi] карта не отвечает: MAC_CSR0 = {:#010x}\n\
                 [wifi] это и есть ответ чекпойнта — дальше по ADR 0021 обсуждается другая карта\n",
                csr0
            )
            .as_bytes(),
        );
        sys::exit(1);
    }
    // У RT2800 старшие 16 бит — семейство (0x3070, 0x5390 и т.д.), младшие — ревизия.
    let (chip, rev) = ((csr0 >> 16) as u16, csr0 as u16);
    let sys_ctrl = unsafe { rd32(MAC_SYS_CTRL) };
    let (a0, a1) = unsafe { (rd32(MAC_ADDR_DW0), rd32(MAC_ADDR_DW1)) };
    let mac = [a0 as u8, (a0 >> 8) as u8, (a0 >> 16) as u8, (a0 >> 24) as u8, a1 as u8, (a1 >> 8) as u8];
    let efuse = unsafe { rd32(EFUSE_CTRL) };

    sys::write(
        alloc::format!(
            "[wifi] ASIC {:04x} ревизия {:04x} (MAC_CSR0 {:#010x})\n\
             [wifi] MAC_SYS_CTRL {:#010x} — приём {}, передача {}\n\
             [wifi] адрес карты {:02x}:{:02x}:{:02x}:{:02x}:{:02x}:{:02x}\n\
             [wifi] EFUSE_CTRL {:#010x} — калибровки {}\n",
            chip,
            rev,
            csr0,
            sys_ctrl,
            if sys_ctrl & (1 << 3) != 0 { "включён" } else { "выключен" },
            if sys_ctrl & (1 << 2) != 0 { "включена" } else { "выключена" },
            mac[0], mac[1], mac[2], mac[3], mac[4], mac[5],
            efuse,
            // Бит 31 — «EFUSE присутствует»: у поздних Ralink калибровки лежат в нём, а не во
            // внешней EEPROM, и путь чтения от этого зависит целиком.
            if efuse & (1 << 31) != 0 { "в EFUSE" } else { "во внешней EEPROM" },
        )
        .as_bytes(),
    );
    // ── EFUSE: то, что карта знает о себе (Веха 206.2) ───────────────────────────────────
    //
    // Адрес, число антенн, тип радиочасти и опорная частота лежат не в регистрах, а в
    // однократно прошитой памяти карты. Без них драйвер не может ни назваться в эфире, ни
    // настроить приём: RF-тип выбирает таблицы инициализации, а поправка частоты — то, попадём
    // ли мы вообще в канал.
    if efuse & EFUSE_PRESENT == 0 {
        w("[wifi] EFUSE нет — калибровки во внешней EEPROM, её чтение ещё не написано\n");
        sys::exit(0);
    }
    let mut ee = [0u16; EE_WORDS];
    for blk in 0..EE_WORDS / 8 {
        let mut part = [0u16; 8];
        if efuse_block(blk * 8, &mut part).is_none() {
            sys::write(
                alloc::format!("[wifi] EFUSE молчит на блоке {} — дальше читать нечего\n", blk)
                    .as_bytes(),
            );
            sys::exit(1);
        }
        ee[blk * 8..blk * 8 + 8].copy_from_slice(&part);
    }
    // Адрес лежит тремя словами, по два байта в каждом, младшим вперёд.
    let mut addr = [0u8; 6];
    for i in 0..3 {
        addr[i * 2] = ee[EE_MAC0 + i] as u8;
        addr[i * 2 + 1] = (ee[EE_MAC0 + i] >> 8) as u8;
    }
    let conf0 = ee[EE_NIC_CONF0];
    // Тип радиочасти у RT53xx лежит НЕ в конфигурации, а в `CHIP_ID` — так его и читает Linux
    // (`rf = rt2800_eeprom_read(EEPROM_CHIP_ID)` для RT3290/RT5390/RT5392/RT6352). По
    // конфигурации там приезжает `0xf`, то есть чужой чип: разбор выглядел бы правдоподобно и
    // врал бы о самом главном — по типу RF выбираются все таблицы инициализации.
    let (rx_path, tx_path) = (conf0 & 0xf, (conf0 >> 4) & 0xf);
    let rf_type = if chip == 0x5390 || chip == 0x5392 || chip == 0x3290 {
        ee[EE_CHIP_ID]
    } else {
        (conf0 >> 8) & 0xf
    };
    sys::write(
        alloc::format!(
            "[wifi] EFUSE: chip-id {:04x} версия {:04x}\n\
             [wifi] адрес в EFUSE {:02x}:{:02x}:{:02x}:{:02x}:{:02x}:{:02x}\n\
             [wifi] антенн приём {} передача {}, RF {:#06x}, conf1 {:04x}, поправка частоты {:#04x}\n",
            ee[EE_CHIP_ID], ee[EE_VERSION],
            addr[0], addr[1], addr[2], addr[3], addr[4], addr[5],
            rx_path, tx_path, rf_type, ee[EE_NIC_CONF1], ee[EE_FREQ] & 0xff,
        )
        .as_bytes(),
    );
    // Сырые слова — по той же причине, что и дамп регистров: разбор может соврать, а числа нет.
    for row in 0..EE_WORDS / 8 {
        let mut line = alloc::format!("[wifi] ee {:02}:", row * 8);
        for i in 0..8 {
            line += &alloc::format!(" {:04x}", ee[row * 8 + i]);
        }
        sys::write((line + "\n").as_bytes());
    }
    // ── прошивка (Веха 207) ──────────────────────────────────────────────────────────────
    //
    // Без неё карта не делает ничего: в ней живёт буферный процессор, который и принимает кадры.
    // Прошивка — блоб производителя, приезжает в образе корнем `fw/rt2860` (если её положили в
    // сборку). Нет — так и скажем: система при этом целая, просто Wi-Fi не оживёт.
    let store = sys::cap_named("STORE").unwrap_or(sys::NO_CAP);
    if store == sys::NO_CAP {
        w("[wifi] нет права на store — прошивку не прочитать (нужен `store:r` в строке сервиса)\n");
        sys::exit(0);
    }
    let mut id = [0u8; 32];
    if sys::obj_get_root(store, FW_ROOT, &mut id) != 32 {
        w("[wifi] прошивки rt2860 в образе нет — положи её в Code/assets/firmware и пересобери\n");
        sys::exit(0);
    }
    let mut fw = alloc::vec![0u8; 16 * 1024];
    let (got, full) = sys::obj_get_ex(store, &id, &mut fw);
    if got == 0 || got > fw.len() {
        w("[wifi] прошивка не читается из store\n");
        sys::exit(1);
    }
    fw.truncate(got);
    sys::write(
        alloc::format!("[wifi] прошивка: {} Б (в объекте {} Б), гружу\n", got, full).as_bytes(),
    );
    match load_firmware(&fw) {
        Ok(()) => {
            let (pbf, mac_ctrl) = unsafe { (rd32(PBF_SYS_CTRL), rd32(MAC_SYS_CTRL)) };
            sys::write(
                alloc::format!(
                    "[wifi] прошивка записана: PBF_SYS_CTRL {:#010x}, MAC_SYS_CTRL {:#010x}\n",
                    pbf, mac_ctrl
                )
                .as_bytes(),
            );
            // А вот теперь — ожила ли она. Разница между «байты лежат в памяти карты» и «в
            // карте кто-то работает» по регистрам не видна никак; видно только по тому, забрали
            // ли письмо из ящика.
            if mcu_command(MCU_WAKEUP, 0, 2) {
                w("[wifi] ПРОШИВКА ОТВЕЧАЕТ: письмо забрано, процессор карты жив\n");
            } else {
                sys::write(
                    alloc::format!(
                        "[wifi] прошивка НЕ отвечает: письмо лежит непрочитанным \
(H2M_MAILBOX_CSR {:#010x})\n",
                        unsafe { rd32(H2M_MAILBOX_CSR) }
                    )
                    .as_bytes(),
                );
            }
        }
        Err(why) => {
            sys::write(alloc::format!("[wifi] прошивка НЕ загрузилась: {}\n", why).as_bytes());
            sys::exit(1);
        }
    }
    // ── радиочасть (Веха 208) ────────────────────────────────────────────────────────────
    //
    // Прошивка ожила — значит можно говорить с BBP и радио. Они сидят на отдельных шинах внутри
    // карты, и обращение к ним идёт через регистры-посредники; первое, что стоит спросить, —
    // версию BBP: это ответ самой цифровой части, а не памяти карты.
    unsafe { rt2800::attach(MMIO_VA) };
    // Сперва СНЯТЬ СБРОС. Карта после загрузки прошивки остаётся в нём (это видно по
    // `MAC_SYS_CTRL 0x7003` выше), и удерживаемая в ресете цифровая часть честно отвечает нулём
    // — первый заход принял этот ноль за поломку.
    if !rt2800::wake_mac() {
        sys::write(
            alloc::format!(
                "[wifi] BBP не проснулся: MAC_SYS_CTRL {:#010x}, MAC_STATUS_CFG {:#010x}\n",
                rt2800::rd32(rt2800::MAC_SYS_CTRL),
                rt2800::rd32(rt2800::MAC_STATUS_CFG),
            )
            .as_bytes(),
        );
        sys::exit(1);
    }
    // Сказать прошивке, что загрузка позади: с этого Linux начинает работу с радио. Ответа не
    // ждём — письмо без обязательств, и карта на него не отвечает.
    mcu_command(MCU_BOOT_SIGNAL, 0, 0);
    sys::sleep_ns(1_000_000);
    match rt2800::bbp_read(0) {
        Some(v) if v != 0 && v != 0xff => {
            sys::write(alloc::format!("[wifi] BBP отвечает: версия {:#04x}\n", v).as_bytes());
        }
        other => {
            sys::write(
                alloc::format!(
                    "[wifi] BBP молчит ({:?}) — радиочасть не поднялась, дальше идти незачем\n",
                    other
                )
                .as_bytes(),
            );
            sys::exit(1);
        }
    }
    // То же про радио: его регистр 0 — это идентификатор, и он обязан совпасть с тем, что EFUSE
    // назвала типом RF. Два независимых источника об одном чипе — лучшая из доступных проверок.
    match rt2800::rfcsr_read(0) {
        Some(v) => {
            sys::write(alloc::format!("[wifi] RFCSR[0] = {:#04x}\n", v).as_bytes());
        }
        None => w("[wifi] радио не отвечает на чтение\n"),
    }
    // ── таблицы (Веха 209) ───────────────────────────────────────────────────────────────
    //
    // Цифровая часть и радио отвечают — значит можно их настраивать. Записи сверяются чтением:
    // у BBP и радио свои шины, и запись в занятую шину теряется МОЛЧА, оставляя драйвер в
    // уверенности, что карта настроена.
    let (bbp_n, rf_n) = rt2800::table_sizes(rev);
    let mut diff = [(0u8, 0u8, 0u8); 12];
    let (bbp_ok, rf_ok, n_diff) = rt2800::load_tables(rev, &mut diff);
    sys::write(
        alloc::format!(
            "[wifi] таблицы: BBP {} из {}, радио {} из {}\n",
            bbp_ok, bbp_n, rf_ok, rf_n
        )
        .as_bytes(),
    );
    // Какие именно не сошлись — называем поимённо. «Часть записей не легла» без списка
    // отправляет искать вслепую, а половина таких расхождений — не поломка, а регистры, где
    // живут биты состояния: их значение по чтению и не обязано совпадать с записанным.
    for &(reg, want, got) in diff.iter().take(n_diff.min(diff.len())) {
        let (kind, num) = if reg & 0x80 != 0 { ("радио", reg & 0x7f) } else { ("BBP", reg) };
        sys::write(
            alloc::format!(
                "[wifi]   {} {}: писали {:#04x}, читается {:#04x}\n",
                kind, num, want, got
            )
            .as_bytes(),
        );
    }
    // Нормальный режим: одноантенной карте второй тракт не нужен — он тратит питание и добавляет
    // шум, а сигнала по нему нет. Числа антенн берём из EFUSE, а не из предположений.
    rt2800::normal_mode_5xxx(rx_path, tx_path);
    w("[wifi] радио в нормальном режиме: лишние тракты выключены, калибровка сделана\n");
    if n_diff > diff.len() {
        sys::write(alloc::format!("[wifi]   …и ещё {}\n", n_diff - diff.len()).as_bytes());
    }
    // ── канал и приём (Веха 210) ─────────────────────────────────────────────────────────
    //
    // Шестой канал — середина диапазона: на нём слышно и соседей снизу, и сверху, а выбирать
    // «правильный» пока незачем — сканирование по каналам будет следующей вехой.
    let ch = 6u8;
    let freq_offset = (ee[EE_FREQ] & 0xff) as u8;
    let lna_gain = (ee[EE_LNA] & 0xff) as u8;
    // Инициализация MAC — ДО настройки канала: она снимает часть регистров в исходное, и канал,
    // настроенный раньше неё, частью потерялся бы.
    rt2800::init_mac();
    if !rt2800::set_channel(ch, freq_offset, lna_gain) {
        sys::write(alloc::format!("[wifi] канала {} в таблице нет\n", ch).as_bytes());
        sys::exit(1);
    }
    rt2800::rx_enable();
    let (rf1, sys_ctrl, filt, pin) = (
        rt2800::rfcsr_read(1).unwrap_or(0),
        rt2800::rd32(rt2800::MAC_SYS_CTRL),
        rt2800::rd32(rt2800::RX_FILTER_CFG),
        rt2800::rd32(rt2800::TX_PIN_CFG),
    );
    sys::write(
        alloc::format!(
            "[wifi] канал {} (поправка {:#04x}, усиление {:#04x}): радио {:#04x}, \
MAC_SYS_CTRL {:#010x}, фильтр {:#010x}, выводы радио {:#010x}\n",
            ch, freq_offset, lna_gain, rf1, sys_ctrl, filt, pin
        )
        .as_bytes(),
    );
    // Доказательство — не передатчик (он для приёма не нужен и включается своим порядком), а
    // то, что коэффициенты синтезатора читаются такими же, какими их записали, и что приёмный
    // тракт включён. Первый заход судил по передатчику и объявил бы неудачей работающий приём.
    if rt2800::channel_ok(ch) {
        sys::write(
            alloc::format!(
                "[wifi] КАНАЛ {} НАСТРОЕН: синтезатор принял коэффициенты, приёмник включён \
(радио {:#04x})\n",
                ch, rf1
            )
            .as_bytes(),
        );
    } else {
        sys::write(
            alloc::format!(
                "[wifi] канал не дошёл: радио {:#04x}, rf8 {:?}, rf9 {:?}\n",
                rf1,
                rt2800::rfcsr_read(8),
                rt2800::rfcsr_read(9),
            )
            .as_bytes(),
        );
    }
    // ── кольцо приёма и первые кадры из эфира (Веха 211) ─────────────────────────────────
    //
    // Дескрипторы и буферы просим ОДНИМ куском DMA-памяти: карта ходит по ней сама, по
    // физическим адресам, и разрывы ей объяснить нечем.
    const DESC_VA: usize = 0x5400_0000;
    // Страница под дескрипторы обоих колец, дальше буферы: приёмные (8 × 2 КиБ) и передающие
    // (8 × 2 КиБ). Веха 220 — десять страниц, а не восемь: передающий буфер вырос с полукилобайта
    // до двух килобайт, потому что кадр с данными длиннее управляющего втрое.
    const PAGES: usize = 10;
    let Some(dma_pa) = sys::dma_alloc_pages(dma_cap, DESC_VA, PAGES) else {
        w("[wifi] DMA-памяти не дали — кольцо приёма не завести\n");
        sys::exit(1);
    };
    let buf_va = DESC_VA + 4096;
    let buf_pa = dma_pa + 4096;
    rt2800::tx_rings_idle();
    rt2800::rx_ring_init(DESC_VA, dma_pa, buf_pa);
    rt2800::wpdma_rx_on();
    sys::write(
        alloc::format!(
            "[wifi] кольцо приёма: {} буферов по {} Б, физ {:#x}, движок {:#010x}; слушаю эфир\n",
            rt2800::RX_RING,
            rt2800::RX_BUF,
            dma_pa,
            rt2800::rd32(rt2800::WPDMA_GLO_CFG),
        )
        .as_bytes(),
    );

    // ── обход каналов (Веха 211.3) ───────────────────────────────────────────────────────
    //
    // Радио слышит один канал за раз — значит обойти надо все тринадцать. Задержка на канале
    // выбрана не «на глаз»: маяк точка шлёт примерно каждые сто миллисекунд, и четверти секунды
    // хватает, чтобы услышать её дважды и не принять пропуск за отсутствие сети. Тринадцать
    // каналов по 250 мс — три с небольшим секунды на весь обзор.
    const DWELL_NS: u64 = 250_000_000;
    // Поправка уровня своя у каждого экземпляра карты и лежит в EEPROM знаковым байтом. Значение
    // больше десяти по модулю означает испорченную память — Linux в этом случае берёт ноль, и мы
    // тоже: лучше показать уровень без поправки, чем с заведомо ложной.
    let rssi_offset = {
        let v = (ee[EE_RSSI_BG] & 0xff) as i8 as i32;
        if v.abs() > 10 { 0 } else { v }
    };
    let mut nets: alloc::vec::Vec<Net> = alloc::vec::Vec::new();
    let mut beacons = 0usize;
    let mut rx = Rx { desc_va: DESC_VA, buf_va, idx: 0, порченых: 0 };
    for ch in 1u8..=13 {
        if !rt2800::set_channel(ch, freq_offset, lna_gain) {
            continue;
        }
        let until = sys::monotonic_ns() + DWELL_NS;
        while sys::monotonic_ns() < until {
            let Some(f) = rx.next() else {
                sys::sleep_ns(2_000_000);
                continue;
            };
            if let Some(b) = parse_beacon(&f.body) {
                beacons += 1;
                let rssi = rssi_dbm(f.rssi_raw, rssi_offset, lna_gain);
                match nets.iter_mut().find(|n| n.bssid == b.bssid) {
                    // Уже знакомая точка: берём ЛУЧШИЙ уровень, а не последний. Маяки ловятся
                    // неровно, и одно слабое попадание не повод занизить всю сеть.
                    Some(n) => {
                        n.beacons += 1;
                        n.rssi = n.rssi.max(rssi);
                    }
                    None => nets.push(Net {
                        bssid: b.bssid,
                        ssid: b.ssid,
                        ch: if b.ch != 0 { b.ch } else { ch },
                        rssi,
                        secure: b.secure,
                        beacons: 1,
                    }),
                }
            }
        }
    }
    // Сильные сверху: список сетей читают глазами, и порядок здесь — половина пользы.
    nets.sort_by(|a, b| b.rssi.cmp(&a.rssi));
    sys::write(
        alloc::format!("[wifi] ЭФИР: сетей {}, маяков {}\n", nets.len(), beacons).as_bytes(),
    );
    for n in &nets {
        sys::write(
            alloc::format!(
                "[wifi]   {:<24} к{:<3} {:>4} дБм  {}  {:02x}:{:02x}:{:02x}:{:02x}:{:02x}:{:02x} ({} маяков)\n",
                n.ssid,
                n.ch,
                n.rssi,
                if n.secure { "с ключом " } else { "открытая " },
                n.bssid[0], n.bssid[1], n.bssid[2], n.bssid[3], n.bssid[4], n.bssid[5],
                n.beacons,
            )
            .as_bytes(),
        );
    }
    sys::write(
        alloc::format!(
            "[wifi] кольцо: индекс карты {}, наш {}\n",
            rt2800::rd32(rt2800::RX_DRX_IDX),
            rt2800::rd32(rt2800::RX_CRX_IDX),
        )
        .as_bytes(),
    );

    // ── подключение к названной сети (Веха 215, шаг 3 ADR 0021) ──────────────────────────
    //
    // Кому представляться — НЕ УГАДЫВАЕМ. Самая громкая сеть в списке принадлежит соседу чаще,
    // чем владельцу, и лезть в неё незваным нельзя. Имя приходит строкой `arg:ssid=…` на
    // строке сервиса; нет её — обзор эфира был всей работой, и это честный конец.
    let mut argbuf = [0u8; 256];
    let n = sys::args(&mut argbuf);
    let args = &argbuf[..n];
    let Some(цель) = arg(args, b"ssid=") else {
        w("[wifi] кому представляться, не сказано — добавьте `arg:ssid=ИМЯ` в строку сервиса\n");
        rt2800::stop();
        w("[wifi] карта остановлена; обзор эфира — вся работа этого запуска\n");
        sys::exit(0);
    };
    let Some(сеть) = nets.iter().find(|n| n.ssid.as_bytes() == цель) else {
        sys::write(
            alloc::format!(
                "[wifi] сети «{}» в эфире не нашлось — подключаться не к чему\n",
                core::str::from_utf8(цель).unwrap_or("?")
            )
            .as_bytes(),
        );
        rt2800::stop();
        sys::exit(0);
    };
    sys::write(
        alloc::format!(
            "[wifi] подключаюсь к «{}» (канал {}, {} дБм, {})\n",
            сеть.ssid,
            сеть.ch,
            сеть.rssi,
            if сеть.secure { "с ключом" } else { "открытая" },
        )
        .as_bytes(),
    );

    // Веха 219 — ПАРОЛЬ ДОБЫВАЕМ ДО ВЫХОДА В ЭФИР.
    //
    // Не из осторожности, а по времени: растянуть пароль в ключ сети — это четыре тысячи проходов
    // SHA-1, и это самая долгая работа во всём подключении. Точка ждёт наш второй кадр
    // рукопожатия десятые доли секунды; посчитанный заранее ключ к тому моменту уже готов.
    let mut pmk = None;
    if сеть.secure {
        let Some(имя_корня) = arg(args, b"key=") else {
            w("[wifi] сеть с ключом, а пароля не дали: задай его командой `secret ИМЯ` и добавь \
`arg:key=@ИМЯ` в строку сервиса\n");
            rt2800::stop();
            sys::exit(1);
        };
        // Знак `@` говорит «это имя корня store, а не значение»: по нему `rebuild` проверяет, что
        // корень существует, и отказывается собирать конфиг, ссылающийся в никуда. Нам он уже не
        // нужен — но и без него имя годится, чтобы старый конфиг не сломался.
        let имя_корня = имя_корня.strip_prefix(b"@".as_slice()).unwrap_or(имя_корня);
        let mut пароль = [0u8; 64];
        let len = match read_secret(store, имя_корня, &mut пароль) {
            Ok(len) => len,
            Err(почему) => {
                sys::write(
                    alloc::format!(
                        "[wifi] пароль не прочитан ({}): {}\n",
                        core::str::from_utf8(имя_корня).unwrap_or("?"),
                        почему
                    )
                    .as_bytes(),
                );
                rt2800::stop();
                sys::exit(1);
            }
        };
        // Восемь знаков — нижняя граница самого WPA2, а не наша придирка. Короткий пароль точка
        // отвергнет молча, и искать причину пришлось бы в эфире.
        if len < 8 {
            w("[wifi] пароль короче восьми знаков — WPA2 такой не принимает\n");
            rt2800::stop();
            sys::exit(1);
        }
        pmk = Some(wpa::pmk(&пароль[..len], сеть.ssid.as_bytes()));
        // Сам пароль больше не нужен: из него уже выведен ключ сети.
        пароль.fill(0);
    }

    // Встать на канал сети и назваться карте: свой адрес и адрес точки. Без этого карта не
    // считает ответ точки нашим и не подтверждает его.
    rt2800::set_channel(сеть.ch, freq_offset, lna_gain);
    rt2800::set_addresses(&addr, &сеть.bssid);
    // Кольцо передачи кладём за кольцом приёма, в той же выданной памяти. Раскладка страницы:
    // дескрипторы приёма, дескрипторы передачи, буферы приёма, буферы передачи — всё подряд,
    // потому что карта ходит по физическим адресам и разрывы ей объяснить нечем.
    let tx_buf_off = 4096 + rt2800::RX_RING * rt2800::RX_BUF;
    let mut tx = Tx { desc_va: DESC_VA + 2048, buf_va: DESC_VA + tx_buf_off, idx: 0 };
    rt2800::tx_ring_init(tx.desc_va, dma_pa + 2048, dma_pa + tx_buf_off);
    rt2800::wpdma_tx_on();
    // Хватит слушать соседей: дальше в кольцо должно попадать наше, иначе рукопожатие утонет в
    // чужом трафике (разбор в `rt2800::rx_filter_station`).
    rt2800::rx_filter_station();
    // Кадры рукопожатия, пришедшие раньше, чем мы их ждём, складываются сюда.
    let mut отложенные: alloc::vec::Vec<alloc::vec::Vec<u8>> = alloc::vec::Vec::new();

    // Шаг 1: представиться. Срок ответа щедрый: точка отвечает за миллисекунды, но занятый эфир
    // и повторы растягивают это на порядок.
    tx.send(&frame_auth(&сеть.bssid, &addr), None);
    let Some(ответ) = wait_mgmt(&mut rx, &addr, MGMT_AUTH, 500, &mut отложенные) else {
        w("[wifi] точка не ответила на представление — дальше идти некуда\n");
        rt2800::stop();
        sys::exit(1);
    };
    // Ответ: алгоритм, шаг, состояние. Ненулевое состояние — отказ, и его причину надо назвать.
    let состояние = if ответ.len() >= 6 { u16::from_le_bytes([ответ[4], ответ[5]]) } else { 0xffff };
    if состояние != 0 {
        sys::write(
            alloc::format!("[wifi] точка отказала в представлении: состояние {}\n", состояние)
                .as_bytes(),
        );
        rt2800::stop();
        sys::exit(1);
    }

    // Шаг 2: проситься в сеть.
    tx.send(&frame_assoc(&сеть.bssid, &addr, цель, сеть.secure), None);
    let Some(ответ) = wait_mgmt(&mut rx, &addr, MGMT_ASSOC_RESP, 800, &mut отложенные) else {
        w("[wifi] точка не ответила на просьбу о подключении\n");
        rt2800::stop();
        sys::exit(1);
    };
    // Ответ: возможности, состояние, наш номер в сети.
    let состояние = if ответ.len() >= 4 { u16::from_le_bytes([ответ[2], ответ[3]]) } else { 0xffff };
    if состояние != 0 {
        sys::write(
            alloc::format!(
                "[wifi] точка отказала в подключении: состояние {} (обычные причины: не те \
шифры в описании защиты либо сеть не принимает новых станций)\n",
                состояние
            )
            .as_bytes(),
        );
        rt2800::stop();
        sys::exit(1);
    }
    let aid = if ответ.len() >= 6 { u16::from_le_bytes([ответ[4], ответ[5]]) & 0x3fff } else { 0 };

    // ── шаг 3: рукопожатие (Веха 219, шаг 4 ADR 0021) ────────────────────────────────────
    //
    // До этого места пароля никто не спрашивал: открытая аутентификация не проверяет ничего,
    // ассоциация — только совместимость шифров. У открытой сети на этом всё и кончается, у сети
    // с ключом самое главное только начинается.
    let Some(pmk) = pmk else {
        sys::write(
            alloc::format!("[wifi] в открытой сети «{}», номер {}\n", сеть.ssid, aid).as_bytes(),
        );
        rt2800::stop();
        sys::exit(0);
    };
    let mut ключи = match handshake(&mut rx, &mut tx, &addr, &сеть.bssid, &pmk, &mut отложенные) {
        Ok(ключи) => ключи,
        Err(почему) => {
            sys::write(alloc::format!("[wifi] рукопожатие не вышло: {}\n", почему).as_bytes());
            rt2800::stop();
            sys::exit(1);
        }
    };
    rt2800::install_pairwise_key(&сеть.bssid, &ключи.tk);
    let групповой = match ключи.gtk {
        Some((номер, ключ)) => {
            rt2800::install_group_key(номер, &ключ);
            alloc::format!("групповой {}", номер)
        }
        // Групповой ключ нужен только для того, что точка шлёт всем сразу; без него разговор с
        // точкой работает, а широковещательное — нет. Молчать об этом нельзя.
        None => alloc::string::String::from("группового точка не дала"),
    };
    sys::write(
        alloc::format!("[wifi] в сети «{}»: пароль верный, ключи в карте ({})\n", сеть.ssid, групповой)
            .as_bytes(),
    );

    // ── шаг 4: карта системы (Веха 220, шаг 5 ADR 0021) ──────────────────────────────────
    //
    // Право «быть картой» — отдельный токен `netdev` в строке сервиса. Нет его — соединение
    // установлено, но кадрам некуда идти, и честнее сказать это, чем уйти молча.
    let Some(netdev) = sys::cap_named("NETDEV") else {
        rt2800::stop();
        w("[wifi] соединение есть, а права `netdev` нет — кадры некуда девать; допиши его в \
строку сервиса\n");
        sys::exit(1);
    };
    let почему = serve(&mut rx, &mut tx, netdev, &addr, &сеть.bssid, &mut ключи);

    // Веха 213.2 — ОСТАНОВИТЬ КАРТУ ПЕРЕД ВЫХОДОМ. Разбор в `rt2800::stop`: карта, оставленная
    // с живым кольцом, продолжает писать маяки по физическим адресам, которые ядро уже вернуло
    // в общий котёл, — и рано или поздно кладёт кусок эфира на список свободных кадров.
    sys::netdev_detach(netdev);
    rt2800::stop();
    sys::write(alloc::format!("[wifi] соединение закончилось: {}\n", почему).as_bytes());
    sys::exit(1);
}
