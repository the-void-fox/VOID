//! `wifi` — ДРАЙВЕР беспроводной карты Ralink RT5390 (Вехи 206–219, [[0021-wifi-own-stack]]).
//!
//! ## Что это делает
//!
//! Программа проходит подключение от начала до конца, и каждый шаг — отдельная веха фазы:
//!
//! 1. опознать карту и прочитать, что она о себе знает (версия ASIC, адрес и калибровки в EFUSE);
//! 2. загрузить прошивку в её буферный процессор и убедиться, что он ожил;
//! 3. настроить радио и BBP по таблицам, встать на канал, завести кольца приёма и передачи;
//! 4. обойти тринадцать каналов и напечатать список сетей;
//! 5. представиться названной сети, попроситься в неё и провести рукопожатие WPA2.
//!
//! Начиналось это разведкой, которая только читала регистры, — и порядок шагов до сих пор тот же
//! не случайно: каждый следующий имеет смысл, только если предыдущий ответил. Поэтому в журнал
//! уходят не «получилось/нет», а сами числа: разбор может соврать, числа — нет.
//!
//! ## Чего это НЕ делает
//!
//! Не держит соединение. Ключи добыты и лежат в карте, но программа сейчас же выходит, и с ней
//! уходит соединение: службой она ещё не стала (шаг 5 ADR). Не шифрует кадры с данными — карта
//! умеет это сама, но заголовок CCMP и счётчик кадров ей надо давать, а этого пока нет. Значит и
//! `net-srv` от неё кадров не получает, и адреса по DHCP нет.
//!
//! ## Почему драйвер — обычная программа
//!
//! По той же причине, что у звука и сети: драйвер в VOID — процесс под capability (`mmio:wifi`,
//! `dma`, `store:r`). Ядро отдаёт окно регистров и DMA-память, дальше всё решает программа.
//! Падение драйвера не трогает систему, а прав у него ровно три.
//!
//! ## Что нужно в конфиге
//!
//! ```text
//! service("wifi", "mmio:wifi", "dma", "store:r",
//!         "arg:ssid=ИМЯ_СЕТИ", "arg:key=@ИМЯ_КОРНЯ")
//! ```
//!
//! `arg:key` — ИМЯ КОРНЯ store со знаком `@`, а не пароль: значение кладёт человек командой
//! `secret ИМЯ`, а знак `@` говорит `rebuild`, что корень надо проверить (Веха 219.1).
//! Конфиг после этого можно показывать и копировать. Без `arg:ssid` программа осматривает эфир и
//! честно на этом заканчивает: к какой сети подключаться, угадывать нельзя.

