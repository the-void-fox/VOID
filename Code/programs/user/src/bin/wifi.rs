//! `wifi` — РАЗВЕДКА беспроводной карты (Веха 206, шаг 1 по [[0021-wifi-own-stack]]).
//!
//! ## Что это и чего это НЕ делает
//!
//! Это не драйвер. Программа отображает окно регистров карты, читает из него несколько чисел и
//! печатает их человеку — и ни одного байта туда не пишет. Смысл ровно один: **снять сомнение
//! раньше работы**. Пока неизвестно, отвечает ли карта и что она о себе говорит, писать
//! драйвер — значит писать вслепую.
//!
//! Чекпойнт фазы сформулирован в ADR так: «карта отвечает». Ответом считается непустая и
//! неединичная версия ASIC и осмысленный MAC-адрес из EEPROM. Если вместо чисел приходят нули
//! или `ffffffff`, дальше идти незачем — обсуждается другая карта.
//!
//! ## Почему регистры читает userspace, а не ядро
//!
//! По той же причине, что у звука и сети: драйвер в VOID — обычный процесс под capability
//! (`mmio:wifi`). Ядро отдаёт окно и DMA, дальше всё решает программа. Падение разведки не
//! трогает систему, а право у неё ровно одно.
//!
//! ## Числа, которые мы спрашиваем
//!
//! У карт семейства RT2800 (наш случай — Ralink RT5390 на X54C) в начале окна лежат:
//!
//! - `0x1000 MAC_CSR0` — версия и ревизия ASIC. Это первое, что читает и Linux: по нему драйвер
//!   выбирает таблицы инициализации. Значение вида `0x5390xxxx` — карта живая и это она.
//! - `0x1004 MAC_SYS_CTRL` — состояние MAC (включены ли приём и передача).
//! - `0x1008`/`0x100c MAC_ADDR_DW0/1` — MAC-адрес, как его выставил драйвер; до инициализации
//!   там нули, и это нормально: адрес карта берёт не сама, его пишет туда хост из EEPROM.
//! - `0x0580 EFUSE_CTRL` — есть ли EFUSE вместо внешней EEPROM: у поздних Ralink калибровки
//!   лежат именно там, и путь чтения от этого зависит.
//!
//! Все четыре — ЧТЕНИЕ. Никакой инициализации: включать питание, грузить прошивку и трогать
//! кольца будет уже драйвер, когда путь будет выбран.

