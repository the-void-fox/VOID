/// Куда отображаем окно регистров карты.
const MMIO_VA: usize = 0x5300_0000;

/// Регистры, которые читаем (смещения в окне).
///
/// Веха 206.1 — `MAC_CSR0` лежит по `0x1000`, а НЕ по нулю: у RT2800 окно поделено на блоки, и
/// блок MAC начинается с четвёртого килобайта (ниже — системные регистры и EFUSE). Первый
/// прогон на живой машине прочитал версию по нулю и получил `0x00001c00` — число из другого
/// регистра, которое выглядит как ответ, но им не является. Вот почему разведка печатает ещё и
/// сырой дамп: одно число легко принять не за то, а десяток подряд врать не умеют.
const MAC_CSR0: usize = 0x1000;
const MAC_SYS_CTRL: usize = 0x1004;
const MAC_ADDR_DW0: usize = 0x1008;
const MAC_ADDR_DW1: usize = 0x100c;
const EFUSE_CTRL: usize = 0x0580;
/// Данные EFUSE приезжают четырьмя словами — и, вопреки ожиданию, С КОНЦА: `DATA3` содержит
/// первые байты блока, `DATA0` — последние. Это не наша догадка, так устроено железо (в Linux
/// об этом стоит комментарий «Apparently the data is read from end to start»).
const EFUSE_DATA0: usize = 0x0590;
const EFUSE_DATA3: usize = 0x059c;

/// Поля `EFUSE_CTRL`.
const EFUSE_KICK: u32 = 1 << 30;
const EFUSE_PRESENT: u32 = 1 << 31;
/// Адрес блока стоит в битах 17..25.
const EFUSE_ADDR_SHIFT: u32 = 17;
const EFUSE_ADDR_MASK: u32 = 0x03fe_0000;
/// Режим работы — биты 6..7; ноль значит «читать».
const EFUSE_MODE_MASK: u32 = 0x0000_00c0;

/// Слова EEPROM, которые нам нужны (нумерация в СЛОВАХ по 16 бит, как в самой EEPROM).
///
/// Веха 206.3 — адреса взяты из ТАБЛИЦЫ СООТВЕТСТВИЯ `rt2800_eeprom_map`, а не из порядка
/// перечисления. Первый разбор читал настройки по словам 5–7, потому что там они стоят в
/// `enum rt2800_eeprom_word`, — но enum в Linux это ИМЕНА, а адреса живут отдельной таблицей, и
/// там `NIC_CONF0` лежит по `0x1a`. Сырой дамп это и показал: по словам 5–6 карта отдала
/// `5390 1814` — собственные идентификаторы PCI, которые ни на какую конфигурацию не похожи.
const EE_CHIP_ID: usize = 0x00;
const EE_VERSION: usize = 0x01;
const EE_MAC0: usize = 0x02;
const EE_NIC_CONF0: usize = 0x1a;
const EE_NIC_CONF1: usize = 0x1b;
const EE_FREQ: usize = 0x1d;
/// Усиление малошумящего усилителя: младший байт — для 2,4 ГГц. От него считаются пороги
/// чувствительности приёмника, и без него они остаются при значениях по умолчанию, то есть
/// глухими к слабому сигналу.
const EE_LNA: usize = 0x22;
/// Поправка уровня сигнала, своя у каждого экземпляра карты (младший байт — знаковый).
const EE_RSSI_BG: usize = 0x23;

// ── регистры, нужные для загрузки прошивки (Веха 207) ────────────────────────────────────────
//
// Смещения и порядок действий сверены с `rt2800pci`/`rt2800lib` из Linux 6.18.7
// (GPL-2.0-or-later — совместимо с нашей GPL-3). Своего даташита у Ralink нет.

/// Куда пишется образ прошивки: окно памяти карты внутри того же BAR.
const FIRMWARE_BASE: usize = 0x2000;
/// Управление буферным процессором: бит 16 — «хост пишет в его память», бит 7 — «готов».
const PBF_SYS_CTRL: usize = 0x0400;
const PBF_READY: u32 = 1 << 7;
const PBF_HOST_RAM_WRITE: u32 = 1 << 16;
/// Общий переключатель DMA: перед загрузкой его надо погасить.
const WPDMA_GLO_CFG: usize = 0x0208;
/// Почтовые ящики к прошивке — обнуляются, чтобы она стартовала с чистого листа.
const H2M_MAILBOX_CSR: usize = 0x7010;
const H2M_BBP_AGENT: usize = 0x7028;
/// Питание и тактирование: на PCIe карту надо «разбудить» явно.
const AUX_CTRL: usize = 0x010c;
const AUX_WAKE_PCIE_EN: u32 = 1 << 1;
const AUX_FORCE_PCIE_CLK: u32 = 1 << 10;
const PWR_PIN_CFG: usize = 0x1204;
/// Автопробуждение: если его не снять, загрузка прошивки виснет намертво (об этом прямо
/// написано в Linux — «иначе rt2800_load_firmware будет висеть вечно»).
const AUTOWAKEUP_CFG: usize = 0x1208;

/// Команда прошивке кладётся ДВУМЯ регистрами: аргументы в почтовый ящик, код команды — в
/// `HOST_CMD_CSR`. Старший байт ящика (`OWNER`) держит хозяин письма: единицу ставим мы, а
/// гасит его САМА прошивка, забрав команду. Именно поэтому он и годится в доказательство: пока
/// в карте нет живого процессора, гасить там нечему.
const HOST_CMD_CSR: usize = 0x0404;
const H2M_OWNER: u32 = 0xff00_0000;
/// «Проснись» — самая безобидная из команд: ничего не включает, а ответить на неё может только
/// работающая прошивка.
const MCU_WAKEUP: u32 = 0x31;
/// «Загрузка закончена» — этим письмом Linux открывает работу с радио. Прошивка по нему
/// переходит из режима загрузки в рабочий; без него она жива, но ждёт.
const MCU_BOOT_SIGNAL: u32 = 0x72;

/// Имя корня, под которым прошивка лежит в store (сеет ядро, см. `FIRMWARE` в `main.rs`).
const FW_ROOT: &[u8] = b"fw/rt2860";

/// Сколько слов EEPROM читаем. Дальше лежат калибровки по каналам — они понадобятся передаче,
/// а приёму хватает начала. Сорок, а не тридцать два: усиление усилителя лежит по `0x22`, и
/// прежней границы на него не хватало — пороги чувствительности считались от нуля.
const EE_WORDS: usize = 40;

unsafe fn rd32(off: usize) -> u32 {
    read_volatile((MMIO_VA + off) as *const u32)
}

unsafe fn wr32(off: usize, v: u32) {
    write_volatile((MMIO_VA + off) as *mut u32, v);
}

/// Прочитать блок EFUSE в 16 байт, начиная со слова `word` (адрес — в БАЙТАХ, кратен 16).
///
/// Это первая и единственная запись, которую делает разведка: в `EFUSE_CTRL` кладётся адрес,
/// режим «чтение» (ноль) и бит «поехали», после чего железо само гасит этот бит. Ничего в карте
/// при этом не меняется — EFUSE только читается.
///
/// `None` — бит «поехали» не погас: карта не ответила, и верить содержимому регистров нельзя.
fn efuse_block(word: usize, out: &mut [u16]) -> Option<()> {
    // Адрес задаётся В СЛОВАХ, а не в байтах (так его ставит Linux: `EFUSE_CTRL_ADDRESS_IN, i`,
    // где `i` — индекс слова с шагом 8). Первый заход умножал на два, и все блоки, кроме
    // нулевого, приезжали из вдвое более далёкого места — дамп выглядел правдоподобно и был
    // сдвинут целиком.
    let addr = (word as u32) << EFUSE_ADDR_SHIFT & EFUSE_ADDR_MASK;
    unsafe {
        let reg = (rd32(EFUSE_CTRL) & !(EFUSE_ADDR_MASK | EFUSE_MODE_MASK)) | addr | EFUSE_KICK;
        wr32(EFUSE_CTRL, reg);
    }
    // Ждём СНОМ, а не пустым циклом: EFUSE отвечает за микросекунды, но мы в обычном процессе,
    // и крутить процессор ради чужой задержки — отнимать его у всей системы (правило Вехи 168).
    let mut left = 100;
    while left > 0 && unsafe { rd32(EFUSE_CTRL) } & EFUSE_KICK != 0 {
        sys::sleep_ns(100_000);
        left -= 1;
    }
    if left == 0 {
        return None;
    }
    // Слова приезжают с конца блока: DATA3 — первые четыре байта, DATA0 — последние.
    for i in 0..4 {
        let v = unsafe { rd32(EFUSE_DATA3 - i * 4) };
        let at = i * 2;
        if at + 1 < out.len() {
            out[at] = v as u16;
            out[at + 1] = (v >> 16) as u16;
        }
    }
    Some(())
}

/// Веха 211 — ВЫТАЩИТЬ ИМЯ СЕТИ из кадра-маяка. `None` — это не маяк.
///
/// Кадр 802.11 начинается с двух байт управления: в них тип (биты 2–3) и подтип (4–7). Маяк —
/// тип 0 (управляющий) и подтип 8. Дальше 24 байта заголовка (длительность, три адреса, номер),
/// затем 12 байт тела маяка (метка времени, интервал, возможности), и только потом элементы
/// вида «номер, длина, данные». Имя сети — элемент с номером 0.
///
/// Скрытая сеть шлёт его пустым или из одних нулей: это не ошибка разбора, а выбор её хозяина,
/// и в списке она появится безымянной.
/// Что маяк рассказывает о сети (Веха 211.3).
struct Beacon {
    /// Адрес точки доступа. Именно он, а не имя, отличает сети друг от друга: имя могут носить
    /// одинаковое несколько точек одной сети, и две разные сети тоже могут назваться одинаково.
    bssid: [u8; 6],
    ssid: alloc::string::String,
    /// Канал, который точка называет сама. Ноль — не назвала; тогда считаем, что это тот, на
    /// котором мы её услышали. Спрашивать стоит: соседний канал «протекает» в наш, и точка с
    /// пятого бывает слышна на шестом.
    ch: u8,
    /// Требует ли сеть ключа.
    secure: bool,
}

/// Разобрать маяк. `None` — это не маяк или кадр оборван.
///
/// Кадр 802.11 начинается с двух байт управления: в них тип и подтип, маяк — тип 0 подтип 8.
/// Дальше фиксированная часть (адреса, номер, метка времени, интервал, возможности) и только
/// потом элементы вида «номер, длина, данные».
fn parse_beacon(f: &[u8]) -> Option<Beacon> {
    if f.len() < 36 {
        return None;
    }
    let (ftype, subtype) = ((f[0] >> 2) & 0x3, (f[0] >> 4) & 0xf);
    if ftype != 0 || subtype != 8 {
        return None;
    }
    let mut bssid = [0u8; 6];
    bssid.copy_from_slice(&f[16..22]);
    // Возможности — два байта сразу после метки времени и интервала. Бит 4 значит «сеть с
    // ключом». Это ответ на «защищена ли», но не на «чем»: старую WEP и современную WPA2 он не
    // различает, для этого дальше смотрим элементы.
    let caps = u16::from_le_bytes([f[34], f[35]]);
    let mut b = Beacon {
        bssid,
        ssid: alloc::string::String::new(),
        ch: 0,
        secure: caps & 0x0010 != 0,
    };
    let mut named = false;
    let mut at = 36;
    while at + 2 <= f.len() {
        let (id, len) = (f[at], f[at + 1] as usize);
        let body = at + 2;
        if body + len > f.len() {
            break; // кадр оборван — дальше уже не элементы
        }
        let data = &f[body..body + len];
        match id {
            // Имя сети. Пустое или из одних нулей — скрытая: это не ошибка разбора, а выбор
            // хозяина сети, и в списке она появится безымянной.
            0 => {
                named = true;
                b.ssid = if data.is_empty() || data.iter().all(|&x| x == 0) {
                    alloc::string::String::from("<скрытая>")
                } else {
                    match core::str::from_utf8(data) {
                        Ok(s) => alloc::string::String::from(s),
                        // Имя — произвольные байты, а не обязательно текст. Своё «не читается»
                        // честнее, чем выбросить сеть из списка.
                        Err(_) => alloc::string::String::from("<не текст>"),
                    }
                };
            }
            // Номер канала, названный самой точкой.
            3 if len == 1 => b.ch = data[0],
            // Современная защита (WPA2/WPA3) — элемент есть, значит ключ нужен.
            48 => b.secure = true,
            // Старая WPA жила в элементе производителя: код 00:50:f2, вид 1.
            221 if len >= 4 && data[..4] == [0x00, 0x50, 0xf2, 0x01] => b.secure = true,
            _ => {}
        }
        at = body + len;
    }
    named.then_some(b)
}

/// Сеть в списке: то же, что в маяке, плюс где и как громко её слышно.
struct Net {
    bssid: [u8; 6],
    ssid: alloc::string::String,
    ch: u8,
    /// Лучший уровень из всех услышанных маяков, дБм.
    rssi: i32,
    secure: bool,
    beacons: u32,
}

/// Веха 211.3 — перевести число из заголовка приёма в дБм.
///
/// В заголовке лежит не уровень, а положение регулировки усиления, и отсчитывается оно ВНИЗ:
/// чем больше число, тем слабее сигнал. Поправки две — общая для карты (`base`, у нашей `-12`) и
/// своя для экземпляра (из EEPROM), плюс усиление усилителя, которое мы уже знаем по каналу.
///
/// Ноль значит «уровень не измерен», а не «тишина»: так его и понимает Linux, отдавая в этом
/// случае заведомо низкое значение.
fn rssi_dbm(raw: u8, offset: i32, lna_gain: u8) -> i32 {
    if raw == 0 {
        return -128;
    }
    -12 - offset - lna_gain as i32 - raw as i32
}

fn w(s: &str) {
    sys::write(s.as_bytes());
}

/// Ждать, пока бит `mask` в регистре `off` примет значение `want`. `false` — не дождались.
///
/// Сном, а не пустым циклом: мы в обычном процессе, и крутить процессор, пока железо думает
/// свою миллисекунду, значит отнимать его у всей системы (правило Вехи 168).
fn wait32(off: usize, mask: u32, want: u32, ms: usize) -> bool {
    for _ in 0..ms * 10 {
        if unsafe { rd32(off) } & mask == want {
            return true;
        }
        sys::sleep_ns(100_000);
    }
    false
}

/// Веха 207 — ЗАГРУЗИТЬ ПРОШИВКУ в буферный процессор карты.
///
/// Порядок действий взят из `rt2800_load_firmware` и `rt2800pci_write_firmware` (Linux
/// 6.18.7, GPL-2.0-or-later). Он не выводится из общих соображений: каждый шаг здесь лечит
/// свою болезнь железа, и это тот случай, когда «сделать по-своему» значит не сделать вовсе.
///
/// `Err` — на каком шаге карта не ответила. Человеку это и нужно знать: «не грузится» без места
/// отказа ничего не говорит.
fn load_firmware(fw: &[u8]) -> Result<(), &'static str> {
    // 1. Снять автопробуждение. Без этого загрузка виснет намертво — прямое предупреждение из
    //    Linux, а не наша осторожность.
    unsafe { wr32(AUTOWAKEUP_CFG, 0) };
    // 2. Дождаться, пока железо вообще отвечает осмысленно.
    let mut stable = false;
    for _ in 0..1000 {
        let v = unsafe { rd32(MAC_CSR0) };
        if v != 0 && v != 0xffff_ffff {
            stable = true;
            break;
        }
        sys::sleep_ns(1_000_000);
    }
    if !stable {
        return Err("железо не стабилизировалось (MAC_CSR0 молчит)");
    }
    // 3. Разбудить PCIe-часть и включить её такт: у RT5390 это обязательный шаг.
    unsafe {
        let aux = rd32(AUX_CTRL) | AUX_FORCE_PCIE_CLK | AUX_WAKE_PCIE_EN;
        wr32(AUX_CTRL, aux);
        wr32(PWR_PIN_CFG, 0x0000_0002);
    }
    // 4. Погасить DMA: прошивка грузится в память карты, и движок в это время трогать нельзя.
    disable_wpdma();
    // 5. Открыть хосту запись в память буферного процессора и вылить туда образ.
    unsafe {
        wr32(PBF_SYS_CTRL, PBF_HOST_RAM_WRITE);
        for (i, chunk) in fw.chunks(4).enumerate() {
            let mut word = [0u8; 4];
            word[..chunk.len()].copy_from_slice(chunk);
            wr32(FIRMWARE_BASE + i * 4, u32::from_le_bytes(word));
        }
        // Закрыть окно записи и дать процессору стартовать.
        wr32(PBF_SYS_CTRL, 0);
        wr32(PBF_SYS_CTRL, 1);
        wr32(H2M_BBP_AGENT, 0);
        wr32(H2M_MAILBOX_CSR, 0);
    }
    // 6. Дождаться, пока он скажет «готов».
    if !wait32(PBF_SYS_CTRL, PBF_READY, PBF_READY, 100) {
        return Err("буферный процессор не поднялся (PBF_SYS_CTRL без бита готовности)");
    }
    // 7. DMA снова гасим: включит его тот, кто будет заводить кольца.
    disable_wpdma();
    unsafe {
        wr32(H2M_BBP_AGENT, 0);
        wr32(H2M_MAILBOX_CSR, 0);
    }
    sys::sleep_ns(1_000_000);
    Ok(())
}

/// Веха 207.1 — СПРОСИТЬ ПРОШИВКУ и дождаться, что она забрала письмо.
///
/// Записанная прошивка и работающая прошивка — разные вещи, а по регистрам они выглядят
/// одинаково: байты в памяти карты лежат в обоих случаях. Разницу видно только так — положить
/// письмо в почтовый ящик и посмотреть, заберут ли его. Поле `OWNER` гасит тот, кто письмо
/// забрал; если в карте никто не проснулся, оно останется нашим навсегда.
///
/// `false` — не забрали: прошивка записана, но не ожила.
fn mcu_command(cmd: u32, arg0: u32, arg1: u32) -> bool {
    // Сперва дождаться, что ящик свободен: писать в занятый — затирать чужое письмо.
    if !wait32(H2M_MAILBOX_CSR, H2M_OWNER, 0, 100) {
        return false;
    }
    unsafe {
        wr32(H2M_MAILBOX_CSR, H2M_OWNER | (arg1 & 0xff) << 8 | (arg0 & 0xff));
        wr32(HOST_CMD_CSR, cmd & 0xff);
    }
    wait32(H2M_MAILBOX_CSR, H2M_OWNER, 0, 100)
}

/// Погасить движок DMA: приём, передача и признаки занятости — в ноль, «запись результата» — в
/// единицу (так делает Linux; бит отвечает за то, куда движок кладёт отчёт о передаче).
fn disable_wpdma() {
    unsafe {
        let reg = rd32(WPDMA_GLO_CFG) & !0x0000_000f | 0x0000_0020;
        wr32(WPDMA_GLO_CFG, reg);
    }
}

#[no_mangle]
pub extern "C" fn _start(mmio_cap: usize, dma_cap: usize) -> ! {
    if !sys::mmio_map(mmio_cap, MMIO_VA) {
        // Веха 206.1 — РАЗЛИЧАЕМ ДВА СЛУЧАЯ. Программа это СЕРВИС: окно регистров ей выдаёт
        // ядро по строке `service wifi mmio:wifi dma`, первым аргументом. Запущенная руками из
        // шелла, она получает на этом месте чужое право — и раньше говорила «карты не нашлось»,
        // хотя карта в машине есть и ядро её нашло. Ровно на это владелец и наткнулся.
        //
        // Отличаем по тому, дали ли нам право вообще: `NO_CAP` значит «запустили без прав».
        if mmio_cap == sys::NO_CAP {
            w("[wifi] это сервис, а не команда: окно регистров даёт ядро по строке \
`service wifi mmio:wifi dma` в конфиге поколения. Отчёт смотри в `klog`.\n");
        } else {
            w("[wifi] окна регистров нет — беспроводной карты в машине не нашлось\n");
        }
        sys::exit(1);
    }
    // Сырой дамп ДВУХ блоков: системного (с нуля) и MAC (с 0x1000). Печатается всегда, потому
    // что именно он позволяет заметить ошибку в смещении — на ней разведка уже споткнулась.
    for (label, base) in [("сис", 0usize), ("mac", 0x1000usize)] {
        let mut line = alloc::format!("[wifi] {} {:#06x}:", label, base);
        for i in 0..8 {
            line += &alloc::format!(" {:08x}", unsafe { rd32(base + i * 4) });
        }
        sys::write((line + "\n").as_bytes());
    }
    // Первое же число отвечает на главный вопрос. `ffffffff` значит «на шине никто не ответил»
    // (так читается отключённое или несуществующее устройство), ноль — «окно есть, карта молчит».
    let csr0 = unsafe { rd32(MAC_CSR0) };
    if csr0 == 0xffff_ffff || csr0 == 0 {
        sys::write(
            alloc::format!(
                "[wifi] карта не отвечает: MAC_CSR0 = {:#010x}\n\
                 [wifi] это и есть ответ чекпойнта — дальше по ADR 0021 обсуждается другая карта\n",
                csr0
            )
            .as_bytes(),
        );
        sys::exit(1);
    }
    // У RT2800 старшие 16 бит — семейство (0x3070, 0x5390 и т.д.), младшие — ревизия.
    let (chip, rev) = ((csr0 >> 16) as u16, csr0 as u16);
    let sys_ctrl = unsafe { rd32(MAC_SYS_CTRL) };
    let (a0, a1) = unsafe { (rd32(MAC_ADDR_DW0), rd32(MAC_ADDR_DW1)) };
    let mac = [a0 as u8, (a0 >> 8) as u8, (a0 >> 16) as u8, (a0 >> 24) as u8, a1 as u8, (a1 >> 8) as u8];
    let efuse = unsafe { rd32(EFUSE_CTRL) };

    sys::write(
        alloc::format!(
            "[wifi] ASIC {:04x} ревизия {:04x} (MAC_CSR0 {:#010x})\n\
             [wifi] MAC_SYS_CTRL {:#010x} — приём {}, передача {}\n\
             [wifi] адрес карты {:02x}:{:02x}:{:02x}:{:02x}:{:02x}:{:02x}\n\
             [wifi] EFUSE_CTRL {:#010x} — калибровки {}\n",
            chip,
            rev,
            csr0,
            sys_ctrl,
            if sys_ctrl & (1 << 3) != 0 { "включён" } else { "выключен" },
            if sys_ctrl & (1 << 2) != 0 { "включена" } else { "выключена" },
            mac[0], mac[1], mac[2], mac[3], mac[4], mac[5],
            efuse,
            // Бит 31 — «EFUSE присутствует»: у поздних Ralink калибровки лежат в нём, а не во
            // внешней EEPROM, и путь чтения от этого зависит целиком.
            if efuse & (1 << 31) != 0 { "в EFUSE" } else { "во внешней EEPROM" },
        )
        .as_bytes(),
    );
    // ── EFUSE: то, что карта знает о себе (Веха 206.2) ───────────────────────────────────
    //
    // Адрес, число антенн, тип радиочасти и опорная частота лежат не в регистрах, а в
    // однократно прошитой памяти карты. Без них драйвер не может ни назваться в эфире, ни
    // настроить приём: RF-тип выбирает таблицы инициализации, а поправка частоты — то, попадём
    // ли мы вообще в канал.
    if efuse & EFUSE_PRESENT == 0 {
        w("[wifi] EFUSE нет — калибровки во внешней EEPROM, её чтение ещё не написано\n");
        sys::exit(0);
    }
    let mut ee = [0u16; EE_WORDS];
    for blk in 0..EE_WORDS / 8 {
        let mut part = [0u16; 8];
        if efuse_block(blk * 8, &mut part).is_none() {
            sys::write(
                alloc::format!("[wifi] EFUSE молчит на блоке {} — дальше читать нечего\n", blk)
                    .as_bytes(),
            );
            sys::exit(1);
        }
        ee[blk * 8..blk * 8 + 8].copy_from_slice(&part);
    }
    // Адрес лежит тремя словами, по два байта в каждом, младшим вперёд.
    let mut addr = [0u8; 6];
    for i in 0..3 {
        addr[i * 2] = ee[EE_MAC0 + i] as u8;
        addr[i * 2 + 1] = (ee[EE_MAC0 + i] >> 8) as u8;
    }
    let conf0 = ee[EE_NIC_CONF0];
    // Тип радиочасти у RT53xx лежит НЕ в конфигурации, а в `CHIP_ID` — так его и читает Linux
    // (`rf = rt2800_eeprom_read(EEPROM_CHIP_ID)` для RT3290/RT5390/RT5392/RT6352). По
    // конфигурации там приезжает `0xf`, то есть чужой чип: разбор выглядел бы правдоподобно и
    // врал бы о самом главном — по типу RF выбираются все таблицы инициализации.
    let (rx_path, tx_path) = (conf0 & 0xf, (conf0 >> 4) & 0xf);
    let rf_type = if chip == 0x5390 || chip == 0x5392 || chip == 0x3290 {
        ee[EE_CHIP_ID]
    } else {
        (conf0 >> 8) & 0xf
    };
    sys::write(
        alloc::format!(
            "[wifi] EFUSE: chip-id {:04x} версия {:04x}\n\
             [wifi] адрес в EFUSE {:02x}:{:02x}:{:02x}:{:02x}:{:02x}:{:02x}\n\
             [wifi] антенн приём {} передача {}, RF {:#06x}, conf1 {:04x}, поправка частоты {:#04x}\n",
            ee[EE_CHIP_ID], ee[EE_VERSION],
            addr[0], addr[1], addr[2], addr[3], addr[4], addr[5],
            rx_path, tx_path, rf_type, ee[EE_NIC_CONF1], ee[EE_FREQ] & 0xff,
        )
        .as_bytes(),
    );
    // Сырые слова — по той же причине, что и дамп регистров: разбор может соврать, а числа нет.
    for row in 0..EE_WORDS / 8 {
        let mut line = alloc::format!("[wifi] ee {:02}:", row * 8);
        for i in 0..8 {
            line += &alloc::format!(" {:04x}", ee[row * 8 + i]);
        }
        sys::write((line + "\n").as_bytes());
    }
    // ── прошивка (Веха 207) ──────────────────────────────────────────────────────────────
    //
    // Без неё карта не делает ничего: в ней живёт буферный процессор, который и принимает кадры.
    // Прошивка — блоб производителя, приезжает в образе корнем `fw/rt2860` (если её положили в
    // сборку). Нет — так и скажем: система при этом целая, просто Wi-Fi не оживёт.
    let store = sys::cap_named("STORE").unwrap_or(sys::NO_CAP);
    if store == sys::NO_CAP {
        w("[wifi] нет права на store — прошивку не прочитать (нужен `store:r` в строке сервиса)\n");
        sys::exit(0);
    }
    let mut id = [0u8; 32];
    if sys::obj_get_root(store, FW_ROOT, &mut id) != 32 {
        w("[wifi] прошивки rt2860 в образе нет — положи её в Code/assets/firmware и пересобери\n");
        sys::exit(0);
    }
    let mut fw = alloc::vec![0u8; 16 * 1024];
    let (got, full) = sys::obj_get_ex(store, &id, &mut fw);
    if got == 0 || got > fw.len() {
        w("[wifi] прошивка не читается из store\n");
        sys::exit(1);
    }
    fw.truncate(got);
    sys::write(
        alloc::format!("[wifi] прошивка: {} Б (в объекте {} Б), гружу\n", got, full).as_bytes(),
    );
    match load_firmware(&fw) {
        Ok(()) => {
            let (pbf, mac_ctrl) = unsafe { (rd32(PBF_SYS_CTRL), rd32(MAC_SYS_CTRL)) };
            sys::write(
                alloc::format!(
                    "[wifi] прошивка записана: PBF_SYS_CTRL {:#010x}, MAC_SYS_CTRL {:#010x}\n",
                    pbf, mac_ctrl
                )
                .as_bytes(),
            );
            // А вот теперь — ожила ли она. Разница между «байты лежат в памяти карты» и «в
            // карте кто-то работает» по регистрам не видна никак; видно только по тому, забрали
            // ли письмо из ящика.
            if mcu_command(MCU_WAKEUP, 0, 2) {
                w("[wifi] ПРОШИВКА ОТВЕЧАЕТ: письмо забрано, процессор карты жив\n");
            } else {
                sys::write(
                    alloc::format!(
                        "[wifi] прошивка НЕ отвечает: письмо лежит непрочитанным \
(H2M_MAILBOX_CSR {:#010x})\n",
                        unsafe { rd32(H2M_MAILBOX_CSR) }
                    )
                    .as_bytes(),
                );
            }
        }
        Err(why) => {
            sys::write(alloc::format!("[wifi] прошивка НЕ загрузилась: {}\n", why).as_bytes());
            sys::exit(1);
        }
    }
    // ── радиочасть (Веха 208) ────────────────────────────────────────────────────────────
    //
    // Прошивка ожила — значит можно говорить с BBP и радио. Они сидят на отдельных шинах внутри
    // карты, и обращение к ним идёт через регистры-посредники; первое, что стоит спросить, —
    // версию BBP: это ответ самой цифровой части, а не памяти карты.
    unsafe { rt2800::attach(MMIO_VA) };
    // Сперва СНЯТЬ СБРОС. Карта после загрузки прошивки остаётся в нём (это видно по
    // `MAC_SYS_CTRL 0x7003` выше), и удерживаемая в ресете цифровая часть честно отвечает нулём
    // — первый заход принял этот ноль за поломку.
    if !rt2800::wake_mac() {
        sys::write(
            alloc::format!(
                "[wifi] BBP не проснулся: MAC_SYS_CTRL {:#010x}, MAC_STATUS_CFG {:#010x}\n",
                rt2800::rd32(rt2800::MAC_SYS_CTRL),
                rt2800::rd32(rt2800::MAC_STATUS_CFG),
            )
            .as_bytes(),
        );
        sys::exit(1);
    }
    // Сказать прошивке, что загрузка позади: с этого Linux начинает работу с радио. Ответа не
    // ждём — письмо без обязательств, и карта на него не отвечает.
    mcu_command(MCU_BOOT_SIGNAL, 0, 0);
    sys::sleep_ns(1_000_000);
    match rt2800::bbp_read(0) {
        Some(v) if v != 0 && v != 0xff => {
            sys::write(alloc::format!("[wifi] BBP отвечает: версия {:#04x}\n", v).as_bytes());
        }
        other => {
            sys::write(
                alloc::format!(
                    "[wifi] BBP молчит ({:?}) — радиочасть не поднялась, дальше идти незачем\n",
                    other
                )
                .as_bytes(),
            );
            sys::exit(1);
        }
    }
    // То же про радио: его регистр 0 — это идентификатор, и он обязан совпасть с тем, что EFUSE
    // назвала типом RF. Два независимых источника об одном чипе — лучшая из доступных проверок.
    match rt2800::rfcsr_read(0) {
        Some(v) => {
            sys::write(alloc::format!("[wifi] RFCSR[0] = {:#04x}\n", v).as_bytes());
        }
        None => w("[wifi] радио не отвечает на чтение\n"),
    }
    // ── таблицы (Веха 209) ───────────────────────────────────────────────────────────────
    //
    // Цифровая часть и радио отвечают — значит можно их настраивать. Записи сверяются чтением:
    // у BBP и радио свои шины, и запись в занятую шину теряется МОЛЧА, оставляя драйвер в
    // уверенности, что карта настроена.
    let (bbp_n, rf_n) = rt2800::table_sizes(rev);
    let mut diff = [(0u8, 0u8, 0u8); 12];
    let (bbp_ok, rf_ok, n_diff) = rt2800::load_tables(rev, &mut diff);
    sys::write(
        alloc::format!(
            "[wifi] таблицы: BBP {} из {}, радио {} из {}\n",
            bbp_ok, bbp_n, rf_ok, rf_n
        )
        .as_bytes(),
    );
    // Какие именно не сошлись — называем поимённо. «Часть записей не легла» без списка
    // отправляет искать вслепую, а половина таких расхождений — не поломка, а регистры, где
    // живут биты состояния: их значение по чтению и не обязано совпадать с записанным.
    for &(reg, want, got) in diff.iter().take(n_diff.min(diff.len())) {
        let (kind, num) = if reg & 0x80 != 0 { ("радио", reg & 0x7f) } else { ("BBP", reg) };
        sys::write(
            alloc::format!(
                "[wifi]   {} {}: писали {:#04x}, читается {:#04x}\n",
                kind, num, want, got
            )
            .as_bytes(),
        );
    }
    // Нормальный режим: одноантенной карте второй тракт не нужен — он тратит питание и добавляет
    // шум, а сигнала по нему нет. Числа антенн берём из EFUSE, а не из предположений.
    rt2800::normal_mode_5xxx(rx_path, tx_path);
    w("[wifi] радио в нормальном режиме: лишние тракты выключены, калибровка сделана\n");
    if n_diff > diff.len() {
        sys::write(alloc::format!("[wifi]   …и ещё {}\n", n_diff - diff.len()).as_bytes());
    }
    // ── канал и приём (Веха 210) ─────────────────────────────────────────────────────────
    //
    // Шестой канал — середина диапазона: на нём слышно и соседей снизу, и сверху, а выбирать
    // «правильный» пока незачем — сканирование по каналам будет следующей вехой.
    let ch = 6u8;
    let freq_offset = (ee[EE_FREQ] & 0xff) as u8;
    let lna_gain = (ee[EE_LNA] & 0xff) as u8;
    // Инициализация MAC — ДО настройки канала: она снимает часть регистров в исходное, и канал,
    // настроенный раньше неё, частью потерялся бы.
    rt2800::init_mac();
    if !rt2800::set_channel(ch, freq_offset, lna_gain) {
        sys::write(alloc::format!("[wifi] канала {} в таблице нет\n", ch).as_bytes());
        sys::exit(1);
    }
    rt2800::rx_enable();
    let (rf1, sys_ctrl, filt, pin) = (
        rt2800::rfcsr_read(1).unwrap_or(0),
        rt2800::rd32(rt2800::MAC_SYS_CTRL),
        rt2800::rd32(rt2800::RX_FILTER_CFG),
        rt2800::rd32(rt2800::TX_PIN_CFG),
    );
    sys::write(
        alloc::format!(
            "[wifi] канал {} (поправка {:#04x}, усиление {:#04x}): радио {:#04x}, \
MAC_SYS_CTRL {:#010x}, фильтр {:#010x}, выводы радио {:#010x}\n",
            ch, freq_offset, lna_gain, rf1, sys_ctrl, filt, pin
        )
        .as_bytes(),
    );
    // Доказательство — не передатчик (он для приёма не нужен и включается своим порядком), а
    // то, что коэффициенты синтезатора читаются такими же, какими их записали, и что приёмный
    // тракт включён. Первый заход судил по передатчику и объявил бы неудачей работающий приём.
    if rt2800::channel_ok(ch) {
        sys::write(
            alloc::format!(
                "[wifi] КАНАЛ {} НАСТРОЕН: синтезатор принял коэффициенты, приёмник включён \
(радио {:#04x})\n",
                ch, rf1
            )
            .as_bytes(),
        );
    } else {
        sys::write(
            alloc::format!(
                "[wifi] канал не дошёл: радио {:#04x}, rf8 {:?}, rf9 {:?}\n",
                rf1,
                rt2800::rfcsr_read(8),
                rt2800::rfcsr_read(9),
            )
            .as_bytes(),
        );
    }
    // ── кольцо приёма и первые кадры из эфира (Веха 211) ─────────────────────────────────
    //
    // Дескрипторы и буферы просим ОДНИМ куском DMA-памяти: карта ходит по ней сама, по
    // физическим адресам, и разрывы ей объяснить нечем.
    const DESC_VA: usize = 0x5400_0000;
    const PAGES: usize = 8; // страница под дескрипторы, остальные под буферы
    let Some(dma_pa) = sys::dma_alloc_pages(dma_cap, DESC_VA, PAGES) else {
        w("[wifi] DMA-памяти не дали — кольцо приёма не завести\n");
        sys::exit(1);
    };
    let buf_va = DESC_VA + 4096;
    let buf_pa = dma_pa + 4096;
    rt2800::tx_rings_idle();
    rt2800::rx_ring_init(DESC_VA, dma_pa, buf_pa);
    rt2800::wpdma_rx_on();
    sys::write(
        alloc::format!(
            "[wifi] кольцо приёма: {} буферов по {} Б, физ {:#x}, движок {:#010x}; слушаю эфир\n",
            rt2800::RX_RING,
            rt2800::RX_BUF,
            dma_pa,
            rt2800::rd32(rt2800::WPDMA_GLO_CFG),
        )
        .as_bytes(),
    );

    // ── обход каналов (Веха 211.3) ───────────────────────────────────────────────────────
    //
    // Радио слышит один канал за раз — значит обойти надо все тринадцать. Задержка на канале
    // выбрана не «на глаз»: маяк точка шлёт примерно каждые сто миллисекунд, и четверти секунды
    // хватает, чтобы услышать её дважды и не принять пропуск за отсутствие сети. Тринадцать
    // каналов по 250 мс — три с небольшим секунды на весь обзор.
    const DWELL_NS: u64 = 250_000_000;
    // Поправка уровня своя у каждого экземпляра карты и лежит в EEPROM знаковым байтом. Значение
    // больше десяти по модулю означает испорченную память — Linux в этом случае берёт ноль, и мы
    // тоже: лучше показать уровень без поправки, чем с заведомо ложной.
    let rssi_offset = {
        let v = (ee[EE_RSSI_BG] & 0xff) as i8 as i32;
        if v.abs() > 10 { 0 } else { v }
    };
    let mut nets: alloc::vec::Vec<Net> = alloc::vec::Vec::new();
    let mut beacons = 0usize;
    let mut idx = 0usize;
    for ch in 1u8..=13 {
        if !rt2800::set_channel(ch, freq_offset, lna_gain) {
            continue;
        }
        let until = sys::monotonic_ns() + DWELL_NS;
        while sys::monotonic_ns() < until {
            let d = (DESC_VA + idx * rt2800::RXD_WORDS * 4) as *mut u32;
            let w1 = unsafe { core::ptr::read_volatile(d.add(1)) };
            if w1 & rt2800::RXD_DMA_DONE == 0 {
                sys::sleep_ns(2_000_000);
                continue;
            }
            let len = ((w1 >> rt2800::RXD_SDL0_SHIFT) & rt2800::RXD_SDL0_MASK) as usize;
            if len > rt2800::RXWI_SIZE {
                let head = buf_va + idx * rt2800::RX_BUF;
                // Уровень лежит в заголовке приёма, который карта кладёт ПЕРЕД кадром.
                let raw = unsafe { core::ptr::read_volatile((head + 8) as *const u32) } as u8;
                let n = (len - rt2800::RXWI_SIZE).min(rt2800::RX_BUF - rt2800::RXWI_SIZE);
                let body = unsafe {
                    core::slice::from_raw_parts((head + rt2800::RXWI_SIZE) as *const u8, n)
                };
                if let Some(b) = parse_beacon(body) {
                    beacons += 1;
                    let rssi = rssi_dbm(raw, rssi_offset, lna_gain);
                    match nets.iter_mut().find(|n| n.bssid == b.bssid) {
                        // Уже знакомая точка: берём ЛУЧШИЙ уровень, а не последний. Маяки ловятся
                        // неровно, и одно слабое попадание не повод занизить всю сеть.
                        Some(n) => {
                            n.beacons += 1;
                            n.rssi = n.rssi.max(rssi);
                        }
                        None => nets.push(Net {
                            bssid: b.bssid,
                            ssid: b.ssid,
                            ch: if b.ch != 0 { b.ch } else { ch },
                            rssi,
                            secure: b.secure,
                            beacons: 1,
                        }),
                    }
                }
            }
            // Буфер забрали — вернуть его карте: снять признак готовности и подвинуть свой индекс.
            unsafe { core::ptr::write_volatile(d.add(1), 0) };
            rt2800::wr32(rt2800::RX_CRX_IDX, idx as u32);
            idx = (idx + 1) % rt2800::RX_RING;
        }
    }
    // Сильные сверху: список сетей читают глазами, и порядок здесь — половина пользы.
    nets.sort_by(|a, b| b.rssi.cmp(&a.rssi));
    sys::write(
        alloc::format!("[wifi] ЭФИР: сетей {}, маяков {}\n", nets.len(), beacons).as_bytes(),
    );
    for n in &nets {
        sys::write(
            alloc::format!(
                "[wifi]   {:<24} к{:<3} {:>4} дБм  {}  {:02x}:{:02x}:{:02x}:{:02x}:{:02x}:{:02x} ({} маяков)\n",
                n.ssid,
                n.ch,
                n.rssi,
                if n.secure { "с ключом " } else { "открытая " },
                n.bssid[0], n.bssid[1], n.bssid[2], n.bssid[3], n.bssid[4], n.bssid[5],
                n.beacons,
            )
            .as_bytes(),
        );
    }
    sys::write(
        alloc::format!(
            "[wifi] кольцо: индекс карты {}, наш {}\n",
            rt2800::rd32(rt2800::RX_DRX_IDX),
            rt2800::rd32(rt2800::RX_CRX_IDX),
        )
        .as_bytes(),
    );
    // Веха 213.2 — ОСТАНОВИТЬ КАРТУ ПЕРЕД ВЫХОДОМ. Разбор в `rt2800::stop`: карта, оставленная
    // с живым кольцом, продолжает писать маяки по физическим адресам, которые ядро уже вернуло
    // в общий котёл, — и рано или поздно кладёт кусок эфира на список свободных кадров.
    rt2800::stop();
    sys::write(
        alloc::format!(
            "[wifi] карта остановлена: MAC {:#010x}, движок {:#010x}, кольцо {:#x}\n",
            rt2800::rd32(rt2800::MAC_SYS_CTRL),
            rt2800::rd32(rt2800::WPDMA_GLO_CFG),
            rt2800::rd32(rt2800::RX_BASE_PTR),
        )
        .as_bytes(),
    );
    // Вывод УХОДИТ ЗНАЧЕНИЕМ в журнал ядра, поэтому его видно и через `klog` — на машине без
    // COM-порта это единственный способ прочитать сказанное (Веха 199.2).
    w("[wifi] шаг закончен: карта опознана, EFUSE прочитан, прошивка в буферном процессоре\n");
    sys::exit(0);
}
