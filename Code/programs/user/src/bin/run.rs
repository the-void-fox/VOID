//! `run` — СТОРОЖ ЗАПУСКА (Веха 147): запускает программу и досматривает, чем это кончилось.
//!
//! ```text
//! строка запуска ─ spawn ─→ run ─ spawn(STDIO=run) ─→ программа
//!                            │
//!                            ├─ OP_LAUNCHING(pid, имя) ──→ композитор: плитка «запускается»
//!                            ├─ приём вывода программы (stdio) ─ копит ХВОСТ
//!                            └─ программа умерла ─ OP_LAUNCH_DONE(pid, код, хвост) ──→ карточка
//! ```
//!
//! ## Зачем отдельный процесс
//!
//! Требование ADR 0016: «процесс завершился, не показав окна → карточка с кодом выхода и
//! последними строками вывода». Обе величины умеет добыть **только родитель**: `SYS_WAIT`
//! работает со своими детьми, а вывод идёт тому, кто дал ребёнку `STDIO`. Композитор чужим
//! процессам не родитель и родителем быть не должен — операция «запусти что скажу» в протоколе
//! без прав была бы дырой шире решаемой задачи ([[launcher]], Веха 146).
//!
//! Строка запуска сама сторожить не может: она живёт секунды и обязана исчезнуть с экрана сразу
//! после нажатия. Поэтому сторож — отдельная программа, и она же годится шеллу: `run img wall`
//! из `vvsh` даёт ту же плитку и ту же карточку.
//!
//! ## Почему `WM` ребёнку передавать не надо
//!
//! `SYS_SPAWN` объявляет РОВНО ОДНО именованное право, и мы тратим его на `STDIO`. Ребёнок всё
//! равно находит композитора: стартовые права и окружение НАСЛЕДУЮТСЯ (`cap::endow` при
//! запуске), а `WM=<индекс>` у нас в окружении уже есть — от того, кто запустил нас самих.
//! Проверено опытом до вехи: `winbox`, запущенный без явного `WM`, окно открыл.
//!
//! ## Чего сторож не делает
//!
//! Не убивает ребёнка, не перезапускает его и не решает за человека. Он смотрит и говорит.

#![no_std]
#![no_main]

extern crate alloc;

use alloc::vec::Vec;

use void_user as sys;
use void_user::{stdio, win, Wait};

#[global_allocator]
static ALLOC: sys::heap::Heap<{ 1024 * 1024 }> = sys::heap::Heap::new();

/// Сколько вывода держим. Карточке достаются последние строки — их и хватает, чтобы объяснить
/// смерть; полный журнал программы это не замена и не претензия на неё.
const TAIL_KEEP: usize = 4096;

/// Как часто спрашиваем «жив ли». Первые секунды — часто (человек ждёт ответа прямо сейчас),
/// дальше редко: программа уже живёт своей жизнью, и спешить сторожу некуда.
const POLL_FAST_NS: u64 = 200_000_000;
const POLL_SLOW_NS: u64 = 2_000_000_000;
const FAST_FOR_NS: u64 = 5_000_000_000;

fn say(s: &str) {
    sys::write_console(s.as_bytes());
}

/// Право на store: по имени, иначе перебором стартовых (как у всех наших программ).
fn store_cap() -> Option<usize> {
    let readable = |c: usize| {
        let mut id = [0u8; 32];
        c != sys::NO_CAP && sys::obj_get_root(c, b"system/current", &mut id) == 32
    };
    sys::cap_named("STORE")
        .filter(|&c| readable(c))
        .or_else(|| (0..8).map(sys::start_cap).find(|&c| readable(c)))
}

#[no_mangle]
pub extern "C" fn _start(_a0: usize, _a1: usize) -> ! {
    // argv: [0] — мы сами, [1] — что запускать, дальше — его аргументы.
    let argv = sys::argv::Argv::take();
    let mut words = argv.rest();
    let Some(name) = words.next() else {
        say("run: run <программа> [аргументы]\n");
        sys::exit(2);
    };
    let name_str = core::str::from_utf8(name).unwrap_or("?");
    let mut args: Vec<u8> = Vec::new();
    for w in words {
        args.extend_from_slice(w);
        args.push(0);
    }

    // Плитка — ДО запуска, и это не мелочь порядка. Быстрая программа успевает открыть окно
    // раньше, чем мы о ней скажем: `term` так и делал, и плитка, появившись ПОСЛЕ его окна,
    // висела на экране вечно. Своё окно она узнает по родству — мы ей предок.
    win::launching(name_str);
    let store = store_cap();
    let Some(pid) = store.and_then(|c| sys::spawn_with_stdio(c, name, &args, sys::self_endpoint()))
    else {
        // Запуска не было вовсе — и это ровно тот случай, ради которого плитка и заводится:
        // «нажал, и ничего не произошло» перестаёт быть тишиной.
        say(&alloc::format!("run: не запустилось: {}\n", name_str));
        win::launch_done(127, "нет такой программы в store (bin/<арх>/<имя>)".as_bytes());
        sys::exit(127);
    };

    // ── сторожим ───────────────────────────────────────────────────────────────────────
    //
    // Спим в `recv_timeout`: пока ребёнок пишет — просыпаемся на его сообщения, пока молчит —
    // на свой срок, чтобы спросить, жив ли он. Блокирующего `wait` здесь быть не может: мы
    // ЕГО stdio-хозяин, и уснув в ожидании смерти, мы повесили бы его на первом же `write`.
    let started = sys::monotonic_ns();
    let mut tail: Vec<u8> = Vec::new();
    let mut msg = [0u8; stdio::CHUNK + 64];
    loop {
        let now = sys::monotonic_ns();
        let pause = if now.saturating_sub(started) < FAST_FOR_NS { POLL_FAST_NS } else { POLL_SLOW_NS };
        if let Some(m) = sys::recv_timeout(&mut msg, pause) {
            match m.op & 0xff {
                stdio::OP_STDOUT => {
                    let len = m.len.min(msg.len());
                    tail.extend_from_slice(&msg[..len]);
                    if tail.len() > TAIL_KEEP {
                        tail.drain(..tail.len() - TAIL_KEEP);
                    }
                    // Ответ пустой, но обязательный: он же и регулировка потока — ребёнок не
                    // убежит вперёд, пока мы не разгребли.
                    sys::reply(m.reply_cap, &[]);
                }
                // Ввода у запущенного из строки запуска нет и взяться ему неоткуда: клавиатура
                // принадлежит окну в фокусе, а не нам. Пустой ответ — это конец ввода, и он
                // честнее молчания: на молчании программа повисла бы навсегда.
                stdio::OP_STDIN => {
                    sys::reply(m.reply_cap, &[]);
                }
                // Размер «терминала» у нас условный: окна нет, но программа, спросившая его,
                // должна получить рабочее число, а не ноль (делить на него будут её строки).
                stdio::OP_WINSIZE => {
                    sys::reply(m.reply_cap, &[80, 0, 25, 0]);
                }
                _ => {
                    sys::reply(m.reply_cap, &[]);
                }
            }
        }
        match sys::wait(pid, true) {
            Wait::Running => {}
            Wait::Exited(code) => {
                // Плитки может уже не быть — тогда сообщение пропадёт, и это нормальный исход:
                // окно появилось, программа отработала и закрылась через час.
                win::launch_done(code, &tail);
                sys::exit(0);
            }
            // Ребёнка нет: либо его забрал кто-то другой, либо номер неверен. Молчать нельзя —
            // плитка осталась бы ждать вечно.
            Wait::NoChild => {
                win::launch_done(255, "сторож потерял процесс".as_bytes());
                sys::exit(1);
            }
        }
    }
}
