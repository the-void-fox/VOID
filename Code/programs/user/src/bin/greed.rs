//! `greed` — **ЖАДНЫЙ ПРОЦЕСС**: сколько ресурсов ядра можно съесть и что сломается первым
//! (Веха 225.5).
//!
//! ## Зачем
//!
//! Модель угроз (ADR 0023) честно пишет: «квот почти нет. Есть потолок страниц процесса; памяти
//! ядра, слотов c-space, объектов store процесс может съесть столько, сколько машина даст».
//! Живость ядра при этом объявлена АКТИВОМ — то есть запись выше описывает не особенность, а
//! незакрытую дыру.
//!
//! И она уже стреляла дважды, оба раза в личности Linux (Веха 225.3): `dup3` растил стол
//! дескрипторов до названного числа, `getrandom` выделял буфер по длине от программы. Оба —
//! «выделение по числу из U-mode», и оба нашлись фаззером случайно. Этот зонд ищет их нарочно и
//! по всем ресурсам сразу.
//!
//! ## Что считается находкой
//!
//! **Смерть или зависание ядра.** Отказ — правильный ответ: машина вправе сказать «больше нет»,
//! и жадный процесс обязан получить отказ, а не унести с собой систему.
//!
//! Поэтому зонд не «ломает», а МЕРЯЕТ: берёт ресурс, пока дают, и печатает, на каком счёте
//! остановились. Число само по себе — тоже ответ: «слотов выдано миллион и конца нет» значит
//! потолка нет вовсе.
//!
//! ## Почему печать идёт ДО каждой сотни, а не после
//!
//! Если машина умрёт на жадности, рассказать об этом будет уже некому. Та же причина, по которой
//! `sysfuzz` объявляет случай перед выстрелом, а `void-fuzz` ставит отметки каждую тысячу кругов.

#![no_std]
#![no_main]

extern crate alloc;

use void_user as sys;

/// Потолок счёта. Не «сколько выдержит машина», а «сколько надо, чтобы ответить на вопрос»:
/// если ресурс выдан сто тысяч раз подряд, потолка у него нет, и продолжать незачем.
const LIMIT: usize = 100_000;
/// Как часто говорить, где идём.
const STEP: usize = 1000;

/// Куча маленькая: зонду она нужна лишь под несколько буферов, а мерить его собственный расход
/// вместо расхода ядра — отдельная беда.
#[global_allocator]
static ALLOC: sys::heap::Heap<{ 64 * 1024 }> = sys::heap::Heap::new();

fn w(s: &str) {
    sys::write(s.as_bytes());
}

fn num(mut v: usize) {
    if v == 0 {
        w("0");
        return;
    }
    let mut buf = [0u8; 20];
    let mut i = buf.len();
    while v > 0 {
        i -= 1;
        buf[i] = b'0' + (v % 10) as u8;
        v /= 10;
    }
    sys::write(&buf[i..]);
}

/// Объявить проход и мерить. `take` отдаёт `false`, когда ядро отказало.
fn measure(name: &str, mut take: impl FnMut(usize) -> bool) {
    w("GREED ПРОХОД ");
    w(name);
    w("\n");
    let mut n = 0usize;
    while n < LIMIT {
        if n % STEP == 0 && n > 0 {
            w("  GREED ");
            w(name);
            w(" взято ");
            num(n);
            w("\n");
        }
        if !take(n) {
            break;
        }
        n += 1;
    }
    w("GREED ИТОГ ");
    w(name);
    w(" = ");
    num(n);
    if n >= LIMIT {
        w(" — ПОТОЛКА НЕТ (дошли до предела счёта)\n");
    } else {
        w(" — ядро отказало, это ПРАВИЛЬНО\n");
    }
}

#[no_mangle]
pub extern "C" fn _start(_a0: usize, _a1: usize) -> ! {
    w("GREED START\n");

    // ПОРЯДОК ВАЖЕН, и это не мелочь. Сперва shm, потом слоты: создание области МИНТИТ
    // дескриптор, то есть ест слот. Когда проходы шли наоборот, shm отказывал мгновенно — не
    // потому что у него есть потолок, а потому что слоты уже кончились, — и отчёт показывал
    // «объекты shm = 0 — ядро отказало», то есть врал о причине.
    //
    // 1. РАЗДЕЛЯЕМАЯ ПАМЯТЬ. Каждый объект — и запись в ядре, и настоящие страницы. Берём по
    //    одной странице: вопрос в ЧИСЛЕ объектов, а не в их размере.
    measure("объекты shm", |i| {
        // Адреса не пересекаются: иначе мерили бы отображение, а не создание.
        let va = 0x7000_0000 + i * 4096;
        va < 0x7F00_0000 && sys::shm_new(4096, va).is_some()
    });

    // 2. СЛОТЫ C-SPACE. `SYS_CAP_DERIVE` кладёт в домен новую запись на каждый вызов, а вектор
    //    слотов растёт `push`-ем — то есть в куче ядра.
    let me = sys::self_endpoint();
    measure("слоты c-space", |_| sys::cap_derive(me, usize::MAX) != usize::MAX);

    w("GREED VERDICT SURVIVED\n");
    sys::exit(0)
}
