//! `sysfuzz` — **граница системного вызова под обстрелом аргументами** (Веха 225).
//!
//! ## Зачем, если есть красная команда
//!
//! Оракул конфайнмента ([`probe`]) перебирает СЛОТЫ ПРАВ, агент ([[redteam]]) печатает команды в
//! шелл, `hostile` приходит с испорченным СОСТОЯНИЕМ регистров. Ни один из них не бьёт по
//! АРГУМЕНТАМ, и это видно по тому, чего они не нашли.
//!
//! Две системные мины, найденные случайно и обе смертельные для ядра:
//!
//! 1. `read(0, NULL, 1)` из любой программы РОНЯЛ ЯДРО: проверка диапазона пропускала всё, что не
//!    куча, включая нулевой адрес, и ядро разыменовывало ноль само (Веха 223.6).
//! 2. Пробуждение заблокированного вызова затирало НОМЕР вызова: `rax` у `syscall` — и номер, и
//!    возврат, и `clock_nanosleep` просыпался как `read(1, NULL, …)` (Веха 223.5).
//!
//! Класс один: **ядро верит числу, пришедшему из U-mode.** Защита от класса — не список
//! проверок, а процесс, который приносит на границу заведомо враждебные числа и требует, чтобы
//! ядро выжило.
//!
//! ## Что считается находкой
//!
//! Только одно: **ядро не пережило вызов** — паника, аварийная ловушка или зависание. Отказ в
//! вызове находкой НЕ является, он и есть правильный ответ; смерть самого зонда — тоже не
//! находка сама по себе, но её видно по тому, на каком случае оборвался вывод.
//!
//! Усиление прав здесь не проверяется НАМЕРЕННО: это дело [`probe`], и мешать два оракула в один
//! значит получить отчёт, по которому неясно, что сломалось.
//!
//! ## Почему зонд идёт с БОГАТЫМИ правами
//!
//! Обратное правилу красной команды, и это осознанно. Там противник — процесс с малой властью, и
//! вопрос «дотянется ли он дальше». Здесь вопрос другой: **переживёт ли ядро враждебное число**,
//! а до проверки числа надо сперва пройти проверку права. Зонд без прав получал бы «нет
//! полномочий» и не доходил бы до кода, который мы и проверяем. Модель угроз (ADR 0023) это
//! допускает прямо: противник — «программа на машине», не обязательно вредоносная, в том числе
//! своя, которой права выдал владелец, и драйвер, потерявший рассудок.
//!
//! ## Запуск
//!
//! ```text
//! sysfuzz            все случаи подряд
//! sysfuzz 120        начать со случая 120 (продолжить после гибели зонда)
//! ```
//!
//! Каждый случай печатается ДО вызова: если машина встала, последняя строка и есть виновник.

#![no_std]
#![no_main]

use void_user as sys;

/// Номера системных вызовов идут подряд с запасом: дыры в нумерации — тоже случай, и ядро
/// обязано отвечать на неизвестный номер отказом, а не чем попало.
const SYS_MAX: usize = 80;

/// Что делать с вызовом. Пропуск — всегда С ПРИЧИНОЙ: молчаливо пропущенный вызов выглядит в
/// отчёте так же, как проверенный, и создаёт ровно ту уверенность, которой нет.
enum Policy {
    /// Бить всеми наборами аргументов.
    Fire,
    /// Не трогать. Причина — человеку в отчёт.
    Skip(&'static str),
}

/// Политика по номеру вызова.
///
/// Пропускаются ровно три рода вызовов, и ни один — «на всякий случай»:
///
/// * **кончающие прогон** (выход, замена образа, выключение машины) — после них проверять
///   нечего, причём не из-за хрупкости зонда, а потому что проверяемого больше нет;
/// * **ждущие бесконечно** (приём IPC, сон, ожидание прерывания и потомка) — ожидание тут
///   законно, а харнесс читает его как ЗАВИСАНИЕ, то есть как находку. Ложная находка хуже
///   пропуска: она обесценивает отчёт целиком;
/// * **пишущие на диск** — установщик разворачивает образ на носитель, и «враждебный аргумент»
///   здесь означает испорченный диск владельца.
fn policy(n: usize) -> Policy {
    match n {
        2 => Policy::Skip("SYS_EXIT — кончает зонд"),
        15 => Policy::Skip("SYS_EXEC — подменяет образ процесса"),
        24 => Policy::Skip("SYS_THREAD_EXIT — кончает нить"),
        29 => Policy::Skip("SYS_RESTORE — подменяет состояние процесса"),
        30 => Policy::Skip("SYS_INSTALL — пишет на диск владельца"),
        44 => Policy::Skip("SYS_POWEROFF — выключает машину"),
        45 => Policy::Skip("SYS_KILL — может убить шелл, из которого запущен прогон"),
        4 | 5 => Policy::Skip("приём/вызов IPC — ждут бесконечно, ожидание законно"),
        25 => Policy::Skip("SYS_THREAD_JOIN — ждёт бесконечно"),
        26 => Policy::Skip("SYS_FUTEX — ждёт бесконечно"),
        33 => Policy::Skip("SYS_IRQ_WAIT — ждёт бесконечно"),
        42 => Policy::Skip("SYS_WAIT — ждёт потомка бесконечно"),
        47 => Policy::Skip("SYS_SLEEP — спит столько, сколько сказали"),
        14 => Policy::Skip("SYS_READ — ждёт ввода; по НЕМУ бьёт отдельный случай ниже"),
        _ => Policy::Fire,
    }
}

/// Набор враждебных чисел. Каждое — не фантазия, а известный способ обмануть проверку диапазона.
const EVIL: &[(usize, &str)] = &[
    (0, "ноль"),
    (1, "единица (невыровнено, не страница)"),
    (usize::MAX, "максимум (переполнит любое сложение)"),
    (usize::MAX - 7, "почти максимум (переполнит с длиной)"),
    // Половина адресного пространства ядра: higher-half с Вехи 87. Процесс не вправе ни читать
    // её, ни заставить ядро писать туда по своей просьбе.
    (0xFFFF_8000_0000_0000, "адрес ЯДРА (higher-half)"),
    // Ровно под началом пользовательской области: соседняя страница уже не наша.
    (0x4000_0000 - 8, "под началом области процесса"),
    // Внутри области, но заведомо не отображено: между стеком и кучей.
    (0x5F00_0000, "в области процесса, но не отображено"),
];

/// Длины отдельной таблицей: беда чаще в ПАРЕ «адрес + длина», чем в адресе.
const LENS: &[(usize, &str)] = &[
    (0, "ноль"),
    (1, "один байт"),
    (usize::MAX, "максимум"),
    (1 << 40, "терабайт"),
];

fn w(s: &str) {
    sys::write(s.as_bytes());
}

fn num(mut v: usize) {
    if v == 0 {
        w("0");
        return;
    }
    let mut buf = [0u8; 20];
    let mut i = buf.len();
    while v > 0 {
        i -= 1;
        buf[i] = b'0' + (v % 10) as u8;
        v /= 10;
    }
    sys::write(&buf[i..]);
}

/// Объявить случай ДО выстрела и выстрелить.
///
/// Печать перед вызовом, а не после, — весь смысл: если машина встала, последняя строка журнала
/// и есть виновник. Печать после сказала бы только то, что пережитые случаи пережиты.
fn shot(idx: usize, n: usize, what: &str, a: usize, b: usize, c: usize) {
    w("SYSFUZZ CASE ");
    num(idx);
    w(" sys=");
    num(n);
    w(" ");
    w(what);
    w("\n");
    sys::raw_syscall(n, a, b, c);
}

#[no_mangle]
pub extern "C" fn _start(_a0: usize, _a1: usize) -> ! {
    let argv = sys::argv::Argv::take();
    let from = argv
        .rest()
        .next()
        .and_then(|b| core::str::from_utf8(b).ok())
        .and_then(|s| s.parse::<usize>().ok())
        .unwrap_or(0);

    w("SYSFUZZ START from=");
    num(from);
    w("\n");

    // Своя память — чтобы бить не только дикими адресами, но и ЧЕСТНЫМ адресом с дикой длиной:
    // проверка, пропускающая такую пару, пропустит и чтение за границей буфера.
    let mine = [0u8; 64];
    let mine_ptr = mine.as_ptr() as usize;

    let mut idx = 0usize;
    let mut fired = 0usize;
    let mut skipped = 0usize;
    for n in 0..=SYS_MAX {
        match policy(n) {
            Policy::Skip(why) => {
                skipped += 1;
                w("SYSFUZZ SKIP sys=");
                num(n);
                w(" — ");
                w(why);
                w("\n");
                continue;
            }
            Policy::Fire => {}
        }
        for (a, an) in EVIL {
            for (l, _ln) in LENS {
                if idx >= from {
                    shot(idx, n, an, *a, *l, *a);
                    fired += 1;
                }
                idx += 1;
            }
        }
        // Честный адрес с дикой длиной — отдельно: самый тихий из способов прочитать чужое.
        for (l, ln) in LENS {
            if idx >= from {
                shot(idx, n, ln, mine_ptr, *l, mine_ptr);
                fired += 1;
            }
            idx += 1;
        }
    }

    w("SYSFUZZ VERDICT SURVIVED cases=");
    num(fired);
    w(" skipped=");
    num(skipped);
    w("\n");
    sys::exit(0)
}
