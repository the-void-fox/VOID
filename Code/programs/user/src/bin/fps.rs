//! `fps` — сколько кадров РЕАЛЬНО оказалось на экране (Веха 168.3).
//!
//! ## Зачем отдельный инструмент
//!
//! Владелец сказал, что анимации подлагивают, хотя процессор простаивает, и спросил ровно то,
//! что нужно спросить: можно ли мерить не то, что программа ОТПРАВЛЯЕТ на экран, а то, что на
//! нём оказывается.
//!
//! Можно — и место ровно одно. Клиент рисует в свой буфер и говорит композитору «готово»
//! (`OP_COMMIT`); пиксель попадает на экран, только когда композитор запишет его во фреймбуфер
//! (`Wm::flush`). Между этими двумя событиями лежит всё, из чего складывается «подлагивает»:
//! сборка кадра, шина до видеопамяти, чужие сообщения в очереди композитора и его собственный
//! сон. Поэтому счётчик стоит у композитора, а `fps` его читает ([`win::OP_FRAMES`]).
//!
//! ## Что показывает и почему именно это
//!
//! Не «средний FPS». Среднее — самая бесполезная величина для рывка: сорок ровных кадров и
//! тридцать ровных плюс десять слипшихся дают одно и то же число, а на глаз это разные системы.
//! Поэтому здесь РАССТОЯНИЯ между соседними кадрами: середина (медиана), худшие пять процентов
//! и самый долгий. Рывок — это и есть хвост распределения.
//!
//! Рядом — из чего кадр сложился: СБОРКА (наш код: стол, окна, курсор) и ВЫВОД (запись во
//! фреймбуфер). Врозь, потому что лечатся по-разному: первое — алгоритм, второе — шина.
//!
//! И отдельной строкой — КОММИТЫ: сколько клиентских кадров приехало. Если их вдвое меньше, чем
//! кадров экрана, композитор перерисовывает одно и то же; если наоборот — экран не успевает за
//! программой, и рывок в ней, а не в нём.
//!
//! `fps` — что накопилось само; `fps <секунд>` — ЗАМЕР: чистое кольцо, окно, отчёт.

#![no_std]
#![no_main]

extern crate alloc;

use void_user as sys;
use void_user::win;

/// Куча на четверть мегабайта: всё, что здесь выделяется, — один буфер под ответ композитора
/// (шесть килобайт). На стеке ему не место, а мерить расход измерителя — отдельная беда.
#[global_allocator]
static ALLOC: sys::heap::Heap<{ 256 * 1024 }> = sys::heap::Heap::new();

fn w(s: &str) {
    sys::write(s.as_bytes());
}

fn put_num(mut v: u64) {
    if v == 0 {
        sys::write(b"0");
        return;
    }
    let mut buf = [0u8; 24];
    let mut i = buf.len();
    while v > 0 {
        i -= 1;
        buf[i] = b'0' + (v % 10) as u8;
        v /= 10;
    }
    sys::write(&buf[i..]);
}

/// Микросекунды человеку: миллисекунды с десятой долей. Наносекунд и микросекунд глазу не видно,
/// а «41.2 мс» сразу читается как «два с половиной кадра пропало».
fn put_ms(us: u32) {
    put_num((us / 1000) as u64);
    sys::write(b".");
    put_num(((us % 1000) / 100) as u64);
}

/// Кадров в секунду по расстоянию между соседями. Ноль — расстояния ещё нет.
fn hz(us: u32) -> u64 {
    if us == 0 {
        0
    } else {
        1_000_000 / us as u64
    }
}

/// Сортировка вставками: записей две с половиной сотни, и тащить сюда что-то умнее незачем.
fn sorted(vals: &mut [u32]) {
    for i in 1..vals.len() {
        let v = vals[i];
        let mut k = i;
        while k > 0 && vals[k - 1] > v {
            vals[k] = vals[k - 1];
            k -= 1;
        }
        vals[k] = v;
    }
}

const KEPT: usize = 256;

fn report() {
    // Буфер на куче: шесть килобайт на стеке программе без потока не по карману.
    let mut buf = alloc::vec![0u8; 28 + KEPT * 24];
    let n = win::frames_read(&mut buf);
    if n == 0 {
        w("fps: композитор не ответил (нужен WM в окружении)\n");
        sys::exit(1);
    }
    let (sw, sh, total, commits, it) = win::frames(&buf[..n]);
    // Промежутки берём ТОЛЬКО между кадрами «в работе»: между двумя нажатиями клавиш лежит
    // секунда, и записать её в рывки значило бы обвинить систему в том, что человек думал.
    let mut gaps = [0u32; KEPT];
    let mut build = [0u32; KEPT];
    let mut out = [0u32; KEPT];
    let (mut cnt, mut live, mut px_sum, mut still) = (0usize, 0usize, 0u64, 0usize);
    let (mut idle_n, mut idle_max) = (0usize, 0u32);
    let mut span = 0u64;
    let mut prev_live = false;
    let (mut heavy, mut over) = (None::<win::Frame>, 0usize);
    for f in it {
        if cnt >= KEPT {
            break;
        }
        // Первая запись кольца расстояния не имеет — ей не с чем сравниваться.
        if f.gap_us != 0 {
            if prev_live && f.live() {
                gaps[live] = f.gap_us;
                live += 1;
                span += f.gap_us as u64;
            } else {
                idle_n += 1;
                idle_max = idle_max.max(f.gap_us);
            }
        }
        build[cnt] = f.build_us;
        out[cnt] = f.out_us;
        px_sum += f.px as u64;
        if f.commits == 0 {
            still += 1;
        }
        let cost = f.build_us + f.out_us;
        if cost > 8_000 {
            over += 1;
        }
        if heavy.is_none_or(|h| h.build_us + h.out_us < cost) {
            heavy = Some(f);
        }
        prev_live = f.live();
        cnt += 1;
    }
    if cnt == 0 {
        w("fps: кадров ещё не было\n");
        return;
    }
    sorted(&mut build[..cnt]);
    sorted(&mut out[..cnt]);

    w("экран ");
    put_num(sw as u64);
    w("×");
    put_num(sh as u64);
    w(", кадров всего ");
    put_num(total);
    w(", клиентских ");
    put_num(commits);
    w("\n");

    if live == 0 {
        w("движения в кольце нет — мерить нечего\n");
    } else {
        let g = &mut gaps[..live];
        sorted(g);
        let mid = g[live / 2];
        let p95 = g[live * 95 / 100];
        let worst = g[live - 1];
        w("кадров в секунду: ");
        put_num(hz(mid));
        w(" (по середине расстояний), худшие 5% — ");
        put_num(hz(p95));
        w("\n");
        w("расстояние: середина ");
        put_ms(mid);
        w(" мс · 95% ");
        put_ms(p95);
        w(" мс · худшее ");
        put_ms(worst);
        w(" мс\n");
        // Рывок — это не медленный кадр, а ПРОПУЩЕННЫЙ: расстояние вдвое больше середины.
        let jerk = g.iter().filter(|&&v| v > mid * 2 && v > 20_000).count();
        w("рывков (вдвое дольше середины): ");
        put_num(jerk as u64);
        w(" из ");
        put_num(live as u64);
        w(", в работе ");
        put_ms((span / 1000).min(u32::MAX as u64) as u32);
        w(" с\n");
    }
    w("кадр: сборка ");
    put_ms(build[cnt / 2]);
    w(" мс (худшая ");
    put_ms(build[cnt - 1]);
    w(") · вывод ");
    put_ms(out[cnt / 2]);
    w(" мс (худший ");
    put_ms(out[cnt - 1]);
    w(")\n");
    w("пикселей на кадр: ");
    put_num(px_sum / cnt as u64);
    w(" из ");
    put_num(sw as u64 * sh as u64);
    w(" на экране\n");
    // Кадр без единого коммита — экран перерисовал то же самое. Это не всегда ошибка (курсор,
    // всплывашка), но если таких большинство, композитор жжёт шину впустую.
    w("кадров без нового содержимого: ");
    put_num(still as u64);
    w(" из ");
    put_num(cnt as u64);
    w(" · простоев ");
    put_num(idle_n as u64);
    w(", самый долгий ");
    put_ms(idle_max);
    w(" мс\n");
    // Самый тяжёлый кадр — ПОИМЁННО. Средние числа говорят «в целом хорошо», а дёргается ровно
    // тот кадр, который выпал из бюджета, и по площади сразу видно, чем он выпал.
    if let Some(h) = heavy {
        w("самый тяжёлый кадр: сборка ");
        put_ms(h.build_us);
        w(" мс · вывод ");
        put_ms(h.out_us);
        w(" мс · ");
        put_num(h.px as u64);
        w(" точек (");
        put_num(h.px as u64 * 100 / (sw as u64 * sh as u64).max(1));
        w("% экрана)\n");
    }
    // Сколько кадров вообще не уложилось в бюджет: их видно глазом, а среднее их прячет.
    w("кадров дороже 8 мс: ");
    put_num(over as u64);
    w(" из ");
    put_num(cnt as u64);
    w("\n");
}

fn parse_dec(b: &[u8]) -> Option<u64> {
    if b.is_empty() {
        return None;
    }
    let mut v: u64 = 0;
    for &c in b {
        if !c.is_ascii_digit() {
            return None;
        }
        v = v * 10 + (c - b'0') as u64;
    }
    Some(v)
}

#[no_mangle]
pub extern "C" fn _start(_a0: usize, _a1: usize) -> ! {
    let argv = sys::argv::Argv::take();
    match argv.rest().next().and_then(parse_dec) {
        // `fps` — что накопилось само по себе. Годится, чтобы взглянуть, но в кольце тогда лежит
        // и то, что человек делал до вопроса.
        None => report(),
        // `fps <секунд>` — ЗАМЕР: чистое кольцо, окно, отчёт. Всё, что попало внутрь окна, —
        // ответ на вопрос «что было, пока я это делал», и ничего кроме.
        Some(sec) => {
            let sec = sec.clamp(1, 10);
            win::frames_reset();
            w("замер ");
            put_num(sec);
            w(" с — делайте то, что дёргается…\n");
            sys::sleep_ns(sec * 1_000_000_000);
            report();
        }
    }
    sys::exit(0);
}
