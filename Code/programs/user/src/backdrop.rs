//! Подложка рабочего стола: ровный тёмный фон с мягкой виньеткой. Рисуется ФУНКЦИЯМИ.
//!
//! ## Почему не картинка
//!
//! Стол обязан быть у системы ВСЕГДА: на свежей машине, где в store ещё ничего нет, на экране до
//! первого `fetch`, на любом разрешении от 640×480 до 4K. Файл этого не даёт — он приходит из
//! store, зависит от декодера и от того, что кто-то его туда положил. Здесь фон это три
//! константы и уравнение: любой размер выходит точным, а весит он ноль.
//!
//! ## Что тут было раньше (Веха 141 → 158)
//!
//! До этого файл рисовал ЗНАК VOID во весь экран — шестиугольник с ушами и мордой, на 60% высоты.
//! Знак снят с обоев сознательно: во-первых, это был постер, а не обои; во-вторых, знак системы
//! сменился на перечёркнутый глаз, и живёт он теперь иконкой (`Code/assets/icons/logo.vg`), где
//! ему и место, — в меню оболочки и в приветственном окне, а не на весь стол.
//!
//! Вместе со знаком ушли надвыборка 4×4, размытие для свечения и вся геометрия. Рисование
//! векторных фигур с тех пор умеет `void-vec` — общее для всей системы, а не для одного знака.
//!
//! ## Рассеивание
//!
//! Весь перепад фона — десяток уровней на полтысячи пикселей, и без рассеивания градиент ложится
//! видимыми кольцами. Шум в пол-уровня разбрасывает ошибку округления: те же десять уровней, но
//! глаз видит гладко.

/// Цвета стола. Отдельной структурой, потому что стол один, а оттенок у него может быть разный.
pub struct Palette {
    /// Фон в центре и по углам: между ними мягкая виньетка.
    pub bg: (u8, u8, u8),
    pub bg_edge: (u8, u8, u8),
}

impl Palette {
    /// Родная палитра VOID: цвет стола из дизайна (`#151515`), к углам чуть темнее.
    ///
    /// Виньетка слабая намеренно. В макете стол залит ровно, но ровная заливка на настоящем
    /// экране в 27 дюймов выглядит плоской плёнкой; перепад в пять уровней даёт глубину, которую
    /// замечаешь, только если убрать.
    pub const VOID: Palette = Palette { bg: (0x15, 0x15, 0x15), bg_edge: (0x10, 0x10, 0x10) };
}

#[inline]
fn fmin(a: f32, b: f32) -> f32 {
    if a < b {
        a
    } else {
        b
    }
}
#[inline]
fn fmax(a: f32, b: f32) -> f32 {
    if a > b {
        a
    } else {
        b
    }
}

/// Рассеивающий шум ±0.5 уровня: хэш от координат, без состояния и без таблицы.
///
/// Взято вместо порядковой матрицы (Байера) по результату на глаз: матрица — РЕГУЛЯРНАЯ, и на
/// почти чёрном фоне её клетка 4×4 читается вертикальной рябью, то есть меняет одну видимую
/// помеху на другую. Шум даёт зерно, которого на этой яркости не видно вовсе.
#[inline]
fn dither(x: u32, y: u32) -> f32 {
    let mut n = x.wrapping_mul(0x27d4_eb2d) ^ y.wrapping_mul(0x1656_67b1);
    n ^= n >> 15;
    n = n.wrapping_mul(0x2c1b_3c6d);
    n ^= n >> 12;
    ((n >> 8) & 0xffff) as f32 / 65535.0 - 0.5
}

/// Стол целиком: фон с виньеткой. Буфер — RGBA8888 по строкам.
pub fn wallpaper(px: &mut [u8], w: u32, h: u32, pal: &Palette) {
    if w == 0 || h == 0 || px.len() < (w * h * 4) as usize {
        return;
    }
    // Виньетка по КВАДРАТУ расстояния от центра: корень тут не нужен — падение всё равно
    // на глаз, а не по метру, и в no_std его пришлось бы откуда-то брать.
    let (hw, hh) = (w as f32 * 0.5, h as f32 * 0.5);
    let norm = 1.0 / (hw * hw + hh * hh);
    for y in 0..h {
        let dy = y as f32 - hh;
        for x in 0..w {
            let dx = x as f32 - hw;
            let t = fmin(1.0, (dx * dx + dy * dy) * norm * 1.15);
            let d = dither(x, y);
            let i = ((y * w + x) * 4) as usize;
            for c in 0..3 {
                let (a, b) = match c {
                    0 => (pal.bg.0, pal.bg_edge.0),
                    1 => (pal.bg.1, pal.bg_edge.1),
                    _ => (pal.bg.2, pal.bg_edge.2),
                };
                let v = a as f32 + (b as f32 - a as f32) * t + d;
                px[i + c] = fmax(0.0, fmin(255.0, v)) as u8;
            }
            px[i + 3] = 0xff;
        }
    }
}
