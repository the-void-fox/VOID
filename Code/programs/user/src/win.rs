//! Протокол окон (Веха 117, [[0007-graphics-native-compositor]], [[0016-void-ui-toolkit]]).
//!
//! ## Устройство в одном абзаце
//!
//! Композитор — обычный IPC-сервер, как файловый или сетевой. Клиент получает право звать его
//! (тем же способом, что stdio — [[process-stdio]]), просит окно и получает **общий буфер
//! кадра**: те же физические страницы видны и ему, и композитору. Клиент рисует прямо в них и
//! говорит «этот прямоугольник изменился». Ядро про окна не знает ничего.
//!
//! ## Буфер стал общим (Веха 129)
//!
//! До неё пиксели ехали ОБЪЕКТОМ store: клиент клал изменившийся кусок, композитор читал его по
//! content-id. Довод был силён — содержимое адресуется хэшем, а не местом, значит переезд на GPU
//! не меняет протокол, одинаковые кадры дедуплицируются, а окна в принципе могут пережить
//! перезагрузку. Цена честно называлась долгом «настоящая цена появится у видео и игр».
//!
//! Цена оказалась ближе: замер ([[compositor-damage]]) показал, что **платим мы не за пиксели**.
//! Кусок в двести раз больший стоил всего в 1.3 раза дороже — то есть весь счёт шёл за сам факт
//! объекта: syscall, BLAKE3, куча ядра, индекс и групповой коммит, который вставка тащит за
//! собой. Изменившаяся строка окна обходилась в миллисекунды при бюджете кадра 16 мс, и упирался
//! в это обычный вывод `ls` — не видео и не игры.
//!
//! Store в этом не виноват: он сделан для того, что ДОЛЖНО пережить перезагрузку и адресоваться
//! хэшем. Пиксели живут один кадр — им нужна не персистентность, а общая страница.
//!
//! Что осталось от прежних доводов: буфер по-прежнему не адрес В ЧУЖОЙ ПАМЯТИ, а **ресурс под
//! capability** ([[shm]]) — композитор не может смотреть в чужое окно без права, а право не
//! подделать. Переезд на GPU протокол тоже не ломает: сменится то, ЧЕМ является область, а
//! «клиент пишет в буфер и объявляет прямоугольник» останется.
//!
//! ## Кадр доставляет композитор
//!
//! Клиент говорит «готово» и объявляет ПРЯМОУГОЛЬНИК изменений; куда и когда это попадёт на
//! экран, решает композитор. Так же устроены анимации (ADR 0016): их часы — у него, потому что
//! двигать окно, ничего не перерисовывая, может только он.
//!
//! ## Слои (Веха 139)
//!
//! Обои и бар — не окна: они не встают в ленту, не берут фокус и прижаты к краю экрана. Но и не
//! часть композитора: [`OP_LAYER`] даёт им ОБЫЧНУЮ поверхность, только с другим местом в стопке
//! и другим правилом расстановки. Это решение стоит назвать вслух, потому что соблазн был
//! обратный — нарисовать обои внутри `wm`.
//!
//! Внутри композитора обои означали бы, что он умеет читать store, разбирать PNG и JPEG и знает
//! про масштабирование. Каждая из этих способностей — чужая работа и чужая же поверхность атаки:
//! в композиторе лежат буферы ВСЕХ окон, и падение в декодере картинки роняло бы весь экран.
//! Клиент слоя падает в одиночку — на экране просто остаётся цвет стола.

/// Создать окно: `[ширина u16, высота u16, заголовок…]` → `[id u32]` + право на БУФЕР КАДРА.
pub const OP_CREATE: usize = 1;
// 2 и 7 — свободны. Там были `OP_ATTACH` (привязать пиксели прямоугольника объектом store) и
// `OP_SCROLL` (сдвинуть содержимое у композитора). Обе умерли с общим буфером (Веха 129): первой
// нечего пересылать, второй нечего двигать — копия одна, и клиент двигает её сам. Номера
// оставлены пустыми намеренно: перенумеровывать живые операции ради красоты значит ломать
// работающие программы на ровном месте.
/// Кадр готов: `[id u32, x u16, y u16, w u16, h u16]` — прямоугольник изменений.
pub const OP_COMMIT: usize = 3;
/// Ждать событие: `[id u32]` → ответ ОТЛОЖЕННЫЙ, как чтение stdin у терминала.
pub const OP_EVENT: usize = 4;
/// Закрыть окно: `[id u32]`.
pub const OP_DESTROY: usize = 5;
/// Забрать событие БЕЗ ожидания: `[id u32]` → событие или пустой ответ.
///
/// Нужен клиентам, у которых есть свой реактор: терминал — сам сервер для своих панелей, и
/// уснуть в нашем вызове он не может, иначе перестанет обслуживать детей. Простым программам
/// (`winbox`) по-прежнему проще спать в [`OP_EVENT`].
pub const OP_POLL: usize = 6;
/// Веха 129 — НОВЫЙ буфер кадра под изменившийся размер: `[id u32, w u16, h u16]` + право на
/// область. Отдельная операция, а не поле в `OP_CREATE`: размер окна назначает раскладка, и
/// менять буфер приходится по её команде, а не при рождении.
///
/// Веха 145 — у ПОВЕРХНОСТИ СЛОЯ это заодно и смена размера самой поверхности, а у окна ленты —
/// нет. Не исключение, а то же правило, что и при рождении ([`OP_LAYER`]): место окна назначает
/// раскладка, а слой НАЗЫВАЕТ ЕГО САМ. Понадобилось меню: панель на время открытия растит свою
/// поверхность до экрана и сжимается обратно. Занятая зона при этом не меняется — она названа
/// один раз, и окна не ездят.
pub const OP_REBUF: usize = 8;
/// Веха 139 — поверхность СЛОЯ: `[слой u8, якорь u8, w u16, h u16, зона u16, флаги u8,
/// заголовок…]` → `[id u32]` + право на буфер кадра. Дальше она живёт обычным окном: те же
/// `OP_COMMIT`, `OP_EVENT`, `OP_REBUF`, `OP_DESTROY`.
///
/// Флаги (Веха 144): бит 0 — [`LAYER_ALPHA`], «у моих пикселей значима альфа».
///
/// Отдельная операция, а не флаг в [`OP_CREATE`]: у слоя другой СМЫСЛ, а не другая настройка.
/// Обычное окно просит места у раскладки и получает его от неё; поверхность слоя место
/// НАЗЫВАЕТ САМА (край экрана и размер) и в раскладке не участвует вовсе.
pub const OP_LAYER: usize = 9;
/// Веха 140 — СОСТОЯНИЕ рабочего места: `[]` → `[стол u8, столов u8, заголовок…]`.
///
/// Отдельный запрос, а не поле события, потому что заголовок — текст произвольной длины, а
/// событие протокола умещается в семь байт. Разделение получилось честным: [`EV_STATUS`] говорит
/// «что-то изменилось», спрашивают подробности здесь. Так бар не опрашивает композитор впустую и
/// не платит за длинный ответ на каждое движение мыши.
pub const OP_STATUS: usize = 11;
// Ответ: `[стол, столов, раскладка, флаги, заголовок…]` — см. [`Status`].

/// Флаг снимка состояния: композитор в ОБЗОРЕ (Веха 145).
///
/// Панели это нужно не для вида: в обзоре мышь слоям не отдают вовсе (см. `on_mouse` в `wm`),
/// значит открытое меню стало бы неубиваемым — закрыть его кликом было бы нечем. Узнав про
/// обзор, панель закрывает его сама.
pub const ST_OVERVIEW: u8 = 1;
/// Веха 140 — ПОДПИСКА на [`EV_STATUS`]: `[id u32]`. Событие приходит той же поверхности.
///
/// Подписка явная, а не «всем слоям сразу»: обоям состояние стола не нужно, и будить их на каждую
/// смену фокуса значило бы платить за то, чего никто не просил.
pub const OP_WATCH: usize = 12;
/// Ответ [`OP_STATUS`]: состояние рабочего места для панели (Веха 140; раскладка — Веха 143).
pub struct Status {
    pub space: u8,
    pub spaces: u8,
    /// Раскладка клавиатуры: 0 — US, 1 — RU.
    pub layout: u8,
    /// Веха 145 — композитор показывает ОБЗОР ([`ST_OVERVIEW`]).
    pub overview: bool,
    /// Сколько байт заголовка легло в переданный буфер.
    pub title_len: usize,
}

/// Веха 140 — переключить рабочий стол: `[стол u8]`. Нужен бару: столы в панели кликабельны.
///
/// Оговорка, которую стоит назвать вслух: прав у протокола окон нет вовсе, поэтому это может
/// ЛЮБОЙ клиент, а не только панель. Сегодня это ничего не добавляет (клиент и так может открыть
/// окно и увести фокус), но когда права появятся, действия композитора — первое, что попадёт под
/// разграничение. Записано в [[known-gaps]].
pub const OP_SPACE: usize = 13;
/// Веха 144 — переключить РАСКЛАДКУ клавиатуры: `[]`. Просит панель (буквы EN/RU кликабельны).
///
/// Через композитор, а не `SYS_KEYMAP` напрямую, и это не крюк: право переключать раскладку у
/// того, кому принадлежит ЭКРАН (см. syscall 57), а экран принадлежит композитору — панель
/// получила бы от ядра отказ. Тот же довод, что у [`OP_SPACE`]: действие сеанса делает тот, кто
/// сеансом владеет, а панель его об этом просит.
///
/// Побочная выгода — та же, ради которой [`EV_STATUS`] вообще есть: переключив раскладку,
/// композитор сам заметит разницу в снимке состояния и разошлёт событие. Сделай панель это
/// syscall'ом сама — ей пришлось бы ещё и перерисовать себя вручную, то есть помнить о том, о
/// чём она узнаёт событием.
pub const OP_LAYOUT: usize = 14;

/// Веха 147 — **намерение запустить**: `[имя…]` → `[id u32]` (номер плитки).
///
/// Требование ADR 0016 дословно: между «нажал» и «увидел окно» экран обязан говорить правду.
/// Композитор ставит в ленту ПЛИТКУ «запускается: имя» — настоящее место в раскладке, а не
/// всплывашку: окно, ради которого её завели, встанет ровно туда же и ничего не сдвинет.
///
/// Говорит это тот, КТО ЗАПУСКАЕТ (`run`, [[launch-tile]]): композитор не родитель чужим
/// процессам и о запуске узнать не может, а `SYS_WAIT` работает только со своими детьми.
///
/// Номера процесса в запросе НЕТ, и это не экономия: плитку заводят ДО `SYS_SPAWN` — иначе
/// быстрая программа успевает открыть окно раньше, чем о ней сказали (ловилось `term`: плитка
/// появлялась после его окна и висела вечно). Значит назвать можно только СЕБЯ, а себя называет
/// ядро — `m.sender`. Своё окно плитка потом узнаёт по родству (`SYS_PARENT`), ровно как того и
/// требует ADR 0016: «первый commit окна этого процесса ИЛИ ЕГО ПОТОМКА».
pub const OP_LAUNCHING: usize = 15;
/// Веха 147 — **чем кончилось**: `[код u32, текст…]` → `[]`. Чей запуск — снова `m.sender`.
///
/// Плитка становится карточкой итога: код выхода и последние строки вывода. Пришло, когда
/// плитки уже нет (окно успело появиться), — сообщение просто пропадает: значит запуск удался,
/// а смерть программы через час к её запуску отношения не имеет.
pub const OP_LAUNCH_DONE: usize = 16;

/// Веха 150 — **ПОЛОЖИТЬ В БУФЕР ОБМЕНА**: `[вид u8, content-id 32]` → `[1]` (принято) либо
/// пустой ответ (отказ).
///
/// Едет не содержимое, а ИМЯ содержимого. Так решено ADR 0016: буфер обмена — объект store плюс
/// право на него. Копирующий кладёт байты в store сам (право `store:w` у него есть — иначе он не
/// смог бы и окно нарисовать), а композитору называет content-id. Отсюда даром достаются три
/// вещи, за которые в X11 и Wayland платят отдельно:
///
/// - **буфер переживает перезагрузку**: объект лежит на диске, композитор держит на него корень
///   `clip/current`;
/// - **дедупликация**: скопировать один и тот же текст дважды — это один объект;
/// - **размер не ограничен сообщением**: мегабайтный текст не поедет через IPC ни разу.
///
/// Чего это НЕ даёт: отдельного права «читать буфер». Право сегодня одно — на store целиком
/// ([[known-gaps]]), и вычитать корень `clip/current` может любой, кто может читать store.
pub const OP_CLIP_SET: usize = 17;

/// Веха 150 — **ВЗЯТЬ ИЗ БУФЕРА**: `[]` → `[вид u8, content-id 32]`; пустой ответ — буфер пуст.
///
/// Байты по content-id вычитывает сам спрашивающий — своим правом на store ([`clip_read`]).
pub const OP_CLIP_GET: usize = 18;

/// Вид содержимого буфера: текст UTF-8. Пока единственный.
///
/// Байт, а не «всегда текст», потому что второй вид (картинка) появится раньше, чем захочется
/// менять протокол: у нас уже есть и декодеры картинок, и снимок экрана на подходе.
pub const CLIP_TEXT: u8 = 1;

/// Веха 150.1 — **НАЧАТЬ ПЕРЕТАСКИВАНИЕ**: `[вид u8, content-id 32, подпись…]` → `[1]` (принято)
/// либо пустой ответ (отказ).
///
/// Едет ровно то же значение, что и в буфер обмена ([`OP_CLIP_SET`]), — объект store плюс его имя.
/// Разница не в грузе, а в том, КАК он попадает к получателю: буфер спрашивают, перетащенное
/// дают, и адресата назначает место, где отпустили кнопку.
///
/// Подпись хвостом — то, что человек видит под курсором, пока тащит. Она НЕ содержимое и совпадать
/// с ним не обязана: тащить можно мегабайт, а подписан он будет именем.
///
/// Композитор соглашается только на то, что может проверить сам, и проверяет два факта:
///
/// - **кнопка мыши сейчас держится.** Иначе программа завела бы перетаскивание, которого рука не
///   начинала, и ярлык поехал бы за курсором сам по себе;
/// - **курсор над поверхностью САМОГО просящего** — хозяин окна под курсором против отправителя,
///   которого называет ядро. Иначе кто угодно подменял бы груз в чужом перетаскивании.
///
/// Обоих фактов держатель один — композитор: у клиента их нет, а ядру они ничего не значат.
pub const OP_DRAG: usize = 19;

/// Веха 150.1 — **ЗАБРАТЬ УРОНЕННОЕ**: `[]` → `[вид u8, content-id 32]`; пустой ответ — «в тебя
/// ничего не роняли».
///
/// Спрашивают после [`EV_DROP`] и ровно один раз: композитор отдаёт имя тому окну, в которое
/// отпустили кнопку, и забывает его. Байты, как и у буфера, читает сам спрашивающий.
///
/// Здесь у перетаскивания есть то, чего у буфера обмена нет, — **адресат**. Content-id
/// перетащенного композитор называет ОДНОМУ окну, тому, куда целились. Правом на объект это ещё
/// не становится (узнавший имя прочтёт объект любым правом на store), но имени чужой не узнаёт.
pub const OP_DROP: usize = 20;

/// Сколько байт подписи перетаскивания композитор принимает. Хвост режется по границе символа.
pub const LABEL_MAX: usize = 64;

/// Веха 151 — **ЧЕМ МЕНЯ ВЕРНУТЬ**: `[id u32, запуск…]` → `[1]` (записано) либо пустой ответ.
///
/// Ответ на [`EV_SAVE`]. Хвост — КОМАНДНАЯ СТРОКА: имя программы и её аргументы через пробел.
/// Композитор в неё не вчитывается — он её только запустит; смысл слов знает одна программа.
///
/// **Здесь и стоит та самая открытая дверь.** Композитор не спрашивает «заморозься» и не
/// спрашивает «сохрани состояние» — он спрашивает «чем тебя вернуть». Программе, которой удобно
/// сохранить СМЫСЛ (поиск, выбор, историю вывода), достаточно назвать себя и имя своего объекта в
/// store. Программе-вычислению никто не мешает ответить `thaw proc/x86_64/своё-имя` — то есть
/// именем СВОЕГО ЧЕКПОЙНТА ([[checkpoint]]), и протокол об этом даже не узнает. Обязанности
/// замораживаться нет ни у кого — а её и нельзя требовать: драйвер с железным состоянием
/// заморозить нечем, и обязательный чекпойнт закрыл бы дверь именно им.
///
/// Не ответил — окно в сеанс не попадает. Это честнее выдумки: композитор знает про окно всё,
/// кроме одного — как его позвать обратно, и угадать это нечем.
pub const OP_PERSIST: usize = 21;

/// Сколько байт командной строки принимаем в [`OP_PERSIST`].
pub const RUN_MAX: usize = 128;

/// Веха 139 — размер экрана: `[]` → `[w u16, h u16]`.
///
/// Нужен потому, что буфер кадра уезжает вместе с запросом на поверхность, а размер обоев или
