// ── клиентская сторона ───────────────────────────────────────────────────────
//
// Тонкая обёртка над `SYS_CALL`: у приложения не должно быть повода знать раскладку байтов.
// Кучи здесь НЕТ намеренно: библиотеку линкуют и программы без аллокатора, а сообщения
// протокола и так помещаются в десятки байт.

/// Потолок длины заголовка окна. Больше на титульной полосе всё равно не поместится.
pub const TITLE_MAX: usize = 60;

/// Право звать композитор (`WM=<индекс>` в окружении). `None` — окон в этой сессии нет.
///
/// Разбор такой же, как у stdio, и это не совпадение: оба — ХОСТЫ, которых процессу дал
/// родитель, а не права, выданные системой на старте. У вторых имя начинается с `CAP_`
/// (`CAP_STORE`, `CAP_FB` — их кладёт init), у первых — нет.
pub fn endpoint() -> Option<usize> {
    let cap = crate::start_cap(crate::argv::env_num(ENV.as_bytes())?);
    (cap != crate::NO_CAP).then_some(cap)
}

/// Веха 129 — окно ВА-окна под общие буферы кадров: между кучей процесса (`0x6000_0000`) и его
/// стеком (вершина `0x8000_0000`). Образ программы лежит с `0x4000_0000`, и класть буфер туда
/// значит убить процесс его же кодом — на этом уже наступили при первом опыте.
///
/// Шаг 8 МиБ: полноэкранный кадр 1600×1200×4 — 7.3 МиБ, то есть одно окно в слот влезает всегда.
const SHM_BASE: usize = 0x7000_0000;
const SHM_STRIDE: usize = 8 * 1024 * 1024;

/// Сколько слотов помещается до стека (его вершина `0x8000_0000`, под ним 64 страницы).
const SHM_SLOTS: usize = 31;

/// Занятые слоты — по биту на слот. Слоты ПЕРЕИСПОЛЬЗУЮТСЯ: смена размера берёт новую область, и
/// без возврата слотов окно, переложенное тридцать раз, упёрлось бы в край окна ВА, хотя занято
/// при этом одно.
static SLOTS: core::sync::atomic::AtomicUsize = core::sync::atomic::AtomicUsize::new(0);

/// Занять свободный слот. `None` — все заняты (у клиента больше тридцати живых буферов).
fn take_slot() -> Option<usize> {
    use core::sync::atomic::Ordering;
    let mut cur = SLOTS.load(Ordering::Relaxed);
    loop {
        let free = (0..SHM_SLOTS).find(|i| cur & (1 << i) == 0)?;
        match SLOTS.compare_exchange_weak(
            cur, cur | (1 << free), Ordering::Relaxed, Ordering::Relaxed,
        ) {
            Ok(_) => return Some(free),
            Err(now) => cur = now,
        }
    }
}

fn free_slot(i: usize) {
    SLOTS.fetch_and(!(1 << i), core::sync::atomic::Ordering::Relaxed);
}

fn slot_va(i: usize) -> usize {
    SHM_BASE + i * SHM_STRIDE
}

/// Права, с которыми буфер уезжает композитору: `READ | GRANT`, БЕЗ `WRITE`. Он в кадр не пишет —
/// рисует клиент, композитор читает; ядро отобразит область только на чтение, и «композитор не
/// портит чужой кадр» становится свойством ЖЕЛЕЗА, а не обещанием кода.
///
/// `GRANT` тут не про щедрость: отправка права ПО IPC его и требует (ядро проверяет `GRANT` при
/// `CALL` — [[ipc-cap-transfer]]). Чистое `READ` без него не уезжает вовсе, и обнаруживается это
/// не отказом, а тем, что окно не открывается: терминал молча уходил в режим владельца экрана.
const RIGHT_SHARE: usize = 0b101;

/// Окно клиента: право на композитор, выданный им номер и ОБЩИЙ БУФЕР КАДРА.
///
/// Веха 129 — буфер разделяемый, а не пересылаемый. До неё каждый изменившийся кусок ехал
/// объектом store: клиент клал его (BLAKE3 + куча ядра + индекс + групповой коммит), композитор
/// читал по content-id. Замер показал цену — строка окна обходилась в миллисекунды при бюджете
/// кадра 16 мс, причём платили мы не за пиксели: кусок в двести раз больший стоил всего в 1.3
/// раза дороже ([[compositor-damage]]).
///
/// Теперь клиент пишет прямо в кадр, а по IPC уходит только «этот прямоугольник изменился».
/// Никакой копии нет вовсе — ни у клиента, ни в ядре, ни у композитора.
pub struct Window {
    ep: usize,
    id: u32,
    pub width: u16,
    pub height: u16,
    /// Адрес общего буфера кадра в СВОЁМ пространстве и его длина (`width*height*4`).
    buf: usize,
    buf_len: usize,
    /// Право на область (полное, наше) и слот окна ВА — нужны, чтобы её ОТПУСТИТЬ.
    cap: usize,
    slot: usize,
}

/// Буфер кадра: своя область памяти, отображённая в свободный слот.
struct FrameBuf {
    va: usize,
    len: usize,
    cap: usize,
    slot: usize,
}

/// Завести общую область под кадр `width×height` и отобразить её себе.
fn new_frame_buf(width: u16, height: u16) -> Option<FrameBuf> {
    let len = width as usize * height as usize * 4;
    let slot = take_slot()?;
    let va = slot_va(slot);
    match crate::shm_new(len, va) {
        Some(cap) => Some(FrameBuf { va, len, cap, slot }),
        None => {
            free_slot(slot); // область не вышла — слот держать не за что
            None
        }
    }
}

/// Размер экрана у композитора. `None` — окон в этой сессии нет.
///
/// Спрашивать приходится ДО создания поверхности: буфер кадра уезжает вместе с запросом, а
/// обоям и бару его размер диктует экран.
pub fn screen() -> Option<(u16, u16)> {
    let ep = endpoint()?;
    let mut rep = [0u8; 4];
    let n = crate::call(ep, OP_SCREEN, &[], &mut rep);
    if n == crate::NO_CAP {
        return None;
    }
    let s = wire::Screen::decode(&rep[..n.min(rep.len())])?;
    Some((s.w, s.h))
}

/// Веха 150 — **СКОПИРОВАТЬ**: положить байты в store и назвать их композитору ([`OP_CLIP_SET`]).
///
/// `store_cap` нужен с правом записи — тем же, которым клиент кладёт в store что угодно другое.
/// `false` — либо композитора нет, либо store отказал, либо композитор не принял.
pub fn clip_put(store_cap: usize, kind: u8, bytes: &[u8]) -> bool {
    let Some(ep) = endpoint() else { return false };
    let mut id = [0u8; 32];
    if bytes.is_empty() || crate::obj_put(store_cap, bytes, &mut id) != 0 {
        return false;
    }
    let mut req = [0u8; 33];
    let n = wire::Clip { kind, id }.encode(&mut req);
    let mut rep = [0u8; 1];
    crate::call(ep, OP_CLIP_SET, &req[..n], &mut rep) == 1
}

/// Веха 150.1 — **НАЧАТЬ ТАЩИТЬ**: положить байты в store и назвать их композитору ([`OP_DRAG`]).
///
/// Та же пара действий, что у [`clip_put`], и отличие ровно одно — подпись, которую человек
/// увидит под курсором, пока тащит. Звать эту функцию имеет смысл только из обработки движения с
/// зажатой кнопкой: композитор откажет, если кнопки нет или курсор не над окном просящего.
pub fn drag(store_cap: usize, kind: u8, bytes: &[u8], label: &str) -> bool {
    let Some(ep) = endpoint() else { return false };
    let mut id = [0u8; 32];
    if bytes.is_empty() || crate::obj_put(store_cap, bytes, &mut id) != 0 {
        return false;
    }
    // Хвост подписи режем по границе СИМВОЛА: имя корня бывает и кириллицей, а половина буквы
    // приедет к композитору как мусор, который тот честно нарисует.
    let mut cut = LABEL_MAX.min(label.len());
    while cut > 0 && !label.is_char_boundary(cut) {
        cut -= 1;
    }
    let mut req = [0u8; 33 + LABEL_MAX];
    let n = wire::Drag { kind, id, label: &label.as_bytes()[..cut] }.encode(&mut req);
    let mut rep = [0u8; 1];
    crate::call(ep, OP_DRAG, &req[..n], &mut rep) == 1
}

/// Спросить композитора «как называется вот это» — общий разбор для [`OP_CLIP_GET`] и [`OP_DROP`].
///
/// Отвечают они одинаково (`[вид u8, content-id 32]`) не случайно: буфер обмена и перетаскивание
/// возят одно и то же значение, и разница между ними — в том, кто кому его назвал, а не в том,
/// что назвали.
fn named(op: usize) -> Option<(u8, [u8; 32])> {
    let ep = endpoint()?;
    let mut rep = [0u8; 33];
    let n = crate::call(ep, op, &[], &mut rep);
    if n == crate::NO_CAP || n == 0 {
        return None;
    }
    let c = wire::Clip::decode(&rep[..n.min(rep.len())])?;
    Some((c.kind, c.id))
}

/// Прочитать своим правом на store то, что назвал композитор. `(вид, сколько влезло, сколько
/// всего)` — как [`crate::obj_get_ex`]: усечка обязана быть видна читающему.
fn read_named(store_cap: usize, op: usize, out: &mut [u8]) -> Option<(u8, usize, usize)> {
    let (kind, id) = named(op)?;
    let (got, full) = crate::obj_get_ex(store_cap, &id, out);
    (full != 0).then_some((kind, got, full))
}

/// Веха 150 — **что сейчас в буфере**: вид и content-id ([`OP_CLIP_GET`]). `None` — буфер пуст
/// либо композитора нет.
pub fn clip_id() -> Option<(u8, [u8; 32])> {
    named(OP_CLIP_GET)
}

/// Веха 150 — **ВСТАВИТЬ**: содержимое буфера в `out`.
///
/// Читает сам спрашивающий, своим правом на store: композитор имя назвал, байты не возит.
pub fn clip_read(store_cap: usize, out: &mut [u8]) -> Option<(u8, usize, usize)> {
    read_named(store_cap, OP_CLIP_GET, out)
}

/// Веха 150.1 — **что в нас уронили**: вид и content-id ([`OP_DROP`]). `None` — ничего не роняли
/// либо уроненное уже забрали.
pub fn drop_id() -> Option<(u8, [u8; 32])> {
    named(OP_DROP)
}

/// Веха 150.1 — **ЗАБРАТЬ УРОНЕННОЕ**: его содержимое в `out`. Спрашивают после [`EV_DROP`].
pub fn drop_read(store_cap: usize, out: &mut [u8]) -> Option<(u8, usize, usize)> {
    read_named(store_cap, OP_DROP, out)
}

/// Веха 147 — сказать композитору «я запустил вот это, жди окна» ([`OP_LAUNCHING`]).
///
/// `false` — композитора нет либо он отказал; для запускающего это не повод не запускать, а
/// повод не ждать плитки.
pub fn launching(name: &str) -> bool {
    let Some(ep) = endpoint() else { return false };
    // Буфер на стеке, а не `Vec`: библиотека шимов не тянет `alloc` — иначе куча понадобилась бы
    // и программам, которые живут без неё (см. заголовок `heap`).
    let mut req = [0u8; TITLE_MAX];
    let n = name.len().min(TITLE_MAX);
    req[..n].copy_from_slice(&name.as_bytes()[..n]);
    let mut rep = [0u8; 4];
    crate::call(ep, OP_LAUNCHING, &req[..n], &mut rep) == 4
}

/// Веха 147 — сказать композитору, ЧЕМ КОНЧИЛОСЬ ([`OP_LAUNCH_DONE`]): код выхода и хвост
/// вывода. Плитки может уже не быть — тогда сообщение пропадает, и это нормальный исход.
pub fn launch_done(code: usize, tail: &[u8]) -> bool {
    let Some(ep) = endpoint() else { return false };
    let mut req = [0u8; 4 + TAIL_MAX];
    // Приёмный буфер композитора — килобайт: длинный хвост режем ЗДЕСЬ, чтобы обрезка была
    // видна отправителю, а не случилась молча на той стороне. Берём КОНЕЦ вывода: последние
    // строки перед смертью и объясняют смерть.
    let n = tail.len().min(TAIL_MAX);
    let msg = wire::LaunchDone { code: code as u32, tail: &tail[tail.len() - n..] };
    let len = msg.encode(&mut req);
    crate::call(ep, OP_LAUNCH_DONE, &req[..len], &mut []) != crate::NO_CAP
}

/// Сколько байт вывода уезжает в карточку итога.
pub const TAIL_MAX: usize = 768;

impl Window {
    /// Попросить окно. `None` — композитора нет или он отказал.
    pub fn create(width: u16, height: u16, title: &str) -> Option<Window> {
        Self::open(None, width, height, title)
    }

    /// Веха 139 — попросить ПОВЕРХНОСТЬ СЛОЯ: обои, бар, панель. Дальше она ничем не отличается
    /// от окна — те же пиксели, тот же `damage`, те же события.
    pub fn layer(spec: Layer, width: u16, height: u16, title: &str) -> Option<Window> {
        Self::open(Some(spec), width, height, title)
    }

    fn open(spec: Option<Layer>, width: u16, height: u16, title: &str) -> Option<Window> {
        let Some(ep) = endpoint() else {
            crate::write_console("[win] окна нет: WM не объявлен в окружении\n".as_bytes());
            return None;
        };
        // Буфер кадра заводим ДО запроса: право на него уезжает вместе с ним, и композитор
        // получает окно уже с картинкой, а не «сначала окно, потом как-нибудь буфер».
        let Some(fb) = new_frame_buf(width, height) else {
            crate::write_console("[win] окна нет: общая область под кадр не завелась\n".as_bytes());
            return None;
        };
        let ro = crate::cap_derive(fb.cap, RIGHT_SHARE);
        if ro == crate::NO_CAP {
            crate::write_console("[win] окна нет: право на буфер не урезалось\n".as_bytes());
            return None;
        }
        let mut req = [0u8; 9 + TITLE_MAX];
        let t = title.as_bytes();
        let (op, len) = match spec {
            None => (OP_CREATE, wire::Create { w: width, h: height, title: t }.encode(&mut req)),
            Some(spec) => (
                OP_LAYER,
                wire::LayerReq { spec, w: width, h: height, title: t }.encode(&mut req),
            ),
        };
        let mut rep = [0u8; 4];
        let n = crate::call_full(ep, op, &req[..len], &mut rep, ro).0;
        let Some(id) = (n != crate::NO_CAP).then(|| wire::id(&rep[..n.min(4)])).flatten() else {
            crate::write_console("[win] окна нет: композитор не ответил номером окна\n".as_bytes());
            return None;
        };
        Some(Window {
            ep,
            id,
            width,
            height,
            buf: fb.va,
            buf_len: fb.len,
            cap: fb.cap,
            slot: fb.slot,
        })
    }

    /// Кадр окна: RGBA8888 по строкам, ровно `width * height * 4` байта. Пишется НАПРЯМУЮ —
    /// это те же страницы, в которые смотрит композитор.
    pub fn pixels(&mut self) -> &mut [u8] {
        if self.buf == 0 {
            return &mut []; // окно уже закрыто — буфера нет
        }
        unsafe { core::slice::from_raw_parts_mut(self.buf as *mut u8, self.buf_len) }
    }

    /// Веха 129 — сменить размер кадра: новая область, новое право композитору.
    ///
    /// Область берётся новая, а не растягивается: страницы уже розданы обоим, и менять их состав
    /// под работающим композитором значило бы ловить его на полукадре. Старая уходит, когда её
    /// отпустят оба держателя.
    pub fn resize_buf(&mut self, width: u16, height: u16) -> bool {
        let Some(fb) = new_frame_buf(width, height) else { return false };
        let ro = crate::cap_derive(fb.cap, RIGHT_SHARE);
        let mut req = [0u8; 8];
        let len = wire::Rebuf { id: self.id, w: width, h: height }.encode(&mut req);
        if ro == crate::NO_CAP
            || crate::call_full(self.ep, OP_REBUF, &req[..len], &mut [], ro).0 == crate::NO_CAP
        {
            // Не вышло — старый буфер остаётся рабочим, новый отпускаем целиком.
            crate::shm_unmap(fb.cap, fb.va);
            free_slot(fb.slot);
            return false;
        }
        // Вызов синхронный: к этому месту композитор УЖЕ отобразил новую область и отпустил
        // старую. Значит старую можно отпустить и нам — последний держатель уходит, страницы
        // возвращаются системе. Порядок здесь единственно верный: отпусти мы её раньше ответа,
        // композитор какое-то время читал бы освобождённые страницы.
        crate::shm_unmap(self.cap, self.buf);
        free_slot(self.slot);
        self.buf = fb.va;
        self.buf_len = fb.len;
        self.cap = fb.cap;
        self.slot = fb.slot;
        self.width = width;
        self.height = height;
        true
    }

    /// Прокрутить содержимое окна: строки `y0..y1` уезжают на `dy` пикселей вверх.
    ///
    /// Веха 129 — это снова обычный сдвиг памяти У СЕБЯ, и композитору о нём знать не нужно:
    /// буфер общий, значит его копия уехала тем же движением. Операция протокола `OP_SCROLL`
    /// понадобилась в Вехе 120.3 ровно потому, что копий было ДВЕ и переслать вторую стоило
    /// мегабайта на строку текста; с общим буфером пересылать нечего.
    pub fn scroll(&mut self, y0: u16, y1: u16, dy: i16) -> bool {
        if dy <= 0 || y1 <= y0 {
            return false;
        }
        let stride = self.width as usize * 4;
        let (y0, y1, dy) = (y0 as usize, y1.min(self.height) as usize, dy as usize);
        if y1 <= y0 + dy {
            return false;
        }
        let px = self.pixels();
        let (from, to, dst) = ((y0 + dy) * stride, y1 * stride, y0 * stride);
        if to > px.len() {
            return false;
        }
        px.copy_within(from..to, dst);
        // Освободившийся хвост НЕ чистим: клиент сейчас нарисует туда новые строки, а мигание
        // пустой полосой видно.
        self.damage(0, y0 as u16, self.width, (y1 - y0) as u16)
    }

    /// Сказать «кадр готов» и объявить изменившийся прямоугольник.
    pub fn damage(&self, x: u16, y: u16, w: u16, h: u16) -> bool {
        let mut req = [0u8; 12];
        let len = wire::Commit { id: self.id, x, y, w, h }.encode(&mut req);
        crate::call(self.ep, OP_COMMIT, &req[..len], &mut []) != crate::NO_CAP
    }

    /// Ждать событие. Ответ отложенный: пока событий нет, клиент спит в `SYS_CALL` — ровно так
    /// же, как программа спит в чтении stdin у терминала.
    pub fn next_event(&self) -> Option<Event> {
        self.event(OP_EVENT)
    }

    /// Забрать событие, если оно уже есть. `None` — событий нет ПРЯМО СЕЙЧАС.
    pub fn poll_event(&self) -> Option<Event> {
        self.event(OP_POLL)
    }

    /// Веха 140 — ждать событие, но не дольше срока. `None` — срок вышел, событий не было.
    ///
    /// Понадобилось часам в баре: спать до события нельзя (минута не событие), а опрашивать
    /// каждые сто миллисекунд — значит не спать вовсе.
    ///
    /// Веха 145 — срок стал ГОДНЫМ ДЛЯ АНИМАЦИИ. Раньше композитор спал своим шагом простоя
    /// (200 мс) и проверял чужие сроки, только проснувшись: попросив 16 мс, клиент получал ответ
    /// через двести, то есть пять кадров в секунду. Теперь композитор укорачивает собственный сон
    /// до ближайшего чужого срока — движение внутри поверхности клиента (меню, подсветка, капсула
    /// стола) идёт с той же частотой, что и движение окон.
    pub fn next_event_timeout(&self, ms: u32) -> Option<Event> {
        let mut req = [0u8; 8];
        let len = wire::EventReq { id: self.id, ms: Some(ms) }.encode(&mut req);
        let mut rep = [0u8; 16];
        let n = crate::call(self.ep, OP_EVENT, &req[..len], &mut rep);
        if n == 0 || n == crate::NO_CAP {
            return None;
        }
        Event::parse(&rep[..n])
    }

    /// Веха 140 — подписаться на [`EV_STATUS`]: смену стола, их числа и фокуса.
    pub fn watch(&self) -> bool {
        crate::call(self.ep, OP_WATCH, &self.id.to_le_bytes(), &mut []) != crate::NO_CAP
    }

    /// Веха 140 — состояние рабочего места: `(номер стола, сколько столов, длина заголовка)`.
    /// Заголовок окна в фокусе пишется в `title` (UTF-8, обрезан по его длине).
    pub fn status(&self, title: &mut [u8]) -> Option<Status> {
        let mut rep = [0u8; 4 + TITLE_MAX];
        let n = crate::call(self.ep, OP_STATUS, &[], &mut rep);
        if n == crate::NO_CAP {
            return None;
        }
        let s = wire::Status::decode(&rep[..n.min(rep.len())])?;
        let t = s.title.len().min(title.len());
        title[..t].copy_from_slice(&s.title[..t]);
        Some(Status {
            space: s.space,
            spaces: s.spaces,
            layout: s.layout,
            overview: s.overview,
            title_len: t,
        })
    }

    /// Веха 140 — переключить рабочий стол (столы в баре кликабельны).
    pub fn switch_space(&self, n: u8) -> bool {
        crate::call(self.ep, OP_SPACE, &[n], &mut []) != crate::NO_CAP
    }

    /// Веха 144 — переключить раскладку клавиатуры (буквы EN/RU в баре кликабельны).
    pub fn switch_layout(&self) -> bool {
        crate::call(self.ep, OP_LAYOUT, &[], &mut []) != crate::NO_CAP
    }

    /// Номер окна у композитора. Пригождается там, где программе нужно имя, уникальное среди
    /// СВОИХ ЖЕ окон и не растущее от запуска к запуску: номера начинаются с единицы на каждой
    /// загрузке, поэтому имена вроде `app/term/3` не копятся вечно (Веха 151).
    pub fn id(&self) -> u32 {
        self.id
    }

    /// Веха 151 — ответить на [`Event::Save`]: чем позвать это окно обратно ([`OP_PERSIST`]).
    ///
    /// `run` — командная строка: имя программы и аргументы через пробел. Аргумент с пробелом
    /// внутри не поедет, и это не недосмотр: строку разбирает тот же разбор по пробелам, что и
    /// конфиг поколения, а имена корней store пробелов не содержат.
    pub fn persist(&self, run: &str) -> bool {
        let mut req = [0u8; 4 + RUN_MAX];
        let mut cut = RUN_MAX.min(run.len());
        while cut > 0 && !run.is_char_boundary(cut) {
            cut -= 1;
        }
        let n = wire::Persist { id: self.id, run: &run.as_bytes()[..cut] }.encode(&mut req);
        let mut rep = [0u8; 1];
        crate::call(self.ep, OP_PERSIST, &req[..n], &mut rep) == 1
    }

    /// Сказать композитору, что окна больше не будет, и отпустить буфер кадра.
    ///
    /// Отпускаем ПОСЛЕ ответа: композитор доигрывает закрытие (окно сжимается) и всё это время
    /// смотрит в буфер. Уйдут оба держателя — страницы вернутся системе сами.
    pub fn destroy(&mut self) {
        crate::call(self.ep, OP_DESTROY, &self.id.to_le_bytes(), &mut []);
        crate::shm_unmap(self.cap, self.buf);
        free_slot(self.slot);
        self.buf = 0;
        self.buf_len = 0;
    }

    fn event(&self, op: usize) -> Option<Event> {
        let mut rep = [0u8; 16];
        let n = crate::call(self.ep, op, &self.id.to_le_bytes(), &mut rep);
        if n == 0 || n == crate::NO_CAP {
            return None;
        }
        Event::parse(&rep[..n])
    }
}
