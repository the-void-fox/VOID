//! Протокол окон (Веха 117, [[0007-graphics-native-compositor]], [[0016-void-ui-toolkit]]).
//!
//! ## Устройство в одном абзаце
//!
//! Композитор — обычный IPC-сервер, как файловый или сетевой. Клиент получает право звать его
//! (тем же способом, что stdio — [[process-stdio]]), просит окно и получает **общий буфер
//! кадра**: те же физические страницы видны и ему, и композитору. Клиент рисует прямо в них и
//! говорит «этот прямоугольник изменился». Ядро про окна не знает ничего.
//!
//! ## Буфер стал общим (Веха 129)
//!
//! До неё пиксели ехали ОБЪЕКТОМ store: клиент клал изменившийся кусок, композитор читал его по
//! content-id. Довод был силён — содержимое адресуется хэшем, а не местом, значит переезд на GPU
//! не меняет протокол, одинаковые кадры дедуплицируются, а окна в принципе могут пережить
//! перезагрузку. Цена честно называлась долгом «настоящая цена появится у видео и игр».
//!
//! Цена оказалась ближе: замер ([[compositor-damage]]) показал, что **платим мы не за пиксели**.
//! Кусок в двести раз больший стоил всего в 1.3 раза дороже — то есть весь счёт шёл за сам факт
//! объекта: syscall, BLAKE3, куча ядра, индекс и групповой коммит, который вставка тащит за
//! собой. Изменившаяся строка окна обходилась в миллисекунды при бюджете кадра 16 мс, и упирался
//! в это обычный вывод `ls` — не видео и не игры.
//!
//! Store в этом не виноват: он сделан для того, что ДОЛЖНО пережить перезагрузку и адресоваться
//! хэшем. Пиксели живут один кадр — им нужна не персистентность, а общая страница.
//!
//! Что осталось от прежних доводов: буфер по-прежнему не адрес В ЧУЖОЙ ПАМЯТИ, а **ресурс под
//! capability** ([[shm]]) — композитор не может смотреть в чужое окно без права, а право не
//! подделать. Переезд на GPU протокол тоже не ломает: сменится то, ЧЕМ является область, а
//! «клиент пишет в буфер и объявляет прямоугольник» останется.
//!
//! ## Кадр доставляет композитор
//!
//! Клиент говорит «готово» и объявляет ПРЯМОУГОЛЬНИК изменений; куда и когда это попадёт на
//! экран, решает композитор. Так же устроены анимации (ADR 0016): их часы — у него, потому что
//! двигать окно, ничего не перерисовывая, может только он.
//!
//! ## Слои (Веха 139)
//!
//! Обои и бар — не окна: они не встают в ленту, не берут фокус и прижаты к краю экрана. Но и не
//! часть композитора: [`OP_LAYER`] даёт им ОБЫЧНУЮ поверхность, только с другим местом в стопке
//! и другим правилом расстановки. Это решение стоит назвать вслух, потому что соблазн был
//! обратный — нарисовать обои внутри `wm`.
//!
//! Внутри композитора обои означали бы, что он умеет читать store, разбирать PNG и JPEG и знает
//! про масштабирование. Каждая из этих способностей — чужая работа и чужая же поверхность атаки:
//! в композиторе лежат буферы ВСЕХ окон, и падение в декодере картинки роняло бы весь экран.
//! Клиент слоя падает в одиночку — на экране просто остаётся цвет стола.

/// Создать окно: `[ширина u16, высота u16, заголовок…]` → `[id u32]` + право на БУФЕР КАДРА.
pub const OP_CREATE: usize = 1;
// 2 и 7 — свободны. Там были `OP_ATTACH` (привязать пиксели прямоугольника объектом store) и
// `OP_SCROLL` (сдвинуть содержимое у композитора). Обе умерли с общим буфером (Веха 129): первой
// нечего пересылать, второй нечего двигать — копия одна, и клиент двигает её сам. Номера
// оставлены пустыми намеренно: перенумеровывать живые операции ради красоты значит ломать
// работающие программы на ровном месте.
/// Кадр готов: `[id u32, x u16, y u16, w u16, h u16]` — прямоугольник изменений.
pub const OP_COMMIT: usize = 3;
/// Ждать событие: `[id u32]` → ответ ОТЛОЖЕННЫЙ, как чтение stdin у терминала.
pub const OP_EVENT: usize = 4;
/// Закрыть окно: `[id u32]`.
pub const OP_DESTROY: usize = 5;
/// Забрать событие БЕЗ ожидания: `[id u32]` → событие или пустой ответ.
///
/// Нужен клиентам, у которых есть свой реактор: терминал — сам сервер для своих панелей, и
/// уснуть в нашем вызове он не может, иначе перестанет обслуживать детей. Простым программам
/// (`winbox`) по-прежнему проще спать в [`OP_EVENT`].
pub const OP_POLL: usize = 6;
/// Веха 129 — НОВЫЙ буфер кадра под изменившийся размер: `[id u32, w u16, h u16]` + право на
/// область. Отдельная операция, а не поле в `OP_CREATE`: размер окна назначает раскладка, и
/// менять буфер приходится по её команде, а не при рождении.
pub const OP_REBUF: usize = 8;
/// Веха 139 — поверхность СЛОЯ: `[слой u8, якорь u8, w u16, h u16, зона u16, заголовок…]`
/// → `[id u32]` + право на буфер кадра. Дальше она живёт обычным окном: те же `OP_COMMIT`,
/// `OP_EVENT`, `OP_REBUF`, `OP_DESTROY`.
///
/// Отдельная операция, а не флаг в [`OP_CREATE`]: у слоя другой СМЫСЛ, а не другая настройка.
/// Обычное окно просит места у раскладки и получает его от неё; поверхность слоя место
/// НАЗЫВАЕТ САМА (край экрана и размер) и в раскладке не участвует вовсе.
pub const OP_LAYER: usize = 9;
/// Веха 139 — размер экрана: `[]` → `[w u16, h u16]`.
///
/// Нужен потому, что буфер кадра уезжает вместе с запросом на поверхность, а размер обоев или
/// бара считается ОТ ЭКРАНА: не спросив, клиент не знает, сколько памяти заводить. Право на сам
/// фреймбуфер (`mmio:fb`) у него при этом остаётся только у композитора — спрашивают у него, а
/// не у железа.
pub const OP_SCREEN: usize = 10;

/// Слой: под всем (обои). Ниже прочих поверхностей и ниже окон.
pub const LAYER_BG: u8 = 0;
/// Слой под окнами, но над обоями (док, подложка).
pub const LAYER_BOTTOM: u8 = 1;
/// Слой над окнами (бар, панель).
pub const LAYER_TOP: u8 = 2;
/// Слой над всем, кроме курсора (всплывающие меню, уведомления).
pub const LAYER_OVERLAY: u8 = 3;

/// Якорь: прижать к верхнему краю рабочей области.
pub const ANCHOR_TOP: u8 = 1;
pub const ANCHOR_BOTTOM: u8 = 2;
pub const ANCHOR_LEFT: u8 = 4;
pub const ANCHOR_RIGHT: u8 = 8;
/// Все четыре — поверхность растягивается на весь экран (обои).
pub const ANCHOR_ALL: u8 = ANCHOR_TOP | ANCHOR_BOTTOM | ANCHOR_LEFT | ANCHOR_RIGHT;

/// Чего поверхность слоя хочет от композитора (Веха 139).
///
/// Модель та же, что у `wlr-layer-shell` в Wayland, и это не подражание: у задачи «обои и бар»
/// один и тот же набор вопросов — на каком слое, к какому краю прижать и сколько места отнять у
/// прочих. Придумывать четвёртый ответ на них было бы кокетством.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Layer {
    /// [`LAYER_BG`] … [`LAYER_OVERLAY`].
    pub layer: u8,
    /// Маска краёв ([`ANCHOR_TOP`] и т. д.). Прижат к обоим краям оси — растянут по ней.
    pub anchor: u8,
    /// **Занятая зона**: сколько пикселей у края поверхность забирает у окон. 0 — не забирает
    /// ничего (окна лягут под ней). Работает только при якоре ровно к одному краю оси: «бар
    /// сверху отнял 32 пикселя» смысл имеет, «поверхность посередине отняла 32» — нет.
    pub exclusive: u16,
}

impl Layer {
    /// Обои: фоновый слой во весь экран, места у окон не занимает.
    pub const WALLPAPER: Layer = Layer { layer: LAYER_BG, anchor: ANCHOR_ALL, exclusive: 0 };
}

/// Событие: движение мыши над окном — `[1, x u16, y u16]` (координаты внутри окна).
pub const EV_MOTION: u8 = 1;
/// Кнопка мыши — `[2, x u16, y u16, кнопки u8, нажата u8]`.
pub const EV_BUTTON: u8 = 2;
/// Клавиша — `[3, sym u16, mods u8, ch u16, нажата u8]` (Веха 127).
///
/// Раньше здесь ехал ОДИН БАЙТ готового ASCII, и это была дыра, а не упрощение: у стрелок,
/// Home/End и PageUp ASCII нет вовсе, поэтому они терялись по дороге — в окне не работали ни
/// они, ни собственные клавиши терминала (`Shift+PageUp`). Событие окна попросту отстало от
/// события ядра, которое возит `sym` + маску модификаторов с Вехи 119.
///
/// - `sym` — код клавиши в том же пространстве, что у ядра и у схемы `wm`: печатные — свой
///   НЕсдвинутый символ (`l` это `0x6c`), прочие — выше `0x100` (`0x110` Left, `0x116` PageUp).
///   Клавиша именуется собой, а не тем, что напечатает: иначе `Super+L` и `l` разъехались бы.
/// - `mods` — Shift 1, Ctrl 2, Alt 4, Super 8 (как в строке аккорда конфига).
/// - `ch` — кодовая точка символа Unicode или 0, если клавиша ничего не печатает. Не байт:
///   раскладка RU/EN (следующая веха) даёт кириллицу, которая в байт не влезает.
/// - `нажата` — 1 нажатие, 0 отпускание. Сегодня всегда 1: `wm` отсеивает отпускания раньше,
///   и это осознанно. Отдавать их ТОЛЬКО окну было бы хуже молчания — аккорд (`Super+Q`)
///   перехватывает нажатие, и программа получила бы отпускание клавиши, нажатия которой не
///   видела. Место в событии оставлено, чтобы включить их потом без правки протокола.
pub const EV_KEY: u8 = 3;
/// Окно просят закрыться — `[4]`.
pub const EV_CLOSE: u8 = 4;
/// Окну НАЗНАЧЕН новый размер — `[5, w u16, h u16]` (Веха 121).
///
/// В тайлинге размер окна выбирает не приложение, а раскладка: колонка стала уже — окно обязано
/// стать уже вместе с ней. Поэтому размер здесь СОБЫТИЕ, а не пожелание клиента при создании:
/// тот размер был лишь просьбой, и до появления тайлинга её просто некому было пересматривать.
pub const EV_RESIZE: u8 = 5;

/// Имя переменной окружения, в которой хост объявляет индекс права на себя. То же соглашение,
/// что у stdio: искать эндпоинт перебором нельзя — «проба» это отправка сообщения, то есть
/// побочный эффект.
pub const ENV: &str = "WM";

/// Событие, разобранное клиентом.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Event {
    Motion { x: u16, y: u16 },
    Button { x: u16, y: u16, buttons: u8, down: bool },
    /// Клавиша: код, модификаторы, кодовая точка (0 — клавиша ничего не печатает), нажатие.
    Key { sym: u16, mods: u8, ch: u16, down: bool },
    Close,
    /// Новый размер содержимого окна: клиент обязан перерисовать кадр под него.
    Resize { w: u16, h: u16 },
}

/// Прочитать u16 из ответа (little-endian), не выходя за его край.
fn rd16(b: &[u8], i: usize) -> Option<u16> {
    Some(u16::from_le_bytes([*b.get(i)?, *b.get(i + 1)?]))
}

impl Event {
    /// Разобрать байты ответа. `None` — пустой или непонятный ответ.
    pub fn parse(b: &[u8]) -> Option<Event> {
        match *b.first()? {
            EV_MOTION => Some(Event::Motion { x: rd16(b, 1)?, y: rd16(b, 3)? }),
            EV_BUTTON => Some(Event::Button {
                x: rd16(b, 1)?,
                y: rd16(b, 3)?,
                buttons: *b.get(5)?,
                down: *b.get(6)? != 0,
            }),
            EV_KEY => Some(Event::Key {
                sym: rd16(b, 1)?,
                mods: *b.get(3)?,
                ch: rd16(b, 4)?,
                down: *b.get(6)? != 0,
            }),
            EV_CLOSE => Some(Event::Close),
            EV_RESIZE => Some(Event::Resize { w: rd16(b, 1)?, h: rd16(b, 3)? }),
            _ => None,
        }
    }
}

// ── клиентская сторона ───────────────────────────────────────────────────────
//
// Тонкая обёртка над `SYS_CALL`: у приложения не должно быть повода знать раскладку байтов.
// Кучи здесь НЕТ намеренно: библиотеку линкуют и программы без аллокатора, а сообщения
// протокола и так помещаются в десятки байт.

/// Потолок длины заголовка окна. Больше на титульной полосе всё равно не поместится.
pub const TITLE_MAX: usize = 60;

/// Право звать композитор (`WM=<индекс>` в окружении). `None` — окон в этой сессии нет.
///
/// Разбор такой же, как у stdio, и это не совпадение: оба — ХОСТЫ, которых процессу дал
/// родитель, а не права, выданные системой на старте. У вторых имя начинается с `CAP_`
/// (`CAP_STORE`, `CAP_FB` — их кладёт init), у первых — нет.
pub fn endpoint() -> Option<usize> {
    let mut buf = [0u8; 512];
    let n = crate::env(&mut buf).min(buf.len());
    let mut key = [0u8; 16];
    key[..ENV.len()].copy_from_slice(ENV.as_bytes());
    key[ENV.len()] = b'=';
    let klen = ENV.len() + 1;
    for entry in buf[..n].split(|&b| b == 0) {
        if entry.len() <= klen || entry[..klen] != key[..klen] {
            continue;
        }
        let mut idx = 0usize;
        let mut any = false;
        for &d in &entry[klen..] {
            if !d.is_ascii_digit() {
                any = false;
                break;
            }
            idx = idx * 10 + (d - b'0') as usize;
            any = true;
        }
        if any {
            let cap = crate::start_cap(idx);
            return (cap != crate::NO_CAP).then_some(cap);
        }
    }
    None
}

/// Веха 129 — окно ВА-окна под общие буферы кадров: между кучей процесса (`0x6000_0000`) и его
/// стеком (вершина `0x8000_0000`). Образ программы лежит с `0x4000_0000`, и класть буфер туда
/// значит убить процесс его же кодом — на этом уже наступили при первом опыте.
///
/// Шаг 8 МиБ: полноэкранный кадр 1600×1200×4 — 7.3 МиБ, то есть одно окно в слот влезает всегда.
const SHM_BASE: usize = 0x7000_0000;
const SHM_STRIDE: usize = 8 * 1024 * 1024;

/// Сколько слотов помещается до стека (его вершина `0x8000_0000`, под ним 64 страницы).
const SHM_SLOTS: usize = 31;

/// Занятые слоты — по биту на слот. Слоты ПЕРЕИСПОЛЬЗУЮТСЯ: смена размера берёт новую область, и
/// без возврата слотов окно, переложенное тридцать раз, упёрлось бы в край окна ВА, хотя занято
/// при этом одно.
static SLOTS: core::sync::atomic::AtomicUsize = core::sync::atomic::AtomicUsize::new(0);

/// Занять свободный слот. `None` — все заняты (у клиента больше тридцати живых буферов).
fn take_slot() -> Option<usize> {
    use core::sync::atomic::Ordering;
    let mut cur = SLOTS.load(Ordering::Relaxed);
    loop {
        let free = (0..SHM_SLOTS).find(|i| cur & (1 << i) == 0)?;
        match SLOTS.compare_exchange_weak(
            cur, cur | (1 << free), Ordering::Relaxed, Ordering::Relaxed,
        ) {
            Ok(_) => return Some(free),
            Err(now) => cur = now,
        }
    }
}

fn free_slot(i: usize) {
    SLOTS.fetch_and(!(1 << i), core::sync::atomic::Ordering::Relaxed);
}

fn slot_va(i: usize) -> usize {
    SHM_BASE + i * SHM_STRIDE
}

/// Права, с которыми буфер уезжает композитору: `READ | GRANT`, БЕЗ `WRITE`. Он в кадр не пишет —
/// рисует клиент, композитор читает; ядро отобразит область только на чтение, и «композитор не
/// портит чужой кадр» становится свойством ЖЕЛЕЗА, а не обещанием кода.
///
/// `GRANT` тут не про щедрость: отправка права ПО IPC его и требует (ядро проверяет `GRANT` при
/// `CALL` — [[ipc-cap-transfer]]). Чистое `READ` без него не уезжает вовсе, и обнаруживается это
/// не отказом, а тем, что окно не открывается: терминал молча уходил в режим владельца экрана.
const RIGHT_SHARE: usize = 0b101;

/// Окно клиента: право на композитор, выданный им номер и ОБЩИЙ БУФЕР КАДРА.
///
/// Веха 129 — буфер разделяемый, а не пересылаемый. До неё каждый изменившийся кусок ехал
/// объектом store: клиент клал его (BLAKE3 + куча ядра + индекс + групповой коммит), композитор
/// читал по content-id. Замер показал цену — строка окна обходилась в миллисекунды при бюджете
/// кадра 16 мс, причём платили мы не за пиксели: кусок в двести раз больший стоил всего в 1.3
/// раза дороже ([[compositor-damage]]).
///
/// Теперь клиент пишет прямо в кадр, а по IPC уходит только «этот прямоугольник изменился».
/// Никакой копии нет вовсе — ни у клиента, ни в ядре, ни у композитора.
pub struct Window {
    ep: usize,
    id: u32,
    pub width: u16,
    pub height: u16,
    /// Адрес общего буфера кадра в СВОЁМ пространстве и его длина (`width*height*4`).
    buf: usize,
    buf_len: usize,
    /// Право на область (полное, наше) и слот окна ВА — нужны, чтобы её ОТПУСТИТЬ.
    cap: usize,
    slot: usize,
}

/// Буфер кадра: своя область памяти, отображённая в свободный слот.
struct FrameBuf {
    va: usize,
    len: usize,
    cap: usize,
    slot: usize,
}

/// Завести общую область под кадр `width×height` и отобразить её себе.
fn new_frame_buf(width: u16, height: u16) -> Option<FrameBuf> {
    let len = width as usize * height as usize * 4;
    let slot = take_slot()?;
    let va = slot_va(slot);
    match crate::shm_new(len, va) {
        Some(cap) => Some(FrameBuf { va, len, cap, slot }),
        None => {
            free_slot(slot); // область не вышла — слот держать не за что
            None
        }
    }
}

/// Размер экрана у композитора. `None` — окон в этой сессии нет.
///
/// Спрашивать приходится ДО создания поверхности: буфер кадра уезжает вместе с запросом, а
/// обоям и бару его размер диктует экран.
pub fn screen() -> Option<(u16, u16)> {
    let ep = endpoint()?;
    let mut rep = [0u8; 4];
    if crate::call(ep, OP_SCREEN, &[], &mut rep) != 4 {
        return None;
    }
    Some((u16::from_le_bytes([rep[0], rep[1]]), u16::from_le_bytes([rep[2], rep[3]])))
}

impl Window {
    /// Попросить окно. `None` — композитора нет или он отказал.
    pub fn create(width: u16, height: u16, title: &str) -> Option<Window> {
        Self::open(None, width, height, title)
    }

    /// Веха 139 — попросить ПОВЕРХНОСТЬ СЛОЯ: обои, бар, панель. Дальше она ничем не отличается
    /// от окна — те же пиксели, тот же `damage`, те же события.
    pub fn layer(spec: Layer, width: u16, height: u16, title: &str) -> Option<Window> {
        Self::open(Some(spec), width, height, title)
    }

    fn open(spec: Option<Layer>, width: u16, height: u16, title: &str) -> Option<Window> {
        let Some(ep) = endpoint() else {
            crate::write_console("[win] окна нет: WM не объявлен в окружении\n".as_bytes());
            return None;
        };
        // Буфер кадра заводим ДО запроса: право на него уезжает вместе с ним, и композитор
        // получает окно уже с картинкой, а не «сначала окно, потом как-нибудь буфер».
        let Some(fb) = new_frame_buf(width, height) else {
            crate::write_console("[win] окна нет: общая область под кадр не завелась\n".as_bytes());
            return None;
        };
        let ro = crate::cap_derive(fb.cap, RIGHT_SHARE);
        if ro == crate::NO_CAP {
            crate::write_console("[win] окна нет: право на буфер не урезалось\n".as_bytes());
            return None;
        }
        // Заголовок идёт ХВОСТОМ, поэтому у слоя перед ним на четыре байта больше: разбирать
        // такое сообщение можно с одного прохода, не зная заранее, какой оно длины.
        let mut req = [0u8; 8 + TITLE_MAX];
        let (op, head) = match spec {
            None => {
                req[0..2].copy_from_slice(&width.to_le_bytes());
                req[2..4].copy_from_slice(&height.to_le_bytes());
                (OP_CREATE, 4)
            }
            Some(l) => {
                req[0] = l.layer;
                req[1] = l.anchor;
                req[2..4].copy_from_slice(&width.to_le_bytes());
                req[4..6].copy_from_slice(&height.to_le_bytes());
                req[6..8].copy_from_slice(&l.exclusive.to_le_bytes());
                (OP_LAYER, 8)
            }
        };
        let t = title.as_bytes();
        let n = t.len().min(TITLE_MAX);
        req[head..head + n].copy_from_slice(&t[..n]);
        let mut rep = [0u8; 4];
        if crate::call_full(ep, op, &req[..head + n], &mut rep, ro).0 != 4 {
            crate::write_console("[win] окна нет: композитор не ответил номером окна\n".as_bytes());
            return None;
        }
        Some(Window {
            ep,
            id: u32::from_le_bytes(rep),
            width,
            height,
            buf: fb.va,
            buf_len: fb.len,
            cap: fb.cap,
            slot: fb.slot,
        })
    }

    /// Кадр окна: RGBA8888 по строкам, ровно `width * height * 4` байта. Пишется НАПРЯМУЮ —
    /// это те же страницы, в которые смотрит композитор.
    pub fn pixels(&mut self) -> &mut [u8] {
        if self.buf == 0 {
            return &mut []; // окно уже закрыто — буфера нет
        }
        unsafe { core::slice::from_raw_parts_mut(self.buf as *mut u8, self.buf_len) }
    }

    /// Веха 129 — сменить размер кадра: новая область, новое право композитору.
    ///
    /// Область берётся новая, а не растягивается: страницы уже розданы обоим, и менять их состав
    /// под работающим композитором значило бы ловить его на полукадре. Старая уходит, когда её
    /// отпустят оба держателя.
    pub fn resize_buf(&mut self, width: u16, height: u16) -> bool {
        let Some(fb) = new_frame_buf(width, height) else { return false };
        let ro = crate::cap_derive(fb.cap, RIGHT_SHARE);
        let mut req = [0u8; 8];
        req[0..4].copy_from_slice(&self.id.to_le_bytes());
        req[4..6].copy_from_slice(&width.to_le_bytes());
        req[6..8].copy_from_slice(&height.to_le_bytes());
        if ro == crate::NO_CAP
            || crate::call_full(self.ep, OP_REBUF, &req, &mut [], ro).0 == crate::NO_CAP
        {
            // Не вышло — старый буфер остаётся рабочим, новый отпускаем целиком.
            crate::shm_unmap(fb.cap, fb.va);
            free_slot(fb.slot);
            return false;
        }
        // Вызов синхронный: к этому месту композитор УЖЕ отобразил новую область и отпустил
        // старую. Значит старую можно отпустить и нам — последний держатель уходит, страницы
        // возвращаются системе. Порядок здесь единственно верный: отпусти мы её раньше ответа,
        // композитор какое-то время читал бы освобождённые страницы.
        crate::shm_unmap(self.cap, self.buf);
        free_slot(self.slot);
        self.buf = fb.va;
        self.buf_len = fb.len;
        self.cap = fb.cap;
        self.slot = fb.slot;
        self.width = width;
        self.height = height;
        true
    }

    /// Прокрутить содержимое окна: строки `y0..y1` уезжают на `dy` пикселей вверх.
    ///
    /// Веха 129 — это снова обычный сдвиг памяти У СЕБЯ, и композитору о нём знать не нужно:
    /// буфер общий, значит его копия уехала тем же движением. Операция протокола `OP_SCROLL`
    /// понадобилась в Вехе 120.3 ровно потому, что копий было ДВЕ и переслать вторую стоило
    /// мегабайта на строку текста; с общим буфером пересылать нечего.
    pub fn scroll(&mut self, y0: u16, y1: u16, dy: i16) -> bool {
        if dy <= 0 || y1 <= y0 {
            return false;
        }
        let stride = self.width as usize * 4;
        let (y0, y1, dy) = (y0 as usize, y1.min(self.height) as usize, dy as usize);
        if y1 <= y0 + dy {
            return false;
        }
        let px = self.pixels();
        let (from, to, dst) = ((y0 + dy) * stride, y1 * stride, y0 * stride);
        if to > px.len() {
            return false;
        }
        px.copy_within(from..to, dst);
        // Освободившийся хвост НЕ чистим: клиент сейчас нарисует туда новые строки, а мигание
        // пустой полосой видно.
        self.damage(0, y0 as u16, self.width, (y1 - y0) as u16)
    }

    /// Сказать «кадр готов» и объявить изменившийся прямоугольник.
    pub fn damage(&self, x: u16, y: u16, w: u16, h: u16) -> bool {
        let mut req = [0u8; 12];
        req[0..4].copy_from_slice(&self.id.to_le_bytes());
        req[4..6].copy_from_slice(&x.to_le_bytes());
        req[6..8].copy_from_slice(&y.to_le_bytes());
        req[8..10].copy_from_slice(&w.to_le_bytes());
        req[10..12].copy_from_slice(&h.to_le_bytes());
        crate::call(self.ep, OP_COMMIT, &req, &mut []) != crate::NO_CAP
    }

    /// Ждать событие. Ответ отложенный: пока событий нет, клиент спит в `SYS_CALL` — ровно так
    /// же, как программа спит в чтении stdin у терминала.
    pub fn next_event(&self) -> Option<Event> {
        self.event(OP_EVENT)
    }

    /// Забрать событие, если оно уже есть. `None` — событий нет ПРЯМО СЕЙЧАС.
    pub fn poll_event(&self) -> Option<Event> {
        self.event(OP_POLL)
    }

    /// Сказать композитору, что окна больше не будет, и отпустить буфер кадра.
    ///
    /// Отпускаем ПОСЛЕ ответа: композитор доигрывает закрытие (окно сжимается) и всё это время
    /// смотрит в буфер. Уйдут оба держателя — страницы вернутся системе сами.
    pub fn destroy(&mut self) {
        crate::call(self.ep, OP_DESTROY, &self.id.to_le_bytes(), &mut []);
        crate::shm_unmap(self.cap, self.buf);
        free_slot(self.slot);
        self.buf = 0;
        self.buf_len = 0;
    }

    fn event(&self, op: usize) -> Option<Event> {
        let mut rep = [0u8; 16];
        let n = crate::call(self.ep, op, &self.id.to_le_bytes(), &mut rep);
        if n == 0 || n == crate::NO_CAP {
            return None;
        }
        Event::parse(&rep[..n])
    }
}
