//! Растровый шрифт 8×16 (CP866) — общий для всех, кто рисует текст БЕЗ терминала (Веха 140).
//!
//! Таблица глифов живёт в ядре (`arch/x86_64/font.rs`, там она с Вехи 41 для VGA-текста) и
//! подключается ОТСЮДА по пути: копия неизбежно разошлась бы с оригиналом. Файл ядра — только
//! данные (`static [u8; 4096]`), ничего кроме них он не тянет, поэтому годится и для U-mode.
//!
//! Почему модуль отдельный, а не часть [`crate::bitfont`]: тот реализует `Rasterizer` из
//! `ereb-render` и говорит на языке терминала (стили, метрики ячейки, `RasterizedGlyph` с кучей).
//! Бару нужны шестнадцать байт строк глифа и больше ничего — тянуть ради этого крейты терминала
//! значило бы принести в панель весь ereb. Здесь нет ни кучи, ни зависимостей.

// Путь отсчитывается от каталога `src/` — см. то же правило в `bitfont.rs`.
#[path = "../../../kernel/src/arch/x86_64/font.rs"]
mod table;

/// Ширина и высота глифа в пикселях.
pub const W: u32 = 8;
pub const H: u32 = 16;

/// Строки глифа: `H` байт, старший бит — левый пиксель. Для неизвестного символа — `?`.
pub fn rows(ch: char) -> &'static [u8] {
    let code = map_cp866(ch) as usize;
    &table::CP866_8X16[code * H as usize..][..H as usize]
}

/// Unicode → байт CP866. Правило то же, что у консоли ядра (`arch/x86_64/vga.rs::map_cp866`):
/// таблица одна, а отображение в неё короткое, и тащить ради него ещё один файл ядра хуже.
pub fn map_cp866(c: char) -> u8 {
    match c {
        ' '..='~' => c as u8,
        'А'..='Я' => 0x80 + (c as u32 - 'А' as u32) as u8,
        'а'..='п' => 0xA0 + (c as u32 - 'а' as u32) as u8,
        'р'..='я' => 0xE0 + (c as u32 - 'р' as u32) as u8,
        'Ё' => 0xF0,
        'ё' => 0xF1,
        '═' => 0xCD, '║' => 0xBA, '╔' => 0xC9, '╗' => 0xBB, '╚' => 0xC8, '╝' => 0xBC,
        '╟' => 0xC7, '╢' => 0xB6, '╠' => 0xCC, '╣' => 0xB9, '╦' => 0xCB, '╩' => 0xCA, '╬' => 0xCE,
        '─' => 0xC4, '│' => 0xB3, '┌' => 0xDA, '┐' => 0xBF, '└' => 0xC0, '┘' => 0xD9,
        '├' => 0xC3, '┤' => 0xB4, '┬' => 0xC2, '┴' => 0xC1, '┼' => 0xC5,
        '█' => 0xDB, '░' => 0xB0, '▒' => 0xB1, '▓' => 0xB2, '•' => 0x07, '°' => 0xF8,
        '—' | '–' => 0xC4,
        '·' => 0xFA,
        '«' => 0xAE, '»' => 0xAF,
        '→' => 0x1A, '←' => 0x1B, '↑' => 0x18, '↓' => 0x19,
        '…' => b'.',
        '×' => b'x',
        '≈' => b'~',
        '№' => b'#',
        _ => b'?',
    }
}

/// Ширина строки в пикселях при увеличении `scale` — сколько места занять под неё.
pub fn text_width(s: &str, scale: u32) -> u32 {
    s.chars().count() as u32 * W * scale
}
