//! Аргументы и окружение процесса: разобранные ОДИН раз и без ловушки (Веха 148.5).
//!
//! ## Ловушка, ради которой этот модуль есть
//!
//! [`crate::args`] возвращает **полную длину блоба** argv, а в буфер кладёт сколько влезло — так
//! написано в его собственной шапке. Двенадцать из тринадцати вызывающих на это не смотрели:
//! каждый заводил свой буфер (128, 256 или 512 байт — кто во что горазд) и резал `argbuf[..n]`
//! возвращённой длиной. Аргументы длиннее буфера — срез за краем, то есть **паника**.
//!
//! Тринадцатым был сам ОБРАБОТЧИК ПАНИКИ (буфер 64 байта): он берёт argv[0], чтобы сказать, кто
//! именно упал. Поэтому программа с длинными аргументами не падала с сообщением — она исчезала
//! молча: паника внутри обработчика паники прекращает процесс, не напечатав ни строки.
//!
//! Проверено на живой системе (`bin/klog` со ста сорока знаками аргумента): в журнале ядра нет
//! ничего, а шелл говорит «команда не найдена» — то есть ровно то, что говорит о несуществующей
//! программе. Баг, который прячет сам себя.
//!
//! ## Что здесь вместо этого
//!
//! [`Argv`] спрашивает у ядра один раз, в буфер, которого хватает по построению ([`MAX`]), и
//! отдаёт записи. Не влезло — это ВИДНО ([`Argv::cut`]), а не превращается в панику.

/// Потолок ядра на блок АРГУМЕНТОВ, передаваемых при запуске (`ARGS_MAX` в
/// `kernel/src/proc.rs`): длиннее — отказ в `SYS_EXEC`, программа не запустится вовсе.
const KERNEL_ARGS_MAX: usize = 512;

/// Сколько всего может приехать в argv. Больше потолка аргументов, потому что argv[0] ядро
/// приписывает СПЕРЕДИ само и в этот потолок не считает: абсолютный путь из профиля
/// (`/nix/store/<хэш>-<пакет>/bin/<имя>`) съедает под сотню байт, а бывает и длиннее.
pub const MAX: usize = KERNEL_ARGS_MAX + 256;

/// Потолок окружения: у ядра тот же `ARGS_MAX` (`SYS_SETENV` длиннее не принимает).
const ENV_MAX: usize = KERNEL_ARGS_MAX;

/// Аргументы программы, спрошенные у ядра один раз.
///
/// Держать её стоит в `main`: это буфер на стеке, а не куча — модуль линкуется и в программы,
/// живущие без аллокатора.
pub struct Argv {
    buf: [u8; MAX],
    n: usize,
    cut: bool,
}

impl Argv {
    /// Спросить argv у ядра.
    pub fn take() -> Argv {
        let mut buf = [0u8; MAX];
        let full = crate::args(&mut buf);
        // `usize::MAX` — ядро не смогло прочитать наш буфер (такого при своём же буфере на стеке
        // быть не должно, но «не должно» — не то, на чём стоит резать срез).
        let full = if full == usize::MAX { 0 } else { full };
        Argv { buf, n: full.min(MAX), cut: full > MAX }
    }

    /// Не влезло ли argv целиком. Программе, которой это важно, есть о чём сказать вслух;
    /// прочим важно лишь то, что вместо паники они получают усечённый список.
    pub fn cut(&self) -> bool {
        self.cut
    }

    /// Имя программы (argv[0]) — то, чем её назвал запускающий.
    pub fn name(&self) -> &[u8] {
        self.buf[..self.n].split(|&b| b == 0).next().unwrap_or(&[])
    }

    /// Имя программы строкой; `alt` — если argv пуст или это не UTF-8.
    pub fn name_str<'a>(&'a self, alt: &'a str) -> &'a str {
        core::str::from_utf8(self.name()).ok().filter(|s| !s.is_empty()).unwrap_or(alt)
    }

    /// Аргументы БЕЗ имени программы, пустые записи пропущены.
    ///
    /// Пустые пропущены намеренно: блоб оканчивается NUL'ом, и `split` честно отдаёт за ним
    /// пустой хвост — считать его аргументом значило бы, что у всякой программы на один аргумент
    /// больше, чем ей передали.
    pub fn rest(&self) -> impl Iterator<Item = &[u8]> {
        self.buf[..self.n].split(|&b| b == 0).filter(|s| !s.is_empty()).skip(1)
    }

    /// `i`-й аргумент после имени программы (0 — первый настоящий).
    pub fn get(&self, i: usize) -> Option<&[u8]> {
        self.rest().nth(i)
    }

    /// То же строкой. `None` — аргумента нет или он не UTF-8.
    pub fn str(&self, i: usize) -> Option<&str> {
        core::str::from_utf8(self.get(i)?).ok()
    }

    /// Есть ли среди аргументов ровно такая запись (ключ-флаг вроде `-q`).
    pub fn has(&self, flag: &[u8]) -> bool {
        self.rest().any(|a| a == flag)
    }
}

/// Имя программы (argv[0]) в свой буфер; возвращает его длину. Длиннее буфера — обрежется.
///
/// Отдельно от [`Argv`] ради ОДНОГО вызывающего — обработчика паники. Там нельзя занимать
/// килобайт стека (падение вполне могло случиться из-за него же) и нельзя ошибиться в длине:
/// именно эта ошибка и делала панику невидимой — обработчик, взявший срез по возвращённой
/// ядром длине, падал сам, и процесс исчезал, не напечатав ни строки.
pub fn name_into(out: &mut [u8]) -> usize {
    let mut buf = [0u8; 96];
    let n = crate::args(&mut buf).min(buf.len());
    let name = buf[..n].split(|&b| b == 0).next().unwrap_or(&[]);
    let k = name.len().min(out.len());
    out[..k].copy_from_slice(&name[..k]);
    k
}

/// Значение переменной окружения `key` (без `=`) → в `out`. Возвращает длину; `None` — нет
/// такой переменной.
///
/// Окружение спрашивается у ядра каждый раз: переменных единицы, блоб — полкилобайта, а держать
/// его копию значило бы отвечать по устаревшей (`SYS_SETENV` меняет своё окружение на ходу).
pub fn env_raw(key: &[u8], out: &mut [u8]) -> Option<usize> {
    let mut buf = [0u8; ENV_MAX];
    let n = crate::env(&mut buf).min(buf.len());
    for entry in buf[..n].split(|&b| b == 0) {
        let Some(rest) = entry.strip_prefix(key) else { continue };
        let Some((b'=', val)) = rest.split_first() else { continue };
        let k = val.len().min(out.len());
        out[..k].copy_from_slice(&val[..k]);
        return Some(k);
    }
    None
}

/// Значение переменной окружения как ДЕСЯТИЧНОЕ ЧИСЛО — индекс права (`STDIO=3`, `WM=5`,
/// `CAP_STORE=1`). `None` — переменной нет, она пуста или в ней не только цифры.
///
/// Отдельной функцией, а не разбором на месте, потому что мест было четыре: `cap_named`,
/// `stdio::probe`, `win::endpoint` и путь `CWD` — один и тот же цикл по цифрам, набранный
/// заново каждый раз.
pub fn env_num(key: &[u8]) -> Option<usize> {
    let mut val = [0u8; 24];
    let n = env_raw(key, &mut val)?;
    let digits = &val[..n];
    if digits.is_empty() || !digits.iter().all(|d| d.is_ascii_digit()) {
        return None;
    }
    Some(digits.iter().fold(0usize, |a, d| a * 10 + (d - b'0') as usize))
}
