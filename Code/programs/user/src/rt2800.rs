//! `rt2800` — РЕГИСТРЫ И ТАБЛИЦЫ карты Ralink RT5390 (Веха 208, ADR 0021).
//!
//! ## Почему отдельным модулем
//!
//! Драйвер беспроводной карты — это две очень разные вещи в одном файле: порядок действий
//! (его читают и правят) и сотни чисел, которые нельзя вывести ниоткуда (их сверяют). Смешанные,
//! они мешают друг другу: за таблицей в двести строк теряется логика, а в логике теряется
//! случайно испорченное число.
//!
//! ## Откуда числа
//!
//! Из `rt2x00` в ядре Linux 6.18.7 (`drivers/net/wireless/ralink/rt2x00`, GPL-2.0-or-later —
//! совместимо с нашей GPL-3). Даташита у Ralink нет и не будет, поэтому другого источника не
//! существует: значения регистров радиочасти — это результат чужой работы с железом, а не то,
//! что выводится из спецификации.
//!
//! Здесь они переписаны, а не включены как есть: у нас нет ни `rt2x00_dev`, ни его мьютексов,
//! ни ветвлений на полтора десятка чипов — только RT5390 и только то, что ему нужно.
//!
//! ## Три пространства регистров, и все три адресуются по-разному
//!
//! 1. **Обычные регистры MAC** — прямым обращением в окно памяти (`rd32`/`wr32`).
//! 2. **BBP** (baseband processor, цифровая обработка сигнала) — через регистр-посредника
//!    `BBP_CSR_CFG`: кладём номер и значение, ставим бит «занято», ждём, пока железо его снимет.
//! 3. **RFCSR** (собственно радио) — так же, но через `RF_CSR_CFG`.
//!
//! Посредники нужны потому, что BBP и радио физически сидят на отдельных шинах внутри карты, и
//! обращение к ним занимает время. Отсюда и главное правило работы с ними: **перед записью надо
//! дождаться, пока шина освободится**, иначе предыдущая операция потеряется молча.

#![allow(dead_code)] // таблицы пишутся целиком, а используются по мере готовности драйвера

use core::ptr::{read_volatile, write_volatile};
use void_user as sys;

/// Куда драйвер отобразил окно регистров карты. Ставится один раз при старте.
static mut BASE: usize = 0;

/// Сказать модулю, где лежит окно. Зовётся ровно один раз, до всего остального.
///
/// # Safety
/// Вызывающий обещает, что по адресу действительно отображено окно регистров карты.
pub unsafe fn attach(base: usize) {
    BASE = base;
}

pub fn rd32(off: usize) -> u32 {
    unsafe { read_volatile((BASE + off) as *const u32) }
}

pub fn wr32(off: usize, v: u32) {
    unsafe { write_volatile((BASE + off) as *mut u32, v) };
}

/// Ждать, пока биты `mask` в регистре примут значение `want`. `false` — не дождались.
///
/// Сном, а не пустым циклом: драйвер живёт обычным процессом, и крутить процессор, пока железо
/// думает свои микросекунды, значит отнимать его у всей системы (правило Вехи 168).
pub fn wait32(off: usize, mask: u32, want: u32, ms: usize) -> bool {
    for _ in 0..ms * 10 {
        if rd32(off) & mask == want {
            return true;
        }
        sys::sleep_ns(100_000);
    }
    false
}

