/// Веха 211.2 — настроить радио на канал ЦЕЛИКОМ. `false` — такого канала в таблице нет.
///
/// Первые два захода делали здесь только синтезатор: записать коэффициенты, подвести поправку,
/// включить блоки радио. Карта на это отвечала честно — коэффициенты читались обратно, «канал
/// настроен», — и не слышала ничего. Настройка канала в этой карте не кончается синтезатором:
///
/// - `TX_PIN_CFG` держит АНТЕННЫЙ ПЕРЕКЛЮЧАТЕЛЬ и питание малошумящего усилителя. После сброса
///   там ноль, то есть антенна физически отключена от приёмника. Сколько ни настраивай частоту,
///   слушать будет нечего — и именно так выглядел «настроенный» канал без единого кадра;
/// - `TX_BAND_CFG` говорит, какой диапазон слушаем, — без него карта не знает, что мы в 2,4 ГГц;
/// - генератор надо ПЕРЕКАЛИБРОВАТЬ под новую частоту (`VCOCAL_EN`). Калибровка при заливке
///   таблиц делалась для той частоты, которая стояла тогда, а не для нашей;
/// - `BBP` 62/63/64 — пороги чувствительности, они считаются от усиления усилителя (`lna_gain`
///   из EEPROM). При значениях по умолчанию приёмник глухой к слабому сигналу;
/// - регистры радио 55 и 59 — усиление приёмного тракта, своё на каждый канал.
///
/// Порядок и числа — из `rt2800_config_channel` и `rt2800_config_channel_rf53xx` (Linux 6.18.7),
/// ветка «канал ≤ 14, ширина 20 МГц, одна антенна, без Bluetooth».
pub fn set_channel(ch: u8, freq_offset: u8, lna_gain: u8) -> bool {
    let Some(&(_, rf1, rf2, rf3)) = CHANNELS_24.iter().find(|&&(c, ..)| c == ch) else {
        return false;
    };
    rfcsr_write(8, rf1);
    rfcsr_write(9, rf3);
    if let Some(v) = rfcsr_read(11) {
        // Поле R — младшие два бита.
        rfcsr_write(11, (v & !0x03) | (rf2 & 0x03));
    }
    // Мощность передачи: берём умеренную середину. Точные значения по каналам лежат в EFUSE, и
    // это работа для передачи, а не для приёма, — сейчас нам важно, чтобы тракт был включён.
    if let Some(v) = rfcsr_read(49) {
        rfcsr_write(49, (v & !0x3f) | 0x14);
    }
    // Включить блоки: само радио, синтезатор, приёмник и передатчик.
    if let Some(v) = rfcsr_read(1) {
        rfcsr_write(1, v | 0x0f);
    }
    // Поправка частоты из EFUSE: у каждой карты свой кварц, и без поправки мы окажемся рядом с
    // каналом, а не в нём.
    freq_cal(freq_offset);
    // Усиление приёмного тракта под этот канал.
    let idx = (ch - 1) as usize;
    rfcsr_write(55, R55_BY_CHANNEL[idx]);
    rfcsr_write(59, R59_BY_CHANNEL[idx]);
    // Ширина канала 20 МГц: биты «сдвоенный канал» на передачу и на приём — в ноль.
    if let Some(v) = rfcsr_read(30) {
        rfcsr_write(30, v & !0x06);
    }
    // Перекалибровать генератор под новую частоту. Бит самоочищается — читать его обратно
    // бессмысленно, как и у остальных калибровок.
    if let Some(v) = rfcsr_read(3) {
        rfcsr_write(3, v | 0x80);
    }
    // Пороги чувствительности: отсчитываются ВНИЗ от 0x37 на усиление усилителя.
    let thr = 0x37u8.wrapping_sub(lna_gain);
    bbp_write(62, thr);
    bbp_write(63, thr);
    bbp_write(64, thr);
    bbp_write(86, 0);
    // Диапазон: 2,4 ГГц (бит 2), не 5 ГГц (бит 1), не «сдвоенный вниз» (бит 0).
    wr32(TX_BAND_CFG, (rd32(TX_BAND_CFG) & !0x07) | 0x04);
    // И то, ради чего всё: подключить антенну к приёмнику.
    //
    // Бит 1 — усилитель мощности 2,4 ГГц (нужен передаче, но включается здесь же);
    // биты 8 и 9 — питание малошумящего усилителя первого тракта;
    // бит 16 — управление приёмо-передающим переключателем, бит 18 — сам переключатель.
    wr32(TX_PIN_CFG, 0x0005_0302);
    // Ширина полосы в цифровой части и отсутствие сдвига по частоте.
    if let Some(v) = bbp_read(4) {
        bbp_write(4, v & !0x18);
    }
    if let Some(v) = bbp_read(3) {
        bbp_write(3, v & !0x20);
    }
    sys::sleep_ns(1_500_000);
    // Сбросить счётчики занятости канала: они считают с прошлой жизни карты, и «занято» от
    // предыдущего сеанса помешает смотреть на них потом.
    rd32(CH_IDLE_STA);
    rd32(CH_BUSY_STA);
    rd32(CH_BUSY_STA_SEC);
    true
}

/// Веха 210.1 — подвести поправку частоты ПОСТЕПЕННО, по единице с задержкой.
///
/// Первый заход писал её одним числом, и это ошибка того же рода, что запись в занятую шину:
/// формально сделано, а на деле нет. Синтезатору нельзя менять поправку скачком — в Linux она
/// подводится по шагу с паузой в миллисекунду, и это не осторожность, а требование железа.
///
/// Предел — 95: больше кварц не тянет, и число сверх него означает испорченную EEPROM.
pub fn freq_cal(target: u8) {
    const BOUND: u8 = 95;
    let want = (target & 0x7f).min(BOUND);
    let Some(mut cur) = rfcsr_read(17) else { return };
    let mut now = cur & 0x7f;
    while now != want {
        now = if now < want { now + 1 } else { now - 1 };
        cur = (cur & !0x7f) | now;
        rfcsr_write(17, cur);
        sys::sleep_ns(1_200_000);
    }
}

/// Веха 210.1 — ПРОВЕРИТЬ, что канал дошёл до радио: коэффициенты синтезатора читаются такими
/// же, какими их записали, а приёмный тракт включён.
///
/// Передатчик в проверку НЕ входит, и это исправление ошибки: первый заход считал его битом
/// доказательства, а он для приёма не нужен вовсе и включается своим порядком. Судить по нему
/// значило объявить неудачей работающий приём.
pub fn channel_ok(ch: u8) -> bool {
    let Some(&(_, rf1, _, rf3)) = CHANNELS_24.iter().find(|&&(c, ..)| c == ch) else {
        return false;
    };
    let block = rfcsr_read(1).unwrap_or(0) & 0x07 == 0x07;
    // Веха 211.2 — и АНТЕННА подключена. Без этой проверки «канал настроен» говорилось о карте
    // с отключённым от приёмника антенным переключателем, и сказано это было дважды.
    const ANTENNA: u32 = 0x0005_0300;
    let antenna = rd32(TX_PIN_CFG) & ANTENNA == ANTENNA;
    rfcsr_read(8) == Some(rf1) && rfcsr_read(9) == Some(rf3) && block && antenna
}

/// Веха 210 — ВКЛЮЧИТЬ ПРИЁМ: пропускать всё, что слышно, кроме заведомо испорченного.
///
/// Фильтр устроен «от противного»: каждый бит ВЫКЛЮЧАЕТ свой вид кадров. Нам нужны чужие маяки,
/// то есть кадры не нам, — значит соответствующий бит гасим. Испорченные по контрольной сумме
/// роняем: читать в них нечего.
pub fn rx_enable() {
    wr32(RX_FILTER_CFG, DROP_CRC_ERR);
    // Веха 211.1 — включаем ОБА тракта, хотя нужен только приём. Так делает Linux, и это не
    // избыточность: MAC отвечает на принятые кадры подтверждениями, то есть приём без права
    // передать — половина механизма. Карта с одним включённым приёмом кадров не отдаёт.
    let v = rd32(MAC_SYS_CTRL);
    wr32(MAC_SYS_CTRL, v | MAC_RX_EN | MAC_TX_EN);
}

// ── кольцо приёма (Веха 211) ─────────────────────────────────────────────────────────────────
//
// Карта складывает принятые кадры в память хоста сама, по кольцу дескрипторов: в каждом лежит
// физический адрес буфера, а после заполнения железо ставит в нём признак «готово» и двигает
// свой индекс. Драйвер идёт следом и забирает готовые.

pub const RX_BASE_PTR: usize = 0x0290;
pub const RX_MAX_CNT: usize = 0x0294;
/// Где карта (индекс, который она заполнила) и где мы (докуда забрали).
pub const RX_CRX_IDX: usize = 0x0298;
pub const RX_DRX_IDX: usize = 0x029c;

/// Дескриптор — четыре слова: адрес буфера, длина с признаком «готово», второй адрес и флаги.
pub const RXD_WORDS: usize = 4;
/// Бит 31 второго слова — «железо дописало кадр». По нему и только по нему видно, что буфер наш.
pub const RXD_DMA_DONE: u32 = 1 << 31;
/// Длина принятого лежит в битах 16..29 того же слова.
pub const RXD_SDL0_SHIFT: u32 = 16;
pub const RXD_SDL0_MASK: u32 = 0x3fff;

/// Сколько кадров держим в кольце и сколько места даём каждому.
///
/// Восемь буферов по две килобайты: маяк — это сотни байт, и восьми хватает, чтобы не потерять
/// пачку, пришедшую разом; а две килобайты — с запасом на самый длинный кадр 802.11 без
/// агрегации.
pub const RX_RING: usize = 8;
pub const RX_BUF: usize = 2048;

/// Перед кадром карта кладёт СВОЙ заголовок (`RXWI`) — сведения о приёме: скорость, уровень
/// сигнала, длина. Он не часть эфира, его надо пропустить, чтобы добраться до самого кадра.
pub const RXWI_SIZE: usize = 16;

/// Веха 211.2 — объявить кольца ПЕРЕДАЧИ пустыми.
///
/// Передавать нам пока нечего, но движок DMA обходит все кольца, а не только те, которыми
/// пользуются. После сброса в регистрах колец лежит что угодно — адрес от прошлой жизни карты,
/// мусор прошивки, — и движок пойдёт по нему. Объявить кольцо нулевой длины дешевле, чем потом
/// разбираться, почему приём встал: длина ноль значит «сюда не ходи».
pub fn tx_rings_idle() {
    for i in 0..TX_RINGS {
        let base = TX_BASE_PTR0 + i * 0x10;
        wr32(base, 0); // адрес
        wr32(base + 4, 0); // сколько записей
        wr32(base + 8, 0); // где мы
        wr32(base + 12, 0); // где карта
    }
    // Не придерживать кадры ради пачки: мы опрашиваем кольцо сами, и задержка тут только вредит.
    wr32(DELAY_INT_CFG, 0);
}

/// Веха 211 — ЗАВЕСТИ кольцо приёма. `desc_pa` — физический адрес таблицы дескрипторов,
/// `buf_pa` — физический адрес области под буферы (они идут подряд).
///
/// Кольцо заполняется ДО включения DMA: карта, пущенная на кольцо, в котором нет адресов,
/// сложит первый же кадр по нулевому адресу — то есть в чужую память.
pub fn rx_ring_init(desc_va: usize, desc_pa: usize, buf_pa: usize) {
    for i in 0..RX_RING {
        let d = (desc_va + i * RXD_WORDS * 4) as *mut u32;
        unsafe {
            write_volatile(d, (buf_pa + i * RX_BUF) as u32);
            // Длину железо проставит само; нам важно СНЯТЬ признак готовности, иначе карта
            // решит, что буфер ещё не отдан ей, и обойдёт его стороной.
            write_volatile(d.add(1), 0);
            write_volatile(d.add(2), 0);
            write_volatile(d.add(3), 0);
        }
    }
    wr32(RX_BASE_PTR, desc_pa as u32);
    wr32(RX_MAX_CNT, RX_RING as u32);
    // Мы стоим на последнем: значит карте отданы все буферы, кроме него.
    wr32(RX_CRX_IDX, (RX_RING - 1) as u32);
    wr32(RX_DRX_IDX, 0);
}

/// Веха 211.1 — ИНИЦИАЛИЗАЦИЯ MAC: без неё приёмник включён, а кадров нет.
///
/// Первый заход её пропустил целиком — казалось, для приёма хватит радио, канала и кольца.
/// Карта на это ответила честно: кольцо завелось, а её индекс не сдвинулся ни на один кадр.
/// MAC — это не только «принимать/не принимать»: без таймингов, длин и правил ответа он не
/// считает кадр состоявшимся и не отдаёт его в DMA.
///
/// Значения взяты из `rt2800_init_registers` (Linux 6.18.7) — те, что для нашего чипа
/// фиксированы. Поля, которые там собираются из отдельных битов, развёрнуты в готовые числа:
/// читать «9 в биты 0..7, 32 в биты 8..15» в трёх строках хуже, чем одно число с объяснением.
pub fn init_mac() {
    // Скорости, на которые карта обязана уметь отвечать.
    wr32(LEGACY_BASIC_RATE, 0x0000_013f);
    wr32(HT_BASIC_RATE, 0x0000_8003);
    // Маяков мы не шлём: интервал оставляем, но генерацию, синхронизацию и тиканье — выключаем.
    wr32(BCN_TIME_CFG, 0x0000_0640);
    // Тайминги доступа к среде: слот 9 мкс, задержка обнаружения несущей 2.
    wr32(BKOFF_SLOT_CFG, 0x0000_0209);
    // Аналоговая часть передатчика — числа для RT5390.
    wr32(TX_SW_CFG0, 0x0000_0404);
    wr32(TX_SW_CFG1, 0x0008_0606);
    wr32(TX_SW_CFG2, 0x0000_0000);
    // Время жизни кадра, ожидание подтверждения, предел занятия среды.
    wr32(TX_TIMEOUT_CFG, 0x000a_2090);
    // Длины: максимальная единица данных, минимальные пороги.
    wr32(MAX_LEN_CFG, 0x0000_1fff);
    // Индикатор: постоянное свечение вместо мигания — у нас нет кода, который бы им управлял.
    wr32(LED_CFG, 0x7c31_3b32);
    // Пределы очередей буферного процессора.
    wr32(PBF_MAX_PCNT, 0x1f3f_bf9f);
    // Повторы передачи.
    wr32(TX_RTY_CFG, 0x4700_4002);
    // Автоответчик: карта сама шлёт подтверждения — иначе точка доступа сочтёт нас глухими.
    wr32(AUTO_RSP_CFG, 0x0000_0013);
    // Время ожидания подтверждения.
    wr32(EXP_ACK_TIME, 0x0024_00ca);
    // Межкадровые интервалы.
    wr32(XIFS_TIME_CFG, 0x3308_0a06);
    // Размеры очередей передачи в буферном процессоре.
    wr32(PBF_CFG, 0x00f4_0006);
}

/// Включить движок DMA на приём. Передачу не трогаем: она нам пока не нужна, а включённая
/// вхолостую очередь передачи — это ещё один источник неожиданностей.
pub fn wpdma_rx_on() {
    let v = rd32(WPDMA_GLO_CFG);
    // Бит 2 — приём, бит 5 — «класть отчёт о передаче туда, куда мы просили».
    wr32(WPDMA_GLO_CFG, (v & !0x0000_000f) | 0x0000_0024);
}

