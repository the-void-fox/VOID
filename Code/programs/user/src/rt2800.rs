/// Фильтр приёма: каждый бит ВЫКЛЮЧАЕТ свой вид кадров. Ноль значит «показывай всё».
/// Кадры не нам (бит 1) — их-то и надо видеть, пока мы ищем сети; испорченные (бит 0) роняем
/// всегда, читать в них нечего.
pub const DROP_CRC_ERR: u32 = 1 << 0;
pub const DROP_NOT_TO_ME: u32 = 1 << 1;

// ── доступ к BBP ─────────────────────────────────────────────────────────────────────────────

const BBP_CSR_CFG: usize = 0x101c;
const BBP_VALUE: u32 = 0x0000_00ff;
const BBP_REGNUM_SHIFT: u32 = 8;
const BBP_READ_CONTROL: u32 = 1 << 16;
const BBP_BUSY: u32 = 1 << 17;
const BBP_RW_MODE: u32 = 1 << 19;

/// Записать байт в регистр BBP. `false` — шина не освободилась (карта не отвечает).
pub fn bbp_write(reg: u8, value: u8) -> bool {
    if !wait32(BBP_CSR_CFG, BBP_BUSY, 0, 20) {
        return false;
    }
    wr32(
        BBP_CSR_CFG,
        value as u32 | (reg as u32) << BBP_REGNUM_SHIFT | BBP_BUSY | BBP_RW_MODE,
    );
    true
}

/// Прочитать байт из регистра BBP. `None` — шина не освободилась либо ответа не дождались.
///
/// Чтение — это тоже запись: в регистр-посредник кладётся номер и признак «читать», а результат
/// приезжает туда же, когда железо снимет бит занятости.
pub fn bbp_read(reg: u8) -> Option<u8> {
    if !wait32(BBP_CSR_CFG, BBP_BUSY, 0, 20) {
        return None;
    }
    wr32(
        BBP_CSR_CFG,
        (reg as u32) << BBP_REGNUM_SHIFT | BBP_BUSY | BBP_RW_MODE | BBP_READ_CONTROL,
    );
    if !wait32(BBP_CSR_CFG, BBP_BUSY, 0, 20) {
        return None;
    }
    Some((rd32(BBP_CSR_CFG) & BBP_VALUE) as u8)
}

// ── доступ к радио (RFCSR) ───────────────────────────────────────────────────────────────────

const RF_CSR_CFG: usize = 0x0500;
const RF_DATA: u32 = 0x0000_00ff;
const RF_REGNUM_SHIFT: u32 = 8;
const RF_WRITE: u32 = 1 << 16;
const RF_BUSY: u32 = 1 << 17;

pub fn rfcsr_write(reg: u8, value: u8) -> bool {
    if !wait32(RF_CSR_CFG, RF_BUSY, 0, 20) {
        return false;
    }
    wr32(
        RF_CSR_CFG,
        value as u32 | ((reg as u32) & 0x3f) << RF_REGNUM_SHIFT | RF_WRITE | RF_BUSY,
    );
    true
}

pub fn rfcsr_read(reg: u8) -> Option<u8> {
    if !wait32(RF_CSR_CFG, RF_BUSY, 0, 20) {
        return None;
    }
    wr32(RF_CSR_CFG, ((reg as u32) & 0x3f) << RF_REGNUM_SHIFT | RF_BUSY);
    if !wait32(RF_CSR_CFG, RF_BUSY, 0, 20) {
        return None;
    }
    Some((rd32(RF_CSR_CFG) & RF_DATA) as u8)
}

/// Веха 208.1 — РАЗБУДИТЬ MAC, чтобы к BBP вообще можно было обратиться.
///
/// Первый заход спрашивал версию BBP сразу после загрузки прошивки и получал ноль. Причина
/// видна в том же выводе, если на него посмотреть: `MAC_SYS_CTRL 0x7003` — стоят биты сброса
/// MAC и BBP. Карта после прошивки ОСТАЁТСЯ В СБРОСЕ, и цифровая часть в нём молчит по
/// определению; ноль был не поломкой, а честным ответом удерживаемого в ресете блока.
///
/// Порядок взят из `rt2800mmio_init_registers` и `rt2800_wait_bbp_ready` (Linux 6.18.7).
/// `false` — BBP так и не отозвался.
pub fn wake_mac() -> bool {
    // Сбросить индексы колец DMA: они могли остаться от прошлой жизни карты. Шесть младших
    // битов — очереди передачи, бит 16 — очередь приёма (нумерация не подряд, и это именно та
    // мелочь, из-за которой «сброс» делают наполовину).
    wr32(WPDMA_RST_IDX, 0x0001_003f);
    wr32(PBF_SYS_CTRL, 0x0000_0e1f);
    wr32(PBF_SYS_CTRL, 0x0000_0e00);
    // Разбудить PCIe-часть и подать питание на выводы.
    let aux = rd32(AUX_CTRL) | AUX_FORCE_PCIE_CLK | AUX_WAKE_PCIE_EN;
    wr32(AUX_CTRL, aux);
    wr32(PWR_PIN_CFG, 0x0000_0003);
    // Дёрнуть сброс MAC и BBP — и СНЯТЬ его. Второй записи и не хватало.
    wr32(MAC_SYS_CTRL, MAC_SRST | BBP_HRST);
    wr32(MAC_SYS_CTRL, 0);
    // Дождаться, пока шина к BBP освободится.
    if !wait32(MAC_STATUS_CFG, BBP_RF_BUSY, 0, 100) {
        return false;
    }
    // Прошивка включила BBP при старте, но его надо «переоткрыть»: обнулить оба почтовых ящика
    // и дать ему миллисекунду (так делает `rt2800_wait_bbp_ready`).
    wr32(H2M_BBP_AGENT, 0);
    wr32(H2M_MAILBOX_CSR, 0);
    sys::sleep_ns(1_000_000);
    // И только теперь спрашивать версию: ответ обязан быть не нулём и не «ffff».
    for _ in 0..1000 {
        match bbp_read(0) {
            Some(v) if v != 0 && v != 0xff => return true,
            _ => sys::sleep_ns(100_000),
        }
    }
    false
}

/// Веха 209 — ЗАЛИТЬ ТАБЛИЦЫ в цифровую часть и радио.
///
/// Возвращает, сколько записей ЛЕГЛО: после каждой таблицы несколько регистров читаются обратно
/// и сверяются. Это не паранойя — у BBP и радио свои шины, и запись, ушедшая в занятую шину,
/// теряется МОЛЧА: регистр останется прежним, а драйвер будет думать, что настроил карту.
///
/// Сверяем не всё подряд: часть регистров радио на чтение отдаёт не то, что в них писали (там
/// живут биты состояния), и «расхождение» на них означало бы ложную тревогу. Берём те, что
/// читаются как записаны.
pub fn load_tables(rev: u16) -> (usize, usize) {
    let mut bbp_ok = 0;
    for &(reg, val) in BBP_53XX {
        if bbp_write(reg, val) && bbp_read(reg) == Some(val) {
            bbp_ok += 1;
        }
    }
    // Ревизия R и новее: программный выбор антенны отключается, за него отвечает железо.
    if rev >= REV_5390R {
        for &(reg, val) in BBP_53XX_REV_R {
            if bbp_write(reg, val) && bbp_read(reg) == Some(val) {
                bbp_ok += 1;
            }
        }
    }
    let mut rf_ok = 0;
    for &(reg, val) in RFCSR_5390 {
        if rfcsr_write(reg, val) && rfcsr_read(reg) == Some(val) {
            rf_ok += 1;
        }
    }
    (bbp_ok, rf_ok)
}

/// Сколько записей в таблицах — чтобы вызывающий мог сказать «легло столько-то из стольких-то».
pub fn table_sizes(rev: u16) -> (usize, usize) {
    let bbp = BBP_53XX.len() + if rev >= REV_5390R { BBP_53XX_REV_R.len() } else { 0 };
    (bbp, RFCSR_5390.len())
}

