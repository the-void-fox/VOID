//! Цикл приложения: завод, события, сон и кадр (Веха 148.3).
//!
//! ## Почему цикл, а не виджеты
//!
//! Виджетов в тулките хватает — за четыре вехи ни разу не понадобилось «а такого нет». Трижды
//! скопирован был ЦИКЛ: поколение → тема → шрифт → поверхность, потом `Ui::new` → `input` →
//! `dirty` → `damage` → сброс клика, потом разбор `Motion`/`Button`/`Resize`/`Close`, потом сон.
//!
//! Верхние строки этого списка — просто скука. А вот нижние оказались доводом: **каждый клиент
//! решал одну и ту же задачу сам, и решил по-своему**. Слипание событий было ровно у одного
//! (вьювер корней, Веха 148.2), объём кадра — у двух из трёх и разными способами, сон при
//! движении — у двух и тоже разными. Библиотека здесь нужна не чтобы меньше печатать, а чтобы
//! правильное решение было единственным доступным.
//!
//! ## Почему это НЕ egui
//!
//! egui перерисовывает весь интерфейс каждый кадр — так можно, когда рядом GPU и свободное ядро.
//! Веха 148.2 выиграла ровно обратным: тем, что кадра НЕ БЫЛО. Возьми мы форму egui («зови
//! `update` каждый кадр, нужен ещё — попроси `request_repaint`»), объём кадра стал бы тем, что
//! фреймворк угадывает, а не тем, что программа знает.
//!
//! Поэтому цикл забирается, а **объём остаётся у программы**: [`Client::event`] возвращает
//! [`Scope`] — что именно изменилось от события. Забыть его нельзя, он на возврате.
//!
//! ## Кто чем владеет
//!
//! | цикл | программа |
//! |---|---|
//! | пачка событий и один кадр по её итогу | что нарисовать |
//! | указатель, клик, зажатая кнопка, «курсор ушёл» | что от них изменилось |
//! | `resize_buf`, `destroy`, конец жизни | своё состояние |
//! | клип по объёму, `dirty` → `damage`, сброс клика | объём |
//! | сон до события или до срока | когда её будить ([`Client::wake`]) |

use alloc::string::String;

use void_user as sys;
use void_user::win::{Event, Window};

use super::{Font, Rect, Theme, Ui};

/// Сколько изменилось — то есть сколько предстоит нарисовать и объявить композитору.
///
/// Складывается объединением за всю пачку событий: два события, задевших разные углы, дают один
/// кадр на оба угла, а не два кадра.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Scope {
    /// Ничего. Кадра не будет вовсе — и это самый частый правильный ответ на движение мыши.
    No,
    /// Изменился кусок поверхности. Клип режет и рисование, и damage.
    Part(Rect),
    /// Изменилось всё.
    All,
}

impl Scope {
    /// Объединить два объёма. `All` поглощает всё, `No` не добавляет ничего.
    pub fn union(self, o: Scope) -> Scope {
        match (self, o) {
            (Scope::All, _) | (_, Scope::All) => Scope::All,
            (Scope::No, x) | (x, Scope::No) => x,
            (Scope::Part(a), Scope::Part(b)) => Scope::Part(a.union(b)),
        }
    }

    pub fn is_none(self) -> bool {
        self == Scope::No
    }
}

/// Ввод, за которым следит цикл. Программе он приезжает готовым — разбирать `0xffff` и помнить,
/// зажата ли кнопка, ей больше не нужно.
#[derive(Clone, Copy, Default)]
pub struct Input {
    /// Где курсор. `None` — не над нами.
    pub ptr: Option<(i32, i32)>,
    /// Где нажали в этом кадре (живёт ровно один кадр).
    pub click: Option<(i32, i32)>,
    /// Где держат левую кнопку. Протяжка полосы прокрутки — это оно.
    pub held: Option<(i32, i32)>,
    /// Веха 167 — модификаторы на момент ПОСЛЕДНЕГО щелчка (`Ctrl`, `Shift`, …). Без них
    /// выделение мышью не построить: щелчок с `Ctrl` и без него — разные действия, а событию
    /// мыши модификаторы не принадлежат ни в железе, ни в ядре — их несёт композитор.
    pub mods: u8,
}

/// Программа с окном. Обязательны два метода; остальные нужны не всем.
pub trait Client {
    /// Событие пришло — что изменилось на экране? Возврат [`Scope::No`] означает «ничего», и
    /// кадра не будет: движение мыши внутри одной строки списка меняет ровно ноль пикселей, и
    /// кадр на него — чистый убыток (Веха 148.2).
    fn event(&mut self, e: Event, input: &Input) -> Scope;

    /// Нарисовать кадр. Возврат — что ЕЩЁ предстоит нарисовать: [`Scope::No`] в обычном случае,
    /// иначе цикл рисует снова тем же заходом.
    ///
    /// Второй проход не перестраховка: щелчок по строке меняет выбор, а подсветка и подробности
    /// считаются ДО того, как виджет ответит на клик. Без него выбранное менялось бы кадром
    /// позже собственного щелчка.
    fn draw(&mut self, u: &mut Ui) -> Scope;

    /// Перед кадром, пока поверхность цела: здесь ей можно поменять БУФЕР.
    ///
    /// Понадобилось панели: её меню растёт до экрана, то есть открытие меню — это `OP_REBUF`.
    /// Делать такое посреди кадра значило бы рисовать в область, которую уже отпустили, а после
    /// кадра — показать меню на кадр позже собственного клика.
    fn before(&mut self, surf: &mut Window) -> Scope {
        let _ = surf;
        Scope::No
    }

    /// После кадра: исполнить то, что кадр решил.
    ///
    /// Отдельно от рисования намеренно: переключение стола вызывает у композитора новое
    /// состояние, а значит и новое событие нам, — делать это посреди кадра значило бы рисовать
    /// по данным, которые уже устарели.
    fn after(&mut self, surf: &Window) -> Scope {
        let _ = surf;
        Scope::No
    }

    /// Веха 151 — **записывается СЕАНС: сохранись и назовись.** Ответ — командная строка, которой
    /// программу надо позвать обратно; `None` (по умолчанию) — «меня не восстанавливать».
    ///
    /// Умолчание именно «нет», а не «моё имя»: тулкит не знает, чем зовут программу, а угадать по
    /// заголовку окна — это выдумать команду, которой может не быть. Кто хочет возвращаться,
    /// называет себя сам, и заодно решает, что положить в store и как это назвать.
    ///
    /// Здесь же и дверь наружу: вернуть строку `thaw proc/x86_64/своё-имя` никто не запрещает —
    /// композитор запустит написанное, не вчитываясь ([[checkpoint]]).
    fn persist(&mut self) -> Option<String> {
        None
    }

    /// Через сколько миллисекунд разбудить, если событий не будет. `None` — спать до события.
    ///
    /// Опрос в цикле стоил бы системе простоя (Веха 139.3), а движение без своего срока шло бы
    /// рывками — поэтому срок называет программа: пока что-то едет, это кадр анимации; панели —
    /// остаток до следующей минуты.
    fn wake(&mut self) -> Option<u32> {
        None
    }

    /// Срок вышел, событий не было — что изменилось?
    fn tick(&mut self) -> Scope {
        Scope::No
    }

    /// Пора уходить. Цикл уберёт за собой поверхность сам.
    fn done(&self) -> bool {
        false
    }

    /// Веха 166 — **композитор ПРОСИТ закрыться** (`EV_CLOSE`). `true` — «ухожу сам»: цикл
    /// продолжается, и программа обязана довести себя до [`Client::done`].
    ///
    /// Умолчание — `false`, то есть поверхность убирается немедленно, как было. Это правильный
    /// ответ для окна с данными: у него на закрытии может не быть никакого движения, и лишний
    /// круг цикла ему не нужен.
    ///
    /// А вот строка запуска на этом попадалась. Она умеет уходить плавно (`Escape`, щелчок мимо),
    /// но `Super+D` при открытой строке — это `EV_CLOSE` от композитора, и цикл сносил поверхность
    /// ДО того, как программа об этом узнавала: один и тот же жест закрывался то плавно, то
    /// рывком, в зависимости от того, чем его сделали. Разницу видно, а объяснить её нечем —
    /// снаружи это один и тот же «закрой».
    fn close(&mut self) -> bool {
        false
    }
}

/// Сколько раз подряд [`Client::draw`] может попросить ещё кадр. Потолок, а не вежливость:
/// программа, просящая кадр всегда, повесила бы цикл насмерть, и найти это было бы нечем.
const MAX_PASSES: usize = 4;

/// Крутить программу, пока она не закончится. Поверхность создаёт вызывающий — окна и слои
/// рождаются слишком по-разному (Веха 144: у слоя другой СМЫСЛ, а не другая настройка).
pub fn run(surf: &mut Window, th: &Theme, font: &mut Font, c: &mut impl Client) {
    let mut input = Input::default();
    // Первый кадр — всегда целиком: до него в буфере нет ничего.
    let mut scope = Scope::All;

    loop {
        if !scope.is_none() {
            for pass in 0..MAX_PASSES {
                // Поверхность правим ДО кадра: буфер, в который сейчас польются пиксели, должен
                // быть тем самым, а не прошлым.
                scope = scope.union(c.before(surf));
                let (w, h) = (surf.width as i32, surf.height as i32);
                let more = {
                    let mut u = Ui::new(surf.pixels(), w, h, th, font);
                    if let Scope::Part(r) = scope {
                        u.clip(r);
                    }
                    u.input(input.ptr, input.click, input.held, input.mods);
                    let more = c.draw(&mut u);
                    let d = u.dirty();
                    if !d.is_empty() {
                        // `damage` у нас и есть commit: композитор берёт кадр из общего буфера.
                        surf.damage(d.x as u16, d.y as u16, d.w as u16, d.h as u16);
                    }
                    more
                };
                // Клик живёт один проход: иначе один щелчок сработал бы дважды.
                input.click = None;
                scope = more.union(c.after(surf));
                if scope.is_none() || pass + 1 == MAX_PASSES {
                    break;
                }
            }
            scope = Scope::No;
        }

        if c.done() {
            surf.destroy();
            return;
        }

        // Спим до события, а если программа назвала срок — до срока. Событие композитора будит
        // раньше, и это ровно то, чего мы ждём.
        let first = match c.wake() {
            Some(ms) => match surf.next_event_timeout(ms) {
                Some(e) => Some(e),
                // Срок вышел: спрашиваем программу и идём рисовать, не заходя в разбор событий.
                None => {
                    scope = scope.union(c.tick());
                    continue;
                }
            },
            None => surf.next_event(),
        };
        let Some(first) = first else { continue };

        // СГРЕБАЕМ всю пачку, накопившуюся, пока мы рисовали, и только потом рисуем один кадр.
        // Мышь шлёт движения десятками в секунду; отвечать на каждое отдельным кадром — это
        // гарантированно отставать от руки на всю пачку (Веха 148.2).
        let mut ev = Some(first);
        while let Some(e) = ev {
            match e {
                // Курсор УШЁЛ с поверхности — композитор говорит это координатами вне её
                // (Веха 144). Без такого сообщения подсветка под курсором залипала бы навсегда.
                Event::Motion { x, y } => {
                    input.ptr = (x != u16::MAX).then_some((x as i32, y as i32));
                    // Движение с зажатой кнопкой — это протяжка: точка едет за рукой.
                    if input.held.is_some() {
                        input.held = input.ptr;
                    }
                }
                Event::Button { x, y, down, buttons, mods } => {
                    let p = (x as i32, y as i32);
                    input.mods = mods;
                    if down {
                        input.click = Some(p);
                        if buttons & 1 != 0 {
                            input.held = Some(p);
                        }
                    } else {
                        input.held = None;
                    }
                }
                Event::Resize { w, h } => {
                    // Буфер меняем МЫ: программе остаётся узнать новый размер из того же
                    // события. Не вышло — размер не менялся, и говорить о нём нечего.
                    if (w, h) == (surf.width, surf.height) || !surf.resize_buf(w, h) {
                        ev = surf.poll_event();
                        continue;
                    }
                }
                Event::Close => {
                    // Спрашиваем программу: уйдёт сама — цикл живёт дальше, и она доигрывает
                    // своё движение. Не ответила «сам» — убираем поверхность, как было.
                    if !c.close() {
                        surf.destroy();
                        return;
                    }
                    scope = scope.union(Scope::All);
                    ev = surf.poll_event();
                    continue;
                }
                // Веха 151 — отвечаем СРАЗУ, не дожидаясь кадра: композитор ждёт ответов недолго,
                // а следующий кадр может не понадобиться вовсе. Сохраняться программе поэтому
                // надо прямо в [`Client::persist`] — событие она увидит уже после ответа.
                Event::Save => {
                    if let Some(run) = c.persist() {
                        surf.persist(&run);
                    }
                }
                _ => {}
            }
            scope = scope.union(c.event(e, &input));
            ev = surf.poll_event();
        }
    }
}

/// Завод: поколение, тема и шрифт — три строки, одинаковые у всех клиентов.
///
/// Отдельно от [`run`], потому что между заводом и циклом программа делает своё: читает store,
/// собирает список, создаёт поверхность нужного вида.
pub fn boot() -> (String, Theme, Font) {
    let generation = super::conf::generation().unwrap_or_default();
    let th = Theme::from_config(&generation);
    let font = Font::load(th.font.as_deref(), th.font_px);
    (generation, th, font)
}

/// Пожаловаться на себя в консоль ядра.
///
/// В графическом режиме она уезжает в serial — это единственный способ клиента сказать о себе,
/// когда экран рисует композитор, а не он. Было восемью копиями в восьми файлах, и копии успели
/// разойтись: половина добавляла перевод строки, половина нет.
pub fn say(s: &str) {
    sys::write_console(s.as_bytes());
}
