//! Движение в тулките (Веха 145) — «fusion»-анимации панели и выезд меню.
//!
//! ## Почему часы здесь, а не у композитора
//!
//! Двигать ОКНО может только композитор: он один знает, где окно на экране, и умеет возить его
//! пиксели, ничего не перерисовывая ([[animations]]). А здесь двигается СОДЕРЖИМОЕ поверхности —
//! капсула активного стола, подсветка под курсором, карточка меню. Композитор о них не знает
//! ничего и знать не должен: внутри чужого кадра лежат чужие виджеты.
//!
//! Значит часы у клиента. Цена названа честно: пока что-то движется, панель просыпается каждые
//! [`FRAME_MS`] — то есть её простой перестаёт быть нулевым НА ВРЕМЯ ДВИЖЕНИЯ. Движение конечно,
//! и по его окончании панель снова спит до минуты или до события.
//!
//! ## Срок — тот же, что у окон
//!
//! [`duration_from_config`] читает ту же строку `desktop anim <мс>`, по которой живёт композитор,
//! и кривая здесь та же ([`ease_out`], кубический ease-out). Заведи мы свой срок или свою
//! кривую — «плавно» у панели и «плавно» у окна разошлись бы по темпу, и это видно сразу: меню
//! выезжает не в такт окну, рядом с которым выезжает.
//!
//! ## Тулкит при этом остаётся БЕЗ СОСТОЯНИЯ
//!
//! [`Motion`] принадлежит КЛИЕНТУ, а виджету анимированное значение приезжает обычным числом
//! (`hot`, `on`, прозрачность). Это не педантизм: панель рисует по damage и обязана знать, что
//! изменилось, ДО того как коснётся холста. Спрячь мы движение внутрь виджета — подпись острова
//! считалась бы по одним числам, а рисовался бы он по другим, и панель либо мигала бы каждый
//! кадр, либо замирала посреди движения.

use alloc::vec::Vec;

/// Сколько длится движение по умолчанию — ровно столько же, сколько переезд окна (`ANIM_MS` в
/// `bin/wm.rs`).
pub const ANIM_MS: u64 = 360;
/// Потолок: анимация длиннее секунды — это уже не «плавно», а «система задумалась».
pub const ANIM_MAX: u64 = 1000;
/// Шаг кадров, пока что-то движется: 16 мс ≈ 60 кадров в секунду, то есть частота экрана.
/// Чаще рисовать некуда — vsync'а нет, и лишние кадры затираются, не доехав до глаза
/// ([[cpu-budget]]).
pub const FRAME_MS: u32 = 16;

/// Ease-out кубический: `1 − (1−t)³`, всё в 1/1024. Копия формулы композитора — по той же
/// причине, что и `rrect_sd` в [`super::paint`]: две кривые дали бы две разные системы.
pub fn ease_out(t: i32) -> i32 {
    let inv = (1024 - t.clamp(0, 1024)) as i64;
    (1024 - (inv * inv * inv) / (1024 * 1024)) as i32
}

/// Доля пути между `a` и `b` (`p` — 0..1024).
pub fn lerp(a: i32, b: i32, p: i32) -> i32 {
    a + ((b - a) as i64 * p as i64 / 1024) as i32
}

/// Срок анимаций из конфига поколения: строка `desktop anim <мс>`.
///
/// Читается ТА ЖЕ строка, что у композитора, а не своя `ui("anim", …)`: скорость движения — одно
/// свойство системы, и два числа на него разъехались бы (см. заголовок модуля).
pub fn duration_from_config(text: &str) -> u64 {
    for line in text.lines() {
        let Some(rest) = line.trim().strip_prefix("desktop ") else { continue };
        let Some(v) = rest.trim().strip_prefix("anim") else { continue };
        if let Ok(n) = v.trim().parse::<u64>() {
            return n.min(ANIM_MAX);
        }
    }
    ANIM_MS
}

/// Одно движущееся число.
struct Slot {
    id: u32,
    from: i32,
    to: i32,
    /// Когда движение началось; `0` — стоим на месте (значение равно `to`).
    at: u64,
}

/// Таблица движущихся чисел клиента: «где сейчас капсула», «насколько проявилась подсветка».
///
/// Ключ — номер, который назначает сам клиент. Не адрес вызова и не строка: у панели анимируемых
/// величин десяток, они перечислены константами в одном месте, и это честнее любой магии с
/// автоматическими идентификаторами (на которой immediate-mode тулкиты и спотыкаются, когда
/// список виджетов меняет длину).
pub struct Motion {
    dur: u64,
    now: u64,
    slots: Vec<Slot>,
    moving: bool,
}

impl Motion {
    /// `ms == 0` — движения нет вовсе: значения ставятся сразу. Это законная настройка
    /// (`desktop anim 0`), а не вырожденный случай, и она обязана работать без единой ветки у
    /// вызывающего.
    pub fn new(ms: u64) -> Motion {
        Motion { dur: ms * 1_000_000, now: 0, slots: Vec::new(), moving: false }
    }

    /// Начать кадр: запомнить время и забыть, двигалось ли что-то в прошлом.
    pub fn begin(&mut self, now_ns: u64) {
        self.now = now_ns;
        self.moving = false;
    }

    /// Двигалось ли что-нибудь на этом кадре. Клиент по этому числу решает, когда просыпаться.
    pub fn moving(&self) -> bool {
        self.moving
    }

    /// Поставить значение НА МЕСТО, без движения: первый кадр не должен выглядеть как влёт
    /// панели с левого края.
    pub fn set(&mut self, id: u32, v: i32) {
        let i = self.slot(id, v);
        self.slots[i] = Slot { id, from: v, to: v, at: 0 };
    }

    /// Текущее значение, не трогая цель. Нужно тому, у кого движение двухтактное (заголовок
    /// гаснет, меняется и загорается снова): он обязан узнать «уже погас» ДО того, как назначит
    /// новую цель.
    pub fn peek(&self, id: u32) -> i32 {
        match self.slots.iter().position(|s| s.id == id) {
            Some(i) => self.value(i),
            None => 0,
        }
    }

    /// Двигать `id` к `target` и отдать значение ЭТОГО кадра.
    pub fn val(&mut self, id: u32, target: i32) -> i32 {
        let i = self.slot(id, target);
        if self.slots[i].to != target {
            let cur = self.value(i);
            self.slots[i] = Slot { id, from: cur, to: target, at: self.now.max(1) };
        }
        if self.dur == 0 {
            self.slots[i].at = 0;
            return self.slots[i].to;
        }
        let v = self.value(i);
        if self.slots[i].at != 0 {
            if v == self.slots[i].to && self.elapsed(i) >= 1024 {
                self.slots[i].at = 0;
            } else {
                self.moving = true;
            }
        }
        v
    }

    /// Найти слот или завести его на месте `v`.
    fn slot(&mut self, id: u32, v: i32) -> usize {
        match self.slots.iter().position(|s| s.id == id) {
            Some(i) => i,
            None => {
                self.slots.push(Slot { id, from: v, to: v, at: 0 });
                self.slots.len() - 1
            }
        }
    }

    fn elapsed(&self, i: usize) -> i32 {
        let s = &self.slots[i];
        if self.dur == 0 || s.at == 0 {
            return 1024;
        }
        ((self.now.saturating_sub(s.at)) * 1024 / self.dur).min(1024) as i32
    }

    fn value(&self, i: usize) -> i32 {
        let s = &self.slots[i];
        let t = self.elapsed(i);
        if t >= 1024 {
            s.to
        } else {
            lerp(s.from, s.to, ease_out(t))
        }
    }
}
