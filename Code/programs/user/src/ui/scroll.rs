//! Прокрутка списка: где мы в нём и как это меняется (Веха 202.10).
//!
//! ## Зачем отдельно
//!
//! Потому что это писалось уже трижды: в фильтрованном списке ([`super::list::List`]), во
//! вьювере корней и в панели уведомлений. Каждый раз — одни и те же четыре строки: ступенька
//! колеса, потолок «дальше конца не уехать», пол «выше начала не подняться», сброс при смене
//! содержимого. И каждый раз со своей ступенькой: в списке три записи, в панели была одна, и
//! владелец сразу сказал, что панель листается «крайне медленно». Разошлись они молча — как и
//! всё, что написано дважды.
//!
//! ## Единица — ЗАПИСЬ, а не пиксель
//!
//! Прокрутка на полстроки не значит ничего: человек листает список, а не холст. От этого
//! проще всё остальное — потолок считается вычитанием, а рисующему достаточно `skip(off)`.
//! Плавная прокрутка пикселями понадобится тексту, и тогда это будет другой тип: у него другая
//! арифметика и другое поведение на краях.
//!
//! ## Рисует полосу не этот файл
//!
//! Полоса прокрутки — [`super::Ui::scrollbar`], и она без памяти: ей на вход точка, на выход
//! число. Здесь — само число и правила, по которым оно меняется.

/// Где мы в списке: сколько записей пропущено сверху.
#[derive(Default, Clone, Copy)]
pub struct Scroll {
    pub off: usize,
}

impl Scroll {
    /// Ступенька колеса — три записи.
    ///
    /// Не одна: щелчок колеса на одну строку заставляет крутить его столько раз, сколько в
    /// списке записей, и это первое, что замечает человек. Не экран: тогда теряется место, где
    /// смотрел, — список прыгает, а не едет.
    pub const STEP: usize = 3;

    /// Колесо. `true` — список правда сдвинулся; упёрлись в край — кадра это не стоит.
    ///
    /// Знак как у события: положительное — от себя (вверх, к свежим), отрицательное — на себя.
    pub fn wheel(&mut self, delta: i8, total: usize, visible: usize) -> bool {
        let was = self.off;
        self.off = if delta > 0 {
            self.off.saturating_sub(Self::STEP)
        } else {
            (self.off + Self::STEP).min(total.saturating_sub(visible))
        };
        self.off != was
    }

    /// Поставить начало списка (полоса прокрутки отвечает числом, а не сдвигом).
    pub fn set(&mut self, off: usize, total: usize, visible: usize) -> bool {
        let off = off.min(total.saturating_sub(visible));
        let moved = off != self.off;
        self.off = off;
        moved
    }

    /// Содержимое сменилось — проверить, что смещение ещё указывает внутрь списка.
    ///
    /// Звать обязательно там, где список мог укоротиться: смещение за его концом даёт пустое
    /// тело при непустом списке, и выглядит это как пропажа записей.
    pub fn clamp(&mut self, total: usize, visible: usize) {
        self.off = self.off.min(total.saturating_sub(visible));
    }

    /// К началу — когда список сменился целиком и старое место в нём ничего не значит.
    pub fn reset(&mut self) {
        self.off = 0;
    }
}
