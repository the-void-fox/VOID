//! Прокрутка: где мы в содержимом, которое не помещается (Вехи 202.10, 202.11).
//!
//! ## Зачем отдельно
//!
//! Потому что это писалось уже трижды: в фильтрованном списке ([`super::list::List`]), во
//! вьювере корней и в панели уведомлений. Каждый раз — одни и те же правила: ступенька колеса,
//! потолок «дальше конца не уехать», пол «выше начала не подняться», сброс при смене
//! содержимого. И каждый раз со своей ступенькой: в списке три записи, в панели была одна, и
//! владелец сразу сказал, что панель листается «крайне медленно». Разошлись они молча — как и
//! всё, что написано дважды.
//!
//! ## Смещение в ПИКСЕЛЯХ, а не в записях
//!
//! Первая версия считала записями: «показать следующее» вместо «сдвинуть на столько-то точек».
//! Владелец попросил иначе — чтобы следующее уведомление могло быть видно наполовину, и он
//! прав. Прокрутка по записям означает, что содержимое прыгает ступенями в высоту строки: при
//! мелких строках это незаметно, а при карточках в три пальца — именно прыжок. Ещё она врёт
//! про край: последняя запись либо видна целиком, либо не видна вовсе, хотя места под неё
//! ровно половина.
//!
//! Ступенька колеса при этом по-прежнему считается СТРОКАМИ ([`Scroll::STEP_ROWS`]) — человек
//! крутит колесо, чтобы увидеть следующие записи, а не следующие сто точек.
//!
//! ## Рисует полосу не этот файл
//!
//! Полоса прокрутки — [`super::Ui::scrollbar`], и она без памяти: ей на вход точка, на выход
//! число. Единицы ей безразличны, лишь бы совпадали: с пиксельной прокруткой в неё уезжают
//! высота содержимого и высота окна, а не число записей.

/// Где мы в содержимом: сколько ТОЧЕК прокручено сверху.
#[derive(Default, Clone, Copy)]
pub struct Scroll {
    pub px: i32,
}

impl Scroll {
    /// Ступенька колеса — три строки.
    ///
    /// Не одна: щелчок колеса на строку заставляет крутить его столько раз, сколько в списке
    /// записей, и это первое, что замечает человек. Не экран: тогда теряется место, где
    /// смотрел, — содержимое прыгает, а не едет.
    pub const STEP_ROWS: i32 = 3;

    /// Колесо. `row_h` — высота одной записи вместе с зазором, `content` и `view` — полная и
    /// видимая высота. `true` — правда сдвинулись; упёрлись в край — кадра это не стоит.
    ///
    /// Знак как у события: положительное — от себя (вверх, к началу), отрицательное — на себя.
    pub fn wheel(&mut self, delta: i8, row_h: i32, content: i32, view: i32) -> bool {
        let step = row_h.max(1) * Self::STEP_ROWS;
        self.set(if delta > 0 { self.px - step } else { self.px + step }, content, view)
    }

    /// Поставить смещение (полоса прокрутки отвечает числом, а не сдвигом). `true` — изменилось.
    pub fn set(&mut self, px: i32, content: i32, view: i32) -> bool {
        let px = px.clamp(0, (content - view).max(0));
        let moved = px != self.px;
        self.px = px;
        moved
    }

    /// Содержимое сменилось — проверить, что смещение ещё указывает внутрь.
    ///
    /// Звать обязательно там, где содержимое могло укоротиться: смещение за его концом даёт
    /// пустоту при непустом списке, и выглядит это как пропажа записей.
    pub fn clamp(&mut self, content: i32, view: i32) {
        self.px = self.px.clamp(0, (content - view).max(0));
    }

    /// К началу — когда содержимое сменилось целиком и старое место в нём ничего не значит.
    pub fn reset(&mut self) {
        self.px = 0;
    }

    /// Сколько ЦЕЛЫХ записей ушло вверх — для подписи «выше N».
    pub fn rows_above(&self, row_h: i32) -> usize {
        // С ОКРУГЛЕНИЕМ ВВЕРХ: уехавшая наполовину запись уже не читается целиком, и не
        // посчитать её значит сказать человеку «выше ничего нет», когда там половина карточки.
        let row = row_h.max(1);
        ((self.px + row - 1) / row).max(0) as usize
    }
}
