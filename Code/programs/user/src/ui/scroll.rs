//! Прокрутка: где мы в содержимом, которое не помещается (Вехи 202.10, 202.11).
//!
//! ## Зачем отдельно
//!
//! Потому что это писалось уже трижды: в фильтрованном списке ([`super::list::List`]), во
//! вьювере корней и в панели уведомлений. Каждый раз — одни и те же правила: ступенька колеса,
//! потолок «дальше конца не уехать», пол «выше начала не подняться», сброс при смене
//! содержимого. И каждый раз со своей ступенькой: в списке три записи, в панели была одна, и
//! владелец сразу сказал, что панель листается «крайне медленно». Разошлись они молча — как и
//! всё, что написано дважды.
//!
//! ## Смещение в ПИКСЕЛЯХ, а не в записях
//!
//! Первая версия считала записями: «показать следующее» вместо «сдвинуть на столько-то точек».
//! Владелец попросил иначе — чтобы следующее уведомление могло быть видно наполовину, и он
//! прав. Прокрутка по записям означает, что содержимое прыгает ступенями в высоту строки: при
//! мелких строках это незаметно, а при карточках в три пальца — именно прыжок. Ещё она врёт
//! про край: последняя запись либо видна целиком, либо не видна вовсе, хотя места под неё
//! ровно половина.
//!
//! Ступенька колеса при этом по-прежнему считается СТРОКАМИ ([`Scroll::STEP_ROWS`]) — человек
//! крутит колесо, чтобы увидеть следующие записи, а не следующие сто точек.
//!
//! ## Рисует полосу не этот файл
//!
//! Полоса прокрутки — [`super::Ui::scrollbar`], и она без памяти: ей на вход точка, на выход
//! число. Единицы ей безразличны, лишь бы совпадали: с пиксельной прокруткой в неё уезжают
//! высота содержимого и высота окна, а не число записей.

/// Веха 204.2 — ПОПАЛИ ЛИ В ПОЛОСУ прокрутки (её прямоугольник — `track`).
///
/// Ловим ШИРЕ самой полосы по горизонтали: она тонкая, и попадать в неё точно — работа, которой
/// человек заниматься не обязан. По вертикали запаса нет: там начинается список.
///
/// Живёт здесь, а не у каждого клиента, потому что решение «схватили полосу» теперь означает
/// больше, чем раньше: схваченная полоса ведётся, пока держат кнопку, ГДЕ БЫ ни был курсор
/// (см. [`super::Ui::scrollbar_from`]). Разойдись это правило по трём программам — в одной из
/// них список поехал бы от нажатия где угодно.
pub fn on_track(track: super::Rect, p: (i32, i32)) -> bool {
    let slack = track.w * 2;
    p.0 >= track.x - slack && p.0 < track.right() + slack && p.1 >= track.y && p.1 < track.bottom()
}

/// Где мы в содержимом: сколько ТОЧЕК прокручено сверху.
#[derive(Default, Clone, Copy)]
pub struct Scroll {
    pub px: i32,
}

impl Scroll {
    /// Ступенька колеса — три строки.
    ///
    /// Не одна: щелчок колеса на строку заставляет крутить его столько раз, сколько в списке
    /// записей, и это первое, что замечает человек. Не экран: тогда теряется место, где
    /// смотрел, — содержимое прыгает, а не едет.
    pub const STEP_ROWS: i32 = 3;

    /// Колесо. `row_h` — высота одной записи вместе с зазором, `content` и `view` — полная и
    /// видимая высота. `true` — правда сдвинулись; упёрлись в край — кадра это не стоит.
    ///
    /// Знак как у события: положительное — от себя (вверх, к началу), отрицательное — на себя.
    pub fn wheel(&mut self, delta: i8, row_h: i32, content: i32, view: i32) -> bool {
        let step = row_h.max(1) * Self::STEP_ROWS;
        self.set(if delta > 0 { self.px - step } else { self.px + step }, content, view)
    }

    /// Поставить смещение (полоса прокрутки отвечает числом, а не сдвигом). `true` — изменилось.
    pub fn set(&mut self, px: i32, content: i32, view: i32) -> bool {
        let px = px.clamp(0, (content - view).max(0));
        let moved = px != self.px;
        self.px = px;
        moved
    }

    /// Содержимое сменилось — проверить, что смещение ещё указывает внутрь.
    ///
    /// Звать обязательно там, где содержимое могло укоротиться: смещение за его концом даёт
    /// пустоту при непустом списке, и выглядит это как пропажа записей.
    pub fn clamp(&mut self, content: i32, view: i32) {
        self.px = self.px.clamp(0, (content - view).max(0));
    }

    /// К началу — когда содержимое сменилось целиком и старое место в нём ничего не значит.
    pub fn reset(&mut self) {
        self.px = 0;
    }

    /// Веха 202.17 — ГДЕ БЕГУНОК на полосе высотой `track`: (верх, высота).
    ///
    /// Считается здесь, а не в рисующем виджете, потому что нужен обоим: виджет его рисует, а
    /// обработчик события решает по нему, схватили бегунок или ткнули мимо. Пока формула жила
    /// только внутри рисования, смещение и могло меняться ТОЛЬКО во время кадра — а кадр
    /// рисуется по состоянию, посчитанному до него, и список отставал от бегунка.
    pub fn knob(track: i32, view: i32, content: i32, off: i32, min_h: i32) -> (i32, i32) {
        if content <= view || track <= 0 {
            return (0, track);
        }
        let h = (track * view / content).max(min_h).min(track);
        let span = (track - h).max(0);
        let last = (content - view).max(1);
        (span * off.clamp(0, last) / last, h)
    }

    /// Смещение, отвечающее протяжке бегунка на `dy` точек от места захвата.
    pub fn drag(track: i32, view: i32, content: i32, off0: i32, dy: i32, min_h: i32) -> i32 {
        let (_, h) = Self::knob(track, view, content, off0, min_h);
        let span = (track - h).max(1);
        let last = (content - view).max(0);
        (off0 as i64 + dy as i64 * last as i64 / span as i64).clamp(0, last as i64) as i32
    }

    /// Смещение, при котором центр бегунка встаёт в точку `y` полосы (щелчок мимо бегунка).
    pub fn jump(track: i32, view: i32, content: i32, y: i32, min_h: i32) -> i32 {
        let (_, h) = Self::knob(track, view, content, 0, min_h);
        let span = (track - h).max(1);
        let last = (content - view).max(0);
        ((y - h / 2).clamp(0, span) as i64 * last as i64 / span as i64) as i32
    }

    /// Сколько ЦЕЛЫХ записей ушло вверх — для подписи «выше N».
    pub fn rows_above(&self, row_h: i32) -> usize {
        // С ОКРУГЛЕНИЕМ ВВЕРХ: уехавшая наполовину запись уже не читается целиком, и не
        // посчитать её значит сказать человеку «выше ничего нет», когда там половина карточки.
        let row = row_h.max(1);
        ((self.px + row - 1) / row).max(0) as usize
    }
}

/// Веха 223.4 — ЗАХВАТ БЕГУНКА: щелчок мимо него — прыжок, попадание — протяжка от якоря.
///
/// ## Зачем отдельно от всего остального
///
/// Потому что это было написано ЧЕТЫРЕЖДЫ и слово в слово: в панели уведомлений, во вьювере
/// корней, в диспетчере задач и в окне руководства. Каждый раз одно и то же — поле
/// `drag: Option<((i32, i32), usize)>`, вызов [`on_track`] в обработчике кнопки, `Scroll::knob`
/// ради вопроса «попали ли в сам бегунок», `Scroll::jump` мимо него и `Scroll::drag` по нему.
///
/// И три копии из четырёх разошлись с четвёртой одинаково: смещение они считали ВО ВРЕМЯ КАДРА,
/// возвратом [`super::Ui::scrollbar_from`]. Кадр рисуется по состоянию, посчитанному ДО него, —
/// и список доезжал до бегунка на кадр-два позже руки. В панели это починили ещё Вехой 202.17,
/// но починка осталась там же, где была написана, потому что делиться ей было нечем.
///
/// Те же три копии ловили попадание по НЕ ТОМУ прямоугольнику: рисовалась полоса с полями
/// внутрь (`inset_xy`), а `on_track` спрашивали у полосы без полей. Здесь прямоугольник один —
/// тот, которым полосу рисуют ([`Grab::measure`]).
///
/// ## Единицы ему безразличны
///
/// На вход «сколько сверху / сколько видно / сколько всего», на выход — новое «сколько сверху».
/// Точки это или строки, он не знает и знать не должен: у [`Pane`] точки, у
/// [`List`](super::List) строки, у панели уведомлений точки при рядах разной высоты.
#[derive(Default)]
pub struct Grab {
    /// Полоса — ТОТ ЖЕ прямоугольник, которым она рисуется.
    track: super::Rect,
    /// Якорь протяжки: вертикаль захвата и смещение на её начало.
    anchor: Option<(i32, i32)>,
}

impl Grab {
    /// Сказать, где полоса нарисована. Зовётся КАДРОМ (раскладку знает только он).
    pub fn measure(&mut self, track: super::Rect) {
        self.track = track;
    }

    /// Где полоса — чтобы её нарисовать.
    pub fn track(&self) -> super::Rect {
        self.track
    }

    /// Ведут ли её сейчас. Схваченная полоса принадлежит руке, пока кнопку держат, — где при
    /// этом курсор, значения не имеет (Веха 204.2).
    pub fn active(&self) -> bool {
        self.anchor.is_some()
    }

    /// Кнопку отпустили — протяжка кончилась.
    pub fn release(&mut self) {
        self.anchor = None;
    }

    /// Нажали левую кнопку. `Some(смещение)` — нажатие НАШЕ, и вот куда встать.
    ///
    /// Ткнули мимо бегунка — прыжок туда, куда показали. Попали в бегунок — смещение не меняется
    /// вовсе, запоминается только якорь: дальше ведём ОТНОСИТЕЛЬНО, и точка под пальцем остаётся
    /// под ним (Веха 202.14). Без якоря бегунок на длинном списке большой, и первые полбегунка
    /// движения руки не меняли ничего — владелец назвал это телепортацией.
    pub fn press(&mut self, p: (i32, i32), off: i32, view: i32, total: i32) -> Option<i32> {
        self.anchor = None;
        if self.track.is_empty() || total <= view || !on_track(self.track, p) {
            return None;
        }
        let min_h = self.track.w * 2;
        let (ky, kh) = Scroll::knob(self.track.h, view, total, off, min_h);
        let local = p.1 - self.track.y;
        let off = if local < ky || local >= ky + kh {
            Scroll::jump(self.track.h, view, total, local, min_h)
        } else {
            off
        };
        self.anchor = Some((p.1, off));
        Some(off)
    }

    /// Движение мыши. `Some(смещение)`, пока полоса схвачена.
    pub fn motion(&self, p: (i32, i32), view: i32, total: i32) -> Option<i32> {
        let (y0, off0) = self.anchor?;
        if self.track.is_empty() {
            return None;
        }
        Some(Scroll::drag(self.track.h, view, total, off0, p.1 - y0, self.track.w * 2))
    }
}

/// Веха 223.3 — ПРОКРУЧИВАЕМОЕ ПОЛОТНО: окно, ряды равной высоты и смещение — в одном месте.
///
/// ## Чем оно отличается от [`Scroll`]
///
/// [`Scroll`] знает одно число — сколько точек ушло вверх. Всё остальное каждый потребитель
/// считал сам: какая запись первая, сколько их влезает, на сколько поднять верх, чтобы крайняя
/// нарисовалась половиной, попали ли в полосу, куда прыгнуть от щелчка мимо бегунка и откуда
/// вести протяжку. Это ровно тот счёт, который уже написан в [`List`](super::List) и в панели
/// уведомлений, — и окно руководства стало ему третьей копией.
///
/// ## В третьей копии он разошёлся — и это видно глазами
///
/// В окне руководства рисование считало шаг строки ТЕКСТА (`line_h + px(4)`), а обработчик
/// колеса брал высоту строки ЛЕВОГО ПЕРЕЧНЯ (`line_h + px(10)`) — просто потому, что она лежала
/// под рукой в готовой раскладке. Высота содержимого выходила на четверть больше настоящей: ход
/// прокрутки оказывался длиннее текста, текст кончался до конца хода, а при возврате вверх ту же
/// пустоту приходилось отматывать назад. Владелец описал это точно: «пропадает слишком рано и
/// возвращается слишком поздно».
///
/// Разойтись две меры могли только потому, что приходили в прокрутку ИЗВНЕ и по отдельности — в
/// рисование одна, в колесо другая. Здесь мера приходит ОДИН раз ([`Pane::measure`]), а
/// [`Pane::wheel`] не принимает мер вовсе: ему нечего получить неправильно.
///
/// ## Условие на содержимое: запись = строка экрана
///
/// Полотно считает высоту содержимого как «записей на шаг», и потому запись, которая рисуется на
/// той же высоте, что предыдущая, лжёт о содержимом. Это не придирка: в том же окне ряд таблицы
/// хранился ЗАПИСЬЮ НА ЯЧЕЙКУ, а рисовался одной строкой, и содержимое выходило короче хода —
/// вторая причина того же симптома. Кому нужны ряды разной высоты (карточки уведомлений), тому
/// нужен [`Scroll`] напрямую.
///
/// ## Смещение считается СОБЫТИЕМ, а не кадром
///
/// Полоса [`super::Ui::scrollbar_from`] умеет отвечать новым смещением прямо во время рисования,
/// и это выглядит удобно, но кадр рисуется по состоянию, посчитанному ДО него: смещение,
/// менявшееся внутри кадра, доезжало до содержимого на кадр-два позже бегунка — бегунок ехал за
/// рукой, содержимое рывками следом (Веха 202.17). Поэтому здесь [`Pane::press`] и
/// [`Pane::motion`] живут в обработчике события, а [`Pane::bar`] только РИСУЕТ.
#[derive(Default)]
pub struct Pane {
    /// Сколько точек содержимого ушло вверх.
    off: Scroll,
    /// Куда рисуется содержимое (полоса сюда не входит).
    area: super::Rect,
    /// Полоса и её захват — общие с перечнем и панелью уведомлений ([`Grab`]).
    grab: Grab,
    row_h: i32,
    rows: usize,
}

impl Pane {
    /// Сказать полотну, где оно и из чего состоит. Зовётся КАДРОМ, до рисования рядов.
    ///
    /// `bar` — прямоугольник полосы ровно такой, каким она будет нарисована: по нему же считается
    /// и попадание, и геометрия бегунка. Два разных прямоугольника (один рисовать, другой
    /// попадать) — это опять вторая мера, то есть та самая ошибка, от которой здесь уходим.
    pub fn measure(&mut self, area: super::Rect, bar: super::Rect, row_h: i32, rows: usize) {
        self.area = area;
        self.grab.measure(bar);
        self.row_h = row_h.max(1);
        self.rows = rows;
        // Содержимое могло укоротиться (другой раздел) или окно подрасти: смещение за его концом
        // даёт пустоту при непустом содержимом, и выглядит это как пропажа текста.
        let (content, view) = (self.content(), self.view());
        self.off.clamp(content, view);
    }

    /// Высота всего содержимого в точках.
    pub fn content(&self) -> i32 {
        self.rows as i32 * self.row_h
    }

    /// Высота видимой части в точках.
    pub fn view(&self) -> i32 {
        self.area.h.max(0)
    }

    /// Куда рисуется содержимое — этим его и режут.
    pub fn area(&self) -> super::Rect {
        self.area
    }

    /// Сколько точек ушло вверх.
    pub fn px(&self) -> i32 {
        self.off.px
    }

    /// Есть ли что прокручивать.
    pub fn overflows(&self) -> bool {
        self.content() > self.view()
    }

    /// К началу — содержимое сменилось целиком, и старое место в нём ничего не значит.
    pub fn reset(&mut self) {
        self.off.reset();
    }

    /// Колесо. Мер не принимает НАМЕРЕННО — см. описание типа. `true` — правда поехало.
    pub fn wheel(&mut self, delta: i8) -> bool {
        let (content, view) = (self.content(), self.view());
        self.off.wheel(delta, self.row_h, content, view)
    }

    /// Нажали левую кнопку. `true` — нажатие НАШЕ (попали в полосу). Решает [`Grab`].
    pub fn press(&mut self, p: (i32, i32)) -> bool {
        let (content, view) = (self.content(), self.view());
        match self.grab.press(p, self.off.px, view, content) {
            Some(px) => {
                self.off.set(px, content, view);
                true
            }
            None => false,
        }
    }

    /// Ведут полосу?
    pub fn dragging(&self) -> bool {
        self.grab.active()
    }

    /// Движение мыши при схваченной полосе. `true` — содержимое правда поехало.
    pub fn motion(&mut self, p: (i32, i32)) -> bool {
        let (content, view) = (self.content(), self.view());
        match self.grab.motion(p, view, content) {
            Some(px) => self.off.set(px, content, view),
            None => false,
        }
    }

    /// Кнопку отпустили — протяжка кончилась.
    pub fn release(&mut self) {
        self.grab.release();
    }

    /// Ряды, которые видно ХОТЯ БЫ КРАЕМ, вместе с их местом на экране.
    ///
    /// Крайние приходят сюда со своим ПОЛНЫМ прямоугольником — наполовину их обрежет клип
    /// области, и в этом вся разница с построчной прокруткой: там ряд либо нарисован целиком,
    /// либо не нарисован вовсе, и содержимое дёргается — верхний исчезает раньше, чем уйдёт за
    /// край, нижний появляется, только войдя целиком.
    ///
    /// Клип ставит ВЫЗЫВАЮЩИЙ: область он знает ([`Pane::area`]), а чем резать — его дело (у
    /// ряда может быть своя подложка во всю ширину, у содержимого — свой отступ).
    pub fn visible(&self) -> Rows {
        let frac = self.off.px.rem_euclid(self.row_h);
        let first = (self.off.px / self.row_h).max(0) as usize;
        // С ОКРУГЛЕНИЕМ ВВЕРХ и с запасом на уехавшую вверх половину: ряд видно, пока его верх
        // выше низа области, то есть `k * row_h < view + frac`.
        let count = ((self.view() + frac + self.row_h - 1) / self.row_h).max(0) as usize;
        Rows {
            i: first,
            end: self.rows.min(first.saturating_add(count)),
            y: self.area.y - frac,
            x: self.area.x,
            w: self.area.w,
            row_h: self.row_h,
        }
    }

    /// Нарисовать полосу — и только. Смещение к этому моменту уже посчитано событием.
    ///
    /// Сама решает, нужна ли она: при полностью видимом содержимом полоса — украшение, которое
    /// врёт («тут ещё что-то есть»). Это решение внутри [`super::Ui::scrollbar`], общее на всех.
    pub fn bar(&self, u: &mut super::Ui) {
        if self.grab.track().is_empty() {
            return;
        }
        u.scrollbar(
            self.grab.track(),
            self.off.px.max(0) as usize,
            self.view().max(1) as usize,
            self.content().max(0) as usize,
            None,
        );
    }
}

/// Видимые ряды полотна: номер записи и её место на экране.
pub struct Rows {
    i: usize,
    end: usize,
    y: i32,
    x: i32,
    w: i32,
    row_h: i32,
}

impl Iterator for Rows {
    type Item = (usize, super::Rect);

    fn next(&mut self) -> Option<Self::Item> {
        if self.i >= self.end {
            return None;
        }
        let out = (self.i, super::Rect::new(self.x, self.y, self.w, self.row_h));
        self.i += 1;
        self.y += self.row_h;
        Some(out)
    }
}
