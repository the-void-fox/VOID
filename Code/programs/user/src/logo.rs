//! Знак VOID — шестиугольник с открытым глазом, уши сверху, морда снизу. Рисуется ФУНКЦИЯМИ.
//!
//! ## Почему не картинка
//!
//! Знак системы обязан быть у системы ВСЕГДА: на свежей машине, где в store ещё ничего нет, на
//! экране до первого `fetch`, на любом разрешении от 640×480 до 4K. Файл этого не даёт — он
//! приходит из store, зависит от декодера и от того, что кто-то его туда положил, и на чужом
//! разрешении либо мылится, либо режется. Здесь знак — сорок констант и уравнения: любой размер
//! получается точным, а весит он ноль.
//!
//! Второй довод: набросок от руки не бывает ровным. Уши разного размера, кольцо гуляет по
//! толщине, зрачок съехал. Всё это исправляется не аккуратностью руки, а тем, что фигуры
//! ВЫВОДЯТСЯ друг из друга: уши стоят на рёбрах шестиугольника, морда обнимает его нижний угол,
//! и все три отстоят от кольца на ОДИН и тот же зазор [`GAP`]. Симметрия здесь не нарисована, а
//! посчитана — левое ухо это правое с зеркальным `x`.
//!
//! ## Единицы
//!
//! Всё в долях `R` — радиуса описанной окружности шестиугольника; начало координат в его центре,
//! `y` вниз (как на экране). Шестиугольник «острым углом вверх»: вершины сверху и снизу, слева и
//! справа вертикальные рёбра.
//!
//! ```text
//!            /\  ухо              вершины: (0,-1) (±S,-0.5) (±S,+0.5) (0,+1),  S = √3/2
//!        ___/  \___
//!       |   ~<o>~  |               глаз: две дуги + зрачок в центре
//!       |__      __|
//!          \    /
//!           \  /  морда
//! ```
//!
//! ## Сглаживание и свечение
//!
//! Края считаются НАДВЫБОРКОЙ 4×4: у каждой фигуры есть только предикат «точка внутри», и
//! доля попавших подточек и есть прозрачность пикселя. Так сглаживание получается одинаковым и
//! для многоугольника, и для дуги, и не требует ни SDF, ни корней — в no_std нет ни `sqrt`, ни
//! `sin`, и тянуть ради знака `libm` было бы платой за то, чего можно не делать: круг проверяется
//! сравнением КВАДРАТОВ расстояний, шестиугольник — тремя модулями.
//!
//! Свечение — размытие той же маски (три прохода коробочного фильтра, они дают почти гаусс) и
//! добавление цветом. Радиус размытия на скорость не влияет: фильтр идёт бегущей суммой.

use alloc::vec;
use alloc::vec::Vec;

// ── Геометрия знака (доли R) ────────────────────────────────────────────────────────────────

/// √3/2 — апофема шестиугольника с R=1, она же половина его ширины.
const S: f32 = 0.866_025_4;
/// Толщина кольца, перпендикулярная ребру. Обводка идёт ВНУТРЬ контура: снаружи размер знака
/// задан вершинами, и толщина не должна его менять.
const T_HEX: f32 = 0.125;
/// Зазор между кольцом и отростками. Один на всех — уши и морда «висят» на равном расстоянии,
/// и это единственное, что делает их роднёй, а не тремя случайными фигурами.
const GAP: f32 = 0.13;

/// Ухо: начало и конец основания вдоль ребра (ребро длиной 1 от верхней вершины к боковой).
const EAR_A: f32 = 0.16;
const EAR_B: f32 = 0.80;
/// Кончик уха: смещён к ВНЕШНЕМУ концу основания (0.48 было бы серединой) — от этого ухо
/// смотрит наружу, а не строго вверх.
const EAR_TIP: f32 = 0.58;
/// Высота уха над основанием.
const EAR_H: f32 = 0.86;
/// Выпуклость наружного ребра уха и вогнутость внутреннего.
const EAR_OUT: f32 = 0.10;
const EAR_IN: f32 = 0.06;

/// Морда: половина верхней кромки вдоль каждого нижнего ребра, от выемки.
const MUZ_HALF: f32 = 0.50;
/// Кончик морды по вертикали.
const MUZ_TIP: f32 = 1.82;
/// Выпуклость боков морды.
const MUZ_OUT: f32 = 0.08;

/// Глаз: половина ширины, подъём верхнего века и опускание нижнего. Веки разные намеренно:
/// одинаковые дают «рыбий глаз» — линзу, а не глаз.
const EYE_W: f32 = 0.66;
const EYE_UP: f32 = 0.22;
const EYE_DN: f32 = 0.18;
/// Уголки глаза по вертикали.
const EYE_Y: f32 = 0.02;
/// Толщина века в середине; к уголкам сходит на нет.
const T_LID: f32 = 0.095;
/// Зрачок: радиус и центр. Центр — середина ПРОСВЕТА между веками, а не уголков: веки разной
/// высоты, и по уголкам зрачок сидел бы низко. При EYE_UP/EYE_DN 0.22/0.18 просвет симметричен
/// относительно нуля — отсюда и ноль.
const PUPIL_R: f32 = 0.125;
const PUPIL_Y: f32 = 0.0;

/// Габарит знака вместе с ушами и мордой (для вписывания в экран).
pub const HALF_W: f32 = 1.0;
pub const TOP: f32 = -1.58;
pub const BOTTOM: f32 = MUZ_TIP + 0.02;

/// Надвыборка на пиксель по каждой оси.
const SUB: u32 = 4;

// ── Мелкая арифметика ───────────────────────────────────────────────────────────────────────
// `f32::abs`/`min`/`max` живут в std; в no_std их нет, а ради трёх сравнений тянуть libm глупо.

#[inline]
fn fabs(x: f32) -> f32 {
    if x < 0.0 {
        -x
    } else {
        x
    }
}
#[inline]
fn fmin(a: f32, b: f32) -> f32 {
    if a < b {
        a
    } else {
        b
    }
}
#[inline]
fn fmax(a: f32, b: f32) -> f32 {
    if a > b {
        a
    } else {
        b
    }
}

// ── Многоугольники (уши и морда) ────────────────────────────────────────────────────────────

/// Замкнутый контур, уже разложенный на отрезки, с габаритом для быстрого отказа.
struct Poly {
    pts: Vec<(f32, f32)>,
    x0: f32,
    y0: f32,
    x1: f32,
    y1: f32,
}

impl Poly {
    fn new(pts: Vec<(f32, f32)>) -> Poly {
        let (mut x0, mut y0) = (f32::MAX, f32::MAX);
        let (mut x1, mut y1) = (f32::MIN, f32::MIN);
        for &(x, y) in &pts {
            x0 = fmin(x0, x);
            y0 = fmin(y0, y);
            x1 = fmax(x1, x);
            y1 = fmax(y1, y);
        }
        Poly { pts, x0, y0, x1, y1 }
    }

    /// Чётность пересечений луча вправо. Годится и для невыпуклых (морда с выемкой — как раз).
    fn hit(&self, x: f32, y: f32) -> bool {
        if x < self.x0 || x > self.x1 || y < self.y0 || y > self.y1 {
            return false;
        }
        let mut inside = false;
        let n = self.pts.len();
        let mut j = n - 1;
        for i in 0..n {
            let (xi, yi) = self.pts[i];
            let (xj, yj) = self.pts[j];
            if (yi > y) != (yj > y) && x < xi + (y - yi) / (yj - yi) * (xj - xi) {
                inside = !inside;
            }
            j = i;
        }
        inside
    }
}

/// Ломаная-строитель: кривые второго порядка разбиваются здесь и дальше не существуют.
struct Path(Vec<(f32, f32)>);

impl Path {
    fn start(p: (f32, f32)) -> Path {
        Path(vec![p])
    }
    fn line(&mut self, p: (f32, f32)) {
        self.0.push(p);
    }
    /// Квадратичная кривая: 12 отрезков. На знаке высотой в пол-экрана это доли пикселя, а
    /// надвыборка добивает остальное.
    fn quad(&mut self, c: (f32, f32), p: (f32, f32)) {
        let a = *self.0.last().unwrap();
        for i in 1..=12 {
            let t = i as f32 / 12.0;
            let m = 1.0 - t;
            self.0.push((
                m * m * a.0 + 2.0 * m * t * c.0 + t * t * p.0,
                m * m * a.1 + 2.0 * m * t * c.1 + t * t * p.1,
            ));
        }
    }
}

#[inline]
fn mid(a: (f32, f32), b: (f32, f32)) -> (f32, f32) {
    ((a.0 + b.0) * 0.5, (a.1 + b.1) * 0.5)
}

/// Ухо на верхнем ребре. Считается в системе координат самого РЕБРА (`s` вдоль, `d` наружу) и
/// переносится на место — потому оно и стоит на ребре ровно, при любых правках констант.
fn ear(right: bool) -> Poly {
    // Ребро от верхней вершины (0,-1) к боковой (S,-0.5): длина 1, наружная нормаль (0.5,-S).
    let (ux, uy) = (S, 0.5);
    let (nx, ny) = (0.5, -S);
    let put = |s: f32, d: f32| {
        let x = ux * s + nx * d;
        let y = -1.0 + uy * s + ny * d;
        if right {
            (x, y)
        } else {
            (-x, y)
        }
    };

    let a = put(EAR_A, GAP);
    let b = put(EAR_B, GAP);
    let tip = put(EAR_TIP, GAP + EAR_H);
    // Управляющие точки тоже в системе ребра — сдвиг «в сторону +s» одинаково гнёт оба ребра
    // уха: наружное делает выпуклым, внутреннее вогнутым.
    let c_out = put(
        (EAR_B + EAR_TIP) * 0.5 + EAR_OUT,
        GAP + EAR_H * 0.5,
    );
    let c_in = put((EAR_TIP + EAR_A) * 0.5 + EAR_IN, GAP + EAR_H * 0.5);

    let mut p = Path::start(a);
    p.line(b);
    p.quad(c_out, tip);
    p.quad(c_in, a);
    Poly::new(p.0)
}

/// Морда под нижним углом. Её верхняя кромка — это в точности контур шестиугольника, отодвинутый
/// на [`GAP`]: выемка приходится ровно на нижнюю вершину, и знак читается как одно целое.
fn muzzle() -> Poly {
    // Угол, отодвинутый от двух рёбер сразу, уходит вниз на GAP/cos30°.
    let notch = (0.0, 1.0 + GAP / S);
    let l = (-MUZ_HALF * S, notch.1 - MUZ_HALF * 0.5);
    let r = (MUZ_HALF * S, notch.1 - MUZ_HALF * 0.5);
    let tip = (0.0, MUZ_TIP);

    let mut p = Path::start(l);
    p.line(notch);
    p.line(r);
    let cr = mid(r, tip);
    p.quad((cr.0 + MUZ_OUT, cr.1), tip);
    let cl = mid(tip, l);
    p.quad((cl.0 - MUZ_OUT, cl.1), l);
    Poly::new(p.0)
}

// ── Аналитические части: кольцо, веки, зрачок ───────────────────────────────────────────────

/// «Шестиугольный радиус» точки: 1.0 — точно на контуре знака, меньше — внутри. Три модуля по
/// трём нормалям — весь тест на принадлежность шестиугольнику.
#[inline]
fn hexr(x: f32, y: f32) -> f32 {
    fmax(fabs(x), fmax(fabs(0.5 * x + S * y), fabs(0.5 * x - S * y))) / S
}

#[inline]
fn ring(x: f32, y: f32) -> bool {
    let k = hexr(x, y);
    k <= 1.0 && k >= 1.0 - T_HEX / S
}

/// Веко: дуга окружности, проведённая через уголки глаза и через свою макушку. Проверяется без
/// корня — сравнением квадрата расстояния с квадратами внешнего и внутреннего радиусов.
#[inline]
fn lid(x: f32, y: f32, up: bool) -> bool {
    if fabs(x) > EYE_W {
        return false;
    }
    // К уголкам веко сходит на нет: иначе дуги обрубались бы вертикально и глаз выглядел
    // прямоугольным. Четвёртая степень держит середину полной толщины и убирает только края.
    let u = x / EYE_W;
    let t = T_LID * (1.0 - u * u * u * u);
    if t <= 0.0 {
        return false;
    }
    let h = if up { EYE_UP } else { EYE_DN };
    let r = (EYE_W * EYE_W + h * h) / (2.0 * h);
    let cy = if up { EYE_Y - h + r } else { EYE_Y + h - r };
    // Дальняя половина той же окружности лежит по другую сторону центра — её отсекаем, иначе
    // под мордой всплыла бы призрачная дуга.
    if up && y > cy || !up && y < cy {
        return false;
    }
    let d2 = x * x + (y - cy) * (y - cy);
    let ro = r + t * 0.5;
    let ri = r - t * 0.5;
    d2 <= ro * ro && d2 >= ri * ri
}

#[inline]
fn pupil(x: f32, y: f32) -> bool {
    let dy = y - PUPIL_Y;
    x * x + dy * dy <= PUPIL_R * PUPIL_R
}

/// Собранный знак: то, что нельзя посчитать формулой, посчитано один раз здесь.
pub struct Mark {
    ears: [Poly; 2],
    muz: Poly,
}

impl Mark {
    pub fn new() -> Mark {
        Mark { ears: [ear(false), ear(true)], muz: muzzle() }
    }

    /// Точка внутри знака (без зрачка — он идёт отдельным слоем ради своего свечения).
    #[inline]
    fn hit(&self, x: f32, y: f32) -> bool {
        ring(x, y)
            || lid(x, y, true)
            || lid(x, y, false)
            || self.ears[0].hit(x, y)
            || self.ears[1].hit(x, y)
            || self.muz.hit(x, y)
    }
}

// ── Растр ───────────────────────────────────────────────────────────────────────────────────

/// Маска знака во весь буфер `w × h`: центр шестиугольника в `(cx, cy)`, радиус `r` пикселей.
/// Возвращает (знак, зрачок) — второй нужен отдельно, чтобы глаз светился ярче остального.
fn masks(m: &Mark, w: u32, h: u32, cx: f32, cy: f32, r: f32) -> (Vec<u8>, Vec<u8>) {
    let mut a = vec![0u8; (w * h) as usize];
    let mut p = vec![0u8; (w * h) as usize];
    // Габарит в пикселях: за его пределами ни одна фигура не проверяется вовсе.
    let x0 = fmax(0.0, cx - HALF_W * r - 2.0) as u32;
    let x1 = fmin(w as f32, cx + HALF_W * r + 2.0) as u32;
    let y0 = fmax(0.0, cy + TOP * r - 2.0) as u32;
    let y1 = fmin(h as f32, cy + BOTTOM * r + 2.0) as u32;
    let step = 1.0 / SUB as f32;
    let full = (SUB * SUB) as f32;

    for py in y0..y1 {
        for px in x0..x1 {
            let (mut na, mut np) = (0u32, 0u32);
            for sy in 0..SUB {
                let y = ((py as f32 + (sy as f32 + 0.5) * step) - cy) / r;
                for sx in 0..SUB {
                    let x = ((px as f32 + (sx as f32 + 0.5) * step) - cx) / r;
                    if pupil(x, y) {
                        np += 1;
                    } else if m.hit(x, y) {
                        na += 1;
                    }
                }
            }
            let i = (py * w + px) as usize;
            // Зрачок входит и в общую маску: он часть знака, просто светится сам по себе.
            a[i] = ((na + np) as f32 / full * 255.0) as u8;
            p[i] = (np as f32 / full * 255.0) as u8;
        }
    }
    (a, p)
}

/// Коробочное размытие бегущей суммой: цена не зависит от радиуса. Три прохода ≈ гаусс.
fn blur(src: &[u8], w: u32, h: u32, r: u32, passes: u32) -> Vec<u8> {
    let mut cur: Vec<u16> = src.iter().map(|&v| v as u16).collect();
    let mut tmp: Vec<u16> = vec![0; cur.len()];
    let win = (2 * r + 1) as u32;
    for _ in 0..passes {
        // по горизонтали
        for y in 0..h {
            let row = (y * w) as usize;
            let mut sum: u32 = 0;
            for x in 0..=r.min(w - 1) {
                sum += cur[row + x as usize] as u32;
            }
            for x in 0..w {
                tmp[row + x as usize] = (sum / win) as u16;
                let add = x + r + 1;
                let sub = x as i64 - r as i64;
                if add < w {
                    sum += cur[row + add as usize] as u32;
                }
                if sub >= 0 {
                    sum -= cur[row + sub as usize] as u32;
                }
            }
        }
        // по вертикали
        for x in 0..w {
            let mut sum: u32 = 0;
            for y in 0..=r.min(h - 1) {
                sum += tmp[(y * w + x) as usize] as u32;
            }
            for y in 0..h {
                cur[(y * w + x) as usize] = (sum / win) as u16;
                let add = y + r + 1;
                let sub = y as i64 - r as i64;
                if add < h {
                    sum += tmp[(add * w + x) as usize] as u32;
                }
                if sub >= 0 {
                    sum -= tmp[(sub as u32 * w + x) as usize] as u32;
                }
            }
        }
    }
    cur.iter().map(|&v| v.min(255) as u8).collect()
}

/// Цвета обоев. Отдельной структурой, потому что знак один, а фон у него может быть разный.
pub struct Palette {
    /// Фон в центре и по углам: между ними мягкая виньетка.
    pub bg: (u8, u8, u8),
    pub bg_edge: (u8, u8, u8),
    /// Штрих знака.
    pub ink: (u8, u8, u8),
    /// Свечение вокруг знака и вокруг зрачка.
    pub glow: (u8, u8, u8),
    /// Сила свечения, 0 — выключено.
    pub glow_gain: f32,
}

impl Palette {
    /// Родная палитра VOID: цвет стола из `wm`, синий акцент оттуда же.
    pub const VOID: Palette = Palette {
        bg: (0x0d, 0x11, 0x17),
        bg_edge: (0x06, 0x08, 0x0c),
        ink: (0xe6, 0xed, 0xf3),
        glow: (0x4c, 0x7d, 0xfd),
        glow_gain: 1.0,
    };
}

/// Рассеивающий шум ±0.5 уровня: хэш от координат, без состояния и без таблицы.
///
/// Взято вместо порядковой матрицы (Байера) по результату на глаз: матрица — РЕГУЛЯРНАЯ, и на
/// почти чёрном фоне её клетка 4×4 читается вертикальной рябью, то есть меняет одну видимую
/// помеху на другую. Шум даёт зерно, которого на этой яркости не видно вовсе.
#[inline]
fn dither(x: u32, y: u32) -> f32 {
    let mut n = x.wrapping_mul(0x27d4_eb2d) ^ y.wrapping_mul(0x1656_67b1);
    n ^= n >> 15;
    n = n.wrapping_mul(0x2c1b_3c6d);
    n ^= n >> 12;
    ((n >> 8) & 0xffff) as f32 / 65535.0 - 0.5
}

#[inline]
fn mix(dst: u8, src: u8, a: u16) -> u8 {
    ((dst as u16 * (255 - a) + src as u16 * a) / 255) as u8
}

#[inline]
fn add(dst: u8, c: u8, a: u32) -> u8 {
    (dst as u32 + c as u32 * a / 255).min(255) as u8
}

/// Обои целиком: фон с виньеткой, свечение, знак. Буфер — RGBA8888 по строкам.
pub fn wallpaper(px: &mut [u8], w: u32, h: u32, pal: &Palette) {
    if w == 0 || h == 0 || px.len() < (w * h * 4) as usize {
        return;
    }
    // Знак занимает 60% высоты экрана — заметен, но обои остаются обоями, а не постером.
    let r = fmin(h as f32 * 0.60 / (BOTTOM - TOP), w as f32 * 0.42 / (2.0 * HALF_W));
    let cx = w as f32 * 0.5;
    // Центр шестиугольника выше середины экрана: у знака длинная морда, и по габариту его центр
    // тяжести ниже центра кольца.
    let cy = h as f32 * 0.5 - (TOP + BOTTOM) * 0.5 * r;

    // Фон: виньетка по квадрату расстояния от центра (корень тут не нужен — падение всё равно
    // на глаз, а не по метру).
    //
    // С РАССЕИВАНИЕМ: весь перепад фона — десяток уровней на полтысячи пикселей, и без него
    // градиент ложится видимыми кольцами. Шум в пол-уровня (см. [`dither`]) разбрасывает ошибку
    // округления — те же десять уровней, но глаз видит гладко.
    let (hw, hh) = (w as f32 * 0.5, h as f32 * 0.5);
    let norm = 1.0 / (hw * hw + hh * hh);
    for y in 0..h {
        let dy = y as f32 - hh;
        for x in 0..w {
            let dx = x as f32 - hw;
            let t = fmin(1.0, (dx * dx + dy * dy) * norm * 1.15);
            let d = dither(x, y);
            let i = ((y * w + x) * 4) as usize;
            for c in 0..3 {
                let (a, b) = match c {
                    0 => (pal.bg.0, pal.bg_edge.0),
                    1 => (pal.bg.1, pal.bg_edge.1),
                    _ => (pal.bg.2, pal.bg_edge.2),
                };
                let v = a as f32 + (b as f32 - a as f32) * t + d;
                px[i + c] = fmax(0.0, fmin(255.0, v)) as u8;
            }
            px[i + 3] = 0xff;
        }
    }

    let mark = Mark::new();
    let (a, p) = masks(&mark, w, h, cx, cy, r);

    if pal.glow_gain > 0.0 {
        // Два свечения: широкое от всего знака и тесное от зрачка. Одно общее давало бы либо
        // ровное пятно без взгляда, либо ореол размером с экран.
        let wide = blur(&a, w, h, (r * 0.16) as u32 + 1, 3);
        let eye = blur(&p, w, h, (r * 0.10) as u32 + 1, 3);
        for i in 0..(w * h) as usize {
            let g = (wide[i] as f32 * 0.55 + eye[i] as f32 * 1.6) * pal.glow_gain;
            let g = fmin(255.0, g) as u32;
            if g == 0 {
                continue;
            }
            let o = i * 4;
            px[o] = add(px[o], pal.glow.0, g);
            px[o + 1] = add(px[o + 1], pal.glow.1, g);
            px[o + 2] = add(px[o + 2], pal.glow.2, g);
        }
    }

    for i in 0..(w * h) as usize {
        if a[i] == 0 {
            continue;
        }
        let o = i * 4;
        px[o] = mix(px[o], pal.ink.0, a[i] as u16);
        px[o + 1] = mix(px[o + 1], pal.ink.1, a[i] as u16);
        px[o + 2] = mix(px[o + 2], pal.ink.2, a[i] as u16);
    }
}
